import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { testEnv } from './helpers.js';

/**
 * Purpose: My profile (2.1.8). A person signed in to the studio changes their own password at any time and
 * makes their own API tokens (30, 60 or 90 days) that act as them, with their roles: for the studio MCP server
 * and scripts. A token cannot make tokens or change the password; an expired token is renewed with a new value.
 * Administrators see and revoke people's tokens, can switch personal tokens off, and signing out everywhere,
 * a password reset or disabling the person ends them.
 */
testEnv(24250);
const { boot } = await import('../server/src/index.js');
const { q } = await import('../server/src/db.js');

let srv: Awaited<ReturnType<typeof boot>>;
let admin = '', alice = '', a = '', b = '';
const req = (method: string, url: string, o: { cookie?: string; token?: string; body?: any } = {}) => srv.admin.inject({
  method: method as any, url, ...(o.body !== undefined ? { payload: o.body } : {}),
  headers: { ...(o.token ? { authorization: `Bearer ${o.token}` } : { 'x-sutra': '1' }), ...(o.cookie ? { cookie: o.cookie } : {}) },
});
const cookieOf = (r: any) => String(r.headers['set-cookie'] || '').split(';')[0];
const signIn = async (username: string, password: string) => cookieOf(await req('POST', '/api/auth/login', { body: { username, password } }));
const mcp = (token: string, name: string, args: any) => srv.admin.inject({ method: 'POST', url: '/mcp/studio', payload: { jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } }, headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' } });
const days = (iso: string) => Math.round((Date.parse(iso) - Date.now()) / 86400e3);

before(async () => {
  srv = await boot({ listenAdmin: false, gateway: false });
  admin = cookieOf(await req('POST', '/api/auth/setup', { body: { username: 'root', password: 'first-admin-pass-1' } }));
  a = (await req('POST', '/api/projects', { cookie: admin, body: { name: 'Alpha' } })).json().id;
  b = (await req('POST', '/api/projects', { cookie: admin, body: { name: 'Bravo' } })).json().id;
  assert.equal((await req('POST', '/api/access/users', { cookie: admin, body: { username: 'alice', password: 'Temporary-pass-91', mustChange: false, grants: [{ role: 'developer', project: a }] } })).statusCode, 200);
  alice = await signIn('alice', 'Temporary-pass-91');
});
after(async () => { await srv.stop(); });

test('a person makes their own token: 30, 60 or 90 days, shown once, acting as them with their roles', async () => {
  const list = (await req('GET', '/api/access/me/tokens', { cookie: alice })).json();
  assert.deepEqual({ allowed: list.allowed, days: list.days, tokens: list.tokens }, { allowed: true, days: [30, 60, 90], tokens: [] });
  for (const bad of [0, 45, 365, undefined]) assert.equal((await req('POST', '/api/access/me/tokens', { cookie: alice, body: { name: 'x', expiresDays: bad } })).statusCode, 400, `expiresDays ${bad}`);
  const made = (await req('POST', '/api/access/me/tokens', { cookie: alice, body: { name: 'Copilot', expiresDays: 60 } })).json();
  assert.match(made.token, /^sut_[0-9a-f]{12}_/);
  assert.equal(days(made.expiresAt), 60);
  const listed = (await req('GET', '/api/access/me/tokens', { cookie: alice })).body;
  assert.ok(listed.includes('Copilot') && !listed.includes(made.token), 'listed without its value');

  const me = (await req('GET', '/api/access/me', { token: made.token })).json();
  assert.equal(me.username, 'alice');
  assert.equal(me.kind, 'user');
  assert.equal(me.viaToken, true);
  assert.equal((await req('GET', `/api/flows?projectId=${a}`, { token: made.token })).statusCode, 200);
  assert.equal((await req('GET', `/api/flows?projectId=${b}`, { token: made.token })).statusCode, 403, 'only her roles');

  // A token cannot make or renew tokens, nor change the password.
  assert.equal((await req('POST', '/api/access/me/tokens', { token: made.token, body: { name: 'more', expiresDays: 30 } })).statusCode, 403);
  assert.equal((await req('POST', `/api/access/me/tokens/${made.id}/renew`, { token: made.token })).statusCode, 403);
  assert.equal((await req('POST', '/api/auth/password', { token: made.token, body: { current: 'Temporary-pass-91', password: 'Another-pass-772' } })).statusCode, 400);
  // Personal tokens are made only by the person: an administrator cannot mint one for her.
  assert.equal((await req('POST', '/api/access/users/alice/tokens', { cookie: admin, body: { name: 'x' } })).statusCode, 400);
});

test('the studio MCP server with a personal token: her roles, her name in the audit log', async () => {
  const { token } = (await req('POST', '/api/access/me/tokens', { cookie: alice, body: { name: 'Claude', expiresDays: 30 } })).json();
  const doc = { name: 'From her assistant', nodes: [{ id: 's', type: 'start', name: 'Start', config: { payload: '{"x":1}' } }, { id: 'l', type: 'log', name: 'Note', config: { message: 'x={{input.x}}' } }], edges: [{ from: 's', to: 'l' }] };
  const made = (await mcp(token, 'create_sutra', { projectId: a, doc })).json().result;
  assert.ok(!made.isError, made.content?.[0]?.text);
  const t = (await mcp(token, 'test_sutra', { sutraId: made.structuredContent.sutraId })).json().result.structuredContent;
  assert.equal(t.passed, true, JSON.stringify(t));
  assert.equal((await mcp(token, 'create_sutra', { projectId: b, doc })).json().result.isError, true, 'not in Bravo');
  const rec = q.get<any>(`select actor, actor_kind, details from audit where action = 'MCP studio create_sutra' and outcome = 'ok'`);
  assert.deepEqual([rec.actor, rec.actor_kind, JSON.parse(rec.details).generated], ['alice', 'user', true]);
  assert.equal(q.get<any>(`select started_by from runs where id = ?`, t.runId).started_by.includes('alice'), true);
});

test('an expired token is refused and renewed with a new value, same name and period', async () => {
  const made = (await req('POST', '/api/access/me/tokens', { cookie: alice, body: { name: 'Antigravity', expiresDays: 30 } })).json();
  q.run('update api_tokens set expires_at = ? where id = ?', Date.now() - 1000, made.id);
  assert.equal((await req('GET', '/api/access/me', { token: made.token })).statusCode, 401);
  const row = (await req('GET', '/api/access/me/tokens', { cookie: alice })).json().tokens.find((t: any) => t.id === made.id);
  assert.equal(row.expired, true);
  const renewed = (await req('POST', `/api/access/me/tokens/${made.id}/renew`, { cookie: alice })).json();
  assert.notEqual(renewed.token, made.token);
  assert.equal(days(renewed.expiresAt), 30, 'same period as before');
  assert.equal((await req('GET', '/api/access/me', { token: renewed.token })).json().username, 'alice');
  const after = (await req('GET', '/api/access/me/tokens', { cookie: alice })).json().tokens;
  assert.ok(!after.some((t: any) => t.id === made.id), 'the old one is gone');
  assert.equal(after.filter((t: any) => t.name === 'Antigravity').length, 1);
  // Someone else's token id: not found.
  const other = (await req('POST', '/api/access/users', { cookie: admin, body: { username: 'bob', password: 'Temporary-pass-92', mustChange: false, grants: [{ role: 'viewer', project: a }] } }));
  assert.equal(other.statusCode, 200);
  const bob = await signIn('bob', 'Temporary-pass-92');
  assert.equal((await req('POST', `/api/access/me/tokens/${renewed.id}/renew`, { cookie: bob })).statusCode, 404);
  assert.equal((await req('DELETE', `/api/access/me/tokens/${renewed.id}`, { cookie: bob })).statusCode, 200);
  assert.equal((await req('GET', '/api/access/me', { token: renewed.token })).statusCode, 200, 'bob cannot revoke her token');
});

test('change password at any time; single sign-on people have none to change', async () => {
  const { token } = (await req('POST', '/api/access/me/tokens', { cookie: alice, body: { name: 'Kept', expiresDays: 90 } })).json();
  assert.equal((await req('GET', '/api/access/me', { cookie: alice })).json().hasPassword, true);
  assert.equal((await req('POST', '/api/auth/password', { cookie: alice, body: { current: 'wrong-one-1', password: 'Brand-new-pass-551' } })).statusCode, 400);
  const r = await req('POST', '/api/auth/password', { cookie: alice, body: { current: 'Temporary-pass-91', password: 'Brand-new-pass-551' } });
  assert.equal(r.statusCode, 200, r.body);
  alice = cookieOf(r);
  assert.equal((await req('GET', '/api/access/me', { cookie: alice })).statusCode, 200);
  assert.ok(await signIn('alice', 'Brand-new-pass-551'));
  assert.equal((await req('GET', '/api/access/me', { token })).statusCode, 200, 'her own change keeps her tokens');
  const { createAccount, me } = await import('../server/src/access.js');
  createAccount({ username: 'sso-carol', sso: true });
  assert.equal(me({ u: 'sso-carol', kind: 'user' }).hasPassword, false);
});

test('administrators see and revoke tokens, can switch them off; sign out everywhere, reset and disable end them', async () => {
  const mint = async (name: string) => (await req('POST', '/api/access/me/tokens', { cookie: alice, body: { name, expiresDays: 30 } })).json();
  const t1 = await mint('Revoke me');
  const seen = (await req('GET', '/api/access/users/alice/tokens', { cookie: admin })).json();
  assert.ok(seen.some((t: any) => t.id === t1.id));
  assert.equal((await req('DELETE', `/api/access/users/alice/tokens/${t1.id}`, { cookie: admin })).statusCode, 200);
  assert.equal((await req('GET', '/api/access/me', { token: t1.token })).statusCode, 401);

  // Off: tokens stop working and none can be made; on again: they work again.
  const t2 = await mint('Switch');
  assert.equal((await req('PUT', '/api/access/personal-tokens', { cookie: alice, body: { allowed: false } })).statusCode, 403, 'only administrators');
  assert.equal((await req('PUT', '/api/access/personal-tokens', { cookie: admin, body: { allowed: false } })).json().allowed, false);
  assert.equal((await req('GET', '/api/access/me', { token: t2.token })).statusCode, 401);
  assert.equal((await req('POST', '/api/access/me/tokens', { cookie: alice, body: { name: 'x', expiresDays: 30 } })).statusCode, 400);
  assert.equal((await req('GET', '/api/access/me/tokens', { cookie: alice })).json().allowed, false);
  await req('PUT', '/api/access/personal-tokens', { cookie: admin, body: { allowed: true } });
  assert.equal((await req('GET', '/api/access/me', { token: t2.token })).statusCode, 200);

  // Sign out everywhere ends her tokens with her sessions.
  assert.equal((await req('POST', '/api/access/users/alice/sign-out', { cookie: admin })).statusCode, 200);
  assert.equal((await req('GET', '/api/access/me', { token: t2.token })).statusCode, 401);
  alice = await signIn('alice', 'Brand-new-pass-551');
  // A password an administrator sets ends them too.
  const t3 = await mint('Reset');
  assert.equal((await req('POST', '/api/access/users/alice/password', { cookie: admin, body: { password: 'Admin-set-pass-339', mustChange: false } })).statusCode, 200);
  assert.equal((await req('GET', '/api/access/me', { token: t3.token })).statusCode, 401);
  // Disabled: refused.
  alice = await signIn('alice', 'Admin-set-pass-339');
  const t4 = await mint('Disable');
  await req('PUT', '/api/access/users/alice', { cookie: admin, body: { disabled: true } });
  assert.equal((await req('GET', '/api/access/me', { token: t4.token })).statusCode, 401);
  // System account tokens are unchanged by the switch and still made by administrators.
  await req('POST', '/api/access/users', { cookie: admin, body: { username: 'ci-bot', kind: 'system', grants: [{ role: 'viewer', project: a }] } });
  const sys = (await req('POST', '/api/access/users/ci-bot/tokens', { cookie: admin, body: { name: 'ci', expiresDays: 0 } })).json();
  await req('PUT', '/api/access/personal-tokens', { cookie: admin, body: { allowed: false } });
  assert.equal((await req('GET', '/api/access/me', { token: sys.token })).json().kind, 'system');
  await req('PUT', '/api/access/personal-tokens', { cookie: admin, body: { allowed: true } });
});

import { test, after } from 'node:test';

/**
 * Purpose: the connection-limit suite (connlimits.test.ts) on a real PostgreSQL server, with its pool,
 * advisory locks and two engines. Needs SUTRA_TEST_PG_URL (an administrator address); the test makes a
 * database of its own and drops it afterwards.
 */
const ADMIN = process.env.SUTRA_TEST_PG_URL;
if (!ADMIN) {
  test('connection limits on a real PostgreSQL server', { skip: 'set SUTRA_TEST_PG_URL to run against a PostgreSQL server' }, () => {});
} else {
  const { default: pg } = await import('pg');
  const admin = new pg.Client({ connectionString: ADMIN });
  admin.on('error', () => {});
  await admin.connect();
  const dbName = `sutra_connlimits_${Date.now()}`;
  await admin.query(`CREATE DATABASE ${dbName}`);
  const u = new URL(ADMIN); u.pathname = `/${dbName}`;
  process.env.SUTRA_DB = u.toString();
  await import('./connlimits.test.js');
  // Registered after the suite's own hooks, so its server stops before the database goes.
  after(async () => {
    await admin.query(`DROP DATABASE IF EXISTS ${dbName} WITH (FORCE)`).catch(() => {});
    await admin.end();
  });
}

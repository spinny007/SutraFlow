test('a suggested chart is used only for known settings and fields of the data; titles lose markup; the data comes from the rows', () => {
  const good = checkChartSettings('{"type": "line", "values": ["revenue", "orders"], "title": "Trend"}', rows, base);
  assert.deepEqual(good.problems, []);
  assert.equal(good.settings.type, 'line');
  assert.deepEqual(good.settings.values, ['revenue', 'orders']);
  const bad = checkChartSettings({ type: 'sankey', category: 'country', values: ['profit'], title: '<img src=x onerror=alert(1)> javascript:go', formatter: 'function(){}', palette: 'Neon' }, rows, base);
  assert.equal(bad.settings.type, 'bar', 'an unknown chart type is refused');
  assert.equal(bad.settings.category, 'month', 'a field not in the data is refused');
  assert.deepEqual(bad.settings.values, ['revenue']);
  assert.ok(!/[<>]|javascript:/i.test(bad.settings.title), `markup removed: ${bad.settings.title}`);
  for (const want of [/sankey/, /"country" is not in the data/, /"profit"/, /"formatter" is not a chart setting/, /Palette "Neon"/]) assert.ok(bad.problems.some(p => want.test(p)), `${want} in ${bad.problems.join(' | ')}`);
  assert.equal(checkChartSettings('not json', rows, base).problems[0], 'The suggested chart is not JSON');
  const chart = chartFrom(rows, { ...base, type: 'horizontal bar', sort: 'descending', limit: 2 });
  assert.deepEqual(chart.option!.dataset.source.map((r: any) => r.month), ['Feb', 'Mar'], 'sorted and limited');
  assert.equal(chart.option!.yAxis.type, 'category', 'horizontal: categories on the y axis');
  assert.ok(!JSON.stringify(chart.option).includes('function'), 'plain JSON only');
  assert.equal(chartFrom(rows, { ...base, type: 'number' }).value, 60);
  assert.deepEqual(chartFrom(rows, { ...base, type: 'table', values: ['revenue'] }).columns, ['month', 'revenue']);
  assert.equal(chartFrom(rows, { ...base, type: 'donut' }).option!.series[0].data.length, 3);
});


test('a dashboard cached for each caller keeps callers apart by everything the Sutra sees: issuer and claims, not the subject only (2.1.6)', async () => {
  const { SignJWT } = await import('jose');
  setSecret('DASH_JWT', 'dash-jwt-secret-0123456789abcdef0123');
  const key = new TextEncoder().encode('dash-jwt-secret-0123456789abcdef0123');
  const pol = saveResource({ kind: 'inboundPolicy', name: 'Dashboard JWT', project_id: pid, config: { auth: 'jwt', jwtMode: 'sharedSecret', jwtSecret: 'DASH_JWT', jwtIssuer: '', jwtAudience: '', requireHttps: false } }).id;
  const doc = { name: 'Level dashboard', nodes: [
    { id: 't', type: 'dashboardPage', name: 'Page', x: 0, y: 0, config: { name: 'levels', title: 'Levels', policy: pol, refreshSeconds: 300, cachePer: 'each caller', columns: 1 } },
    { id: 'c', type: 'chart', name: 'Level', x: 200, y: 0, config: { rows: '[{"n": {{input.caller.claims.level}}}]', title: 'Level', type: 'number', category: '', values: 'n' } },
    { id: 'r', type: 'dashboardReply', name: 'Reply', x: 400, y: 0, config: { charts: [{ k: 'Level', v: '{{nodes.Level.chart}}' }] } },
  ], edges: [{ id: 'e1', from: 't', port: 'out', to: 'c' }, { id: 'e2', from: 'c', port: 'out', to: 'r' }] };
  const f = flows.saveFlow(undefined, doc, pid);
  flows.deploy(f.id);
  const tok = (iss: string, level: number, iat?: number) => { const j = new SignJWT({ level }).setProtectedHeader({ alg: 'HS256' }).setSubject('user-1').setIssuer(iss).setExpirationTime('5m'); if (iat) j.setIssuedAt(iat); return j.sign(key); };
  const get = async (t: string) => (await fetch(`${env.http}/dash/levels/data`, { headers: { authorization: `Bearer ${t}` } })).json();
  const customer = await get(await tok('https://customers.example', 1));
  assert.equal(customer.charts[0].value, 1);
  const staff = await get(await tok('https://staff.example', 2));
  assert.equal(staff.charts[0].value, 2, 'same subject, another issuer: its own result');
  assert.equal(staff.cached, false);
  const again = await get(await tok('https://customers.example', 1, Math.floor(Date.now() / 1000) - 60));
  assert.equal(again.charts[0].value, 1);
  assert.equal(again.cached, true, 'a renewed token of the same caller keeps the cache');
  const promoted = await get(await tok('https://customers.example', 3));
  assert.equal(promoted.charts[0].value, 3, 'other claims: its own result');
  flows.undeploy(f.id);
});

test('raw JSON rows: grouped by month, split into series, counted, nested fields, the page filters, KPI cards and the list inside an answer', async () => {
  const { applyFilters, rowsFrom, dateBucket, filterValues, pageFilters, suggestCharts } = await import('../server/src/palettes/dashboard.js');
  const orders = [
    { id: 1, day: '2026-09-03', region: 'North', total: 100, customer: { city: 'Pune' } },
    { id: 2, day: '2026-09-20', region: 'South', total: 50, customer: { city: 'Delhi' } },
    { id: 3, day: '2026-10-02', region: 'North', total: 80, customer: { city: 'Pune' } },
    { id: 4, day: '2026-10-15', region: 'South', total: 40, customer: { city: 'Kandy' } },
    { id: 5, day: '2026-10-30', region: 'North', total: 30, customer: { city: 'Pune' } },
  ];
  const k = { ...base, aggregate: 'sum' as const, dateGroup: 'month' as const, category: 'day', values: ['total'] };
  assert.deepEqual(chartFrom(orders, k).option!.dataset.source, [{ day: '2026-09', total: 150 }, { day: '2026-10', total: 150 }], 'grouped by month and added up');
  const split = chartFrom(orders, { ...k, splitBy: 'region', type: 'line' });
  assert.deepEqual(split.option!.series.map((s: any) => s.name), ['North', 'South'], 'one series per region');
  assert.deepEqual(split.option!.dataset.source[1], { day: '2026-10', North: 110, South: 40 });
  const count = chartFrom(orders, { ...base, category: 'region', values: [], aggregate: 'count', type: 'pie' });
  assert.deepEqual(count.option!.series[0].data, [{ name: 'North', value: 3 }, { name: 'South', value: 2 }]);
  assert.equal(count.field, 'region', 'the chart names its field, for clicks that filter');
  const nested = chartFrom(orders, { ...base, category: 'customer.city', values: ['total'], aggregate: 'average', sort: 'descending' });
  assert.deepEqual(nested.option!.dataset.source, [{ 'customer.city': 'Pune', total: 70 }, { 'customer.city': 'Delhi', total: 50 }, { 'customer.city': 'Kandy', total: 40 }]);
  const kpi = chartFrom(orders, { ...k, type: 'kpi', kpi: 'latest', target: 300 });
  assert.equal(kpi.value, 150); assert.equal(kpi.previous, 150); assert.deepEqual(kpi.trend, [150, 150]); assert.equal(kpi.target, 300);
  assert.equal(chartFrom(orders, { ...k, type: 'kpi', kpi: 'total', aggregate: 'count', values: [] }).value, 5);
  assert.equal(chartFrom(orders, { ...base, type: 'number', values: ['total'], aggregate: 'max' }).value, 100);
  assert.equal(applyFilters(orders, { region: 'north' }).length, 3, 'a list filter, any case');
  assert.equal(applyFilters(orders, { region: ['South'], day: { from: '2026-10-01', to: '2026-10-31' } }).length, 1, 'a multi list and a date range');
  assert.equal(applyFilters(orders, { total: { from: '45', to: '90' } }).length, 2, 'a number range');
  assert.equal(applyFilters(orders, { 'customer.city': { contains: 'pu' } }).length, 3, 'a search on a nested field');
  assert.equal(applyFilters(orders, { warehouse: 'X', region: '' }).length, 5, 'a filter on a field the rows lack, or empty, keeps them');
  assert.equal(rowsFrom({ data: { orders } }, 'data.orders').length, 5, 'the list inside an answer');
  assert.equal(rowsFrom(JSON.stringify({ page: 1, items: orders })).length, 5, 'JSON text: its first list');
  assert.throws(() => rowsFrom('not rows'), /list of objects/);
  assert.equal(dateBucket('2026-10-02', 'quarter'), '2026-Q4'); assert.equal(dateBucket('2026-01-01', 'week'), '2026-W01'); assert.equal(dateBucket('2026-10-02T10:00:00Z', 'day'), '2026-10-02');
  const defs = pageFilters([{ k: 'region', v: 'list: North, South' }, { k: 'channel', v: 'multi list' }, { k: 'day', v: 'date range' }, { k: 'customer.city', v: 'search' }, { k: 'bad key!', v: 'list' }]);
  assert.deepEqual(defs.map(d => [d.field, d.kind]), [['region', 'list'], ['channel', 'multi list'], ['day', 'date range'], ['customer.city', 'search']]);
  assert.deepEqual(defs[0].choices, ['North', 'South']); assert.equal(defs[3].label, 'City');
  const q = new URLSearchParams('region=North&channel=Web&channel=Shop&day_from=2026-10-01&day_to=bad&customer.city=pu');
  const fv = filterValues(defs, x => q.getAll(x));
  assert.deepEqual(fv.params, { region: 'North', channel: 'Web,Shop', day_from: '2026-10-01', day_to: '', 'customer.city': 'pu' }, 'every filter present for SQL; a wrong date is dropped');
  assert.deepEqual(fv.filters, { region: 'North', channel: ['Web', 'Shop'], day: { from: '2026-10-01', to: '' }, 'customer.city': { contains: 'pu' } });
  const plan = suggestCharts(orders, 6);
  assert.deepEqual(plan.map(p => p.type), ['kpi', 'kpi', 'area', 'horizontal bar', 'donut', 'table'], 'rules: KPIs, a trend, a ranking, a share and the details');
  assert.ok(!plan.filter(p => p.type !== 'table').some(p => p.values.includes('id')), 'an id is not a figure');
});


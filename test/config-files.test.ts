const cli = (args: string[], env: Record<string, string> = {}) => new Promise<{ status: number | null; out: string; err: string }>(res => {
  const c = spawn(process.execPath, ['--disable-warning=ExperimentalWarning', '--import', 'tsx', path.join(root, 'server/src/cli.ts'), ...args], { cwd: root, env: { ...process.env, ...env } });
  let out = '', err = '';
  c.stdout.on('data', d => (out += d)); c.stderr.on('data', d => (err += d));
  c.on('close', status => res({ status, out, err }));
});
const write = (name: string, doc: unknown) => { const f = path.join(dir, name); fs.writeFileSync(f, typeof doc === 'string' ? doc : YAML.stringify(doc)); return f; };

test('export: server settings and projects as YAML, secrets as ${env:} placeholders, connections named, never people (2.1.6)', async () => {
  const out = path.join(dir, 'export.yaml');
  const r = await cli(['config', 'export', '--server-settings', '--project', 'Orders', '--out', out, '--server', ADMIN]);
  assert.equal(r.status, 0, r.err + r.out);
  const text = fs.readFileSync(out, 'utf8');
  assert.ok(!text.includes(SECRET), 'never a secret value');
  const doc = YAML.parse(text);
  const orders = doc.projects.find((p: any) => p.name === 'Orders');
  assert.equal(orders.properties.find((p: any) => p.name === 'DB_PASS').value, '${env:SUTRA_ORDERS_DB_PASS}');
  assert.equal(orders.properties.find((p: any) => p.name === 'RUNTIME').value, '$${env:ORDERS_RUNTIME}', 'a run-time reference stays one');
  assert.equal(orders.connections.find((c: any) => c.name === 'Order cache').settings.database, 'Orders SQLite');

  const body = (await srv.admin.inject({ method: 'POST', url: '/api/config/export', payload: { server: true }, headers: { authorization: `Bearer ${process.env.SUTRA_ADMIN_TOKEN}` } })).json();
  assert.ok(body.server.roles.some((x: any) => x.name === 'Release bot'));
  assert.ok(!body.server.roles.some((x: any) => x.name === 'Administrator'), 'built-in roles are on every server');
  const acc = body.server.systemAccounts.find((x: any) => x.name === 'ci-deployer');
  assert.deepEqual(acc.roles, [{ role: 'Viewer', project: 'Orders' }]);
  assert.ok(!JSON.stringify(body).includes('"password"') && !body.server.systemAccounts.some((x: any) => x.tokens), 'no tokens, no passwords');
  assert.equal(body.server.apps.find((x: any) => x.name === 'Partner portal').plan, 'Partners');
  assert.deepEqual(body.server.alerts.rules.find((x: any) => x.name === 'Failures').channels, ['Ops hook']);
  assert.ok(!('users' in body.server) && !('people' in body.server));
});

test('check changes nothing; apply creates a new project with its connections and vault secret, all at once (2.1.6)', async () => {
  const doc = YAML.parse(fs.readFileSync(path.join(dir, 'export.yaml'), 'utf8'));
  const p = doc.projects.find((x: any) => x.name === 'Orders');
  p.name = 'Orders test';
  const file = write('orders-test.yaml', { sutraflow: 'config', version: 1, projects: [p] });
  const envFile = write('env-test.yaml', { projects: [{ name: 'Orders test', properties: [{ name: 'REGION', value: 'test-1' }], connections: [{ name: 'Shop API', settings: { baseUrl: 'https://test-shop.example.test' } }] }] });
  const env = { SUTRA_ORDERS_DB_PASS: 'test-db-secret-7' };

  let r = await cli(['config', 'check', file, '--env', envFile, '--server', ADMIN], env);
  assert.equal(r.status, 0, r.err + r.out);
  assert.match(r.out, /Would create:/);
  assert.match(r.out, /project Orders test/);
  assert.match(r.out, /connection Order cache \(memoryTable\) in Orders test/);
  assert.ok(!projects.listProjects().some(x => x.name === 'Orders test'), 'a check creates nothing');

  r = await cli(['config', 'apply', file, '--env', envFile, '--yes', '--server', ADMIN], env);
  assert.equal(r.status, 0, r.err + r.out);
  assert.match(r.out, /Created:/);
  assert.ok(!r.out.includes('test-db-secret-7'), 'secret values are never printed');
  const made = projects.listProjects().find(x => x.name === 'Orders test')!;
  assert.ok(made);
  const vars = projects.getProject(made.id)!.config.variables;
  assert.equal(vars.find(v => v.name === 'REGION')!.value, 'test-1', 'the environment file wins');
  assert.equal(vars.find(v => v.name === 'RUNTIME')!.value, '${env:ORDERS_RUNTIME}');
  const pass = vars.find(v => v.name === 'DB_PASS')!;
  assert.equal(pass.type, 'secret');
  assert.equal(getSecret(pass.value), 'test-db-secret-7', 'stored in the vault');
  const res = listResources(undefined, made.id);
  assert.equal(res.find(x => x.name === 'Shop API')!.config.baseUrl, 'https://test-shop.example.test');
  assert.equal(res.find(x => x.name === 'Order cache')!.config.database, res.find(x => x.name === 'Orders SQLite')!.id, 'named connections point inside the new project');
});

test('apply again: nothing is changed; what is there is listed with name, type, where and the fields that differ (2.1.6)', async () => {
  const file = path.join(dir, 'orders-test.yaml');
  const envFile = write('env-test2.yaml', { projects: [{ name: 'Orders test', properties: [{ name: 'REGION', value: 'test-2' }], connections: [{ name: 'Shop API', settings: { baseUrl: 'https://other.example.test' } }] }] });
  const md = path.join(dir, 'checklist.md');
  const r = await cli(['config', 'apply', file, '--env', envFile, '--yes', '--checklist', md, '--server', ADMIN], { SUTRA_ORDERS_DB_PASS: 'another-secret' });
  assert.equal(r.status, 0, r.err + r.out);
  assert.match(r.out, /Nothing to create/);
  assert.match(r.out, /\[ \] connection Shop API \(httpConnection, https:\/\/test-shop\.example\.test\) in Orders test: .*other values for baseUrl/);
  assert.match(r.out, /\[ \] project property REGION \(string\) in Orders test: .*other values for value/);
  assert.match(r.out, /\[ \] project property DB_PASS \(secret\) in Orders test: .*other values for value/);
  assert.match(r.out, /\[ \] connection Orders SQLite \(database, orders\.sqlite\) in Orders test: .*the same values/);
  const made = projects.listProjects().find(x => x.name === 'Orders test')!;
  assert.equal(projects.getProject(made.id)!.config.variables.find(v => v.name === 'REGION')!.value, 'test-1', 'kept');
  assert.equal(getSecret(projects.getProject(made.id)!.config.variables.find(v => v.name === 'DB_PASS')!.value), 'test-db-secret-7', 'kept');
  assert.equal(listResources(undefined, made.id).find(x => x.name === 'Shop API')!.config.baseUrl, 'https://test-shop.example.test', 'kept');
  assert.ok(!r.out.includes('another-secret'));
  assert.match(fs.readFileSync(md, 'utf8'), /- \[ \] connection \*\*Shop API\*\* \(httpConnection, https:\/\/test-shop\.example\.test\) in Orders test/);
});

test('all or nothing: one item that cannot be created stops the apply and nothing is created (2.1.6)', async () => {
  const file = write('broken.yaml', {
    server: { roles: [{ name: 'Night shift', permissions: ['view'] }] },
    projects: [{ name: 'Broken', properties: [{ name: 'A', value: '1' }], connections: [{ name: 'Good', kind: 'httpConnection', settings: { baseUrl: 'https://a.example.test' } }, { name: 'Bad', kind: 'noSuchKind', settings: {} }, { name: 'Cache', kind: 'memoryTable', settings: { key: 'id', source: 'database query', database: 'Missing DB' } }] }],
  });
  const r = await cli(['config', 'apply', file, '--yes', '--server', ADMIN]);
  assert.equal(r.status, 1, r.out);
  assert.match(r.out, /Not applied: nothing was created/);
  assert.match(r.out, /connection Bad \(noSuchKind\) in Broken cannot be created: Unknown resource kind noSuchKind/);
  assert.match(r.out, /connection Cache \(memoryTable\) in Broken cannot be created: no connection named "Missing DB"/);
  assert.ok(!projects.listProjects().some(x => x.name === 'Broken'), 'the project was not kept');
  assert.ok(!access.listRoles().some(x => x.name === 'Night shift'), 'the role was not kept');
  // The server still serves as before (caches read the saved state again).
  assert.equal((await srv.admin.inject({ method: 'GET', url: '/api/projects', headers: { authorization: `Bearer ${process.env.SUTRA_ADMIN_TOKEN}` } })).statusCode, 200);
});

test('server part: missing items created, existing ones listed; a person never set by a file (2.1.6)', async () => {
  access.createAccount({ username: 'asha.p', password: 'Asha-demo-Passw0rd!', grants: [] });
  const file = write('server.yaml', {
    server: {
      roles: [{ name: 'Release bot', permissions: ['view', 'deploy', 'operate'] }, { name: 'Auditors', permissions: ['view'] }],
      systemAccounts: [{ name: 'ci-deployer', roles: [{ role: 'Viewer', project: 'Orders' }] }, { name: 'monitor-bot', displayName: 'Monitor', roles: [{ role: 'Auditors', project: '*' }] }],
      plans: [{ name: 'Partners', perMinute: 120 }],
      gateway: { firewall: { allow: ['10.0.0.0/8'] } },
      engineProperties: [{ name: 'SMTP_PASS', type: 'secret', value: '${env:SMTP_PASS}' }],
    },
  });
  let r = await cli(['config', 'apply', file, '--yes', '--server', ADMIN], { SMTP_PASS: 'smtp-secret-1' });
  assert.equal(r.status, 0, r.err + r.out);
  assert.match(r.out, /role Auditors/);
  assert.match(r.out, /system account monitor-bot/);
  assert.match(r.out, /setting gateway firewall/);
  assert.match(r.out, /\[ \] role Release bot: .*other values for permissions/);
  assert.match(r.out, /\[ \] system account ci-deployer: .*the same values/);
  assert.match(r.out, /\[ \] gateway plan Partners: .*other values for perMinute/);
  const mon = access.listUsers('system').find(u => u.username === 'monitor-bot')!;
  assert.equal(mon.grants[0].project, '');
  assert.deepEqual(gwa.getFirewall().allow, ['10.0.0.0/8']);
  const ev = projects.listEngineVariables().find(v => v.name === 'SMTP_PASS')!;
  assert.equal(getSecret(ev.value), 'smtp-secret-1');

  // The firewall is saved now: another file lists it instead of changing it.
  const again = write('server2.yaml', { server: { gateway: { firewall: { allow: ['192.168.0.0/16'] } }, systemAccounts: [{ name: 'asha.p', roles: [] }] } });
  r = await cli(['config', 'apply', again, '--yes', '--server', ADMIN]);
  assert.equal(r.status, 1, r.out);
  assert.match(r.out, /system account asha\.p: a person's account has this name; people are never set by a config file/);
  r = await cli(['config', 'check', write('server3.yaml', { server: { gateway: { firewall: { allow: ['192.168.0.0/16'] } } } }), '--server', ADMIN]);
  assert.equal(r.status, 0, r.out);
  assert.match(r.out, /\[ \] setting gateway firewall: .*other values for allow/);
  assert.deepEqual(gwa.getFirewall().allow, ['10.0.0.0/8']);
});

test('values: ${env:} read where the command runs, $${env:} kept, file: for secrets, plain secrets warned, missing ones stop it (2.1.6)', async () => {
  const secretFile = path.join(dir, 'db-pass.txt');
  fs.writeFileSync(secretFile, 'from-a-file\n');
  const r1 = resolveConfigValues({ projects: [{ name: 'P', properties: [
    { name: 'A', value: '${env:HOST_A}' }, { name: 'B', value: '$${env:KEEP}' }, { name: 'C', type: 'secret', value: `file:${secretFile}` },
    { name: 'D', type: 'secret', value: 'plain!' }, { name: 'E', type: 'secret', value: '${env:NOPE}' }, { name: 'F', value: 'file:/not/a/secret' },
  ] }] }, { HOST_A: 'a.example.test' });
  const v = Object.fromEntries(r1.doc.projects[0].properties.map((p: any) => [p.name, p.value]));
  assert.deepEqual(v, { A: 'a.example.test', B: '${env:KEEP}', C: 'from-a-file', D: 'plain!', E: '', F: 'file:/not/a/secret' });
  assert.deepEqual(r1.plainSecrets, ['P: property D']);
  assert.deepEqual(r1.missing, ['environment variable NOPE (projects[P].properties[E].value)']);
  assert.deepEqual(mergeConfig({ projects: [{ name: 'P', a: 1, l: [{ name: 'x', v: 1 }] }] }, { projects: [{ name: 'p', l: [{ name: 'X', v: 2 }, { name: 'y' }] }, { name: 'Q' }] }),
    { projects: [{ name: 'P', a: 1, l: [{ name: 'x', v: 2 }, { name: 'y' }] }, { name: 'Q' }] });

  const file = write('plain.yaml', { projects: [{ name: 'Orders', properties: [{ name: 'NEW_PASS', type: 'secret', value: 'written-here' }, { name: 'TOKEN', type: 'secret', value: '${env:NOT_SET_ANYWHERE}' }] }] });
  let r = await cli(['config', 'check', file, '--server', ADMIN]);
  assert.equal(r.status, 1);
  assert.match(r.out, /missing environment variable NOT_SET_ANYWHERE/);
  r = await cli(['config', 'check', write('plain2.yaml', { projects: [{ name: 'Orders', properties: [{ name: 'NEW_PASS', type: 'secret', value: 'written-here' }] }] }), '--server', ADMIN]);
  assert.equal(r.status, 0, r.out);
  assert.match(r.out, /warning  Orders: property NEW_PASS: a secret written directly in the file/);
  assert.ok(!r.out.includes('written-here'));
  r = await cli(['config', 'check', path.join(dir, 'plain2.yaml'), '--allow-plain-secrets', '--server', ADMIN]);
  assert.ok(!/warning/.test(r.out), r.out);
});

test('permissions follow what the file holds: Deploy on its projects, Users for accounts, Server settings for the server part (2.1.6)', async () => {
  const t = access.createToken('ci-deployer', 'config test');
  const as = (url: string, payload: any) => srv.admin.inject({ method: 'POST', url, payload, headers: { authorization: `Bearer ${t.token}` } });
  // ci-deployer only views Orders.
  let r = await as('/api/config/check', { config: { projects: [{ name: 'Orders', properties: [{ name: 'X', value: '1' }] }] } });
  assert.equal(r.statusCode, 403, r.body);
  assert.match(r.json().error, /deploy on Orders/);
  r = await as('/api/config/apply', { config: { server: { roles: [{ name: 'Sneaky', permissions: ['view'] }] } } });
  assert.equal(r.statusCode, 403);
  assert.match(r.json().error, /users/);
  r = await as('/api/config/export', { server: true });
  assert.equal(r.statusCode, 403);
  assert.ok(!access.listRoles().some(x => x.name === 'Sneaky'));
});

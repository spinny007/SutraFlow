/** trigger -> split (Switch-like fan-out) -> a (lane A) -> c ; split -> b (lane B). */
function lanes(cExpr: string) {
  return {
    name: 'Lanes',
    nodes: [
      node('t', 'start', 'Start', { payload: '{"x":1}' }),
      node('s', 'mapper', 'Split', { mapping: { rules: { x: { expr: '{input.x}' } } } }),
      node('a', 'mapper', 'Step a', { mapping: { rules: { a: { expr: "'A'" } } } }),
      node('b', 'mapper', 'Step b', { mapping: { rules: { b: { expr: "'B'" } } } }),
      node('c', 'mapper', 'Step c', { mapping: { rules: { out: { expr: cExpr } } } }),
    ],
    edges: [edge('t', 's'), edge('s', 'a'), edge('s', 'b'), edge('a', 'c')],
  };
}

async function waitRun(id: string) {
  await engine.waitFor(id, 20000);
  const r: any = q.get('select * from runs where id = ?', id);
  const tasks = q.all<any>('select * from tasks where run_id = ? order by id', id).map(t => ({ ...t, output: t.output ? JSON.parse(t.output) : t.output }));
  return { ...r, tasks };
}

test('steps before a step: lanes, joins and loops', () => {
  const doc = lanes('{nodes.Step a.a}');
  assert.deepEqual([...stepsBefore(doc, 'c')].sort(), ['a', 's', 't']);
  assert.ok(!stepsBefore(doc, 'c').has('b'), 'a step in another lane is not before c');
  const joined = { ...doc, edges: [...doc.edges, edge('b', 'c')] };
  assert.ok(stepsBefore(joined, 'c').has('b'), 'after a join both lanes are before the step');
  const loop = { edges: [edge('t', 'a'), edge('a', 'b'), edge('b', 'a')] };
  assert.ok(stepsBefore(loop, 'a').has('b'), 'a loop back reaches the step again');
  assert.equal(stepsBefore(doc, 't').size, 0, 'nothing is before the trigger');
});

test('step references: templates, formulas, JSONata, code; names with spaces, longest first', () => {
  const names = ['Orders', 'Orders by category', 'Total revenue', 'Step a'];
  assert.deepEqual(stepRefs('{{nodes.Total revenue.chart}}', names), ['Total revenue']);
  assert.deepEqual(stepRefs('{nodes.Orders by category.rows}', names), ['Orders by category']);
  assert.deepEqual(stepRefs('{{ nodes.Orders }}', names), ['Orders']);
  assert.deepEqual(stepRefs('$nodes.`Step a`.a', names), ['Step a']);
  assert.deepEqual(stepRefs("return nodes['Orders'].rows.length", names), ['Orders']);
  assert.deepEqual(stepRefs('nodes["Orders by category"]', names), ['Orders by category']);
  assert.deepEqual(stepRefs('subnodes.Orders and nodes.Unknown step', names), [], 'other words and unknown names are not references');
  assert.deepEqual(stepRefs('{{nodes.Orders.rows}} {{nodes.Total revenue.value}}', names).sort(), ['Orders', 'Total revenue']);
});

test('the lanes example: c sees a, not b (design check and data list)', () => {
  const ok = lanes('{nodes.Step a.a}');
  assert.deepEqual(offPathRefs(ok, ok.nodes[4]), []);
  assert.deepEqual(validateDoc(ok).errors, []);
  const bad = lanes('{nodes.Step b.b}');
  assert.deepEqual(offPathRefs(bad, bad.nodes[4]), [{ field: 'mapping', step: 'Step b' }]);
  const errors = validateDoc(bad).errors;
  assert.equal(errors.length, 1);
  assert.match(errors[0], /^Step c: The field "Target" uses the step "Step b", which is not on its path/);
  // The designer's data list shows the same steps as the rule, nothing from the other lane.
  const acts = engine.allActivities().map((a: any) => ({ type: a.type, name: a.name, ports: a.ports }));
  const listed = mappingSources(bad, 'c', acts).sources.map(s => s.node.id).sort();
  assert.ok(!listed.includes('b'), 'Step b is not offered to Step c');
  assert.deepEqual(listed, ['s', 't'], 'the earlier steps are offered (Step a is the current input)');
  const joined = { ...bad, edges: [...bad.edges, edge('b', 'c')] };
  assert.deepEqual(validateDoc(joined).errors, [], 'joining the lanes makes it valid');
});

test('the data list agrees with the rule on every sample step', () => {
  const p = saveProject({ name: 'Path data list', config: { variables: [] } });
  const acts = engine.allActivities().map((a: any) => ({ type: a.type, name: a.name, ports: a.ports }));
  for (const s of addSamples(p.id)) {
    const doc = getFlow(s.id)!.doc;
    for (const n of doc.nodes) {
      const before = stepsBefore(doc, n.id);
      const info = mappingSources(doc as any, n.id, acts);
      for (const src of info.sources) assert.ok(before.has(src.node.id), `${doc.name}/${n.name} offers ${src.node.name}, which is not before it`);
      for (const id of before) if (id !== n.id && !info.sources.some(x => x.node.id === id)) {
        const name = doc.nodes.find(x => x.id === id)?.name;
        assert.equal(name, info.inputAliasName, `${doc.name}/${n.name} misses ${name}`);
      }
    }
  }
});

test('Test and Deploy are refused for a reference to another lane', async () => {
  const p = saveProject({ name: 'Path refusal', config: { variables: [] } });
  const { saveFlow, publish } = await import('../server/src/flows.js');
  const f = saveFlow(undefined, lanes('{nodes.Step b.b}'), p.id);
  assert.throws(() => publish(f.id), /not on its path/);
});

test('the engine refuses a reference to another lane at run time (a version made before 2.1.7)', async () => {
  const doc = lanes('{nodes.Step b.b}');
  const runId = await engine.startRun({ doc, source: 'test', input: { x: 1 } } as any);
  const r = await waitRun(runId);
  assert.equal(r.status, 'failed');
  const failed = r.tasks.find((t: any) => t.node_id === 'c');
  assert.equal(failed.status, 'failed');
  assert.match(failed.error, /^The field "Target" uses the step "Step b", which is not on its path/);
  assert.match(r.error, /^Step c: The field "Target" uses the step "Step b"/, 'the run error names the step once');
  assert.ok(!/Step c: Step c:/.test(r.error));
});

test('at run time a step sees only the outputs on its path, and the Error handler sees all', () => {
  const doc = lanes('{nodes.Step a.a}');
  const outputs = { Start: { x: 1 }, Split: { x: 1 }, 'Step a': { a: 'A' }, 'Step b': { b: 'B' } };
  assert.deepEqual(Object.keys(allowedOutputs(doc, 'c', outputs)).sort(), ['Split', 'Start', 'Step a']);
  assert.deepEqual(Object.keys(allowedOutputs(doc, 'c', outputs, true)).sort(), ['Split', 'Start', 'Step a', 'Step b']);
});

test('a valid run across a join completes with both lanes', async () => {
  const doc = lanes('{nodes.Step a.a}');
  doc.nodes.push(node('m', 'merge', 'Join', {}), node('d', 'mapper', 'After join', { mapping: { rules: { both: { expr: 'concat({nodes.Step a.a}, {nodes.Step b.b})' } } } }));
  doc.edges.push(edge('c', 'm'), edge('b', 'm'), edge('m', 'd'));
  assert.deepEqual(validateDoc(doc).errors, []);
  const r = await waitRun(await engine.startRun({ doc, source: 'test', input: { x: 1 } } as any));
  assert.equal(r.status, 'done', JSON.stringify(r.error || r));
  const out = (r.tasks || []).find((t: any) => t.node_id === 'd')?.output;
  assert.deepEqual(out, { both: 'AB' });
});

test('conditions use only their source step and the steps before it', () => {
  const doc: any = lanes('{nodes.Step a.a}');
  doc.edges[3] = { ...edge('a', 'c'), when: 'when', condition: "{nodes.Step b.b} = 'B'" };
  assert.deepEqual(edgeOffPathRefs(doc, doc.edges[3]), ['Step b']);
  assert.ok(validateDoc(doc).errors.some((e: string) => /^Connection Step a to Step c: its condition uses the step "Step b"/.test(e)));
  doc.edges[3].condition = "{nodes.Step a.a} = 'A' and {nodes.Split.x} = 1";
  assert.deepEqual(edgeOffPathRefs(doc, doc.edges[3]), []);
});

test('the Error handler may use every step', () => {
  const doc: any = lanes('{nodes.Step a.a}');
  doc.nodes.push(node('h', 'catch', 'On error', {}), node('r', 'mapper', 'Report', { mapping: { rules: { failed: { expr: '{nodes.Step b.b}' } } } }));
  doc.edges.push(edge('h', 'r'));
  assert.ok(engine.activity('catch')?.noInput, 'the Error handler starts by itself');
  assert.deepEqual(offPathRefs(doc, doc.nodes[5], true), [], 'the Error handler may use every step');
  assert.deepEqual(offPathRefs(doc, doc.nodes[6]).map(r => r.step), ['Step b'], 'a step after the Error handler follows the rule from it');
});

test('every bundled sample follows the path rule', () => {
  const p = saveProject({ name: 'Path sample gate', config: { variables: [] } });
  const problems: string[] = [];
  for (const s of addSamples(p.id)) {
    const doc = getFlow(s.id)!.doc;
    for (const e of validateDoc(doc).errors) if (/not on its path/.test(e)) problems.push(`${doc.name}: ${e}`);
  }
  assert.deepEqual(problems, []);
});

test('the designer says where each reference comes from (trigger, steps, properties, SQL binding)', async () => {
  const { refOrigin, splitRef, fieldRefs } = await import('../web/src/ref-origin.js');
  const doc: any = lanes('{nodes.Step a.a}');
  const acts = engine.allActivities().map((a: any) => ({ type: a.type, name: a.name, trigger: !!a.trigger }));
  const o = { doc, nodeId: 'c', activities: acts };
  assert.deepEqual(splitRef('nodes.Total revenue.chart', ['Total revenue']), ['nodes', 'Total revenue', 'chart']);
  assert.deepEqual(splitRef('trigger.params.region'), ['trigger', 'params', 'region']);
  assert.equal(refOrigin('trigger.params.region', { ...o, bound: true }).text, 'trigger data → Start (Manual start) → params → region, sent as a bound parameter');
  assert.equal(refOrigin('nodes.Step a.a', o).text, 'step Step a (Map data) → a');
  const other = refOrigin('nodes.Step b.b', o);
  assert.equal(other.warn, true);
  assert.match(other.text, /^Step b \(Map data\) is not on this step's path/);
  assert.equal(refOrigin('gv.ORDERS_TABLE', { ...o, bound: true }).text, 'project property ORDERS_TABLE, written into the SQL');
  assert.equal(refOrigin('input.a', o).text, 'current input (the output of Step a) → a');
  assert.equal(refOrigin('nodes.Nobody.x', o).warn, true);
  assert.deepEqual(fieldRefs("WHERE ({{trigger.params.region}} = '' OR region = {{trigger.params.region}}) FROM {{gv.ORDERS_TABLE}}"), ['trigger.params.region', 'gv.ORDERS_TABLE']);
});

let edges = 0;
const node = (id: string, type: string, name: string, config: Record<string, any> = {}) => ({ id, type, name, x: 0, y: 0, config });
const edge = (from: string, to: string, port = 'out') => ({ id: `e${++edges}`, from, port, to });

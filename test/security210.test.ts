const run = async (projectId: string, step: ReturnType<typeof node>) => {
  const s = node('start', 'Start', { payload: '{}' });
  const id = await engine.startRun({ projectId, doc: { name: 'Security check', nodes: [s, step], edges: [edge(s, step)] } });
  await engine.waitFor(id, 15000);
  return { ...q.get<any>('select status, error from runs where id = ?', id), out: runState(id)?.outputs[step.name] };
};

test('a mapping path can never reach the object prototype, and an inherited flag never grants a permission', async () => {
  const before = Object.prototype.hasOwnProperty.call(Object.prototype, 'all');
  const m = await run(a, node('mapper', 'Map', { map: [{ k: '__proto__.all', v: 'true' }, { k: 'safe', v: 'ok' }] }));
  assert.equal(m.status, 'failed');
  assert.match(m.error, /__proto__/);
  for (const p of ['constructor.prototype.all', 'a.__proto__.all', 'x.prototype.y']) assert.throws(() => setPath({}, p, true), /not a data field name/, p);
  assert.equal(({} as any).all, undefined, 'Object.prototype was not changed');
  assert.equal(Object.prototype.hasOwnProperty.call(Object.prototype, 'all'), before);
  assert.equal(getPath({ a: 1 }, '__proto__'), undefined);
  assert.equal(getPath({ a: 1 }, 'constructor'), undefined);
  assert.throws(() => resolve("=object('__proto__', 1)", {}), /not a data field name/);
  assert.equal(Object.getPrototypeOf(resolve("=count-by(list(object('k', '__proto__')), 'k')", {})), Object.prototype, 'count-by keeps an ordinary object');
  // Even if a prototype were polluted, can() trusts only the caller's own flag.
  const developer = { u: 'nobody-with-grants' } as any;
  const proto = Object.prototype as any;
  proto.all = true;
  try { assert.equal(access.can(developer, 'server'), false, 'an inherited "all" is ignored'); }
  finally { delete proto.all; }
  void evaluate;
});

test('a step cannot use a connection of another project; shared connections stay usable', async () => {
  const privateMemory = saveResource({ kind: 'aiMemory', name: 'B private chats', project_id: b, config: { store: 'built-in' } });
  const shared = saveResource({ kind: 'aiMemory', name: 'Shared chats', config: { store: 'built-in' } });
  const foreign = await run(a, node('memoryLoad', 'Load', { memory: privateMemory.id, session: 'x' }));
  assert.equal(foreign.status, 'failed');
  assert.match(foreign.error, /B private chats belongs to another project/);
  const own = await run(b, node('memoryLoad', 'Load', { memory: privateMemory.id, session: 'x' }));
  assert.notEqual(own.error && /another project/.test(own.error), true, 'its own project may use it');
  const sharedUse = await run(a, node('memoryLoad', 'Load', { memory: shared.id, session: 'x' }));
  assert.ok(!/another project/.test(String(sharedUse.error || '')), 'a connection of no project is shared');
  // Outside any work (the Admin Console) lookups are not limited by this rule.
  assert.ok(effectiveResource(privateMemory.id));
  assert.throws(() => inProject(a, () => effectiveResource(privateMemory.id)), /another project/);
  // A connection cannot point at another project's connection.
  const dbB = saveResource({ kind: 'database', name: 'B database', project_id: b, config: { driver: 'sqlite', file: 'b.sqlite' } });
  assert.throws(() => saveResource({ kind: 'aiMemory', name: 'A memory on B db', project_id: a, config: { store: 'database', database: dbB.id } }), /B database belongs to another project/);
});

test('a Git repository cannot make the import read a file outside it', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sutra-git-escape-'));
  const repo = path.join(tmp, 'repo');
  fs.mkdirSync(path.join(repo, 'schemas'), { recursive: true });
  fs.writeFileSync(path.join(tmp, 'outside.json'), JSON.stringify({ type: 'object', title: 'PRIVATE-MARKER-123' }));
  fs.writeFileSync(path.join(repo, 'sutraflow.json'), JSON.stringify({ name: 'Escape', variables: [] }));
  fs.writeFileSync(path.join(repo, 'schemas', 'Leak.schema.json'), JSON.stringify({ id: 'leak-1', name: 'Leak', kind: 'json', file: '../../outside.json' }));
  fs.writeFileSync(path.join(repo, 'schemas', 'Leak2.schema.json'), JSON.stringify({ id: 'leak-2', name: 'Leak2', kind: 'json', file: 'C:/Windows/win.ini' }));
  let linked = false;
  try { fs.symlinkSync(path.join(tmp, 'outside.json'), path.join(repo, 'schemas', 'Link.json')); linked = true; } catch { /* no symlink right on this machine */ }
  if (linked) fs.writeFileSync(path.join(repo, 'schemas', 'Link.schema.json'), JSON.stringify({ id: 'leak-3', name: 'Link', kind: 'json', file: 'Link.json' }));
  const target = saveProject({ name: 'Git escape target' }).id;
  const report: any = readWorkingTree(repo, target, 'escape-ws');
  const schemas = listSchemas(target);
  assert.deepEqual(schemas.map((s: any) => s.name), [], 'no schema was made from outside content');
  assert.ok(report.problems.some((p: string) => /Leak\.schema\.json/.test(p)), JSON.stringify(report.problems));
  assert.doesNotMatch(JSON.stringify(schemas), /PRIVATE-MARKER-123/);
  fs.rmSync(tmp, { recursive: true, force: true });
});

test('the sign-in return path can never carry a script or leave this server', () => {
  for (const bad of ['/</script><script>alert(1)</script>', '/a"onmouseover=x', "/a'b", '/a b', '/a\\b', '/a\u2028b', '/a\nb', '//evil.example', '/\\evil', 'https://evil.example', '/' + 'x'.repeat(2001), '/a<b', '/a`b']) {
    assert.equal(safeReturn(bad), '/', JSON.stringify(bad));
  }
  for (const good of ['/', '/admin', '/admin#overview', '/approvals?tab=mine&x=1', '/guide#ch-mapping']) assert.equal(safeReturn(good), good);
});

test('two identity realms with the same subject are different owners of jobs and conversations', () => {
  const started = { subject: 'alice', method: 'jwt', realm: 'policy-1|https://idp-one.example' };
  assert.equal(sameCaller(started, { subject: 'alice', method: 'jwt', realm: 'policy-1|https://idp-one.example' } as any), true);
  assert.equal(sameCaller(started, { subject: 'alice', method: 'jwt', realm: 'policy-1|https://idp-two.example' } as any), false, 'same subject, other issuer');
  assert.equal(sameCaller(started, { subject: 'alice', method: 'jwt', realm: 'policy-2|https://idp-one.example' } as any), false, 'same subject, other policy');
  const scope = (realm: string) => ({ run: { project: a }, trigger: { channel: 'chat', agent: 'desk', caller: { subject: 'alice', method: 'jwt', realm } } });
  assert.notEqual(memoryKey('s-1', scope('p|https://idp-one.example')), memoryKey('s-1', scope('p|https://idp-two.example')));
  assert.equal(memoryKey('s-1', scope('p|x')), memoryKey('s-1', scope('p|x')));
  assert.equal(memoryKey('s-1', { run: { project: a }, trigger: { payload: 1 } }), 's-1', 'runs that did not come through a channel use the session as given');
});

/** A zip with one deflated entry of n bytes of 'A' (it compresses to almost nothing). */
function bomb(n: number, entries = 1) {
  const parts: Buffer[] = [], central: Buffer[] = [];
  let offset = 0;
  for (let i = 0; i < entries; i++) {
    const name = Buffer.from(`f${i}.txt`), data = zlib.deflateRawSync(Buffer.alloc(n, 65));
    const local = Buffer.alloc(30); local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(8, 8); local.writeUInt32LE(data.length, 18); local.writeUInt32LE(n, 22); local.writeUInt16LE(name.length, 26);
    const c = Buffer.alloc(46); c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(8, 10); c.writeUInt32LE(data.length, 20); c.writeUInt32LE(n, 24); c.writeUInt16LE(name.length, 28); c.writeUInt32LE(offset, 42);
    parts.push(local, name, data); central.push(c, name);
    offset += 30 + name.length + data.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries, 8); end.writeUInt16LE(entries, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, cd, end]);
}

test('an archive is read only within per-entry, total and entry-count limits, measured on what it really unpacks to', () => {
  const small = bomb(1000);
  assert.equal(unzip(small).get('f0.txt')!.length, 1000);
  const big = bomb(8 * 1048576);
  assert.ok(big.length < 20000, 'a tiny file');
  assert.throws(() => unzip(big, { maxEntries: 10, maxEntryBytes: 1048576, maxTotalBytes: 4 * 1048576 }), /unpacks to more than 1 MB/);
  assert.throws(() => unzip(bomb(600 * 1024, 4), { maxEntries: 10, maxEntryBytes: 1048576, maxTotalBytes: 2 * 1048576 }), /unpacks to more than/, 'the total budget counts every entry');
  assert.throws(() => unzip(bomb(10, 12), { maxEntries: 10, maxEntryBytes: 1048576, maxTotalBytes: 4 * 1048576 }), /12 entries; at most 10/);
  const broken = Buffer.from(small); broken.writeUInt32LE(0xffff0, broken.length - 6);
  assert.throws(() => unzip(broken), /damaged|not a zip/);
});

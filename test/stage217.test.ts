const row = (id: string) => q.get<any>('select stage, client, source, version from runs where id = ?', id);
const everyone = () => true;

test(`each source and version has its stage; the client is recorded (${ADMIN ? 'PostgreSQL' : 'SQLite'})`, () => {
  assert.equal(dbKind(), ADMIN ? 'postgres' : 'sqlite');
  assert.equal(runStage({ source: 'test', version: 0 }), 'design');
  assert.equal(runStage({ source: 'debug', version: 0 }), 'design');
  assert.equal(runStage({ source: 'test', version: 3 }), 'design', 'a test is design even of a deployed version');
  assert.equal(runStage({ source: 'rest', version: 0 }), 'design', 'a draft is design');
  for (const source of ['api', 'rest', 'soap', 'timer', 'file', 'mcp', 'websocket', 'channel', 'manual']) assert.equal(runStage({ source, version: 2 }), 'runtime', source);
  assert.equal(runStage({ source: 'sutra', version: 2, parentStage: 'design' }), 'design', 'a called Sutra takes its caller\'s stage');
  assert.equal(runStage({ source: 'sutra', version: 0, parentStage: 'runtime' }), 'runtime');
  assert.equal(runClient({ source: 'test' }), 'studio');
  assert.equal(runClient({ source: 'api' }), 'api');
  assert.equal(runClient({ source: 'api', client: 'cli' }), 'cli');
  assert.equal(runClient({ source: 'timer' }), null, 'automatic starts have no client');
});

function child(name: string) {
  const start = node('start', 'In', { payload: '{}' });
  const ret = node('return', 'Out', { source: 'value', value: '{{input}}' });
  return saveFlow(undefined, { name, nodes: [start, ret], edges: [edge(start, ret)] }, projectId);
}
function caller(name: string, childId: string) {
  const start = node('start', 'Go', { payload: '{"n": 1}' });
  const call = node('callProcess', 'Call', { process: childId, use: 'deployed', source: 'value', input: '{{input}}', wait: true });
  return saveFlow(undefined, { name, nodes: [start, call], edges: [edge(start, call)] }, projectId);
}
const childOf = (runId: string) => q.get<any>(`select id from runs where started_by like ?`, `%"id":"${runId}"%`)?.id;

test('runs started by the studio, the Run API, the CLI and a trigger get their stage and client; a child takes its caller\'s stage', async () => {
  const c = child('Stage child'); deploy(c.id);
  const p = caller('Stage parent', c.id); deploy(p.id);
  const pv = versionDoc(p.id, 1)!;
  // A studio test of the draft calls the deployed child: both are design.
  const t = await engine.startRun({ doc: p.doc, flowId: p.id, projectId, version: 0, source: 'test', client: 'studio' });
  await engine.waitFor(t, 10000);
  assert.deepEqual({ ...row(t), version: undefined }, { stage: 'design', client: 'studio', source: 'test', version: undefined });
  const tc = childOf(t);
  assert.ok(tc, 'the child ran');
  assert.equal(row(tc).stage, 'design', 'the deployed child called by a test is design');
  assert.equal(Number(row(tc).version), 1);
  // The Run API (from the CLI) on the deployed version: runtime, and so is its child.
  const a = await engine.startRun({ doc: pv, flowId: p.id, projectId, version: 1, source: 'api', client: 'cli' });
  await engine.waitFor(a, 10000);
  assert.equal(row(a).stage, 'runtime'); assert.equal(row(a).client, 'cli');
  assert.equal(row(childOf(a)).stage, 'runtime');
  // A trigger: runtime, no client.
  const timer = await engine.startRun({ doc: pv, flowId: p.id, projectId, version: 1, source: 'timer' });
  await engine.waitFor(timer, 10000);
  assert.equal(row(timer).stage, 'runtime'); assert.equal(row(timer).client, null);
});

test('figures and traces leave out design runs; the Design / Runtime / All filter in Traceability and Runs', async () => {
  const f = child('Stage figures');
  deploy(f.id);
  const design = await engine.startRun({ doc: f.doc, flowId: f.id, projectId, version: 0, source: 'test' });
  const runtime = await engine.startRun({ doc: versionDoc(f.id, 1)!, flowId: f.id, projectId, version: 1, source: 'api' });
  await engine.waitFor(design, 10000); await engine.waitFor(runtime, 10000);
  const ids = (o: any) => traceRuns(everyone, { projectId, flowId: f.id, ...o }).runs.map((r: any) => r.id).sort();
  assert.deepEqual(ids({}), [runtime], 'Traceability shows runtime runs by default');
  assert.deepEqual(ids({ stage: 'design' }), [design]);
  assert.deepEqual(ids({ stage: 'all' }), [design, runtime].sort());
  assert.deepEqual(ids({ tests: true }), [design, runtime].sort(), 'the older "tests" switch still means all');
  assert.equal(traceRuns(everyone, { projectId, flowId: f.id, stage: 'all' }).runs.find((r: any) => r.id === design)?.stage, 'design');
  const sutra = traceProjects(everyone).find((p: any) => p.id === projectId)?.sutras.find((s: any) => s.id === f.id);
  assert.equal(sutra?.done, 1, 'the project figures count the runtime run only');
  // Runs in the designer: all by default, or one stage. The first administrator of this test database signs in.
  const setup = await srv.admin.inject({ method: 'POST', url: '/api/auth/setup', payload: { username: 'stage-admin', password: crypto.randomBytes(18).toString('base64url') }, headers: { 'x-sutra': '1' } });
  const cookie = String(setup.headers['set-cookie']).split(';')[0];
  const call = (url: string) => srv.admin.inject({ method: 'GET', url, headers: { 'x-sutra': '1', cookie } }).then(r => { const b = r.json(); if (!Array.isArray(b)) throw new Error(`${r.statusCode} ${JSON.stringify(b)}`); return b; }).then((b: any[]) => b.filter((x: any) => x.flowId === f.id).map((x: any) => x.id).sort());
  assert.deepEqual(await call('/api/runs?limit=500'), [design, runtime].sort());
  assert.deepEqual(await call('/api/runs?limit=500&stage=design'), [design]);
  assert.deepEqual(await call('/api/runs?limit=500&stage=runtime'), [runtime]);
});

test('the upgrade fills the stage of older runs from source and version, in batches', () => {
  const old = [['old-test', 'test', 0], ['old-debug', 'debug', 0], ['old-draft-rest', 'rest', 0], ['old-timer', 'timer', 4], ['old-api', 'api', 2], ['old-child', 'sutra', 0]] as const;
  for (const [id, source, version] of old) {
    q.run(`insert into runs(id, flow_id, project_id, flow_name, version, doc, status, source, state, started_at) values(?, null, ?, 'Old', ?, '{}', 'done', ?, '{}', ?)`, id, projectId, version, source, new Date().toISOString());
  }
  assert.equal(q.get<any>(`select count(*) n from runs where stage is null`).n, old.length, 'made as an older version would');
  assert.equal(fillRunStages(undefined, 2), old.length, 'filled two at a time');
  const stages = Object.fromEntries(old.map(([id]) => [id, row(id).stage]));
  assert.deepEqual(stages, { 'old-test': 'design', 'old-debug': 'design', 'old-draft-rest': 'design', 'old-timer': 'runtime', 'old-api': 'runtime', 'old-child': 'design' });
  assert.equal(fillRunStages(), 0, 'nothing left on the next start');
});

test('retention: design runs are kept for their own time; runtime runs as before', () => {
  const at = (days: number) => new Date(Date.now() - days * 86400000).toISOString();
  const add = (id: string, stage: string, days: number) => q.run(`insert into runs(id, flow_id, project_id, flow_name, version, doc, status, source, state, started_at, finished_at, stage) values(?, null, ?, 'Kept', 1, '{}', 'done', 'api', '{}', ?, ?, ?)`, id, projectId, at(days), at(days), stage);
  add('keep-design-new', 'design', 2); add('drop-design-old', 'design', 10); add('keep-runtime-old', 'runtime', 10);
  housekeeping({ designRetentionDays: 0, retentionDays: 0 });
  assert.ok(row('drop-design-old'), '0 days keeps design runs');
  housekeeping({ designRetentionDays: 7, retentionDays: 0 });
  assert.equal(row('drop-design-old'), undefined, 'a design run older than 7 days is deleted');
  assert.ok(row('keep-design-new'));
  assert.ok(row('keep-runtime-old'), 'runtime runs follow Keep finished runs only');
});

async function delayedServer() {
  const sockets = new Set<any>();
  const server = http.createServer((req, res) => { req.resume(); setTimeout(() => { if (!res.destroyed) res.end('{"model":"slow","message":{"content":"ok"}}'); }, 180); });
  server.on('connection', s => { sockets.add(s); s.on('close', () => sockets.delete(s)); });
  await new Promise<void>(r => server.listen(0, '127.0.0.1', r));
  return { url: `http://127.0.0.1:${(server.address() as any).port}`, close: async () => { for (const s of sockets) s.destroy(); await new Promise<void>(r => server.close(() => r())); } };
}

test('connection deadline aborts a delayed model request and discovery', async () => {
  const s = await delayedServer();
  try {
    const r = resource({ baseUrl: s.url, model: 'slow', timeoutMs: 35 });
    await assert.rejects(aiCall(r, secret, request), /timed out|timeout/i);
    await assert.rejects(listModels(r, secret), /timed out|timeout/i);
  } finally { await s.close(); }
});

test('caller cancellation wins, and concurrent activity timeout overrides stay isolated', async () => {
  const s = await delayedServer();
  try {
    const r = resource({ baseUrl: s.url, model: 'slow', timeoutMs: 35 });
    const [short, long] = await Promise.allSettled([aiCall(r, secret, request), withAiExecution({ timeoutMs: 600 }, () => aiCall(r, secret, request))]);
    assert.equal(short.status, 'rejected'); assert.equal(long.status, 'fulfilled');
    const stop = new AbortController();const pending = aiCall(resource({ ...r.config, timeoutMs: 1000 }), secret, { ...request, signal: stop.signal });
    stop.abort(new Error('user stopped'));
    await assert.rejects(pending, /user stopped/);
    assert.equal(aiTimeoutMs(r), 35);
  } finally { await s.close(); }
});

test('engine inherits the AI connection deadline and an explicit step override can extend it', async () => {
  const s = await delayedServer();
  try {
    const r = saveResource({ name: 'Slow provider', kind: 'aiProvider', project_id: projectId, config: { engine: 'Ollama', model: 'slow', baseUrl: s.url, timeoutMs: 45 } });
    for (const override of [undefined, 600]) {
      const start = node('start', 'Input'), ai = node('aiPrompt', 'Answer', { provider: r.id, prompt: 'x', system: '' }, override ? { timeoutMs: override } : undefined);
      const id = await engine.startRun({ projectId, doc: { name: 'Timeout inheritance', nodes: [start, ai], edges: [edge(start, ai)] } });
      await engine.waitFor(id, 10000);const result: any = q.get('select * from runs where id = ?', id);
      assert.equal(result.status, override ? 'done' : 'failed', result.error);
      const logs = runState(id)!.logs.map((l: any) => l.msg).join('\n');assert.match(logs, /model slow/);
    }
  } finally { await s.close(); }
});


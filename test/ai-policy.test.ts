test('invalid timeout values and embedded URL credentials fail clearly; CLI has no API URL', async () => {
  for (const timeoutMs of [0, -1, 1.5, Infinity, 'bad']) assert.throws(() => aiTimeoutMs(resource({ timeoutMs })), /AI timeout/);
  assert.throws(() => rootOf(resource({ baseUrl: 'http://user:password@localhost:11434' })), /without credentials/);
  assert.equal(rootOf(resource({ engine: 'Claude CLI' })), '');
  await assert.rejects(resolveAiModel(resource({ engine: 'Claude CLI', modelSelection: 'automatic' }), secret), /explicit model/);
});


test('CLI deadline terminates its process instead of returning a stale success', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sutra-cli-deadline-'));
  const file = path.join(dir, 'wait.cjs');
  fs.writeFileSync(file, "process.stdin.resume(); setInterval(() => {}, 1000);");
  const started = Date.now();
  try {
    await allowPrograms(`"${process.execPath}"`); // 2.1.8: AI command-line tools need the administrator's allowance
    await assert.rejects(aiCall(resource({ engine: 'Claude CLI', model: 'explicit-model', command: process.execPath, args: `"${file}"`, timeoutMs: 300 }), secret, request), /timed out after 300 ms/);
    assert(Date.now() - started < 10000, 'CLI cancellation must close the subprocess promptly');
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});

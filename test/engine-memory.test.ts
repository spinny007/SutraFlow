import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { testEnv } from './helpers.js';

// This engine runs as the launcher's headless engine in the foreground (a service manager restarts it),
// with a settings file of its own: a changed Node memory is written there, and a restart is refused.
const { dir } = testEnv(23860);
const envFile = path.join(dir, 'sutraflow.env');
fs.writeFileSync(envFile, '# Settings\nENGINE_PORT=4801\n# ENGINE_MEMORY_MB=2048\nSUTRA_ENVIRONMENT=test\n');
Object.assign(process.env, { SUTRA_ENV_FILE: envFile, SUTRA_ROLE: 'engine', SUTRA_LAUNCHED: 'foreground', SUTRA_MEMORY_MB: '0', SUTRA_ENGINE_ID: 'mem-test' });

const { boot } = await import('../server/src/index.js');
const { beat, clusterStatus } = await import('../server/src/cluster.js');
const { setEngineTuning } = await import('../server/src/tuning.js');
const { requestRestart } = await import('../server/src/console.js');

let srv: any;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv?.stop(); });

test('Node memory: each engine reports its heap and machine; a changed value goes to its own settings file and waits for a restart', () => {
  beat();
  let me = clusterStatus().engines.find(e => e.id === 'mem-test')!;
  assert.ok(me.memory.heapLimitMb > 0 && me.memory.heapUsedMb > 0 && me.memory.machineMb > 0, JSON.stringify(me.memory));
  assert.equal(me.memory.wantedMb, me.memory.startedMb, 'nothing waits for a restart');
  assert.doesNotMatch(fs.readFileSync(envFile, 'utf8'), /^ENGINE_MEMORY_MB=/m, 'the settings file is not touched while nothing changed');

  assert.throws(() => setEngineTuning({ memoryMb: 100 }, 'mem-test'), /0 or at least 256/);
  setEngineTuning({ memoryMb: 1024 }, 'mem-test');
  beat();
  me = clusterStatus().engines.find(e => e.id === 'mem-test')!;
  assert.equal(me.memory.wantedMb, 1024);
  assert.equal(me.memory.startedMb, 0);
  const file = fs.readFileSync(envFile, 'utf8');
  assert.match(file, /^ENGINE_MEMORY_MB=1024$/m, 'written where the example line was');
  assert.match(file, /^# Settings$/m, 'its comments are kept');
  assert.match(me.memory.note, /applies when the engine restarts/);

  // Started by a service manager: the Admin Console does not restart it, and says how.
  assert.equal(me.memory.restartable, false);
  assert.throws(() => requestRestart('mem-test'), /not started in the background with sutraflow/);
  assert.throws(() => requestRestart('no-such-engine'), /No engine named/);

  // Back to Node's own: the line is emptied, so the launcher passes no limit.
  setEngineTuning({}, 'mem-test');
  beat();
  assert.match(fs.readFileSync(envFile, 'utf8'), /^ENGINE_MEMORY_MB=$/m);
});

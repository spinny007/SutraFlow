import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { testEnv } from './helpers.js';

/**
 * Purpose: 2.1.8 review: a directory junction (or symbolic link) inside a File step's folder or a project's
 * files folder carried reads and writes outside it, because paths were checked by their text only.
 */
testEnv(24183);
const { safePath, listFiles } = await import('../server/src/palettes/file.js');
const { writeProjectFiles } = await import('../server/src/bundles.js');
const { confine } = await import('../server/src/fs-confine.js');

const top = fs.mkdtempSync(path.join(os.tmpdir(), 'sutra-confine-'));
const inbox = path.join(top, 'inbox'), secret = path.join(top, 'elsewhere');
fs.mkdirSync(inbox); fs.mkdirSync(secret);
fs.writeFileSync(path.join(secret, 'private.txt'), 'outside the folder');
fs.writeFileSync(path.join(inbox, 'a.csv'), 'x');
// A junction on Windows (no special rights needed), a directory link elsewhere.
fs.symlinkSync(secret, path.join(inbox, 'door'), process.platform === 'win32' ? 'junction' : 'dir');

test('a File step path through a junction inside its folder is refused, for reading and for writing', () => {
  assert.equal(safePath(inbox, 'a.csv'), path.join(inbox, 'a.csv'), 'an ordinary file is fine');
  assert.equal(safePath(inbox, 'new/out.csv'), path.join(inbox, 'new', 'out.csv'), 'a file not written yet is fine');
  assert.throws(() => safePath(inbox, 'door/private.txt'), /through a link or junction/);
  assert.throws(() => safePath(inbox, 'door/new.txt'), /through a link or junction/, 'writing a new file through it too');
  assert.throws(() => safePath(inbox, '../elsewhere/private.txt'), /outside the folder/);
  assert.throws(() => confine(inbox, path.join(secret, 'private.txt')), /outside the folder/);
});

test('listing a folder does not follow junctions', async () => {
  const names = (await listFiles(inbox, '*', true)).map(f => f.name);
  assert.deepEqual(names, ['a.csv']);
});

test('a release cannot write its files through a junction in the project files folder', () => {
  assert.throws(() => writeProjectFiles(inbox, [['door/planted.txt', Buffer.from('x')]]), /through a link or junction/);
  assert.ok(!fs.existsSync(path.join(secret, 'planted.txt')));
  assert.equal(writeProjectFiles(inbox, [['ok/fine.txt', Buffer.from('x')]]), 1);
});

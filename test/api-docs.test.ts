import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { testEnv } from './helpers.js';
import { root } from './proc.js';

testEnv(23990);
const { API_DOCS } = await import('../server/src/api-docs.js');
const { RULES, OPEN_ROUTES } = await import('../server/src/guard.js');
const { apiChapters, groupedRoutes } = await import('../tools/guide/api-reference.js');

const routes = [...Object.keys(RULES), ...OPEN_ROUTES];

test('every admin API route is described in the Admin API reference', () => {
  const missing = routes.filter(r => !API_DOCS[r] || API_DOCS[r].does.trim().length < 15);
  assert.deepEqual(missing, [], `describe these in server/src/api-docs.ts: ${missing.join(', ')}`);
});

test('the reference describes no route that does not exist', () => {
  const known = new Set(routes);
  const extra = Object.keys(API_DOCS).filter(k => !known.has(k));
  assert.deepEqual(extra, [], `remove or correct in server/src/api-docs.ts: ${extra.join(', ')}`);
});

test('every route the sutra command calls names its sutra command', () => {
  // call('METHOD', '/api/...') and call('METHOD', `/api/...${x}...`) in cli.ts, with ${...} as one path segment.
  const cli = fs.readFileSync(path.join(root, 'server/src/cli.ts'), 'utf8');
  const calls = [...cli.matchAll(/call(?:<[^>]*>)?\('(GET|POST|PUT|PATCH|DELETE)',\s*[`'](\/api\/[^`']*)[`']/g)]
    .map(m => ({ method: m[1], path: m[2].replace(/\$\{[^}]*\}/g, 'x').split('?')[0] }));
  const patterns = Object.keys(RULES).map(k => { const [m, p] = k.split(' '); return { key: k, m, re: new RegExp(`^${p.replace(/:[A-Za-z]+/g, '[^/]+')}$`) }; });
  const found = new Set<string>();
  for (const c of calls) { const hit = patterns.find(p => p.m === c.method && p.re.test(c.path)); if (hit) found.add(hit.key); }
  assert.ok(found.size >= 60, `the scan of cli.ts found ${found.size} routes; it should find most of them`);
  const noCli = [...found].filter(k => !API_DOCS[k]?.cli);
  assert.deepEqual(noCli, [], `add cli to these in server/src/api-docs.ts: ${noCli.join(', ')}`);
});

test('the Admin API part places every described route in exactly one chapter', () => {
  const grouped = groupedRoutes();
  const placed = [...grouped.values()].flat();
  assert.equal(placed.length, Object.keys(API_DOCS).length);
  assert.equal(new Set(placed).size, placed.length);
  const chapters = apiChapters();
  assert.equal(chapters[0].id, 'api-overview');
  const html = chapters.map(c => c.html).join('\n');
  for (const k of ['POST /api/packages/deploy', 'GET /api/engine/status', 'PUT /api/secrets/:name']) assert.ok(html.includes(k.replace(' ', '&nbsp;')), `${k} is in the reference`);
  assert.match(chapters[0].html, /X-Sutra: 1/);
  assert.match(chapters[0].html, /sutra deploy &lt;release.zip&gt;/);
});

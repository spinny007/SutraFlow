import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import v8 from 'node:v8';
import vm from 'node:vm';
import { testEnv, node, edge } from './helpers.js';

testEnv(23700);
v8.setFlagsFromString('--expose-gc');
const gc = vm.runInNewContext('gc') as () => void;
const { boot } = await import('../server/src/index.js');
const { engine, DocCache } = await import('../server/src/engine/engine.js');

let srv: any;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv?.stop(); });

const settle = async () => { for (let i = 0; i < 3; i++) { await new Promise(r => setTimeout(r, 20)); gc(); } };

test('a finished run is freed: the garbage collector takes its Sutra document, nothing in the engine keeps it', async () => {
  // Seen in the 2.1.0 soak: engine memory rose with the number of runs finished. What a run holds in
  // memory must be released once it ends, so only runs still going cost memory.
  // Each run in a function of its own, so this test keeps no reference to its document.
  const one = async (i: number) => {
    const s = node('start', 'Start', { payload: '{"n":1}' }), m = node('jsonata', 'Double', { source: '{{input}}', expression: '{ "n": n * 2, "pad": $pad }' });
    const doc: any = { name: `Memory ${i}`, nodes: [s, m], edges: [edge(s, m)], pad: 'x'.repeat(20000) };
    const ref = new WeakRef(doc);
    assert.equal(await engine.waitFor(await engine.startRun({ doc }), 20000), 'done');
    return ref;
  };
  const refs: WeakRef<object>[] = [];
  for (let i = 0; i < 40; i++) refs.push(await one(i));
  // One more run: whatever refers to the latest run only (one reference, not one per run) moves on to it.
  const s = node('start', 'Start', { payload: '{}' });
  assert.equal(await engine.waitFor(await engine.startRun({ doc: { name: 'Last', nodes: [s], edges: [] } }), 20000), 'done');
  await settle();
  const kept = refs.map((r, i) => (r.deref() ? i : -1)).filter(i => i >= 0);
  assert.deepEqual(kept, [], `finished runs still held in memory: ${kept.join(', ')}`);
  assert.equal(engine.docs.size, 0, 'no document of a finished run is cached');
});

test('documents of runs settled by another engine are dropped once unused', () => {
  // An engine runs steps of runs that another engine starts and settles: it never sees them end.
  const cache = new DocCache(50);
  const doc: any = { name: 'Elsewhere', nodes: [], edges: [] };
  for (let i = 0; i < 100; i++) cache.set(`run-${i}`, doc);
  assert.equal(cache.size, 100);
  const later = Date.now() + 120;
  while (Date.now() < later) { /* let the entries go idle */ }
  cache.set('run-new', doc);
  assert.equal(cache.size, 1, 'only the entry just used is kept');
  assert.equal(cache.get('run-new'), doc);
});

test('work the database lost track of while away is picked up: a run left open with every step ended is closed, a step stuck as running on a live engine runs again', async () => {
  // Seen in the 2.1.0 ten-minute soak: during a 20 s database cut the closing writes failed, leaving runs
  // "running" with every step done, and a step "running" under a live engine that no longer ran it.
  const { q } = await import('../server/src/db.js');
  const s = node('start', 'Start', { payload: '{"n":1}' }), m = node('jsonata', 'Double', { source: '{{input}}', expression: '{ "n": n * 2 }' });
  const doc = { name: 'Stranded', nodes: [s, m], edges: [edge(s, m)] };
  const later = Date.now() + 120000;

  const a = await engine.startRun({ doc });
  assert.equal(await engine.waitFor(a, 20000), 'done');
  q.run(`update runs set status = 'running', finished_at = null where id = ?`, a);
  assert.equal(await engine.settleStranded(later), 1);
  assert.equal(q.get<any>('select status from runs where id = ?', a).status, 'done', 'closed from its steps');

  const b = await engine.startRun({ doc });
  assert.equal(await engine.waitFor(b, 20000), 'done');
  const last = q.get<any>(`select * from tasks where run_id = ? and node_id = ?`, b, m.id);
  q.run(`update tasks set status = 'running', owner = ?, finished_at = null where id = ?`, engine.id, last.id);
  q.run(`update runs set status = 'running', finished_at = null where id = ?`, b);
  assert.equal(await engine.requeueStrandedHere(later), 1);
  assert.equal(await engine.waitFor(b, 20000), 'done', 'the step ran again and the run ended');
  assert.notEqual(q.get<any>('select status from tasks where id = ?', last.id).status, 'running');
});

test('a step that fails to prepare (the database away) is no longer listed as running, so the sweep runs it again', async () => {
  // Seen in the 2.1.0 ten-minute soak: six steps failed to read their run's outputs during a database cut
  // and stayed listed as running on a live engine, so nothing ever ran them again.
  const { q } = await import('../server/src/db.js');
  const s = node('start', 'Start', { payload: '{"n":1}' }), m = node('jsonata', 'Double', { source: '{{input}}', expression: '{ "n": n * 2 }' });
  const e = engine as any;
  const real = e.outputsOf;
  let failed = 0;
  e.outputsOf = async function (this: any, db: any, run: any) { if (!failed++) throw Object.assign(new Error('PostgreSQL cannot be reached; trying again in a moment'), { code: 'SUTRA_DB_UNREACHABLE' }); return real.call(this, db, run); };
  try {
    const id = await engine.startRun({ doc: { name: 'Prepare fails', nodes: [s, m], edges: [edge(s, m)] } });
    let stuck: any;
    for (let i = 0; i < 100 && !stuck; i++) { stuck = q.get<any>(`select id from tasks where run_id = ? and status = 'running'`, id); if (!stuck) await new Promise(r => setTimeout(r, 20)); }
    assert.ok(stuck, 'the step is left running in the database');
    await new Promise(r => setTimeout(r, 50));
    assert.equal(e.controllers.has(Number(stuck.id)), false, 'but not listed as running in the engine');
    assert.equal(await engine.requeueStrandedHere(Date.now() + 120000), 1);
    assert.equal(await engine.waitFor(id, 20000), 'done', 'the sweep ran it again');
  } finally { e.outputsOf = real; }
});

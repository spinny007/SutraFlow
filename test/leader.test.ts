import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { testEnv } from './helpers.js';

/** SUTRA_CAN_LEAD=0: an engine that must not lead (it cannot reach the watched folders, say) never takes the lease. */
testEnv(20880);
const { boot } = await import('../server/src/index.js');
const { config } = await import('../server/src/config.js');
const { beat, cluster, clusterStatus, setMayLead, setClusterName } = await import('../server/src/cluster.js');
const { sqliteFileOf } = await import('../server/src/sqlite-file.js');
const { q } = await import('../server/src/db.js');

let srv: Awaited<ReturnType<typeof boot>>;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { (config as any).canLead = true; await srv.stop(); });

test('an engine with SUTRA_CAN_LEAD=0 lets go of the lease and never takes it; others can', async () => {
  beat();
  assert.equal(cluster.leader, true, 'alone, it leads');
  (config as any).canLead = false;
  q.run('update engines set can_lead = 0 where id = ?', config.engineId);
  beat();
  assert.equal(cluster.leader, false, 'it let go');
  assert.equal(q.get('select 1 from leases where name = ? and holder = ?', 'leader', config.engineId), undefined);
  beat();
  assert.equal(cluster.leader, false, 'and does not take it again');
  assert.equal(clusterStatus().leader, null);
  assert.equal(clusterStatus().engines.find((e: any) => e.id === config.engineId)?.canLead, false, 'the Admin Console shows it');
  (config as any).canLead = true;
  beat();
  assert.equal(cluster.leader, true);
});

test('who may lead and the cluster name are set from the Admin Console, kept in the database, and followed by every engine', () => {
  beat();
  assert.equal(cluster.leader, true);
  assert.throws(() => setMayLead(config.engineId, false), /At least one running engine must be allowed to lead/, 'the only engine cannot be set to never lead');
  // A second engine that may lead: now this one can be set to never lead, and it lets go on its next beat.
  q.run(`insert into engines(id, host, pid, mode, version, started_at, heartbeat_at, workers, active, draining, can_lead) values('other', 'h', 1, 'engine', 'x', 'now', ?, 4, 0, 0, 1)`, Date.now());
  setMayLead(config.engineId, false);
  beat();
  assert.equal(cluster.leader, false, 'it let go');
  assert.equal(clusterStatus().engines.find((e: any) => e.id === config.engineId)?.canLead, false);
  setMayLead(config.engineId, true);
  q.run(`delete from engines where id = 'other'`);
  beat();
  assert.equal(cluster.leader, true, 'and leads again when allowed');
  assert.equal(setClusterName('  Production  '), 'Production');
  assert.equal(clusterStatus().clusterName, 'Production');
  assert.equal(setClusterName(''), '');
  // The SQLite file is always in the data folder, under the name given.
  assert.equal(sqliteFileOf('', '/d'), path.join('/d', 'sutra.db'));
  assert.equal(sqliteFileOf('shop.db', '/d'), path.join('/d', 'shop.db'));
  assert.equal(sqliteFileOf('sqlite:../../etc/x.db', '/d'), path.join('/d', 'x.db'), 'never outside the data folder');
  assert.equal(sqliteFileOf('postgres://u@h/db', '/d'), path.join('/d', 'sutra.db'));
});

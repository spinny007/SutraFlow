import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { testEnv, node, edge } from './helpers.js';
testEnv(23396);
const { boot } = await import('../server/src/index.js');
const { engine, runState } = await import('../server/src/engine/engine.js');
const { q } = await import('../server/src/db.js');
const { saveProject } = await import('../server/src/projects.js');
const { saveSchema } = await import('../server/src/schemas.js');
const { saveFlow, getFlow, deploy } = await import('../server/src/flows.js');
const { manualStartPayload } = await import('../server/src/contracts.js');
const { calledContract } = await import('../server/src/call-contract.js');
const { designSchemas } = await import('../server/src/design.js');

const ORDER_XSD = `<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">
  <xs:element name="Order"><xs:complexType><xs:sequence>
    <xs:element name="orderId" type="xs:string"/>
    <xs:element name="amount" type="xs:decimal"/>
  </xs:sequence></xs:complexType></xs:element>
</xs:schema>`;
const GOOD_XML = '<Order><orderId>A-1001</orderId><amount>12.5</amount></Order>';

let server: Awaited<ReturnType<typeof boot>>, projectId: string, xsd: string, json: string;
before(async () => {
  server = await boot({ listenAdmin: false, gateway: false });
  projectId = saveProject({ name: 'Called Sutra contracts' }).id;
  xsd = saveSchema({ project_id: projectId, name: 'Order XML', kind: 'xsd', root: 'Order', text: ORDER_XSD }).id;
  json = saveSchema({ project_id: projectId, name: 'Order JSON', kind: 'json', text: JSON.stringify({ type: 'object', required: ['orderId'], properties: { orderId: { type: 'string' }, qty: { type: 'integer' } } }) }).id;
});
after(async () => { await server.stop(); });

const runsOf = (flowName: string) => Number(q.get<any>(`select count(*) n from runs r join flows f on f.id = r.flow_id where f.name = ?`, flowName)?.n ?? 0);

test('Manual start with an XSD: XML test payload in, Parse XML shape plus the text out', async () => {
  const config = { schema: xsd, validateSchema: true, payload: GOOD_XML };
  const out: any = await manualStartPayload(config, undefined, {}, projectId, 'Order');
  assert.deepEqual(out.Order, { orderId: 'A-1001', amount: 12.5 });
  assert.equal(out.xml, GOOD_XML, 'the original text is kept under xml');
  assert.deepEqual((await manualStartPayload(config, { xml: GOOD_XML }, {}, projectId, 'Order') as any).Order.orderId, 'A-1001', '{ "xml": "<…>" } from the Run API');
  assert.deepEqual((await manualStartPayload(config, GOOD_XML, {}, projectId, 'Order') as any).Order.amount, 12.5, 'a plain XML string');
  // Data from a caller (the Parse XML shape) is written as XML, checked, and given back with the text.
  const fromData: any = await manualStartPayload(config, { Order: { orderId: 'B-7', amount: 3 } }, {}, projectId, 'Order');
  assert.equal(fromData.Order.orderId, 'B-7');
  assert.match(fromData.xml, /^<Order><orderId>B-7<\/orderId><amount>3<\/amount><\/Order>$/);
});

test('Manual start with an XSD refuses a wrong root, a missing field, a wrong type and text that is not XML', async () => {
  const config = { schema: xsd, validateSchema: true, payload: GOOD_XML };
  await assert.rejects(manualStartPayload(config, '<Invoice><orderId>A</orderId></Invoice>', {}, projectId, 'Order'), /root element must be Order/);
  await assert.rejects(manualStartPayload(config, '<Order><orderId>A</orderId></Order>', {}, projectId, 'Order'), /does not match Order XML/);
  await assert.rejects(manualStartPayload(config, '<Order><orderId>A</orderId><amount>lots</amount></Order>', {}, projectId, 'Order'), /does not match Order XML/);
  await assert.rejects(manualStartPayload(config, { Order: { orderId: 'A' } }, {}, projectId, 'Order'), /does not match Order XML/, 'data from a caller is checked too');
  await assert.rejects(manualStartPayload(config, 'orderId=A', {}, projectId, 'Order'), /must be XML text/);
  await assert.rejects(manualStartPayload(config, '<!DOCTYPE x [<!ENTITY e "x">]><Order/>', {}, projectId, 'Order'), /DTD\/entity/);
  // Strict validation Off: still parsed, never checked.
  const loose: any = await manualStartPayload({ ...config, validateSchema: false }, '<Order><orderId>A</orderId></Order>', {}, projectId, 'Order');
  assert.deepEqual(loose.Order, { orderId: 'A' });
});

test('the designer: an XSD Manual start gives the schema shape plus xml, and warns about a JSON test payload', () => {
  const start = node('start', 'Order', { schema: xsd, validateSchema: true, payload: '{"orderId": "A"}' });
  const d = designSchemas({ name: 'XML start', nodes: [start], edges: [] })[start.id];
  assert.deepEqual(d.out?.children?.map(c => c.name), ['Order', 'xml']);
  assert.deepEqual(d.out?.children?.[0].children?.map(c => c.name), ['orderId', 'amount']);
  assert.ok(d.warnings.some(w => /write the test payload as XML/.test(w)));
  const jsonStart = node('start', 'Order', { schema: json, validateSchema: true, payload: '{"orderId": "A"}' });
  assert.deepEqual(designSchemas({ name: 'JSON start', nodes: [jsonStart], edges: [] })[jsonStart.id].out?.children?.map(c => c.name), ['orderId', 'qty'], 'JSON payloads are unchanged');
});

/** A called Sutra: Manual start with a payload schema, then Return of its input. */
function child(name: string, schema: string, strict = true) {
  const start = node('start', 'Order in', { schema, validateSchema: strict, payload: schema === xsd ? GOOD_XML : '{"orderId": "A"}' });
  const ret = node('return', 'Give back', { source: 'value', value: '{{input}}' });
  return saveFlow(undefined, { name, nodes: [start, ret], edges: [edge(start, ret)] }, projectId);
}
function caller(name: string, config: Record<string, any>) {
  const start = node('start', 'Parent', { payload: '{}' });
  const call = node('callProcess', 'Call it', { use: 'draft', source: 'value', input: '{{input}}', wait: true, ...config });
  const after = node('noop', 'After', {});
  return { doc: { name, nodes: [start, call, after], edges: [edge(start, call), edge(call, after)] }, call };
}

test('Call Sutra takes the called Sutra\'s payload schema as its contract: targets, notes, change since accepted', () => {
  const c = child('Contract XML child', xsd);
  const found = calledContract(c.id, 'draft');
  assert.ok(!('problem' in found));
  assert.equal(found.ref, xsd); assert.equal(found.kind, 'xsd'); assert.equal(found.strict, true); assert.equal(found.version, 0);
  const { doc, call } = caller('Contract parent', { process: c.id, inputContract: true, contractSeen: found.fingerprint, source: 'mapping', inputMapping: { rules: {} } });
  const d = designSchemas(doc as any)[call.id];
  assert.equal((d.contract as any).follows, true);
  assert.equal((d.contract as any).changed, false);
  assert.deepEqual(d.inputTrees.inputMapping.children?.map(x => x.name), ['Order'], 'the mapping targets are the called Sutra\'s input');
  assert.deepEqual(d.warnings, []);
  // The called Sutra changes its schema: the caller says so until the designer accepts it.
  const changedDoc = getFlow(c.id)!.doc;
  changedDoc.nodes[0].config.schema = json;
  saveFlow(c.id, changedDoc, projectId);
  const after = designSchemas(doc as any)[call.id];
  assert.equal((after.contract as any).changed, true);
  assert.ok(after.warnings.some(w => /Contract XML child changed its input since this step was saved \(now Order JSON\)/.test(w)));
  assert.deepEqual(after.inputTrees.inputMapping.children?.map(x => x.name), ['orderId', 'qty'], 'the targets follow the called Sutra at once');
  call.config.contractSeen = (after.contract as any).fingerprint;
  assert.equal((designSchemas(doc as any)[call.id].contract as any).changed, false, 'accepted');
});

test('Call Sutra: an old step with its own Input schema keeps it; the contract is offered, not forced', () => {
  const c = child('Contract kept child', xsd);
  const { doc, call } = caller('Old parent', { process: c.id, inputSchema: json, source: 'mapping', inputMapping: { rules: {} } });
  const d = designSchemas(doc as any)[call.id];
  assert.equal((d.contract as any).follows, false);
  assert.equal((d.contract as any).ref, xsd, 'offered as a suggestion');
  assert.deepEqual(d.inputTrees.inputMapping.children?.map(x => x.name), ['orderId', 'qty'], 'still its own schema');
  assert.deepEqual(d.warnings, [], 'no warning: nothing changed for the old step');
});

test('Call Sutra: draft and deployed versions have their own contracts', () => {
  const c = child('Contract versions child', xsd);
  deploy(c.id);
  const draft = getFlow(c.id)!.doc;
  draft.nodes[0].config.schema = json;
  saveFlow(c.id, draft, projectId);
  const deployed = calledContract(c.id, 'deployed') as any, current = calledContract(c.id, 'draft') as any;
  assert.equal(deployed.ref, xsd); assert.ok(deployed.version > 0);
  assert.equal(current.ref, json); assert.equal(current.version, 0);
  const { doc, call } = caller('Versions parent', { process: c.id, use: 'deployed', inputContract: true, contractSeen: deployed.fingerprint });
  assert.equal((designSchemas(doc as any)[call.id].contract as any).ref, xsd, 'Version deployed: the deployed contract');
  const notDeployed = child('Contract never deployed', xsd);
  assert.match((calledContract(notDeployed.id, 'deployed') as any).problem, /is not deployed/);
});

test('a bad input fails the Call Sutra step before any step of the called Sutra runs, with or without Wait', async () => {
  const c = child('Contract run child', xsd);
  for (const wait of [true, false]) {
    const { doc } = caller(`Run parent ${wait}`, { process: c.id, inputContract: true, wait });
    const good = await engine.startRun({ projectId, doc, input: { Order: { orderId: 'A-9', amount: 4.5 } } });
    await engine.waitFor(good, 10000);
    assert.equal(q.get<any>('select status from runs where id=?', good).status, 'done', `good input, wait ${wait}`);
    if (wait) {
      const result: any = runState(good)?.outputs['Call it'];
      assert.equal(result.Order.orderId, 'A-9');
      assert.match(result.xml, /<orderId>A-9<\/orderId>/, 'the called Sutra received the data with its XML text');
    }
    // Without Wait the caller may finish before its child's run is written: wait for it, then count.
    for (let i = 0; i < 100 && !q.get<any>(`select id from runs where started_by like ?`, `%"id":"${good}"%`); i++) await new Promise(r => setTimeout(r, 50));
    assert.ok(q.get<any>(`select id from runs where started_by like ?`, `%"id":"${good}"%`), `the good input started the called Sutra, wait ${wait}`);
    const before = runsOf('Contract run child');
    const bad = await engine.startRun({ projectId, doc, input: { Order: { orderId: 'A-9' } } });
    await engine.waitFor(bad, 10000);
    assert.equal(q.get<any>('select status from runs where id=?', bad).status, 'failed', `bad input, wait ${wait}`);
    const task = q.get<any>(`select error from tasks where run_id = ? and status = 'failed'`, bad);
    assert.match(task.error, /Input for Contract run child refused: Order in \(Manual start\) payload: does not match Order XML/);
    assert.equal(runState(bad)?.outputs.After, undefined);
    assert.equal(runsOf('Contract run child'), before, 'the called Sutra did not start');
  }
});

test('the studio Test and the Run API refuse the same bad input to a Sutra with an XSD Manual start', async () => {
  const c = child('Contract entry child', xsd);
  const doc = getFlow(c.id)!.doc;
  const count = Number(q.get<any>('select count(*) n from runs').n);
  for (const source of ['test', 'api'] as const) {
    await assert.rejects(engine.startRun({ doc, flowId: c.id, projectId, source, input: '<Order><orderId>A</orderId></Order>' }), /does not match Order XML/, source);
    await assert.rejects(engine.startRun({ doc, flowId: c.id, projectId, source, input: { xml: '<Invoice/>' } }), /root element must be Order/, source);
  }
  assert.equal(Number(q.get<any>('select count(*) n from runs').n), count, 'no run was created');
  const ok = await engine.startRun({ doc, flowId: c.id, projectId, source: 'api', input: { xml: GOOD_XML } });
  await engine.waitFor(ok, 10000);
  assert.equal(q.get<any>('select status from runs where id=?', ok).status, 'done');
});

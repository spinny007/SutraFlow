const startLog = (name: string, message = 'Order {{input.order}}') => ({
  name, nodes: [{ id: 'start', type: 'start', name: 'Start', config: { payload: '{"order":"A-1001"}' } }, { id: 'note', type: 'log', name: 'Note', config: { message } }],
  edges: [{ from: 'Start', to: 'Note' }],
});


const SECRET_VALUE = 'zq-SECRET-value-7781';
let srv: Awaited<ReturnType<typeof boot>>;
let admin = '', a = '', b = '', bFlow = '';
const tokens: Record<string, string> = {};
/** Every tool answer the tests saw, to check no secret value ever came back. */
const answers: string[] = [];

const call = (method: string, url: string, payload?: any, cookie = admin) => srv.admin.inject({ method: method as any, url, payload, headers: { 'x-sutra': '1', ...(cookie ? { cookie } : {}) } });
let rpcId = 0;
const rpc = (token: string | undefined, method: string, params?: any) => srv.admin.inject({ method: 'POST', url: '/mcp/studio', payload: { jsonrpc: '2.0', id: ++rpcId, method, params }, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) } });
/** Calls a tool as an account; returns the tool's structured answer, or { error } when it was refused or failed. */
async function tool(who: string, name: string, args: any = {}) {
  const r = await rpc(tokens[who], 'tools/call', { name, arguments: args });
  assert.equal(r.statusCode, 200, r.body);
  answers.push(r.body);
  const res = r.json().result;
  return res.isError ? { error: res.content[0].text as string } : (res.structuredContent ?? JSON.parse(res.content[0].text));
}


import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { testEnv } from './helpers.js';

const { dir } = testEnv(23880);
const { boot } = await import('../server/src/index.js');
const { pemFrom, keyFrom, tlsMaterial, certPath } = await import('../server/src/connectors/tls-files.js');
const { resolveResourceConfig } = await import('../server/src/settings.js');
const projects = await import('../server/src/projects.js');
const { kafkaTlsOptions } = await import('../server/src/connectors/bus.js');

const CA = '-----BEGIN CERTIFICATE-----\nMIIBcA==\n-----END CERTIFICATE-----\n';
const CERT = '-----BEGIN CERTIFICATE-----\nMIIBcB==\n-----END CERTIFICATE-----\n';
const KEY = '-----BEGIN PRIVATE KEY-----\nMIIEvQ==\n-----END PRIVATE KEY-----\n';
const certs = path.join(dir, 'certs');
fs.mkdirSync(certs, { recursive: true });
fs.writeFileSync(path.join(certs, 'ca.pem'), CA);
fs.writeFileSync(path.join(certs, 'client.crt'), CERT);
fs.writeFileSync(path.join(certs, 'client.key'), KEY);
fs.writeFileSync(path.join(certs, 'notes.txt'), 'not a certificate');

let srv: any;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv?.stop(); });

test('certificate settings: a file on Windows or Linux, PEM text, or the older pasted text', () => {
  const abs = path.join(certs, 'ca.pem');
  assert.equal(pemFrom(abs, 'CA'), CA, 'an absolute path (C:\\... on Windows, /... on Linux)');
  assert.equal(pemFrom('certs/ca.pem', 'CA'), CA, 'forward slashes, relative to the data folder');
  assert.equal(pemFrom('certs\\ca.pem', 'CA'), CA, 'backslashes, relative to the data folder (also on Linux)');
  assert.equal(pemFrom(CA, 'CA'), CA.trim(), 'PEM text from a Certificate property or pasted');
  assert.equal(pemFrom(' CA ', 'CA'), 'CA', 'older pasted text that is not a path stays as it was');
  assert.equal(pemFrom('', 'CA'), '');
  assert.throws(() => pemFrom('certs/missing.pem', 'Kafka CA certificate'), /Kafka CA certificate: cannot read .*missing\.pem \(no such file\)/);
  assert.throws(() => pemFrom(path.join(certs, 'notes.txt'), 'Kafka CA certificate'), /is not a PEM file/);
  // Where each form points (on this machine).
  assert.equal(certPath('~/certs/ca.pem'), path.join(os.homedir(), 'certs', 'ca.pem'));
  assert.equal(certPath('certs/ca.pem'), path.join(dir, 'certs', 'ca.pem'));
  if (process.platform === 'win32') {
    assert.equal(certPath('C:\\certs\\aiven\\ca.pem'), 'C:\\certs\\aiven\\ca.pem');
    assert.equal(certPath('\\\\server\\certs\\ca.pem'), '\\\\server\\certs\\ca.pem');
  } else {
    assert.equal(certPath('/etc/ssl/sutraflow/ca.pem'), '/etc/ssl/sutraflow/ca.pem');
    assert.equal(certPath('certs\\ca.pem'), path.join(dir, 'certs', 'ca.pem'));
  }
});

test('private key settings: a key file, PEM text from a Private key property, or a vault secret', () => {
  const asked: string[] = [];
  const secret = (n: string) => { asked.push(n); return n === 'KAFKA_KEY' ? KEY : ''; };
  assert.equal(keyFrom(path.join(certs, 'client.key'), secret, 'key'), KEY);
  assert.equal(keyFrom('certs\\client.key', secret, 'key'), KEY);
  assert.equal(keyFrom(KEY, secret, 'key'), KEY.trim());
  assert.equal(keyFrom('KAFKA_KEY', secret, 'key'), KEY, 'a vault secret name');
  assert.deepEqual(asked, ['KAFKA_KEY'], 'files are never looked up as secrets');
});

test('a connection takes its certificates and key from files and variables; mutual TLS needs both', () => {
  const t = tlsMaterial({ caPem: path.join(certs, 'ca.pem'), clientCertPem: 'certs/client.crt', clientKeySecret: 'certs/client.key' }, () => '', 'Kafka');
  assert.deepEqual(t, { ca: CA, cert: CERT, key: KEY });
  assert.deepEqual(kafkaTlsOptions({ ssl: true, caPem: 'certs/ca.pem' }, () => ''), { rejectUnauthorized: true, ca: [CA] });
  assert.throws(() => tlsMaterial({ clientCertPem: 'certs/client.crt' }, () => '', 'Kafka'), /both Client certificate and Client private key/);
  // A path may carry a variable; certificate text is never templated.
  const scope = { gv: { KAFKA_CA: 'certs/ca.pem' }, ev: { CERTS: path.join(dir, 'certs') } };
  const got = resolveResourceConfig({ caPem: '{{ev.CERTS}}/ca.pem', clientCertPem: '{{ev.CERTS}}\\client.crt', trustedCertsPem: 'literal {{gv.KAFKA_CA}} suffix', jwtPublicKeyPem: '{{gv.KAFKA_CA}}' }, scope);
  assert.equal(got.caPem, `${path.join(dir, 'certs')}/ca.pem`);
  assert.equal(got.clientCertPem, `${path.join(dir, 'certs')}\\client.crt`);
  assert.equal(got.trustedCertsPem, 'literal {{gv.KAFKA_CA}} suffix');
  assert.equal(got.jwtPublicKeyPem, 'certs/ca.pem');
  assert.equal(pemFrom(got.caPem, 'CA'), CA);
});

test('Certificate and Private key properties: a certificate is readable text or a path, a private key is kept in the vault', () => {
  const p = projects.saveProject({ name: 'Certificates' });
  const saved = projects.saveProject({ id: p.id, name: p.name, config: { variables: [
    { name: 'KAFKA_CA', type: 'certificate', value: CA },
    { name: 'KAFKA_CA_FILE', type: 'certificate', value: 'C:\\certs\\aiven\\ca.pem' },
    { name: 'RATE', type: 'number', value: '12.5' },
  ] } });
  assert.equal(saved.config.variables.length, 3);
  assert.throws(() => projects.saveProject({ id: p.id, name: p.name, config: { variables: [{ name: 'BAD', type: 'certificate', value: 'line one\nline two' }] } }), /give the PEM text .* or the path of a PEM file/);
  assert.throws(() => projects.saveProject({ id: p.id, name: p.name, config: { variables: [{ name: 'RATE', type: 'number', value: '12,5' }] } }), /not a number \(use a point for decimals/);
  assert.equal(projects.effectiveVariables(p.id).values.RATE, 12.5, 'decimal numbers');

  assert.throws(() => projects.storeProjectSecret(p.id, 'KAFKA_KEY', 'not a key', true, true, 'private key'), /paste the PEM private key/);
  const stored = projects.storeProjectSecret(p.id, 'KAFKA_KEY', KEY, true, true, 'private key');
  assert.equal(stored.reference, '{{gv.KAFKA_KEY}}');
  const v = projects.getProject(p.id)!.config.variables.find(x => x.name === 'KAFKA_KEY')!;
  assert.equal(v.type, 'private key');
  assert.notEqual(v.value, KEY, 'the project holds a vault reference, not the key');
  assert.equal(projects.effectiveVariables(p.id).values.KAFKA_KEY, KEY);
  assert.ok(!('KAFKA_KEY' in projects.publicProjectVariableValues(p.id)), 'never given to Get Properties');
  assert.equal(projects.secretVariableReferences(p.id).gv.KAFKA_KEY, v.value, 'a key setting can name it like a Secret');
  assert.equal(projects.publicProjectVariableValues(p.id).KAFKA_CA, CA, 'a certificate is public');
});

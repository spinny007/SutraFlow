import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { testEnv, node, edge } from './helpers.js';

testEnv(23820);
const { boot } = await import('../server/src/index.js');
const { engine } = await import('../server/src/engine/engine.js');
const { q } = await import('../server/src/db.js');
const flows = await import('../server/src/flows.js');
const { setSutraTuning } = await import('../server/src/tuning.js');

let srv: any;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv?.stop(); });

const MB2 = 'x'.repeat(2 * 1024 * 1024);
/** Every byte this run left in the engine database, per table. */
const bytesOf = (runId: string) => {
  const sum = (sql: string) => Number(q.get<any>(sql, runId)?.n || 0);
  return {
    runs: sum('select coalesce(length(input), 0) + coalesce(length(state), 0) as n from runs where id = ?'),
    tasks: sum('select coalesce(sum(coalesce(length(input), 0) + coalesce(length(output), 0)), 0) as n from tasks where run_id = ?'),
    outputs: sum('select coalesce(sum(length(out)), 0) as n from run_outputs where run_id = ?'),
    payloads: sum('select coalesce(sum(length(data)), 0) as n from payloads where run_id = ?'),
  };
};

test('a large message is stored once: the run carries a reference, each step sees the whole value, the caller gets it whole', async () => {
  // Found with the 2.1.0 soak: a 2 MB message body was written about five times per run.
  const s = node('start', 'Start', { payload: '{}' });
  const look = node('jsonata', 'Look', { source: '{{input}}', expression: '{ "n": body.n, "length": $length(body.pad), "textLength": $length(bodyText) }' });
  const back = node('jsonata', 'Back', { source: '{{trigger}}', expression: 'body' });
  const doc = { name: 'Big message', nodes: [s, look, back], edges: [edge(s, look), edge(look, back)] };
  const body = { n: 7, pad: MB2 };
  let reply: any;
  const id = await engine.startRun({ doc, input: { body, bodyText: JSON.stringify(body) }, onReply: r => { reply = r; } });
  assert.equal(await engine.waitFor(id, 30000), 'done');
  const b = bytesOf(id);
  const run = b.runs + b.tasks + b.outputs;
  assert.ok(run < 64 * 1024, `run data holds references only (${run} bytes)`);
  assert.ok(b.payloads > 4 * 1024 * 1024 && b.payloads < 4.2 * 1024 * 1024, `the body and its text are stored once each (${b.payloads} bytes)`);
  const out = JSON.parse(q.get<any>(`select out from run_outputs where run_id = ? and name = 'Look'`, id).out);
  assert.deepEqual(out, { n: 7, length: MB2.length, textLength: JSON.stringify(body).length }, 'the step saw the whole values');
  for (let i = 0; i < 50 && !reply; i++) await new Promise(r => setTimeout(r, 20));
  assert.equal(reply?.body?.pad?.length, MB2.length, 'the caller got the whole body, not a reference');
});

test('small inputs are not touched, and an in-memory run keeps its stored parts when it is saved', async () => {
  const s = node('start', 'Start', { payload: '{}' }), look = node('jsonata', 'Look', { source: '{{input}}', expression: '{ "length": $length(body) }' });
  const small = await engine.startRun({ doc: { name: 'Small', nodes: [s, look], edges: [edge(s, look)] }, input: { body: 'hello' } });
  assert.equal(await engine.waitFor(small, 20000), 'done');
  assert.equal(Number(q.get<any>('select count(*) as n from payloads where run_id = ?', small).n), 0);
  assert.deepEqual(JSON.parse(q.get<any>('select input from runs where id = ?', small).input), { body: 'hello' });

  const f = flows.saveFlow(undefined, { name: 'Big in memory', nodes: [s, look], edges: [edge(s, look)] });
  flows.deploy(f.id); setSutraTuning(f.id, { execution: 'in memory' });
  const d = flows.deployedFlows().find(x => x.flowId === f.id)!;
  const status = await new Promise<string>((resolve, reject) => {
    engine.startRun({ doc: d.doc, flowId: f.id, version: d.version, source: 'api', input: { body: MB2 }, onFinish: st => resolve(st) }).catch(reject);
  });
  assert.equal(status, 'done');
  let saved: any;
  for (let i = 0; i < 100 && !saved; i++) { saved = q.get<any>('select id from runs where flow_id = ?', f.id); if (!saved) await new Promise(r => setTimeout(r, 30)); }
  assert.ok(saved, 'the in-memory run was saved');
  assert.equal(JSON.parse(q.get<any>(`select out from run_outputs where run_id = ? and name = 'Look'`, saved.id).out).length, MB2.length);
  assert.ok(bytesOf(saved.id).payloads >= MB2.length, 'its stored part came with it');
});

const runSample = async (name: string) => {
  const f = flows.listFlows(pid).find(x => x.name === name)!;
  const id = await engine.startRun({ doc: flows.getFlow(f.id)!.doc, flowId: f.id, projectId: pid, source: 'test' });
  await engine.waitFor(id, 60000);
  const r: any = q.get('select status, error from runs where id = ?', id);
  return { id, status: r.status, error: r.error, state: runState(id)!, doc: flows.getFlow(f.id)!.doc };
};

test('the Functions sample has a formula for every function of the library, by its group', () => {
  const missing = functionCatalog().filter(f => !FUNCTION_SAMPLE[f.group] || !(f.name in FUNCTION_SAMPLE[f.group])).map(f => `${f.group}/${f.name}`);
  assert.deepEqual(missing, [], 'add a formula to server/src/sample-functions.ts for each new function');
  const groups = [...new Set(functionCatalog().map(f => f.group))];
  assert.deepEqual(Object.keys(FUNCTION_SAMPLE).sort(), groups.sort(), 'one Map data step per group');
  for (const [g, fields] of Object.entries(FUNCTION_SAMPLE)) for (const [name, expr] of Object.entries(fields))
    assert.ok(expr.toLowerCase().includes(`${name.toLowerCase()}(`), `${g}/${name}: the formula uses the function it is named after`);
});

test('the Functions sample runs: each group is mapped, then logged, one group after another', async () => {
  addSamples(pid, ['functions']);
  const r = await runSample('Sample: Functions');
  assert.equal(r.status, 'done', r.error || '');
  const groups = Object.keys(FUNCTION_SAMPLE);
  const order = r.doc.nodes.filter(n => n.type !== 'start').map(n => n.name);
  assert.deepEqual(order, groups.flatMap(g => [`${g} functions`, `Log ${g}`]));
  const out = (g: string) => r.state.outputs[`${g} functions`];
  assert.equal(out('String')['substring-after'], 'example.com');
  assert.equal(out('String')['capitalize'], 'Asha Kumar');
  assert.equal(out('Conversion')['integer'], 42);
  assert.equal(out('Encode/Decode')['base64-to-string'], 'SutraFlow');
  assert.equal(out('Utility')['json-path'], 'MUG-02');
  assert.equal(out('Date/Time')['format-date'], '28 Oct 2026');
  assert.equal(out('Number')['sum'], 245.5);
  assert.equal(out('Logical')['coalesce'], '+91 98765 43210');
  assert.deepEqual(out('Sequence')['distinct'], ['new', 'vip']);
  assert.deepEqual(out('List')['sort'], ['A-1', 'A-2', 'A-3']);
  assert.deepEqual(out('List')['count-by'], { Asha: 2, Ravi: 1 });
  for (const g of groups) {
    const fields = Object.keys(FUNCTION_SAMPLE[g]);
    assert.deepEqual(Object.keys(out(g)).sort(), [...fields].sort(), `${g}: every field mapped`);
    assert.ok(r.state.logs.some(l => l.step === `Log ${g}` && l.msg.startsWith(`${g} functions: {`)), `${g} logged`);
  }
});

test('the counter sample: local variables as records 1 and 2 in one structure, read back with the run id, a counter kept across runs, every step described; Set Local Variable logs what it set', async () => {
  addSamples(pid, ['counter']);
  const first = await runSample('Sample: Counter, Wait and Sutra variables');
  assert.equal(first.status, 'done', first.error || '');
  assert.ok(first.doc.nodes.every(n => n.description), 'every step is described');
  const byName = (r: typeof first, n: string) => r.state.outputs[n];
  const all = byName(first, 'Read all variables');
  assert.equal(all.runId, first.id, 'the variables come with the id of their run');
  assert.deepEqual(Object.keys(all.variables).sort(), ['1', '2'], 'one structure of records by ID');
  assert.match(all.variables['1'].batch, /^batch-\d{4}$/);
  assert.ok(all.variables['1'].startedAt);
  assert.equal(all.variables['2'].orders, byName(first, 'Orders today').value);
  assert.ok(first.state.logs.some(l => l.step === 'Batch details' && l.msg === `1.batch = ${all.variables['1'].batch}`), 'Set Local Variable logs what it set');
  const second = await runSample('Sample: Counter, Wait and Sutra variables');
  assert.equal(byName(second, 'Orders today').value, byName(first, 'Orders today').value + 1, 'the counter grows across runs');
  const vars2 = byName(second, 'Read all variables').variables;
  assert.ok(second.state.logs.some(l => l.step === 'Log' && l.msg === `${vars2['1'].batch}: order ${vars2['2'].orders} today, counter ${vars2['2'].counter}`), 'the log line reads the records as {vars.1.batch}');
});

test('Set Local Variable: steps with one ID add to one record, another ID makes another, no ID keeps plain variables (Sutras before 2.1.3); Get Local Variables reads one ID', async () => {
  const s = { id: 's', type: 'start', name: 'Start', x: 0, y: 0, config: { payload: '{"orderId":"A-7"}' } };
  const a = { id: 'a', type: 'setVar', name: 'First', x: 0, y: 0, config: { id: '1', vars: [{ k: 'name', v: 'Jane Doe' }, { k: 'role', v: 'admin' }] } };
  const b = { id: 'b', type: 'setVar', name: 'More of 1', x: 0, y: 0, config: { id: '1', vars: [{ k: 'isActive', v: "={input.orderId} = 'A-7'" }] } };
  const c = { id: 'c', type: 'setVar', name: 'Second', x: 0, y: 0, config: { id: '{{input.orderId}}', vars: [{ k: 'who', v: 'jane.doe@example.com' }] } };
  const d = { id: 'd', type: 'setVar', name: 'Plain', x: 0, y: 0, config: { vars: [{ k: 'total', v: '42' }] } };
  const g = { id: 'g', type: 'getVar', name: 'Record 1', x: 0, y: 0, config: { what: 'one ID', name: '1' } };
  const e = (x: { id: string }, y: { id: string }) => ({ id: `${x.id}${y.id}`, from: x.id, port: 'out', to: y.id });
  const f = flows.saveFlow(undefined, { name: 'Records', nodes: [s, a, b, c, d, g], edges: [e(s, a), e(a, b), e(b, c), e(c, d), e(d, g)] } as any, pid);
  const id = await engine.startRun({ doc: flows.getFlow(f.id)!.doc, flowId: f.id, projectId: pid, source: 'test' });
  await engine.waitFor(id, 30000);
  const r: any = q.get('select status, error from runs where id = ?', id);
  assert.equal(r.status, 'done', r.error || '');
  const st = runState(id)!;
  assert.deepEqual(st.vars, { 1: { name: 'Jane Doe', role: 'admin', isActive: true }, 'A-7': { who: 'jane.doe@example.com' }, total: '42' });
  assert.deepEqual(st.outputs['Record 1'], { runId: id, name: '1', value: { name: 'Jane Doe', role: 'admin', isActive: true }, found: true });
});


test('variable designer catalog preserves plain declarations and record-ID paths without inventing dynamic record names', () => {
  const doc: any = {name:'Variables',variables:[{name:'test',type:'string',value:'1'},{name:'document',type:'json',value:'{"ok":true}'}],edges:[],nodes:[
    {type:'setVar',config:{id:'1',vars:[{k:'Name',v:'Jane'}]}},
    {type:'setVar',config:{id:'1',vars:[{k:'Pair',v:'XOXO'}]}},
    {type:'setVar',config:{id:'{{input.id}}',vars:[{k:'dynamic',v:'x'}]}},
  ]};
  const shape = localVariablesShape(doc), fields = shape.children!;
  assert.deepEqual(fields.map(n=>n.name),['test','document','1']);
  assert.deepEqual(fields.find(n=>n.name==='1')!.children!.map(n=>n.name),['Name','Pair']);
  assert.equal(fields.find(n=>n.name==='document')!.type,'object');
  assert.equal(fields.some(n=>n.name==='Name'||n.name==='dynamic'),false);
});

test('General variable config reads declarations, updates a plain name and reads record pairs; earlier Get results remain snapshots', async () => {
  const node = (id: string,type: string,config: any) => ({id,type,name:id,config,x:0,y:0});
  const nodes = [node('Start','start',{}),node('Initial','getVar',{what:'all variables'}),node('Update test','setVar',{id:'',vars:[{k:'test',v:'updated'}]}),node('Read test','getVar',{what:'one variable',name:'test'}),node('Set record','setVar',{id:'1',vars:[{k:'Name',v:'Name Plz'},{k:'Pair',v:'XOXO'}]}),node('Read record','getVar',{what:'one ID',name:'1'})];
  const doc: any = {name:'Local variable UI verification',variables:[{name:'test',type:'string',value:'1'}],nodes,edges:nodes.slice(1).map((n,i)=>({id:'v'+i,from:nodes[i].id,to:n.id,port:'out'}))};
  const id = await engine.startRun({doc,projectId:pid,source:'test'});await engine.waitFor(id,30000);
  assert.equal(q.get<any>('select status from runs where id=?',id)!.status,'done');
  const st=runState(id)!;
  assert.deepEqual(localVariablePairs(st.outputs.Initial,'all variables'),[{name:'test',value:'1'}]);
  assert.deepEqual(localVariablePairs(st.outputs['Read test'],'one variable'),[{name:'test',value:'updated'}]);
  assert.deepEqual(localVariablePairs(st.outputs['Read record'],'one ID'),[{name:'1.Name',value:'Name Plz'},{name:'1.Pair',value:'XOXO'}]);
  assert.equal(st.vars.test,'updated');
  assert.deepEqual(localVariablePairs({name:'missing',found:false,value:null},'one variable'),[]);
});


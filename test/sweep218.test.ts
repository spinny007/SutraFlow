test('packages: testing or opening a package for B needs Deploy on B', async () => {
  const pkg = { format: 'sutraflow-package', name: 'probe', version: '1.0.0', project: { name: 'Bravo', variables: [] }, sutras: [], schemas: [], resources: [] };
  assert.equal((await call(dev, 'POST', '/api/packages/test', { package: pkg })).statusCode, 403, 'the test would run in B with B\'s properties');
  assert.equal((await call(admin, 'POST', '/api/packages/test', { package: { ...pkg, project: { name: 'Bravo', variables: [] } }, project: 'Alpha' })).statusCode, 400, 'a target name beside the package is not accepted (the guard would check Alpha, the test would run in Bravo)');
  assert.equal((await call(dev, 'POST', '/api/packages/open', { package: pkg })).statusCode, 403, 'the plan would list B\'s contents');
  assert.equal((await call(dev, 'POST', '/api/packages/open', { package: { ...pkg, project: { name: 'Alpha', variables: [] } }, project: 'Bravo' })).statusCode, 403, 'naming B as the target');
});

test('Admin Console reads show the caller\'s projects only: memory tables, conversations, alerts', async () => {
  const mem = (await call(dev, 'GET', '/api/console/memory')).json();
  assert.ok(!mem.some((t: any) => t.name === 'B customers'), 'B\'s memory table is not listed');
  assert.ok((await call(admin, 'GET', '/api/console/memory')).json().some((t: any) => t.name === 'B customers'));
  const conv = (await call(dev, 'GET', '/api/console/conversations')).json();
  assert.ok(!conv.some((c: any) => c.agent === 'B agent'));
  assert.ok((await call(admin, 'GET', '/api/console/conversations')).json().some((c: any) => c.agent === 'B agent'));
  const list = await call(dev, 'GET', '/api/alerts');
  assert.equal(list.statusCode, 200, list.body);
  assert.deepEqual(list.json(), [], 'neither B\'s alert nor the server-wide one');
  assert.deepEqual((await call(dev, 'GET', '/api/alerts/rules')).json(), []);
  assert.equal((await call(dev, 'GET', '/api/alerts/summary')).json().open, 0);
  assert.equal((await call(admin, 'GET', '/api/alerts')).json().length, 2);
  assert.equal((await call(admin, 'GET', '/api/alerts/summary')).json().open, 2);
  // Granted B, the developer sees B's alert but still not the server-wide one.
  await call(admin, 'PUT', '/api/access/users/dev', { grants: [{ role: 'developer', project: a }, { role: 'developer', project: b }] });
  const withB = (await call(dev, 'GET', '/api/alerts')).json();
  assert.deepEqual(withB.map((x: any) => x.ruleName), ['B failures']);
  const server = (await call(dev, 'GET', '/api/server')).json();
  assert.deepEqual(server.schedulerErrors, [], 'timer errors are for Server settings');
});

test('WSDL describe: needs a project, reads only its WSDLs, its or shared connections, and http(s) addresses', async () => {
  const cap = await captureServer(() => ({ headers: { 'content-type': 'text/xml' }, body: WSDL }));
  try {
    assert.equal((await call(dev, 'POST', '/api/soap/describe', { wsdlRef: bWsdl })).statusCode, 400, 'no project');
    assert.equal((await call(dev, 'POST', '/api/soap/describe', { projectId: b, wsdlRef: bWsdl })).statusCode, 403, 'B itself');
    const ref = await call(dev, 'POST', '/api/soap/describe', { projectId: a, wsdlRef: bWsdl });
    assert.equal(ref.statusCode, 400); assert.match(ref.json().error, /WSDL of this project/);
    const file = await call(dev, 'POST', '/api/soap/describe', { projectId: a, wsdlUrl: schemas.wsdlPath(bWsdl) });
    assert.equal(file.statusCode, 400, 'a file on the server is not an address'); assert.match(file.json().error, /http:\/\/ or https:\/\//);
    const auth = await call(dev, 'POST', '/api/soap/describe', { projectId: a, wsdlUrl: `${cap.url}/b.wsdl`, auth: bAuth });
    assert.equal(auth.statusCode, 400); assert.match(auth.json().error, /Outbound security: choose one of this project/);
    assert.equal(cap.seen.length, 0, 'B\'s token was never sent');
    assert.ok(cap.seen.every(s => !JSON.stringify(s.headers).includes(B_TOKEN)));
    // Calling another project's published web service stays allowed: its WSDL is loaded by its address.
    const published = await call(dev, 'POST', '/api/soap/describe', { projectId: a, wsdlUrl: `${cap.url}/b-service?wsdl` });
    assert.equal(published.statusCode, 200, published.body);
    assert.equal(cap.seen.length, 1);
  } finally { await cap.close(); }
  // The owner still describes B's own WSDL.
  const own = await call(admin, 'POST', '/api/soap/describe', { projectId: b, wsdlRef: bWsdl });
  assert.equal(own.statusCode, 200, own.body);
});


import { test } from 'node:test';
import assert from 'node:assert/strict';
import dns from 'node:dns';
import { testEnv, engineSecrets } from './helpers.js';

/**
 * Purpose: the studio MCP server against real databases (2.1.8, opt-in). A person signed in to the studio makes
 * their own API token; an AI assistant using it finds the project's database connection, builds a Sutra with a
 * bound query, and its test run passes on the remote PostgreSQL and MySQL. The password never comes back.
 * Uses the same environment as remotedb.test.ts (SUTRA_REMOTE_DB_TEST=1 and SUTRA_TEST_REMOTE_* values).
 */
const enabled = process.env.SUTRA_REMOTE_DB_TEST === '1';
test('a personal token builds and tests a database Sutra over MCP on remote PostgreSQL and MySQL', { skip: enabled ? false : 'set SUTRA_REMOTE_DB_TEST=1 and remote database environment variables' }, async t => {
  testEnv(24260); dns.setDefaultResultOrder('ipv4first');
  const { boot } = await import('../server/src/index.js');
  const { saveResource } = await import('../server/src/resources.js');
  const srv = await boot({ listenAdmin: false, gateway: false });
  const setEngineSecret = await engineSecrets();
  const req = (method: string, url: string, o: { cookie?: string; body?: any } = {}) => srv.admin.inject({ method: method as any, url, ...(o.body !== undefined ? { payload: o.body } : {}), headers: { 'x-sutra': '1', ...(o.cookie ? { cookie: o.cookie } : {}) } });
  const cookieOf = (r: any) => String(r.headers['set-cookie'] || '').split(';')[0];
  try {
    const admin = cookieOf(await req('POST', '/api/auth/setup', { body: { username: 'root', password: 'first-admin-pass-1' } }));
    const pid = (await req('POST', '/api/projects', { cookie: admin, body: { name: 'Remote via MCP' } })).json().id;
    await req('POST', '/api/access/users', { cookie: admin, body: { username: 'dana', password: 'Temporary-pass-93', mustChange: false, grants: [{ role: 'developer', project: pid }] } });
    const dana = cookieOf(await req('POST', '/api/auth/login', { body: { username: 'dana', password: 'Temporary-pass-93' } }));
    const { token } = (await req('POST', '/api/access/me/tokens', { cookie: dana, body: { name: 'assistant', expiresDays: 30 } })).json();
    assert.match(token, /^sut_/);
    const answers: string[] = [];
    const tool = async (name: string, args: any) => {
      const r = await srv.admin.inject({ method: 'POST', url: '/mcp/studio', payload: { jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } }, headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' } });
      answers.push(r.body);
      const res = r.json().result;
      assert.ok(!res.isError, res.content?.[0]?.text);
      return res.structuredContent ?? JSON.parse(res.content[0].text);
    };

    const configs: { driver: string; host: string; port: number; database: string; user: string; password: string }[] = [];
    if (process.env.SUTRA_TEST_REMOTE_PG_URL) { const u = new URL(process.env.SUTRA_TEST_REMOTE_PG_URL); configs.push({ driver: 'postgres', host: u.hostname, port: Number(u.port) || 5432, database: u.pathname.slice(1), user: decodeURIComponent(u.username), password: decodeURIComponent(u.password) }); }
    if (process.env.SUTRA_TEST_REMOTE_MYSQL_HOST) configs.push({ driver: 'mysql', host: process.env.SUTRA_TEST_REMOTE_MYSQL_HOST, port: Number(process.env.SUTRA_TEST_REMOTE_MYSQL_PORT) || 3306, database: process.env.SUTRA_TEST_REMOTE_MYSQL_DATABASE!, user: process.env.SUTRA_TEST_REMOTE_MYSQL_USER!, password: process.env.SUTRA_TEST_REMOTE_MYSQL_PASSWORD! });
    assert.ok(configs.length, 'Provide at least one remote endpoint');

    for (const c of configs) await t.test(c.driver, async () => {
      const secret = `MCP_${c.driver.toUpperCase()}_PASSWORD`;
      setEngineSecret(secret, c.password);
      saveResource({ kind: 'database', name: `Remote ${c.driver}`, project_id: pid, config: { driver: c.driver, host: c.host, port: String(c.port), database: c.database, user: c.user, passwordSecret: secret, ssl: true, verifyTls: true, poolMax: 1 } });
      // What the assistant does: find the connection, read the query activity, build, test.
      const conns = await tool('list_connections', { projectId: pid, kind: 'database' });
      const conn = conns.find((x: any) => x.name === `Remote ${c.driver}`);
      assert.ok(conn, JSON.stringify(conns));
      const act = await tool('list_activities', { type: 'dbQuery' });
      assert.ok(act.fields.some((f: any) => f.key === 'sql'));
      const sql = c.driver === 'postgres' ? 'select :value::text as value' : 'select :value as value';
      const made = await tool('create_sutra', { projectId: pid, doc: {
        name: `Lookup on ${c.driver}`,
        nodes: [
          { id: 'start', type: 'start', name: 'Start', config: { payload: JSON.stringify({ value: "A-100' OR '1'='1" }) } },
          { id: 'query', type: 'dbQuery', name: 'Query', config: { connection: conn.id, sql, params: [{ k: 'value', v: '{{input.value}}' }] } },
          { id: 'note', type: 'log', name: 'Note', config: { message: 'Got {{input.rows}}' } },
        ],
        edges: [{ from: 'Start', to: 'Query' }, { from: 'Query', to: 'Note' }],
      } });
      assert.deepEqual(made.check.errors, []);
      const run = await tool('test_sutra', { sutraId: made.sutraId, waitSeconds: 60 });
      assert.equal(run.passed, true, JSON.stringify(run).slice(0, 1500));
      const q = run.steps.find((s: any) => s.step === 'Query');
      assert.equal(q.output.rows[0].value, "A-100' OR '1'='1", 'bound, not spliced');
      for (const body of answers) assert.ok(!body.includes(c.password), 'the password never comes back');
    });
  } finally { await srv.stop(); }
});

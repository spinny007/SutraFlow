after(async () => { await srv.stop(); fake.close(); });

const run = async (doc: any, input: any, o: { flowId?: string; projectId?: string } = {}) => {
  const id = await engine.startRun({ doc, projectId: o.projectId || pid, flowId: o.flowId, input });
  await engine.waitFor(id, 30000);
  const r: any = q.get('select status, error from runs where id = ?', id);
  const st = runState(id)!;
  return { id, status: r.status, error: r.error, out: st.outputs, logs: (st.logs || []).map((l: any) => `${l.level} ${l.msg}`).join('\n') };
};
/** Start → guard → a log on each port. */
const guardDoc = (cfg: Record<string, any>) => {
  const s = node('start', 'Message', { payload: '{}' });
  const g = node('aiGuard', 'Guard', { text: '{{input.text}}', ...cfg });
  const p = node('log', 'Pass', { message: 'PASS {{input.text}}' });
  const b = node('log', 'Blocked', { message: 'BLOCKED {{input.reason}}' });
  const c = node('log', 'Cached', { message: 'CACHED {{input.answer}}' });
  return { name: 'Guard', nodes: [s, g, p, b, c], edges: [edge(s, g), edge(g, p, 'pass'), edge(g, b, 'blocked'), edge(g, c, 'cached')] };
};
const rows = (v: string) => guard.MODERATION.map(k => ({ k, v }));

test('moderation: a category at its threshold blocks; a warn-only category lets the text through with a warning', async () => {
  assert.deepEqual(guard.moderationScores('Thanks, the tea arrived.'), { hate: 0, harassment: 0, 'self-harm': 0, sexual: 0, violence: 0, 'illegal activity': 0 });
  const rude = 'You are an idiot. Shut up and send my order.';
  assert.equal(guard.moderationScores(rude).harassment, 0.75, 'two phrases: 0.75');

  let r = await run(guardDoc({ checks: ['moderation'], moderation: rows('0.5') }), { text: rude });
  assert.equal(r.status, 'done', r.error);
  assert.match(r.logs, /BLOCKED Moderation: harassment \(0\.75, threshold 0\.5\)/);
  assert.equal(r.out.Guard.moderation.harassment, 0.75);

  // Above the score: not blocked.
  r = await run(guardDoc({ checks: ['moderation'], moderation: [{ k: 'harassment', v: '0.8' }] }), { text: rude });
  assert.match(r.logs, /PASS You are an idiot/);

  // Warn only.
  r = await run(guardDoc({ checks: ['moderation'], moderation: rows('0.5'), moderationWarn: ['harassment'] }), { text: rude });
  assert.match(r.logs, /PASS You are an idiot/);
  assert.deepEqual(r.out.Guard.warnings, ['Moderation: harassment (0.75, threshold 0.5)']);
  assert.match(r.logs, /^warn Guard: Moderation: harassment .*warn only/m);

  // The model's score counts when it is higher than the rules'.
  opinion = { injection: false, topic: '', categories: { violence: 0.9 } };
  r = await run(guardDoc({ checks: ['moderation'], moderation: rows('0.6'), aiCheck: prov }), { text: 'They will regret this tomorrow.' });
  opinion = { injection: false, topic: '' };
  assert.match(r.logs, /BLOCKED Moderation: violence \(0\.9, threshold 0\.6\)/);
});

test('language: detected, and translated with the guard\'s model to the set language', async () => {
  assert.equal(guard.detectLanguage('Where is my order? Please help.').language, 'en');
  assert.equal(guard.detectLanguage('मेरा ऑर्डर कहाँ है').language, 'hi');
  assert.equal(guard.detectLanguage('¿Dónde está mi pedido? Gracias por la ayuda').language, 'es');
  assert.equal(guard.detectLanguage('12345 !!!').language, 'und');

  let r = await run(guardDoc({ checks: ['language'] }), { text: '¿Dónde está mi pedido? Gracias por la ayuda' });
  assert.equal(r.out.Guard.language, 'es');
  assert.equal(r.out.Guard.translatedFrom, undefined, 'no translation without Translate to');

  calls.length = 0;
  r = await run(guardDoc({ checks: ['language'], translateTo: 'en', aiCheck: prov }), { text: '¿Dónde está mi pedido? Gracias por la ayuda' });
  assert.equal(r.status, 'done', r.error);
  assert.match(r.logs, /PASS Where is my order\? Thank you for the help\./);
  assert.equal(r.out.Guard.translatedFrom, 'es');
  assert.equal(r.out.Guard.original, '¿Dónde está mi pedido? Gracias por la ayuda');
  assert.ok(calls.some(c => /ISO 639-1 code "en"/.test(c.system)), 'translated by the guard\'s provider');

  // Already in the set language: no translation call.
  calls.length = 0;
  await run(guardDoc({ checks: ['language'], translateTo: 'en', aiCheck: prov }), { text: 'Where is my order? Please help.' });
  assert.ok(!calls.some(c => /^Translate/.test(c.system)));

  // Settings the designer flags.
  assert.match(guard.guardDesignErrors({ checks: ['language'], translateTo: 'en' }).join(), /Translate to needs an AI provider/);
  assert.match(guard.guardDesignErrors({ cache: 'store the answer', cacheQuestion: '' }).join(), /Store the answer needs the question/);
  assert.deepEqual(guard.guardDesignErrors({ checks: ['language'], translateTo: 'en', aiCheck: prov, cache: 'look up the question' }), []);
});

test('answer cache: per Sutra and per person; never given to another person or an unidentified caller', async () => {
  const flowId = flows.saveFlow(undefined, { name: 'Order desk', nodes: [], edges: [] }, pid).id;
  const store = (cacheFor = 'each person') => guardDoc({ checks: [], text: '{{input.answer}}', cache: 'store the answer', cacheQuestion: '{{input.text}}', cacheFor, cachePerson: '{{input.who}}', cacheMinutes: 30 });
  const look = (cacheFor = 'each person') => guardDoc({ checks: [], cache: 'look up the question', cacheFor, cachePerson: '{{input.who}}' });
  const meera = { subject: 'meera', method: 'token' }, ravi = { subject: 'ravi', method: 'token' };

  let r = await run(look(), { text: 'Where is my order?', who: meera }, { flowId });
  assert.match(r.logs, /PASS/);
  assert.equal(r.out.Guard.cache, 'miss');

  r = await run(store(), { text: 'Where is my order?', answer: 'Your order A-1001 to 12 MG Road ships today.', who: meera }, { flowId });
  assert.equal(r.out.Guard.cache, 'stored');
  assert.ok(!JSON.stringify(q.all('select * from guard_cache')).includes('meera'), 'the person is kept as a hash');

  // The same person, the same question (spacing and case do not matter): the cached port.
  r = await run(look(), { text: '  where is MY order? ', who: meera }, { flowId });
  assert.match(r.logs, /CACHED Your order A-1001 to 12 MG Road ships today\./);
  assert.equal(r.out.Guard.cache, 'hit');

  // A renewed token (new iat, exp, jti, scopes) is the same person; another issuer or method is not.
  const jwt = (claims: Record<string, any>, method = 'jwt') => ({ subject: 'asha', method, claims: { sub: 'asha', iss: 'https://login.example.test', ...claims }, scopes: claims.scp ? [claims.scp] : [] });
  await run(store(), { text: 'My balance?', answer: 'Asha has 1200 points.', who: jwt({ iat: 1, exp: 100, jti: 'a', scp: 'read' }) }, { flowId });
  r = await run(look(), { text: 'My balance?', who: jwt({ iat: 500, exp: 900, jti: 'b', scp: 'read write' }) }, { flowId });
  assert.equal(r.out.Guard.cache, 'hit', 'a renewed token keeps the cache');
  for (const other of [jwt({ iss: 'https://other-issuer.example.test' }), jwt({ tid: 'tenant-2' }), jwt({}, 'oauth2Introspection')]) {
    r = await run(look(), { text: 'My balance?', who: other }, { flowId });
    assert.equal(r.out.Guard.cache, 'miss', JSON.stringify(other));
  }
  assert.deepEqual(guard.cacheIdentity(jwt({ iat: 1, exp: 2, jti: 'x' })), guard.cacheIdentity(jwt({ iat: 3, exp: 4, jti: 'y' })));

  // Another person: never.
  r = await run(look(), { text: 'Where is my order?', who: ravi }, { flowId });
  assert.equal(r.out.Guard.cache, 'miss');
  assert.ok(!r.logs.includes('MG Road'));

  // An anonymous or unknown caller: no cache at all, neither looked up nor stored.
  for (const who of [{ subject: 'anonymous' }, '', undefined]) {
    r = await run(look(), { text: 'Where is my order?', who }, { flowId });
    assert.match(r.out.Guard.cache, /^off: the caller is not identified/);
    assert.ok(!r.logs.includes('CACHED'));
  }
  const before = q.get<any>('select count(*) n from guard_cache').n;
  await run(store(), { text: 'Opening hours?', answer: 'Nine to six.', who: { subject: 'anonymous' } }, { flowId });
  assert.equal(q.get<any>('select count(*) n from guard_cache').n, before, 'nothing stored for an anonymous caller');

  // Another Sutra does not see this Sutra's answers.
  const other = flows.saveFlow(undefined, { name: 'Other desk', nodes: [], edges: [] }, pid).id;
  r = await run(look(), { text: 'Where is my order?', who: meera }, { flowId: other });
  assert.equal(r.out.Guard.cache, 'miss');

  // Everyone: one answer for all callers, anonymous ones too.
  await run(store('everyone'), { text: 'Opening hours?', answer: 'Nine to six.', who: '' }, { flowId });
  r = await run(look('everyone'), { text: 'opening hours?', who: { subject: 'anonymous' } }, { flowId });
  assert.match(r.logs, /CACHED Nine to six\./);

  // Expired answers are not given.
  q.run('update guard_cache set expires_at = ?', Date.now() - 1);
  r = await run(look(), { text: 'Where is my order?', who: meera }, { flowId });
  assert.equal(r.out.Guard.cache, 'miss');

  // A run without a saved Sutra keeps nothing.
  r = await run(look(), { text: 'Where is my order?', who: meera });
  assert.match(r.out.Guard.cache, /^off: the run has no saved Sutra/);
});

test('a project can mask personal data in its log and run history; the steps still pass the real data on', async () => {
  const masked = projects.saveProject({ name: 'Masked', config: { variables: [], logging: { ...projects.defaultLogging, hidePersonalData: true } } }).id;
  const plain = projects.saveProject({ name: 'Plain', config: { variables: [] } }).id;
  const s = node('start', 'Order', { payload: '{}' });
  const l = node('log', 'Note', { message: 'Customer {{input.email}} phone {{input.phone}}' });
  const m = node('log', 'Copy', { message: 'Next step got {{input.email}}' });
  const doc = { name: 'Contact', nodes: [s, l, m], edges: [edge(s, l), edge(l, m)] };
  const input = { email: 'meera@example.com', phone: '+91 98765 43210' };

  const get = async (id: string) => (await srv.admin.inject({ method: 'GET', url: `/api/runs/${id}`, headers: { 'x-sutra': '1', cookie } })).json();

  const r = await run(doc, input, { projectId: masked });
  assert.equal(r.status, 'done', r.error);
  // What the steps passed on is the real data.
  assert.equal(r.out.Note.email, 'meera@example.com');
  assert.match(JSON.stringify(r.out.Copy), /meera@example\.com/);
  // Run history shows it masked: step input and output, outputs, log lines.
  const d = await get(r.id);
  const shown = JSON.stringify({ tasks: d.tasks, outputs: d.outputs, logs: d.logs, vars: d.vars });
  assert.ok(!shown.includes('meera@example.com') && !shown.includes('98765'), shown.slice(0, 400));
  assert.match(shown, /\[EMAIL\]/);
  assert.match(shown, /\[PHONE\]/);
  assert.equal(d.id, r.id, 'ids are not touched');
  assert.equal(d.projectId, masked);
  // The project log file too.
  const lines = tailLog(masked, 50).lines.join('\n');
  assert.match(lines, /Customer \[EMAIL\] phone \[PHONE\]/);
  assert.ok(!lines.includes('meera@example.com'));

  // A project without the option shows the data as it is.
  const p = await run(doc, input, { projectId: plain });
  assert.match(JSON.stringify((await get(p.id)).logs), /meera@example\.com/);
  assert.match(tailLog(plain, 50).lines.join('\n'), /meera@example\.com/);
});

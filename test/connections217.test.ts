test('Tidy lays steps out in columns by order, changes positions only, and removes crossings', () => {
  // Crossed on purpose: lane b drawn above lane a although it comes from a lower step.
  const doc: FlowDoc = {
    name: 'Messy',
    nodes: [N('t', 500, 500), N('p', 0, 0), N('q', 0, 300), N('a', 900, 300), N('b', 900, 0), N('m', 40, 900), N('h', 10, 10)],
    edges: [E('t', 'p'), E('t', 'q'), E('p', 'a'), E('q', 'b'), E('a', 'm'), E('b', 'm'), E('m', 't', 'out', { label: 'again' })],
  };
  doc.nodes.find(n => n.id === 'h')!.type = 'catch';
  const tidy = tidyLayout(doc, () => 80);
  const at = (id: string) => tidy.nodes.find(n => n.id === id)!;
  assert.deepEqual(tidy.edges, doc.edges, 'connections untouched');
  assert.deepEqual(tidy.nodes.map(n => ({ ...n, x: 0, y: 0 })), doc.nodes.map(n => ({ ...n, x: 0, y: 0 })), 'only positions change');
  assert.ok(at('t').x < at('p').x && at('p').x < at('a').x && at('a').x < at('m').x, 'left to right by order, the loop back ignored');
  assert.equal(at('p').x, at('q').x);
  assert.equal(crossings(tidy), 0, 'no crossing lines after Tidy');
  const ys = tidy.nodes.filter(n => n.x === at('p').x).map(n => n.y).sort((x, y) => x - y);
  assert.ok(ys[1] - ys[0] >= 80, 'steps in a column do not overlap');
  assert.deepEqual(tidyLayout({ name: 'Empty', nodes: [], edges: [] }), { name: 'Empty', nodes: [], edges: [] });
});

test('every bundled sample leaves room for its lines: no steps on top of each other, a gap between columns', async () => {
  const { saveProject } = await import('../server/src/projects.js');
  const { addSamples, spreadColumns } = await import('../server/src/samples.js');
  const { getFlow } = await import('../server/src/flows.js');
  assert.deepEqual(spreadColumns({ nodes: [N('a', 60, 5), N('b', 300, 5), N('c', 540, 5)] }).nodes.map(n => n.x), [60, 400, 740], 'columns 240 apart become 340 apart, as Tidy places them');
  // The step heights of the designer: 70 px to the first port, 24 px between ports (web/src/Designer.tsx).
  const height = (n: any) => {
    const act: any = engine.activity(n.type);
    const own: string[] = typeof act?.ports === 'function' ? act.ports(n.config || {}) : act?.ports || [];
    const ports = act?.noErrorPort || act?.trigger ? own : [...own, 'error'];
    return ports.length ? 88 + (ports.length - 1) * 24 : 62;
  };
  const p = saveProject({ name: 'Sample layout', config: { variables: [] } });
  const problems: string[] = [];
  for (const s of addSamples(p.id)) {
    const doc = getFlow(s.id)!.doc;
    for (const a of doc.nodes) for (const b of doc.nodes) {
      if (a === b || a.y > b.y || (a.y === b.y && a.id > b.id)) continue;
      if (Math.abs(a.x - b.x) < 250 + 10 && b.y - a.y < height(a) + 12) problems.push(`${doc.name}: ${a.name} and ${b.name} overlap`);
    }
    for (const e of doc.edges) {
      const a = doc.nodes.find(n => n.id === e.from)!, b = doc.nodes.find(n => n.id === e.to)!;
      if (b.x > a.x && b.x - a.x < 250 + 60) problems.push(`${doc.name}: the line ${a.name} → ${b.name} has ${b.x - a.x - 250} px between the steps`);
    }
  }
  assert.deepEqual(problems, []);
});

const N = (id: string, x = 0, y = 0) => ({ id, type: 'mapper', name: `Step ${id}`, x, y, config: {} });
const E = (from: string, to: string, port = 'out', extra: Record<string, any> = {}) => ({ id: `${from}>${to}:${port}`, from, to, port, ...extra });

/** n sources that all go into one step "m", each fed by the trigger. */
function fan(n: number): FlowDoc {
  const sources = Array.from({ length: n }, (_, i) => `s${i}`);
  return {
    name: 'Fan',
    nodes: [N('t'), ...sources.map((id, i) => N(id, 300, i * 120)), N('m', 600)],
    edges: [...sources.map(id => E('t', id)), ...sources.map(id => E(id, 'm'))],
  };
}

test('automatic colours: only where lines meet, distinct for 2 to 8 lines, by source step', () => {
  for (let n = 2; n <= 8; n++) {
    const doc = fan(n);
    const auto = autoColours(doc);
    const into = doc.edges.filter(e => e.to === 'm').map(e => auto.get(e.id));
    assert.equal(into.length, n);
    assert.ok(into.every(Boolean), 'every line into the meeting step has a colour');
    assert.equal(new Set(into).size, n, `${n} lines into one step have ${n} different colours`);
    assert.ok(doc.edges.filter(e => e.to !== 'm').every(e => !auto.has(e.id)), 'lines into a step that receives one line keep the normal colour');
  }
  // More sources than colours: every colour is used before any repeats, and none more than needed.
  for (let n = 9; n <= 16; n++) {
    const doc = fan(n);
    const auto = autoColours(doc);
    const uses = new Map<string, number>();
    for (const e of doc.edges.filter(x => x.to === 'm')) uses.set(auto.get(e.id)!, (uses.get(auto.get(e.id)!) || 0) + 1);
    assert.equal(uses.size, 8, `${n} lines use all 8 colours`);
    assert.ok(Math.max(...uses.values()) <= Math.ceil(n / 8), `${n} lines: no colour used more than ${Math.ceil(n / 8)} times`);
  }
  // All lines leaving one step share its colour (it meets others at two steps).
  const doc: FlowDoc = { name: 'Two meetings', nodes: [N('a'), N('b'), N('c'), N('m1'), N('m2')], edges: [E('a', 'm1'), E('b', 'm1'), E('a', 'm2'), E('c', 'm2')] };
  const auto = autoColours(doc);
  assert.equal(auto.get('a>m1:out'), auto.get('a>m2:out'), 'the colour follows the source step');
  assert.notEqual(auto.get('a>m1:out'), auto.get('b>m1:out'));
  assert.notEqual(auto.get('a>m2:out'), auto.get('c>m2:out'));
});

test('automatic colours do not change when steps move, and two lines from one step are not a meeting', () => {
  const doc = fan(4);
  const before = [...autoColours(doc)];
  const moved = { ...doc, nodes: doc.nodes.map((n, i) => ({ ...n, x: n.x + 500 - i * 37, y: n.y * 3 + 11 })) };
  assert.deepEqual([...autoColours(moved)], before);
  const same: FlowDoc = { name: 'Same source', nodes: [N('a'), N('m')], edges: [E('a', 'm'), E('a', 'm', 'empty')] };
  assert.equal(autoColours(same).size, 0, 'lines from the same step only: nothing to tell apart');
});

test('colours chosen by hand win, error lines stay red, and the colour survives save, export and import', async () => {
  const doc = fan(2);
  doc.edges.push(E('s0', 'm', 'error'), E('s1', 'm', 'out', { color: 'pink' }));
  doc.edges = doc.edges.filter(e => e.id !== 's1>m:out' || e.color);
  const auto = autoColours(doc);
  assert.equal(lineColour(doc.edges.find(e => e.color === 'pink')!, auto), 'pink');
  assert.equal(lineColour(doc.edges.find(e => e.port === 'error')!, auto), undefined, 'an error line is never coloured');
  assert.ok(![...auto.keys()].some(id => id.endsWith(':error')));
  const { normalizeDoc } = await import('../server/src/flows.js');
  const saved = normalizeDoc(JSON.parse(JSON.stringify(doc)));
  assert.equal(saved.edges.find((e: any) => e.from === 's1' && e.to === 'm')?.color, 'pink', 'saved and exported with the Sutra');
  const imported = normalizeDoc(JSON.parse(JSON.stringify(saved)));
  assert.equal(imported.edges.find((e: any) => e.from === 's1' && e.to === 'm')?.color, 'pink', 'kept on import');
  const unknown = normalizeDoc({ ...doc, edges: [{ ...doc.edges[0], color: 'red; background:url(x)' }] });
  assert.equal(unknown.edges[0].color, undefined, 'only palette names are kept');
  const { LINE_COLOUR_KEYS } = await import('../server/src/flows.js');
  assert.deepEqual([...LINE_COLOUR_KEYS].sort(), LINE_COLOURS.map(c => c.key).sort(), 'server and designer know the same names');
});

/** Hue difference of two #RRGGBB colours in degrees (0 to 180). */
function hueGap(a: string, b: string) {
  const hue = (hex: string) => {
    const [r, g, bl] = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255);
    const max = Math.max(r, g, bl), min = Math.min(r, g, bl), d = max - min;
    if (!d) return 0;
    const h = max === r ? ((g - bl) / d) % 6 : max === g ? (bl - r) / d + 2 : (r - g) / d + 4;
    return (h * 60 + 360) % 360;
  };
  const gap = Math.abs(hue(a) - hue(b)) % 360;
  return gap > 180 ? 360 - gap : gap;
}

/** The custom properties of a CSS block whose selector starts with `selector`. */
function cssVars(css: string, selector: string) {
  const at = css.indexOf(selector);
  const block = css.slice(css.indexOf('{', at) + 1, css.indexOf('}', at));
  return Object.fromEntries([...block.matchAll(/--([\w-]+):\s*(#[0-9A-Fa-f]{6})/g)].map(m => [m[1], m[2]]));
}

test('the palette has 3:1 contrast with the canvas in both themes, and the stylesheet uses the same values', () => {
  const css = fs.readFileSync('web/src/styles.css', 'utf8');
  const light = cssVars(css, ':root {'), dark = cssVars(css, ':root[data-theme="dark"]');
  const darkAuto = cssVars(css, ':root:not([data-theme="light"])');
  for (const c of LINE_COLOURS) {
    assert.equal(light[`lc-${c.key}`], c.light, `light ${c.key} in the stylesheet`);
    assert.equal(dark[`lc-${c.key}`], c.dark, `dark ${c.key} in the stylesheet`);
    assert.equal(darkAuto[`lc-${c.key}`], c.dark, `dark (system) ${c.key} in the stylesheet`);
    assert.ok(contrast(c.light, light.paper) >= 3, `${c.key} on the light canvas: ${contrast(c.light, light.paper).toFixed(2)}`);
    assert.ok(contrast(c.dark, dark.paper) >= 3, `${c.key} on the dark canvas: ${contrast(c.dark, dark.paper).toFixed(2)}`);
    for (const [value, err] of [[c.light, light.err], [c.dark, dark.err]]) assert.ok(hueGap(value, err) >= 25, `${c.key} is far enough in hue from the error red (${hueGap(value, err).toFixed(0)}°)`);
  }
});

test('highlighting: a step lights its own lines; Path lights everything before and after it, across a join', () => {
  const doc: FlowDoc = { name: 'Path', nodes: ['t', 'a', 'b', 'm', 'z', 'x'].map(id => N(id)), edges: [E('t', 'a'), E('t', 'b'), E('a', 'm'), E('b', 'm'), E('m', 'z'), E('t', 'x')] };
  const own = highlightOf(doc, 'a');
  assert.deepEqual([...own.nodes].sort(), ['a', 'm', 't']);
  assert.deepEqual([...own.edges].sort(), ['a>m:out', 't>a:out']);
  const path = highlightOf(doc, 'm', true);
  assert.deepEqual([...path.nodes].sort(), ['a', 'b', 'm', 't', 'z'], 'both lanes of the join and the step after it');
  assert.ok(!path.nodes.has('x'), 'a step in another lane is dimmed');
  assert.ok(path.edges.has('b>m:out') && path.edges.has('m>z:out') && !path.edges.has('t>x:out'));
});


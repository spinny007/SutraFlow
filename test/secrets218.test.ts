test('a step: {{secret.NAME}} works only for names behind A\'s or the engine\'s Secret properties', async () => {
  const theirs = await run(a, node('log', 'Leak', { message: `x {{secret.${bRef}}}` }));
  assert.equal(theirs.status, 'failed');
  assert.match(theirs.error, /not behind a Secret property of this project/);
  const raw = await run(a, node('log', 'Raw', { message: 'x {{secret.RAW_VAULT_KEY}}' }));
  assert.equal(raw.status, 'failed');
  const shared = await run(a, node('mapper', 'Shared', { map: [{ k: 'v', v: '{{secret.ENGINE_KEY_STORE}}' }] }));
  assert.equal(shared.status, 'done', shared.error);
  assert.equal(shared.out?.v, '••••••', 'readable, and masked in history');
});

test('the reader itself: in a project\'s work only its and the engine\'s names; outside, server-level reads still work', () => {
  assert.throws(() => inProject(a, () => getSecret(bRef)), /not behind a Secret property/);
  assert.throws(() => inProject(a, () => requireSecret('RAW_VAULT_KEY', 'API key')), /^Error: API key: /);
  assert.throws(() => inProject(null, () => getSecret(bRef)), /not behind a Secret property/, 'work of no project: engine properties only');
  assert.equal(inProject(null, () => getSecret('ENGINE_KEY_STORE')), ENGINE_SECRET);
  assert.equal(inProject(b, () => getSecret(bRef)), B_SECRET, 'B still reads its own');
  assert.equal(getSecret('RAW_VAULT_KEY'), RAW_SECRET, 'outside project work (sign-in, server settings) nothing changes');
  assert.equal(readSecretUnscoped(bRef), B_SECRET);
});

test('upgrade check: a connection or Sutra naming a stored secret directly is listed for administrators only', async () => {
  const { saveResource } = await import('../server/src/resources.js');
  const flows = await import('../server/src/flows.js');
  const conn = saveResource({ kind: 'smtp', name: 'Old mail', project_id: a, config: { host: '127.0.0.1', port: 25, user: 'u', passwordSecret: 'RAW_VAULT_KEY' } });
  const fine = saveResource({ kind: 'smtp', name: 'New mail', project_id: a, config: { host: '127.0.0.1', port: 25, user: 'u', passwordSecret: '{{gv.A_KEY}}' } });
  const s = node('start', 'Start'), h = node('log', 'Header', { message: 'Bearer {{secret.RAW_VAULT_KEY}} {{secret.ENGINE_KEY_STORE}}' });
  const f = flows.saveFlow(undefined, { name: 'Old header', nodes: [s, h], edges: [edge(s, h)] } as any, a);
  const rows = (await call(admin, 'GET', '/api/console/secret-scope')).json();
  assert.ok(rows.some((r: any) => r.item === 'connection' && r.id === conn.id && r.secret === 'RAW_VAULT_KEY'), JSON.stringify(rows));
  assert.ok(rows.some((r: any) => r.item === 'sutra' && r.id === f.id && r.secret === 'RAW_VAULT_KEY'));
  assert.ok(!rows.some((r: any) => r.id === fine.id || r.secret === 'ENGINE_KEY_STORE'), 'properties and engine secrets are fine');
  assert.ok(!JSON.stringify(rows).includes(RAW_SECRET), 'names only, never values');
  assert.equal((await call(dev, 'GET', '/api/console/secret-scope')).statusCode, 403);
  assert.ok((await call(admin, 'GET', '/api/console/overview')).json().secretScope.length >= 2);
  assert.deepEqual((await call(dev, 'GET', '/api/console/overview')).json().secretScope, []);
});

test('a release that names a stored secret directly stops the deploy check', async () => {
  const { checkPackage } = await import('../server/src/packages.js');
  const s = node('start', 'Start'), h = node('log', 'Header', { message: 'Bearer {{secret.RAW_VAULT_KEY}}' });
  const pkg: any = {
    createdWith: '2.1.8', project: { name: 'Alpha', variables: [{ name: 'PROP_KEY', type: 'secret', value: 'PROP_STORE' }] },
    resources: [{ id: 'r1', kind: 'smtp', name: 'Mail', config: { host: 'h', port: 25, user: 'u', passwordSecret: 'PROP_STORE' } }],
    schemas: [], sutras: [{ id: 'f1', name: 'Release flow', version: 1, deployed: true, doc: { name: 'Release flow', nodes: [s, h], edges: [edge(s, h)] } }],
    manifest: { activityTypes: ['start', 'log'], secrets: ['PROP_STORE', 'RAW_VAULT_KEY'], memoryTables: [], sutras: [] },
  };
  setSecret('PROP_STORE', 'synthetic-prop-store');
  const r = checkPackage(pkg);
  const stop = r.errors.find(e => /Not behind a Secret property/.test(e));
  assert.ok(stop && stop.includes('RAW_VAULT_KEY') && !stop.includes('PROP_STORE'), r.errors.join('\n'));
});

test('a project property cannot read the server environment (SUTRA_ADMIN_TOKEN) unless an administrator allowed the name', async () => {
  process.env.SUTRA_ADMIN_TOKEN = 'synthetic-admin-token-218';
  process.env.ALPHA_REGION = 'north-218';
  const vars = projects.getProject(a)!.config.variables;
  const put = (extra: any[]) => call(dev, 'PUT', `/api/projects/${a}`, { name: 'Alpha', config: { variables: [...vars, ...extra] } });
  assert.equal((await put([{ name: 'LEAK', type: 'string', value: '${env:SUTRA_ADMIN_TOKEN}' }, { name: 'REGION', type: 'string', value: '${env:ALPHA_REGION}' }])).statusCode, 200);
  // The run does not start (as with a variable that is not set), and the value is never read.
  await assert.rejects(run(a, node('log', 'Leak', { message: 'token {{gv.LEAK}}' })), (e: any) => /only the environment variables an administrator allowed/.test(e.message) && !e.message.includes('synthetic-admin-token-218'));
  // The developer cannot allow names; an administrator can, but never the server's own.
  assert.equal((await call(dev, 'PUT', '/api/env-bindings', { allowed: ['ALPHA_REGION'] })).statusCode, 403);
  assert.equal((await call(admin, 'PUT', '/api/env-bindings', { allowed: ['SUTRA_ADMIN_TOKEN'] })).statusCode, 400);
  const asked = (await call(admin, 'GET', '/api/env-bindings')).json();
  assert.ok(asked.requested.some((r: any) => r.name === 'SUTRA_ADMIN_TOKEN' && r.serverOwn && r.found.some((f: string) => f.startsWith('Alpha'))));
  assert.ok(!JSON.stringify(asked).includes('synthetic-admin-token-218'), 'names only');
  assert.equal((await call(admin, 'PUT', '/api/env-bindings', { allowed: ['ALPHA_REGION'] })).statusCode, 200);
  await put([{ name: 'REGION', type: 'string', value: '${env:ALPHA_REGION}' }]);
  const ok = await run(a, node('log', 'Region', { message: 'region {{gv.REGION}}' }));
  assert.equal(ok.status, 'done', ok.error);
  await put([]);
  await call(admin, 'PUT', '/api/env-bindings', { allowed: [] });
  delete process.env.SUTRA_ADMIN_TOKEN; delete process.env.ALPHA_REGION;
});

test('a developer cannot point a Secret property of A at B\'s stored secret, or at a server secret without Manage secrets', async () => {
  const vars = projects.getProject(a)!.config.variables;
  const put = (who: Who, extra: any[]) => call(who, 'PUT', `/api/projects/${a}`, { name: 'Alpha', config: { variables: [...vars, ...extra] } });
  const stolen = await put(dev, [{ name: 'STOLEN', type: 'secret', value: bRef }]);
  assert.ok(stolen.statusCode >= 400, stolen.body);
  assert.match(stolen.body, /belongs to another project/);
  const byAdmin = await put(admin, [{ name: 'STOLEN', type: 'secret', value: bRef }]);
  assert.ok(byAdmin.statusCode >= 400, 'another project\'s secret is refused even for an administrator');
  const ops = await call(admin, 'PUT', `/api/projects/${a}/ops`, { variables: { A_KEY: bRef } });
  assert.ok(ops.statusCode >= 400 && /belongs to another project/.test(ops.body), 'nor through the deployment config');
  const raw = await put(dev, [{ name: 'RAW', type: 'secret', value: 'RAW_VAULT_KEY' }]);
  assert.ok(raw.statusCode >= 400 && /Manage secrets/.test(raw.body), raw.body);
  assert.equal((await put(admin, [{ name: 'RAW', type: 'secret', value: 'RAW_VAULT_KEY' }])).statusCode, 200, 'a vault manager may');
  assert.equal((await put(dev, [{ name: 'RAW', type: 'secret', value: 'RAW_VAULT_KEY' }, { name: 'LATER', type: 'secret', value: 'NOT_STORED_YET' }])).statusCode, 200, 'an unchanged binding and a name not stored yet are fine');
  // A binding made before 2.1.8 (written straight into the project) reads nothing at run time.
  const p = projects.getProject(a)!;
  q.run('update projects set config = ? where id = ?', JSON.stringify({ ...p.config, variables: [...vars, { name: 'STOLEN', type: 'secret', value: bRef, description: '' }] }), a);
  projects.forgetCachedSettings();
  const r = await run(a, node('log', 'Stolen', { message: 'Bearer {{gv.STOLEN}}' }));
  assert.ok(!JSON.stringify(r).includes(B_SECRET), JSON.stringify(r));
  q.run('update projects set config = ? where id = ?', JSON.stringify({ ...p.config, variables: vars }), a);
  projects.forgetCachedSettings();
  // Upgrade: secrets stored from a project's property before 2.1.8 are claimed by that project.
  q.run('update secrets set project_id = null where name = ?', bRef);
  projects.claimProjectSecrets();
  assert.equal(q.get<any>('select project_id from secrets where name = ?', bRef).project_id, b);
});

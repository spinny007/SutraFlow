/**
 * Purpose: the 2.1.7 audit (F1) showed a developer of project A reading project B's secret: the vault list
 * named it, and model discovery sent it to an address of the developer's choice. From 2.1.8 a project's
 * work reads only the stored secrets behind its own Secret properties (GV) and the engine's (EV).
 */
testEnv(24180);
const { boot } = await import('../server/src/index.js');
const { engine, runState } = await import('../server/src/engine/engine.js');
const { q } = await import('../server/src/db.js');
const projects = await import('../server/src/projects.js');
const { inProject } = await import('../server/src/resources.js');
const { setSecret, getSecret, requireSecret, readSecretUnscoped } = await import('../server/src/secrets.js');

let srv: Awaited<ReturnType<typeof boot>>;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv.stop(); });

type Who = { cookie?: string };
const call = (who: Who, method: string, url: string, payload?: any) => srv.admin.inject({ method: method as any, url, payload, headers: { 'x-sutra': '1', ...(who.cookie ? { cookie: who.cookie } : {}) } });
const cookieOf = (r: any) => String(r.headers['set-cookie'] || '').split(';')[0];

const admin: Who = {}, dev: Who = {};
let a = '', b = '', bRef = '';
const B_SECRET = 'synthetic-project-b-secret-218';
const RAW_SECRET = 'synthetic-raw-vault-secret-218';
const ENGINE_SECRET = 'synthetic-engine-secret-218';

const run = async (projectId: string, step: ReturnType<typeof node>) => {
  const s = node('start', 'Start', { payload: '{}' });
  const id = await engine.startRun({ projectId, doc: { name: 'Secret scope', nodes: [s, step], edges: [edge(s, step)] } });
  await engine.waitFor(id, 15000);
  return { ...q.get<any>('select status, error from runs where id = ?', id), out: runState(id)?.outputs[step.name] };
};

test('setup: an administrator, projects A and B, a developer granted only A', async () => {
  const r = await call({}, 'POST', '/api/auth/setup', { username: 'root', password: 'first-admin-pass-1' });
  assert.equal(r.statusCode, 200, r.body);
  admin.cookie = cookieOf(r);
  a = (await call(admin, 'POST', '/api/projects', { name: 'Alpha' })).json().id;
  b = (await call(admin, 'POST', '/api/projects', { name: 'Bravo' })).json().id;
  bRef = projects.storeProjectSecret(b, 'B_KEY', B_SECRET, true).secretRef;
  projects.storeProjectSecret(a, 'A_KEY', 'synthetic-project-a-secret-218', true);
  setSecret('RAW_VAULT_KEY', RAW_SECRET);
  setSecret('ENGINE_KEY_STORE', ENGINE_SECRET);
  projects.saveEngineVariables([{ name: 'SHARED_KEY', type: 'secret', value: 'ENGINE_KEY_STORE' }]);
  assert.equal((await call(admin, 'POST', '/api/access/users', { username: 'dev', password: 'temporary-pass-9', grants: [{ role: 'developer', project: a }] })).statusCode, 200);
  const s = await call({}, 'POST', '/api/auth/login', { username: 'dev', password: 'temporary-pass-9' });
  const changed = await call({ cookie: cookieOf(s) }, 'POST', '/api/auth/password', { current: 'temporary-pass-9', password: 'River-stone-88' });
  assert.equal(changed.statusCode, 200, changed.body);
  dev.cookie = cookieOf(changed);
  assert.equal((await call(dev, 'GET', `/api/resources?projectId=${b}`)).statusCode, 403, 'control: B is closed to the developer');
});

test('the secret list: a project sees only the names it can use; the whole list needs Secrets, Server settings or Alerts', async () => {
  assert.equal((await call(dev, 'GET', '/api/secrets')).statusCode, 403);
  const own = (await call(dev, 'GET', `/api/secrets?projectId=${a}`)).json().map((s: any) => s.name);
  assert.ok(own.includes('ENGINE_KEY_STORE'), 'engine Secret properties are usable by every project');
  assert.ok(own.some((n: string) => n.endsWith('_A_KEY')), 'A sees its own Secret property');
  assert.ok(!own.includes(bRef) && !own.includes('RAW_VAULT_KEY'), `A never sees B's or a raw name: ${own.join(', ')}`);
  assert.equal((await call(dev, 'GET', `/api/secrets?projectId=${b}`)).statusCode, 403);
  const all = (await call(admin, 'GET', '/api/secrets')).json().map((s: any) => s.name);
  assert.ok(all.includes(bRef) && all.includes('RAW_VAULT_KEY'));
});

test('model discovery never sends another project\'s secret or a raw vault name, but does send A\'s own and the engine\'s', async () => {
  const cap = await captureServer(() => ({ body: JSON.stringify({ data: [{ id: 'model-1' }] }) }));
  try {
    for (const apiKeySecret of [bRef, 'RAW_VAULT_KEY']) {
      const r = await call(dev, 'POST', '/api/resources/models', { kind: 'aiProvider', project_id: a, config: { engine: 'OpenAI API', baseUrl: cap.url, apiKeySecret } });
      assert.equal(r.statusCode, 400, r.body);
      assert.match(r.json().error || r.body, /not behind a Secret property of this project/);
      assert.ok(!r.body.includes(apiKeySecret), 'the refused name is not repeated');
    }
    assert.equal(cap.seen.length, 0, 'nothing reached the capture server');
    for (const [apiKeySecret, expected] of [['{{gv.A_KEY}}', 'synthetic-project-a-secret-218'], ['{{ev.SHARED_KEY}}', ENGINE_SECRET]]) {
      const r = await call(dev, 'POST', '/api/resources/models', { kind: 'aiProvider', project_id: a, config: { engine: 'OpenAI API', baseUrl: cap.url, apiKeySecret } });
      assert.equal(r.statusCode, 200, r.body);
      assert.equal(String(cap.seen.at(-1)?.headers.authorization), `Bearer ${expected}`);
    }
  } finally { await cap.close(); }
});


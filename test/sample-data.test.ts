test('everything the samples store is named sample_', () => {
  const p = projects.saveProject({ name: 'Naming check', config: { variables: [] } });
  addSamples(p.id);
  const bad: string[] = [];
  const check = (where: string, v: unknown) => { if (typeof v === 'string' && v && !isSampleName(v)) bad.push(`${where}: ${v}`); };
  // A literal, or the first literal of =concat('sample_...', ...); values built from run data are not names.
  const literal = (v: unknown) => typeof v !== 'string' || !v || v.includes('{{') ? undefined : v.startsWith('=') ? /^=concat\('([^']*)'/.exec(v)?.[1] : v;
  const firstSegment = (v: unknown) => { const l = literal(v); return l === undefined ? undefined : l.replace(/^\/+/, '').split('/')[0]; };
  for (const f of flows.listFlows(p.id).map(x => flows.getFlow(x.id)!)) {
    for (const n of f.doc.nodes) {
      const c = n.config || {}, at = `${f.name} / ${n.name}`;
      if (n.type === 'counter') check(at, literal(c.name));
      if (n.type === 'channelPublish' || n.type === 'channelTrigger') check(at, literal(c.channel));
      if (n.type === 'busPublish' || n.type === 'busSubscribe') { check(at, literal(c.destination)); check(at, literal(c.groupId)); }
      if (/^mongo/.test(n.type) && c.collection) check(at, literal(c.collection));
      if (n.type === 'firestore') check(at, literal(c.collection));
      if (n.type === 'firebaseRtdb' || n.type === 'dropbox') check(at, firstSegment(c.path));
      if (/^remote/.test(n.type)) for (const k of ['path', 'folder', 'moveTo', 'from', 'to']) if (c[k]) check(`${at} ${k}`, firstSegment(c[k]));
      if (/^file/.test(n.type)) for (const k of ['folder', 'location']) {
        const v = literal(c[k]);
        if (v && /^([A-Za-z]:|\/)/.test(v)) bad.push(`${at} ${k}: a fixed folder (${v}); use a project property in \${files}/sample_...`);
      }
      // Tables, databases, procedures and views the SQL makes.
      for (const text of Object.values(c).flat().filter((x): x is string => typeof x === 'string')) {
        for (const m of text.matchAll(/CREATE\s+(?:TABLE|DATABASE|SCHEMA|PROCEDURE|VIEW)\s+(?:IF NOT EXISTS\s+)?([\w.]+)/gi)) for (const part of m[1].split('.')) check(`${at} SQL`, part);
      }
    }
  }
  for (const r of listResources(undefined, p.id)) if (r.kind === 'database' && r.config.driver === 'sqlite') check(r.name, path.basename(String(r.config.file)));
  for (const v of projects.getProject(p.id)!.config.variables) {
    const m = /^\$\{files\}\/([^/]+)/.exec(v.value);
    if (m) check(`property ${v.name}`, m[1]);
  }
  assert.deepEqual(bad, [], 'sample data must be named sample_<objective>');
  assert.ok(SAMPLES.length > 40);
});

test('the installer lists and removes the samples and their data, and keeps the site\'s own', async () => {
  // The Naming check project of the test before holds samples too: removal takes them as well.
  const samples = projects.saveProject({ name: 'Samples', config: { variables: [] } });
  addSamples(samples.id, ['database', 'csv', 'timer']);
  const shop = projects.saveProject({ name: 'Shop', config: { variables: [] } });
  addSamples(shop.id, ['database']);
  const shopDb = listResources('database', shop.id).find(r => r.name === 'Sample SQLite')!;
  const s = node('start', 'Start'), qn = node('dbQuery', 'My report', { connection: shopDb.id, sql: 'SELECT 1', params: [], maxRows: 10 });
  const mine = flows.saveFlow(undefined, { name: 'Orders report', nodes: [s, qn], edges: [edge(s, qn)] }, shop.id);
  const kb = saveResource({ kind: 'aiKnowledge', name: 'Sample knowledge base', project_id: samples.id, config: { store: 'built-in', embedWith: 'built-in' } });
  q.run('insert into ai_knowledge(kb_id, id, source, chunk, text, meta, vector, at) values (?, ?, ?, ?, ?, ?, ?, ?)', kb.id, 'k1', 'faq.md', 0, 'Returns within 30 days', '{}', null, new Date().toISOString());
  const counter = (pid: string, name: string) => q.run('insert into counters(project_id, name, value, updated_at) values (?, ?, ?, ?)', pid, name, 1, new Date().toISOString());
  counter(samples.id, 'sample_poll_1'); counter(shop.id, 'sample-notifications'); counter(shop.id, 'orders_today');
  const put = (f: string, text = 'x') => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); return f; };
  const sFiles = projects.projectFilesDir('Samples'), shopFiles = projects.projectFilesDir('Shop');
  const sampleCsv = put(path.join(sFiles, 'sample_csv', 'sales.csv'));
  const own = put(path.join(shopFiles, 'mine.csv'));
  const oldValidation = put(path.join(shopFiles, 'validation-samples', 'customer.json'));
  const oldDoc = put(path.join(shopFiles, 'documents', 'faq.md'));
  const ownDoc = put(path.join(shopFiles, 'documents', 'my-notes.md'));
  const sqliteFile = put(path.join(config.dataDir, 'sample_sutraflow.sqlite'), '');
  const oldSqlite = put(path.join(config.dataDir, 'samples.sqlite'), '');

  const list = await sampleData({ remove: false });
  const names = list.items.map(i => `${i.what}:${i.name}`);
  for (const want of ['Sutra:Sample: Database (SQLite)', 'connection:Sample knowledge base', 'counter:sample_poll_1', 'counter:sample-notifications', 'project:Samples', 'project property:SAMPLE_CSV_FOLDER'])
    assert.ok(names.includes(want), `listed ${want}: ${names.join(', ')}`);
  assert.ok(list.items.some(i => i.what === 'knowledge' && /Sample knowledge base: 1 pieces/.test(i.name)));
  // Folders named sample_ (and the old validation folder) are listed whole; old sample files one by one.
  const slash = (f: string) => f.split(path.sep).join('/');
  for (const f of [path.dirname(sampleCsv), path.dirname(oldValidation), oldDoc, sqliteFile, oldSqlite]) assert.ok(list.items.some(i => i.name === slash(f)), `listed ${f}: ${names.join(', ')}`);
  assert.ok(!names.some(n => /orders_today|mine\.csv|my-notes|Orders report/.test(n)), 'the site\'s own data is not listed');
  assert.deepEqual(list.kept.map(i => `${i.where}:${i.name}`), ['Shop:Sample SQLite'], 'a Sample connection a site Sutra uses is kept');
  assert.equal(list.items.find(i => i.name === 'sample-notifications')?.old, true);
  assert.ok(flows.listFlows(samples.id).length > 0, 'a list changes nothing');

  const done = await sampleData({ remove: true });
  assert.equal(done.removed, true);
  assert.deepEqual(done.problems, []);
  assert.equal(q.get<{ n: number }>("select count(*) n from flows where name like 'Sample:%'")!.n, 0);
  assert.ok(flows.getFlow(mine.id), 'the site\'s Sutra stays');
  assert.ok(listResources('database', shop.id).some(r => r.id === shopDb.id), 'the connection it uses stays');
  assert.ok(!projects.listProjects().some(p => p.name === 'Samples'), 'the empty Samples project goes');
  assert.ok(projects.listProjects().some(p => p.name === 'Shop'));
  assert.deepEqual(q.all<{ name: string }>('select name from counters order by name').map(c => c.name), ['orders_today']);
  assert.equal(q.get<{ n: number }>('select count(*) n from ai_knowledge where kb_id = ?', kb.id)!.n, 0);
  for (const f of [sampleCsv, oldValidation, oldDoc, sqliteFile, oldSqlite]) assert.ok(!fs.existsSync(f), `removed ${f}`);
  for (const f of [own, ownDoc]) assert.ok(fs.existsSync(f), `kept ${f}`);
  assert.equal((await sampleData({ remove: false })).items.filter(i => i.what === 'Sutra').length, 0);
});

test('the Samples project stays when it holds a connection, schema or property of the site, and the list says why (2.1.6)', async () => {
  const samples = projects.saveProject({ name: 'Samples', config: { variables: [{ name: 'ORDERS_API', type: 'string', value: 'https://orders.example' }] } });
  addSamples(samples.id, ['csv']);
  const mine = saveResource({ kind: 'database', name: 'Orders database', project_id: samples.id, config: { driver: 'sqlite', file: 'orders.sqlite' } });
  const list = await sampleData({ remove: false });
  assert.ok(!list.items.some(i => i.what === 'project' && i.name === 'Samples'), 'the project is not listed for removal');
  const kept = list.kept.find(i => i.what === 'project' && i.name === 'Samples');
  assert.ok(kept, `kept: ${JSON.stringify(list.kept)}`);
  assert.match(kept!.note || '', /connection Orders database/);
  assert.match(kept!.note || '', /project property ORDERS_API/);
  const done = await sampleData({ remove: true });
  assert.deepEqual(done.problems, []);
  const still = projects.listProjects().find(p => p.name === 'Samples');
  assert.ok(still, 'the Samples project stays');
  assert.ok(listResources('database', samples.id).some(r => r.id === mine.id), 'its own connection stays');
  assert.equal(flows.listFlows(samples.id).length, 0, 'the sample Sutras are gone');
  assert.ok(still!.config.variables.some(v => v.name === 'ORDERS_API'), 'its own property stays');
  // Emptied by its owner, the next removal takes the project too.
  deleteResource(mine.id);
  projects.saveProject({ id: still!.id, name: still!.name, description: still!.description, config: { ...still!.config, variables: [] } });
  const list2 = await sampleData({ remove: false });
  assert.ok(list2.items.some(i => i.what === 'project' && i.name === 'Samples'));
  await sampleData({ remove: true });
  assert.ok(!projects.listProjects().some(p => p.name === 'Samples'));
});

test('removal reaches sample_ folders and the old sample files on a Sample SFTP server, and keeps the rest', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sutra-rm-sftp-'));
  const put = (rel: string) => { const f = path.join(root, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, 'x'); return f; };
  const sample = put('sample_archive/orders-20261103-101010.csv'), nested = put('sample_outbox/2026/orders.csv');
  const old = put('outbox/orders.csv'), oldArchive = put('archive/orders-20261001-090000.csv');
  const theirs = put('outbox/invoices.csv'), theirArchive = put('archive/invoices.csv');
  const sftp = await sftpServer(root, { user: 'sample', password: 'Sample-pass-1' });
  try {
    const p = projects.saveProject({ name: 'Partner files', config: { variables: [] } });
    setSecret('SAMPLE_RM_SFTP_PW', 'Sample-pass-1');
    saveResource({ kind: 'sftp', name: 'Sample SFTP partner', project_id: p.id, config: { host: '127.0.0.1', port: sftp.port, user: 'sample', passwordSecret: 'SAMPLE_RM_SFTP_PW', hostKeyFingerprint: '' } });
    const list = await sampleData({ remove: false });
    const mine = list.items.filter(i => i.where === 'Sample SFTP partner').map(i => `${i.what} ${i.name}${i.old ? ' old' : ''}`).sort();
    assert.deepEqual(mine, ['file archive/orders-20261001-090000.csv old', 'file outbox/orders.csv old', 'folder sample_archive', 'folder sample_outbox'], JSON.stringify(list.problems));
    const done = await sampleData({ remove: true });
    assert.deepEqual(done.problems, []);
    for (const f of [sample, nested, old, oldArchive]) assert.ok(!fs.existsSync(f), `removed ${f}`);
    assert.ok(!fs.existsSync(path.join(root, 'sample_outbox')), 'the sample_ folder goes whole');
    for (const f of [theirs, theirArchive]) assert.ok(fs.existsSync(f), `kept ${f}`);
  } finally { await sftp.close(); }
});

const MYSQL = process.env.SUTRA_TEST_MYSQL_URL;
test('removal drops sample_ objects inside the database a Sample MySQL connection names', { skip: !MYSQL && 'set SUTRA_TEST_MYSQL_URL to test against a real MySQL server' }, async () => {
  const u = new URL(MYSQL!);
  const mysql = require('mysql2/promise');
  const name = `sutra_rm_${Date.now().toString(36)}`;
  const admin = await mysql.createConnection({ host: u.hostname, port: Number(u.port) || 3306, user: decodeURIComponent(u.username), password: decodeURIComponent(u.password) || undefined, multipleStatements: true });
  await admin.query(`CREATE DATABASE \`${name}\`; CREATE TABLE \`${name}\`.sample_orders (id INT); CREATE TABLE \`${name}\`.orders (id INT); CREATE PROCEDURE \`${name}\`.sample_report() SELECT 1;`);
  try {
    const p = projects.saveProject({ name: 'MySQL removal', config: { variables: [] } });
    if (u.password) setSecret('SAMPLE_RM_PW', decodeURIComponent(u.password));
    saveResource({ kind: 'database', name: 'Sample MySQL removal', project_id: p.id, config: { driver: 'mysql', host: u.hostname, port: Number(u.port) || 3306, database: name, user: decodeURIComponent(u.username), passwordSecret: u.password ? 'SAMPLE_RM_PW' : '' } });
    const list = await sampleData({ remove: false });
    const mine = list.items.filter(i => i.where === 'Sample MySQL removal').map(i => `${i.what} ${i.name}`).sort();
    assert.deepEqual(mine, [`procedure ${name}.sample_report`, `table ${name}.sample_orders`], 'only sample_ objects, only in its database');
    const r = await sampleData({ remove: true });
    assert.deepEqual(r.problems, []);
    const [tables] = await admin.query('SELECT table_name AS n FROM information_schema.tables WHERE table_schema = ?', [name]);
    assert.deepEqual((tables as any[]).map(t => t.n ?? t.N), ['orders'], 'the database\'s own table stays');
    const [procs] = await admin.query('SELECT routine_name AS n FROM information_schema.routines WHERE routine_schema = ?', [name]);
    assert.equal((procs as any[]).length, 0);
  } finally {
    await admin.query(`DROP DATABASE IF EXISTS \`${name}\``);
    await admin.end();
  }
});

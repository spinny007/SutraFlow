test('a busy port is reported with the next free one; sutraflow.env keeps its comments and order when values are set', async () => {
  const busy = net.createServer();
  await new Promise<void>(r => busy.listen(0, '127.0.0.1', () => r()));
  const port = (busy.address() as net.AddressInfo).port;
  try {
    const [r] = await core.checkPorts('127.0.0.1', [port]);
    assert.equal(r.free, false);
    assert.ok(r.suggest && r.suggest > port, 'a free port is suggested');
  } finally { busy.close(); }

  const dir = tmp();
  fs.writeFileSync(path.join(dir, 'sutraflow.env'), '# The studio\nSTUDIO_PORT=4800\n# The database\nSUTRA_DB=\n');
  core.writeEnv(path.join(dir, 'sutraflow.env'), { STUDIO_PORT: '4900', SUTRA_DB: 'postgres://u@h:5432/d', NEW_ONE: 'x' });
  const text = fs.readFileSync(path.join(dir, 'sutraflow.env'), 'utf8');
  assert.match(text, /# The studio\r?\nSTUDIO_PORT=4900\r?\n# The database\r?\nSUTRA_DB=postgres:\/\/u@h:5432\/d/);
  assert.match(text, /# Set by the SutraFlow installer\r?\nNEW_ONE=x/);
  assert.deepEqual(core.readEnv(path.join(dir, 'sutraflow.env')), { STUDIO_PORT: '4900', SUTRA_DB: 'postgres://u@h:5432/d', NEW_ONE: 'x' });
});

test('install: settings, data folder, tables and the administrator are made, then the installer is locked', async () => {
  const dir = tmp();
  fs.mkdirSync(path.join(dir, 'node_modules')); // the runtime packages, as a release folder has them
  const steps: string[] = [];
  const dry: any = await core.install(config(), dir, () => {}, { dryRun: true });
  assert.ok(dry.dryRun && dry.plan.some((p: string) => /create the administrator chief/.test(p)), 'a dry run only plans');
  assert.equal(fs.existsSync(path.join(dir, 'sutraflow.env')), false, 'and changes nothing');
  const r: any = await core.install(config(), dir, (step, state) => { if (state !== 'run') steps.push(`${step}:${state}`); });
  assert.equal(r.address, 'http://127.0.0.1:47101');
  assert.deepEqual(steps, ['System check:ok', 'Ports:ok', 'Database:ok', 'Settings file:ok', 'Tables and administrator:ok', 'Admin token:ok']);
  const env = core.readEnv(path.join(dir, 'sutraflow.env'));
  assert.deepEqual([env.STUDIO_PORT, env.STUDIO_GATEWAY_HTTP, env.STUDIO_GATEWAY_HTTPS, env.SUTRA_ENVIRONMENT, env.SUTRA_DB], ['47101', '47102', '47103', 'test', '']);
  const db = new DatabaseSync(path.join(dir, 'data', 'sutra.db'), { readOnly: true });
  try {
    assert.equal((db.prepare(`select username from users`).all() as any[]).map(u => u.username).join(','), 'chief');
    assert.equal((db.prepare(`select role_id from grants where username = 'chief'`).get() as any).role_id, 'administrator');
  } finally { db.close(); }
  assert.ok(fs.existsSync(path.join(dir, 'data', 'master.key')) && fs.existsSync(path.join(dir, 'data', 'admin-token.txt')));
  assert.equal(core.isLocked(dir), true);
  await assert.rejects(core.install(config(), dir), /already installed here/);
  // The data a later upgrade must keep, read without opening the database for writing.
  const snap = await core.snapshotDb(dir);
  assert.equal(snap.users.rows, 1);
});

test('upgrade: only from 2.1.0 on, never onto the same or a newer version, and never in the installer\'s own folder', async () => {
  const make = (v: string) => { const d = tmp(); fs.mkdirSync(path.join(d, 'bin')); fs.writeFileSync(path.join(d, 'bin', 'sutraflow.mjs'), ''); fs.writeFileSync(path.join(d, 'package.json'), JSON.stringify({ version: v })); return d; };
  const now = core.thisVersion();
  assert.equal((await core.detectInstall(make('2.0.11'))).upgradable, false);
  assert.match((await core.detectInstall(make('2.0.11'))).note, /older than 2\.1\.0/);
  assert.equal((await core.detectInstall(make(now))).upgradable, false);
  assert.equal((await core.detectInstall(tmp())).exists, false);
  const old = make('2.1.0');
  if (core.cmpVersion(now, '2.1.0') > 0) {
    const found = await core.detectInstall(old);
    assert.equal(found.upgradable, true, found.note);
    const plan: any = await core.upgrade({ from: old }, () => {}, { dryRun: true });
    assert.ok(plan.plan.some((p: string) => /back up its data folder, settings and database/.test(p)));
  }
  await assert.rejects(core.upgrade({ from: make('2.0.11') }), /older than 2\.1\.0/);
});

test('Node memory: 0 or from 256 MB, the processes on this machine leave room for the system, further engines are checked on their own', () => {
  const m = core.memoryInfo();
  assert.ok(m.machineMb > 0 && m.nodeDefaultMb > 0 && m.suggestedMb >= 256, JSON.stringify(m));
  assert.deepEqual(core.memoryProblems(config({ server: { ...config().server, studioMemoryMb: 0 } }), 8192), []);
  assert.deepEqual(core.memoryProblems(config({ server: { ...config().server, studioMemoryMb: 2048, enginePort: 47104, engineHttp: 47105, engineHttps: 47106, engineMemoryMb: 2048 } }), 8192), []);
  const bad = core.memoryProblems(config({ server: { ...config().server, studioMemoryMb: 100, enginePort: 47104, engineHttp: 47105, engineHttps: 47106, engineMemoryMb: 7500 } }), 8192);
  assert.ok(bad.some(b => /Studio memory: 0 \(Node.js decides\) or a whole number/.test(b)), bad.join(' | '));
  assert.ok(bad.some(b => /leave at least 15%/.test(b)), bad.join(' | '));
  assert.ok(core.memoryProblems(config({ server: { ...config().server, studioMemoryMb: 9000 } }), 8192).some(b => /more than the machine has/.test(b)));
  // A further engine runs on its own machine: only its size is checked here.
  assert.deepEqual(core.memoryProblems(config({ cluster: { engines: [{ name: 'big', port: 1, http: 2, https: 3, memoryMb: 65536 }] } }), 8192), []);
  assert.ok(core.memoryProblems(config({ cluster: { engines: [{ name: 'tiny', port: 1, http: 2, https: 3, memoryMb: 64 }] } }), 8192).some(b => /Engine tiny memory/.test(b)));
  const files = core.clusterFiles(config({ database: { kind: 'postgres', host: 'db', database: 'sf', user: 'u' }, cluster: { engines: [{ name: 'e2', port: 4801, http: 9080, https: 9443, memoryMb: 3072 }, { name: 'e3', port: 4801, http: 9080, https: 9443 }] } }));
  assert.match(files[0].env, /^ENGINE_MEMORY_MB=3072$/m);
  assert.doesNotMatch(files[1].env, /ENGINE_MEMORY_MB/);
});


test('install: settings, data folder, tables and the administrator are made, then the installer is locked', async () => {
  const dir = tmp();
  fs.mkdirSync(path.join(dir, 'node_modules')); // the runtime packages, as a release folder has them
  const steps: string[] = [];
  const dry: any = await core.install(config(), dir, () => {}, { dryRun: true });
  assert.ok(dry.dryRun && dry.plan.some((p: string) => /create the administrator chief/.test(p)), 'a dry run only plans');
  assert.equal(fs.existsSync(path.join(dir, 'sutraflow.env')), false, 'and changes nothing');
  const r: any = await core.install(config(), dir, (step, state) => { if (state !== 'run') steps.push(`${step}:${state}`); });
  assert.equal(r.address, 'http://127.0.0.1:47101');
  assert.deepEqual(steps, ['System check:ok', 'Ports:ok', 'Database:ok', 'Settings file:ok', 'Master key:ok', 'Tables and administrator:ok', 'Admin token:ok']);
  // 2.1.4: the new master key and admin token come back once for the last page, the same as their files.
  assert.equal(r.newKeys.masterKey, fs.readFileSync(path.join(dir, 'data', 'master.key'), 'utf8'));
  assert.equal(Buffer.from(r.newKeys.masterKey, 'base64').length, 32);
  assert.equal(r.newKeys.adminToken, fs.readFileSync(path.join(dir, 'data', 'admin-token.txt'), 'utf8'));
  assert.equal(r.keyFiles.masterKey, path.join(dir, 'data', 'master.key'));
  const env = core.readEnv(path.join(dir, 'sutraflow.env'));
  assert.deepEqual([env.STUDIO_PORT, env.STUDIO_GATEWAY_HTTP, env.STUDIO_GATEWAY_HTTPS, env.SUTRA_ENVIRONMENT, env.SUTRA_DB], ['47101', '47102', '47103', 'test', '']);
  const db = new DatabaseSync(path.join(dir, 'data', 'sutra.db'), { readOnly: true });
  try {
    assert.equal((db.prepare(`select username from users`).all() as any[]).map(u => u.username).join(','), 'chief');
    assert.equal((db.prepare(`select role_id from grants where username = 'chief'`).get() as any).role_id, 'administrator');
  } finally { db.close(); }
  assert.ok(fs.existsSync(path.join(dir, 'data', 'master.key')) && fs.existsSync(path.join(dir, 'data', 'admin-token.txt')));
  assert.equal(core.isLocked(dir), true);
  await assert.rejects(core.install(config(), dir), /already installed here/);
  // The data a later upgrade must keep, read without opening the database for writing.
  const snap = await core.snapshotDb(dir);
  assert.equal(snap.users.rows, 1);
});

test('upgrade: only from 2.1.0 on, the same version only as a reinstall, never a newer one, and never in the installer\'s own folder', async () => {
  const make = (v: string) => { const d = tmp(); fs.mkdirSync(path.join(d, 'bin')); fs.writeFileSync(path.join(d, 'bin', 'sutraflow.mjs'), ''); fs.writeFileSync(path.join(d, 'package.json'), JSON.stringify({ version: v })); return d; };
  const now = core.thisVersion();
  assert.equal((await core.detectInstall(make('2.0.11'))).upgradable, false);
  assert.match((await core.detectInstall(make('2.0.11'))).note, /older than 2\.1\.0/);
  assert.equal((await core.detectInstall(make(now))).upgradable, false);
  assert.equal((await core.detectInstall(tmp())).exists, false);
  const old = make('2.1.0');
  if (core.cmpVersion(now, '2.1.0') > 0) {
    const found = await core.detectInstall(old);
    assert.equal(found.upgradable, true, found.note);
    const plan: any = await core.upgrade({ from: old }, () => {}, { dryRun: true });
    assert.ok(plan.plan.some((p: string) => /back up its data folder, settings and database/.test(p)));
    assert.ok(!plan.plan.some((p: string) => /samples/.test(p)), 'samples are kept unless chosen');
    // Samples on upgrade (2.1.5): remove and refresh are in the plan.
    const removing: any = await core.upgrade({ from: old, samples: 'remove' }, () => {}, { dryRun: true });
    assert.ok(removing.plan.some((p: string) => p === 'remove the samples (with their sample_ data)'), removing.plan.join('; '));
    const refreshing: any = await core.upgrade({ from: old, samples: 'refresh' }, () => {}, { dryRun: true });
    assert.ok(refreshing.plan.some((p: string) => /^refresh the samples/.test(p)));
  }
  await assert.rejects(core.upgrade({ from: make('2.0.11') }), /older than 2\.1\.0/);
});

test('reinstall: the same version again only when asked (a repair), a damaged one without its launcher too, never a newer one', async () => {
  const make = (v: string, launcher = true) => { const d = tmp(); if (launcher) { fs.mkdirSync(path.join(d, 'bin')); fs.writeFileSync(path.join(d, 'bin', 'sutraflow.mjs'), ''); } fs.writeFileSync(path.join(d, 'sutraflow.env'), 'STUDIO_PORT=47199\n'); fs.writeFileSync(path.join(d, 'package.json'), JSON.stringify({ version: v })); return d; };
  const now = core.thisVersion();
  const same = make(now);
  const found = await core.detectInstall(same);
  assert.equal(found.upgradable, false);
  assert.equal(found.reinstallable, true);
  assert.match(found.note, /already runs .*Reinstall replaces its program files/);
  // Not without being asked.
  await assert.rejects(core.upgrade({ from: same }, () => {}, { dryRun: true }), /"reinstall": true/);
  const plan: any = await core.upgrade({ from: same, reinstall: true }, () => {}, { dryRun: true });
  assert.ok(plan.plan.includes(`reinstall ${now} from ${core.HOME}`), plan.plan.join('; '));
  assert.ok(plan.plan.some((p: string) => /back up its data folder, settings and database/.test(p)));
  // Damaged: the launcher is gone, the settings file and version are there.
  const damaged = make(now, false);
  const d = await core.detectInstall(damaged);
  assert.equal(d.exists, false);
  assert.equal(d.reinstallable, true);
  assert.ok((await core.upgrade({ from: damaged, reinstall: true }, () => {}, { dryRun: true }) as any).dryRun);
  // A newer installation is never taken back; reinstall does not change an upgrade.
  const newer = make('99.0.0');
  assert.equal((await core.detectInstall(newer)).reinstallable, false);
  await assert.rejects(core.upgrade({ from: newer, reinstall: true }, () => {}, { dryRun: true }), /newer than this package/);
  if (core.cmpVersion(now, '2.1.0') > 0) {
    const up: any = await core.upgrade({ from: make('2.1.0'), reinstall: true }, () => {}, { dryRun: true });
    assert.ok(up.plan.includes(`install ${now} from ${core.HOME}`), up.plan.join('; '));
  }
  // Not in the installer's own folder.
  await assert.rejects(core.upgrade({ from: core.HOME, reinstall: true }, () => {}, { dryRun: true }), /folder of its own/);
});

test('an upgrade took an SQLite file of its own for PostgreSQL, met a folder another program held only halfway through, and its way back copied the whole data folder back (read-only Git objects refused it): SQLite stays SQLite, the folder is checked first, and the old version starts again', async () => {
  assert.equal(core.isPostgres({ SUTRA_DB: 'shop.db' }), false);
  assert.equal(core.isPostgres({ SUTRA_DB: 'sqlite:shop.db' }), false);
  assert.equal(core.isPostgres({ SUTRA_DB: 'postgres://u@h:5432/db' }), true);
  assert.equal(core.isPostgres({}), false);
  // A real 2.1.0-like installation on an SQLite file of its own, with a launcher that only reports.
  const old = tmp();
  fs.mkdirSync(path.join(old, 'node_modules'));
  await core.install(config({ database: { kind: 'sqlite', file: 'shop.db' }, server: { host: '127.0.0.1', studioPort: 47111, gatewayHttp: 47112, gatewayHttps: 47113, environment: 'test' } }), old);
  fs.mkdirSync(path.join(old, 'bin'));
  fs.writeFileSync(path.join(old, 'bin', 'sutraflow.mjs'), `const [c] = process.argv.slice(2); console.log(c === 'stop' ? 'The studio has stopped.' : 'The studio is running (process 1).');`);
  fs.writeFileSync(path.join(old, 'package.json'), JSON.stringify({ version: '2.1.0' }));
  const found = await core.detectInstall(old);
  assert.equal(found.database, 'SQLite: shop.db in the data folder');
  // A read-only file in a project's Git workspace, as Git keeps its objects.
  const obj = path.join(old, 'data', 'workspaces', 'shared', 'Shop', '.git', 'objects', '00', 'abc');
  fs.mkdirSync(path.dirname(obj), { recursive: true });
  fs.writeFileSync(obj, 'x');
  fs.chmodSync(obj, 0o444);
  if (process.platform === 'win32' && core.cmpVersion(core.thisVersion(), '2.1.0') > 0) {
    // A file held without sharing, as a web server or an editor can: the upgrade stops before changing
    // anything, says which file and which process, and the old version starts again.
    const held = path.join(old, 'bin', 'held.txt');
    fs.writeFileSync(held, 'x');
    const holder = spawn('powershell.exe', ['-NoProfile', '-Command', `$f = [IO.File]::Open('${held}', 'Open', 'ReadWrite', 'None'); 'held'; Start-Sleep -Seconds 60`], { stdio: ['ignore', 'pipe', 'ignore'] });
    await new Promise<void>(r => holder.stdout.once('data', () => r()));
    const steps: string[] = [];
    try {
      assert.deepEqual(core.lockedFiles([held, path.join(old, 'bin', 'sutraflow.mjs')]), [held], 'only the held file is locked');
      assert.ok(core.whoHolds([held]).some(w => w.startsWith(`${holder.pid} `)), 'the holding process is named');
      await assert.rejects(core.upgrade({ from: old }, (s, st, d) => { if (st !== 'run') steps.push(`${st} ${s}${d ? `: ${d}` : ''}`); }), /Open in another program, so they cannot be replaced: bin.held\.txt\. Held by process \d+ /);
    } finally { holder.kill(); }
    assert.ok(!steps.some(s => / Backup/.test(s)), `nothing backed up or moved:\n${steps.join('\n')}`);
    assert.ok(steps.some(s => /^ok Putting the previous version back: 2\.1\.0 restored and started$/.test(s)), steps.join('\n'));
    assert.ok(fs.existsSync(path.join(old, 'bin', 'sutraflow.mjs')) && fs.existsSync(obj));
  }
  fs.chmodSync(obj, 0o644);
});


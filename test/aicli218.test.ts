import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { testEnv } from './helpers.js';

/**
 * Purpose: the 2.1.7 audit (F2) showed a project developer starting any program on the server through an
 * AI command-line provider, while script activities were switched off. From 2.1.8 AI command-line tools and
 * MCP servers started by a command run only when an administrator allows them, for listed command lines,
 * in an empty folder and with a small environment.
 */
const env = testEnv(24190);
const here = path.dirname(fileURLToPath(import.meta.url));
const { boot } = await import('../server/src/index.js');
const { q } = await import('../server/src/db.js');
const { saveResource } = await import('../server/src/resources.js');
const policy = await import('../server/src/ai/cli-policy.js');

let srv: Awaited<ReturnType<typeof boot>>;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv.stop(); });

type Who = { cookie?: string };
const call = (who: Who, method: string, url: string, payload?: any) => srv.admin.inject({ method: method as any, url, payload, headers: { 'x-sutra': '1', ...(who.cookie ? { cookie: who.cookie } : {}) } });
const cookieOf = (r: any) => String(r.headers['set-cookie'] || '').split(';')[0];
const admin: Who = {}, dev: Who = {};
let a = '';

// A stand-in "AI tool": reads the prompt, prints JSON with its folder, environment and a marker file it writes.
const marker = path.join(env.dir, 'program-ran.txt');
const fake = path.join(env.dir, 'fake-ai-cli.mjs');
fs.writeFileSync(fake, `import fs from 'node:fs';
let input = ''; process.stdin.on('data', d => input += d); process.stdin.on('end', () => {
  fs.writeFileSync(${JSON.stringify(marker)}, 'ran');
  process.stdout.write(JSON.stringify({ result: JSON.stringify({ cwd: process.cwd(), files: fs.readdirSync(process.cwd()), master: process.env.SUTRA_MASTER_KEY || '', extra: process.env.AICLI_EXTRA || '', path: !!(process.env.PATH || process.env.Path) }) }));
});`);
const node = `"${process.execPath}"`;
const provider = (args: string, extra: Record<string, any> = {}) => ({ kind: 'aiProvider', project_id: a, config: { engine: 'Claude CLI', command: process.execPath, args, model: 'claude-test', ...extra } });

test('setup: an administrator, a project and a developer on it; a new server starts with AI command-line tools off', async () => {
  const r = await call({}, 'POST', '/api/auth/setup', { username: 'root', password: 'first-admin-pass-1' });
  admin.cookie = cookieOf(r);
  a = (await call(admin, 'POST', '/api/projects', { name: 'Alpha' })).json().id;
  await call(admin, 'POST', '/api/access/users', { username: 'dev', password: 'temporary-pass-9', grants: [{ role: 'developer', project: a }] });
  const s = await call({}, 'POST', '/api/auth/login', { username: 'dev', password: 'temporary-pass-9' });
  dev.cookie = cookieOf(await call({ cookie: cookieOf(s) }, 'POST', '/api/auth/password', { current: 'temporary-pass-9', password: 'River-stone-88' }));
  const p = (await call(dev, 'GET', '/api/ai/cli-policy')).json();
  assert.equal(p.allowed, false);
  assert.deepEqual(p.commands, ['claude', 'gemini', 'codex']);
});

test('switched off: Test connection starts no program (the audit probe), and a developer cannot switch it on', async () => {
  const r = (await call(dev, 'POST', '/api/resources/test', provider(`"${fake}"`))).json();
  assert.equal(r.ok, false);
  assert.match(r.message, /AI command-line tools are switched off/);
  assert.equal(fs.existsSync(marker), false, 'no program ran');
  assert.equal((await call(dev, 'PUT', '/api/ai/cli-policy', { allowed: true })).statusCode, 403);
});

test('switched on: only a listed command line runs, and never with a flag that lets the tool act on its own', async () => {
  const on = await call(admin, 'PUT', '/api/ai/cli-policy', { allowed: true });
  assert.equal(on.statusCode, 200, on.body);
  const notListed = (await call(dev, 'POST', '/api/resources/test', provider(`"${fake}"`))).json();
  assert.equal(notListed.ok, false);
  assert.match(notListed.message, /not one of the commands an administrator allowed/);
  assert.equal(fs.existsSync(marker), false);
  // The administrator allows exactly this program and script (a path with spaces stays one word in quotes).
  assert.equal((await call(admin, 'PUT', '/api/ai/cli-policy', { commands: ['claude', `${node} "${fake}"`], env: ['AICLI_EXTRA'] })).statusCode, 200);
  const other = path.join(env.dir, 'other.mjs');
  fs.writeFileSync(other, 'process.stdout.write("{}")');
  assert.match((await call(dev, 'POST', '/api/resources/test', provider(`"${other}"`))).json().message, /not one of the commands/, 'the same program with another script is refused');
  for (const flag of ['--dangerously-skip-permissions', '--yolo', '--add-dir=C:/', '--permission-mode']) {
    const r = (await call(dev, 'POST', '/api/resources/test', provider(`"${fake}" ${flag}`))).json();
    assert.equal(r.ok, false, flag);
    assert.match(r.message, /lets the tool act without asking/, flag);
  }
  assert.equal(fs.existsSync(marker), false);
});

test('an allowed tool runs in an empty folder with a small environment, whatever folder the connection names', async () => {
  process.env.AICLI_EXTRA = 'passed-on';
  const r = (await call(dev, 'POST', '/api/resources/test', provider(`"${fake}"`, { workDir: env.dir }))).json();
  assert.equal(r.ok, true, r.message);
  assert.ok(fs.existsSync(marker), 'the allowed program ran');
  const { aiCall } = await import('../server/src/ai/providers.js');
  const res = await aiCall({ id: 'p', name: 'Fake', kind: 'aiProvider', project_id: a, rev: '1', config: provider(`"${fake}"`, { workDir: env.dir }).config } as any, () => '', { system: '', prompt: 'hi' });
  const seen = JSON.parse(res.text);
  assert.notEqual(path.resolve(seen.cwd), path.resolve(env.dir), 'not the folder the connection named');
  assert.deepEqual(seen.files, [], 'an empty folder');
  assert.equal(seen.master, '', 'server variables such as SUTRA_MASTER_KEY are not passed on');
  assert.equal(seen.extra, 'passed-on', 'a variable the administrator named is passed on');
  assert.equal(seen.path, true, 'the system path is passed on');
});

test('an MCP server started by a command follows the same switch and list', async () => {
  const mcp = { kind: 'mcpClient', project_id: a, config: { transport: 'command', command: `${node} "${path.join(here, 'mcpstdio.mjs')}"` } };
  const refused = (await call(dev, 'POST', '/api/resources/test', mcp)).json();
  assert.equal(refused.ok, false);
  assert.match(refused.message, /MCP server: .* is not one of the commands/);
  assert.equal((await call(admin, 'PUT', '/api/ai/cli-policy', { commands: [`${node} "${path.join(here, 'mcpstdio.mjs')}"`] })).statusCode, 200);
  const ok = (await call(dev, 'POST', '/api/resources/test', mcp)).json();
  assert.equal(ok.ok, true, ok.message);
  assert.equal((await call(admin, 'PUT', '/api/ai/cli-policy', { allowed: false })).statusCode, 200);
  assert.match((await call(dev, 'POST', '/api/resources/test', mcp)).json().message, /switched off/);
});

test('first start of 2.1.8: commands found in connections wait for an administrator; nothing is trusted on its own', async () => {
  q.run(`delete from settings where key = 'aiCliPolicy'`);
  policy.upgradeCliPolicy();
  assert.equal(policy.cliPolicy().allowed, false, 'no CLI connections yet: off');
  saveResource({ kind: 'aiProvider', name: 'Codex here', project_id: a, config: { engine: 'OpenAI Codex CLI', command: 'C:/Tools/AI Tools/codex.cmd' } } as any);
  saveResource({ kind: 'mcpClient', name: 'Files', project_id: a, config: { transport: 'command', command: 'npx -y @modelcontextprotocol/server-filesystem C:/data' } } as any);
  q.run(`delete from settings where key = 'aiCliPolicy'`);
  policy.upgradeCliPolicy();
  const p = policy.cliPolicy();
  assert.equal(p.allowed, false, 'off until an administrator approves');
  assert.deepEqual(p.commands, policy.DEFAULT_CLI_COMMANDS, 'nothing from the connections is trusted');
  assert.deepEqual(p.pending.map(x => x.command).sort(), ['"C:/Tools/AI Tools/codex.cmd"', 'npx -y @modelcontextprotocol/server-filesystem C:/data']);
  assert.ok(p.pending.every(x => x.found.length === 1 && /\(/.test(x.found[0])), 'each says where it was found');
  assert.throws(() => policy.checkCliCommand('AI provider', ['C:/Tools/AI Tools/codex.cmd', 'exec', '-'], true), /approves the commands found/);
  policy.upgradeCliPolicy();
  assert.deepEqual(policy.cliPolicy(), p, 'runs once: a saved policy is never changed again');
  // A developer cannot approve; an administrator approves one and dismisses the other.
  assert.equal((await call(dev, 'PUT', '/api/ai/cli-policy', { approve: ['"C:/Tools/AI Tools/codex.cmd"'] })).statusCode, 403);
  assert.equal((await call(admin, 'PUT', '/api/ai/cli-policy', { approve: ['not pending'] })).statusCode, 400);
  const after = (await call(admin, 'PUT', '/api/ai/cli-policy', { allowed: true, approve: ['"C:/Tools/AI Tools/codex.cmd"'], dismiss: ['npx -y @modelcontextprotocol/server-filesystem C:/data'] })).json();
  assert.deepEqual(after.pending, []);
  assert.ok(after.commands.includes('"C:/Tools/AI Tools/codex.cmd"'));
  assert.ok(!after.commands.some((c: string) => c.startsWith('npx')));
  assert.doesNotThrow(() => policy.checkCliCommand('AI provider', ['C:/Tools/AI Tools/codex.cmd', 'exec', '-'], true));
  assert.throws(() => policy.checkCliCommand('MCP server', ['npx', '-y', '@modelcontextprotocol/server-filesystem', 'C:/data'], false), /not one of the commands/);
});

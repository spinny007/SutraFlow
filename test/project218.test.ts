import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { testEnv, captureServer } from './helpers.js';

/**
 * Purpose: the 2.1.7 audit showed a developer of project A acting in project B by naming A in projectId and
 * B in project_id (F3), and changing B's connection or schema by sending its id to a create route (F4).
 * From 2.1.8 a request has one project, create makes a new item, and an update keeps the item's project.
 */
testEnv(24200);
const { boot } = await import('../server/src/index.js');
const { q } = await import('../server/src/db.js');
const projects = await import('../server/src/projects.js');
const { saveResource, getResource } = await import('../server/src/resources.js');
const schemas = await import('../server/src/schemas.js');
const flows = await import('../server/src/flows.js');

let srv: Awaited<ReturnType<typeof boot>>;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv.stop(); });

type Who = { cookie?: string };
const call = (who: Who, method: string, url: string, payload?: any) => srv.admin.inject({ method: method as any, url, payload, headers: { 'x-sutra': '1', ...(who.cookie ? { cookie: who.cookie } : {}) } });
const cookieOf = (r: any) => String(r.headers['set-cookie'] || '').split(';')[0];
const admin: Who = {}, dev: Who = {};
let a = '', b = '', bConn = '', bSchema = '', bFlow = '';
const B_KEY = 'synthetic-project-b-key-218';
const http = (name: string, extra: Record<string, any> = {}) => ({ kind: 'httpConnection', name, config: { baseUrl: 'http://127.0.0.1:9' }, ...extra });

test('setup: projects A and B, a developer granted only A, and B\'s connection, schema and Sutra', async () => {
  admin.cookie = cookieOf(await call({}, 'POST', '/api/auth/setup', { username: 'root', password: 'first-admin-pass-1' }));
  a = (await call(admin, 'POST', '/api/projects', { name: 'Alpha' })).json().id;
  b = (await call(admin, 'POST', '/api/projects', { name: 'Bravo' })).json().id;
  projects.storeProjectSecret(b, 'PRIVATE_KEY', B_KEY, true);
  bConn = saveResource({ ...http('B endpoint'), project_id: b } as any).id;
  bSchema = schemas.saveSchema({ project_id: b, name: 'B contract', kind: 'json', text: '{"type":"object"}' }).id;
  bFlow = flows.saveFlow(undefined, { name: 'B Sutra', nodes: [], edges: [] }, b).id;
  await call(admin, 'POST', '/api/access/users', { username: 'dev', password: 'temporary-pass-9', grants: [{ role: 'developer', project: a }] });
  const s = await call({}, 'POST', '/api/auth/login', { username: 'dev', password: 'temporary-pass-9' });
  dev.cookie = cookieOf(await call({ cookie: cookieOf(s) }, 'POST', '/api/auth/password', { current: 'temporary-pass-9', password: 'River-stone-88' }));
  assert.equal((await call(dev, 'GET', `/api/resources?projectId=${b}`)).statusCode, 403, 'control: B is closed to the developer');
});

test('F3: a request naming two different projects is refused, on every route that reads the project from the body', async () => {
  const before = q.get<any>('select count(*) n from resources where project_id = ?', b).n;
  const cap = await captureServer(() => ({ body: JSON.stringify({ data: [{ id: 'model-1' }] }) }));
  try {
    const both = { projectId: a, project_id: b };
    const cases: [string, any][] = [
      ['/api/resources', { ...http('Planted'), ...both }],
      ['/api/resources/test', { ...http('Probe'), ...both }],
      ['/api/resources/models', { kind: 'aiProvider', ...both, config: { engine: 'OpenAI API', baseUrl: cap.url, apiKeySecret: '{{gv.PRIVATE_KEY}}' } }],
      ['/api/resources/ai/resolve', { kind: 'aiProvider', ...both, config: { engine: 'OpenAI API', baseUrl: cap.url, apiKeySecret: '{{gv.PRIVATE_KEY}}' } }],
      ['/api/schemas', { name: 'Planted', kind: 'json', text: '{}', ...both }],
      ['/api/flows', { doc: { name: 'Planted', nodes: [], edges: [] }, ...both }],
      ['/api/design/query-preview', { ...both, connection: bConn, sql: 'select 1' }],
      ['/api/design/mapping-preview', { ...both }],
      ['/api/design/schema-from-sample', { ...both, sample: '{}' }],
    ];
    for (const [url, body] of cases) {
      const r = await call(dev, 'POST', url, body);
      assert.equal(r.statusCode, 400, `${url}: ${r.body}`);
      assert.match(r.json().error, /two different projects/, url);
      // The same with the names the other way round.
      assert.equal((await call(dev, 'POST', url, { ...body, projectId: b, project_id: a })).statusCode, 400, url);
    }
    assert.equal(cap.seen.length, 0, 'B\'s property never left the server');
    assert.equal(q.get<any>('select count(*) n from resources where project_id = ?', b).n, before, 'nothing was created in B');
    assert.equal((await call(dev, 'GET', `/api/schemas?projectId=${a}&project_id=${b}`)).statusCode, 400, 'a query naming two projects is refused too');
  } finally { await cap.close(); }
});

test('F3: one name, both names equal, and null or empty values settle to the same project', async () => {
  const ok1 = await call(dev, 'POST', '/api/resources', { ...http('One name'), project_id: a });
  assert.equal(ok1.statusCode, 200, ok1.body);
  const ok2 = await call(dev, 'POST', '/api/resources', { ...http('Both equal'), projectId: a, project_id: a });
  assert.equal(ok2.statusCode, 200, ok2.body);
  assert.equal(getResource(ok2.json().id)?.project_id, a);
  // projectId alone: the handler that reads project_id still works on A (both names are set to the settled one).
  const ok3 = await call(dev, 'POST', '/api/resources', { ...http('Other name'), projectId: a });
  assert.equal(ok3.statusCode, 200, ok3.body);
  assert.equal(getResource(ok3.json().id)?.project_id, a);
  // An empty name does not count as a second project.
  const ok4 = await call(dev, 'POST', '/api/resources', { ...http('Empty other'), projectId: a, project_id: '' });
  assert.equal(ok4.statusCode, 200, ok4.body);
  assert.equal(getResource(ok4.json().id)?.project_id, a);
  const ok5 = await call(dev, 'POST', '/api/resources', { ...http('Null other'), projectId: null, project_id: a });
  assert.equal(ok5.statusCode, 200, ok5.body);
  // B alone stays closed; no project at all is not a way round it.
  assert.equal((await call(dev, 'POST', '/api/resources', { ...http('Only B'), project_id: b })).statusCode, 403);
  assert.equal((await call(dev, 'POST', '/api/resources', { ...http('None') })).statusCode, 400);
  assert.equal((await call(dev, 'POST', '/api/schemas', { name: 'None', kind: 'json', text: '{}' })).statusCode, 400);
  // A Sutra without a project goes to the default project (the least recently changed): make that B.
  const pa = projects.getProject(a)!;
  projects.saveProject({ id: a, name: pa.name, description: pa.description, config: pa.config });
  for (const p of projects.listProjects()) if (p.id !== a && p.id !== b) projects.saveProject({ id: p.id, name: p.name, description: p.description, config: p.config });
  assert.equal(projects.ensureDefaultProject(), b);
  const noProjectFlow = await call(dev, 'POST', '/api/flows', { doc: { name: 'Default project Sutra', nodes: [], edges: [] } });
  assert.equal(noProjectFlow.statusCode, 403, 'the developer cannot design in the default project, so no Sutra is created there');
  assert.equal(flows.listFlows(b).some((f: any) => f.name === 'Default project Sutra'), false);
});

test('F4: a create route sent another item\'s id is refused, and B\'s item is unchanged', async () => {
  const conn = await call(dev, 'POST', '/api/resources', { ...http('Taken over'), id: bConn, project_id: a, config: { baseUrl: 'http://attacker.invalid' } });
  assert.equal(conn.statusCode, 409, conn.body);
  assert.equal(getResource(bConn)?.name, 'B endpoint');
  assert.equal(getResource(bConn)?.config.baseUrl, 'http://127.0.0.1:9');
  const sch = await call(dev, 'POST', '/api/schemas', { id: bSchema, project_id: a, name: 'Taken over', kind: 'json', text: '{"type":"string"}' });
  assert.equal(sch.statusCode, 409, sch.body);
  assert.equal(schemas.getSchema(bSchema)?.name, 'B contract');
  assert.equal(schemas.getSchema(bSchema)?.text, '{"type":"object"}');
  // Even an administrator's create does not replace by id: the item's own address is the way to change it.
  assert.equal((await call(admin, 'POST', '/api/resources', { ...http('Admin create'), id: bConn, project_id: b })).statusCode, 409);
  // A new client-chosen id still creates.
  const fresh = await call(dev, 'POST', '/api/schemas', { id: 'client-chosen-schema-218', project_id: a, name: 'A contract', kind: 'json', text: '{}' });
  assert.equal(fresh.statusCode, 200, fresh.body);
});

test('F4: an update keeps its project; a body naming another project is refused', async () => {
  const mine = (await call(dev, 'POST', '/api/resources', { ...http('Mine'), project_id: a })).json();
  const moved = await call(admin, 'PUT', `/api/resources/${mine.id}`, { ...mine, project_id: b });
  assert.equal(moved.statusCode, 400, moved.body);
  assert.equal(getResource(mine.id)?.project_id, a);
  const renamed = await call(dev, 'PUT', `/api/resources/${mine.id}`, { ...mine, name: 'Mine renamed' });
  assert.equal(renamed.statusCode, 200, renamed.body);
  assert.equal(getResource(mine.id)?.name, 'Mine renamed');
  assert.equal(getResource(mine.id)?.project_id, a);
  // A body without a project keeps the stored one.
  const { project_id: _p, ...noProject } = mine;
  assert.equal((await call(dev, 'PUT', `/api/resources/${mine.id}`, { ...noProject, name: 'Mine again' })).statusCode, 200);
  assert.equal(getResource(mine.id)?.project_id, a);

  const s = (await call(dev, 'POST', '/api/schemas', { project_id: a, name: 'A update', kind: 'json', text: '{}' })).json();
  assert.equal((await call(admin, 'PUT', `/api/schemas/${s.id}`, { ...s, project_id: b })).statusCode, 400);
  assert.equal((await call(dev, 'PUT', `/api/schemas/${s.id}`, { ...s, project_id: a, text: '{"type":"object"}' })).statusCode, 200);
  assert.equal(schemas.getSchema(s.id)?.project_id, a);

  const f = (await call(dev, 'POST', '/api/flows', { doc: { name: 'A Sutra', nodes: [], edges: [] }, projectId: a })).json();
  assert.equal((await call(admin, 'PUT', `/api/flows/${f.id}`, { ...f.doc, projectId: b })).statusCode, 400);
  assert.equal((await call(dev, 'PUT', `/api/flows/${f.id}`, { ...f.doc, name: 'A Sutra renamed' })).statusCode, 200);
  assert.equal(flows.getFlow(f.id)?.project_id, a);
  assert.equal((await call(dev, 'PUT', `/api/flows/${bFlow}`, { name: 'Taken over', nodes: [], edges: [] })).statusCode, 403, 'B\'s Sutra stays closed');
});

test('the save helpers themselves never move an existing item to another project (imports, Git, config apply)', () => {
  assert.throws(() => saveResource({ ...http('Moved'), id: bConn, project_id: a } as any), /belongs to another project/);
  assert.throws(() => schemas.saveSchema({ id: bSchema, project_id: a, name: 'Moved', kind: 'json', text: '{}' }), /belongs to another project/);
  assert.throws(() => flows.saveFlow(bFlow, { name: 'Moved', nodes: [], edges: [] }, a), /belongs to another project/);
  assert.equal(getResource(bConn)?.project_id, b);
  // Saving in the same project is unchanged.
  assert.equal(saveResource({ ...http('B endpoint'), id: bConn, project_id: b } as any).project_id, b);
});

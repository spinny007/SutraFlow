import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { testEnv, node, edge } from './helpers.js';

testEnv(23760);
const { boot } = await import('../server/src/index.js');
const { engine } = await import('../server/src/engine/engine.js');
const { q } = await import('../server/src/db.js');
const flows = await import('../server/src/flows.js');
const projects = await import('../server/src/projects.js');
const trace = await import('../server/src/trace.js');
const { startedByCaller } = await import('../server/src/security/inbound.js');

let srv: any;
before(async () => { srv = await boot({ listenAdmin: false, gateway: false }); });
after(async () => { await srv?.stop(); });
const all = () => true;

test('traceability: Sutras by run outcome per project, runs found by a value in their input or by who started them, and who started each run', async () => {
  const p = projects.saveProject({ name: 'Trace' });
  const s = node('start', 'Start', { payload: '{}' }), m = node('jsonata', 'Check', { source: '{{input}}', expression: '$.fail ? $error("no stock") : { "order": orderId }' });
  const f = flows.saveFlow(undefined, { name: 'Orders', nodes: [s, m], edges: [edge(s, m)] }, p.id) as any;
  const go = async (input: any, startedBy: any) => { const id = await engine.startRun({ doc: f.doc ?? f, flowId: f.id, projectId: p.id, input, source: 'rest', startedBy }); await engine.waitFor(id, 20000); return id; };
  const ok = await go({ orderId: 'ORD-7781' }, startedByCaller({ method: 'jwt', subject: 'erp-system' }, '10.0.0.5'));
  const bad = await go({ orderId: 'ORD-9000', fail: true }, startedByCaller({ method: 'none', subject: 'anonymous' }, '10.0.0.9'));
  const mine = await go({ orderId: 'ORD-1' }, { kind: 'person', id: 'ana' });

  const proj = trace.traceProjects(all, 24).find(x => x.id === p.id)!;
  const sutra = proj.sutras.find(x => x.id === f.id)!;
  assert.deepEqual({ done: sutra.done, failed: sutra.failed }, { done: 2, failed: 1 });
  assert.ok(sutra.lastFailure, 'when it last failed');

  const byValue = trace.traceRuns(all, { projectId: p.id, text: 'ORD-7781' }).runs;
  assert.deepEqual(byValue.map(r => r.id), [ok], 'found by an order number in its input');
  assert.deepEqual(byValue[0].startedBy, { kind: 'client', id: 'erp-system', how: 'jwt', ip: '10.0.0.5' });
  assert.deepEqual(trace.traceRuns(all, { projectId: p.id, status: 'failed' }).runs.map(r => r.id), [bad]);
  assert.equal(trace.traceRuns(all, { projectId: p.id, status: 'failed' }).runs[0].startedBy.anonymous, true, 'a route without a policy: anonymous');
  assert.deepEqual(trace.traceRuns(all, { projectId: p.id, text: 'ana' }).runs.map(r => r.id), [mine], 'found by who started it');
  assert.deepEqual(trace.traceRuns(all, { projectId: p.id, text: ok.slice(0, 8) }).runs.map(r => r.id), [ok], 'found by the start of its id');
  assert.deepEqual(trace.traceRuns(all, { projectId: p.id, text: '%' }).runs, [], 'wildcards are taken literally');
  assert.deepEqual(trace.traceRuns(() => false, { projectId: p.id }).runs, [], 'only projects the caller may see');

  // Runs from before 2.1.0 have no record: their source says what kind of thing started them.
  q.run('update runs set started_by = null where id = ?', mine);
  assert.deepEqual(trace.startedByOf(null, 'timer'), { kind: 'system', id: 'timer', recorded: false });
  assert.equal(trace.traceRuns(all, { projectId: p.id, text: 'ORD-1"' }).runs[0]?.startedBy.recorded, false);
});

test('traceability: a run that called another (Call Sutra) links to it, and the called run back to its caller', async () => {
  const cs = node('start', 'Start', { payload: '{}' }), cr = node('return', 'Done', { source: 'value', value: '{"ok": true}' });
  const child = flows.saveFlow(undefined, { name: 'Child', nodes: [cs, cr], edges: [edge(cs, cr)] }) as any;
  const ps = node('start', 'Start', { payload: '{}' }), call = node('callProcess', 'Call child', { process: child.id, wait: true, source: 'value', input: '{}' });
  const parent = await engine.startRun({ doc: { name: 'Parent', nodes: [ps, call], edges: [edge(ps, call)] }, startedBy: { kind: 'person', id: 'ana' } });
  assert.equal(await engine.waitFor(parent, 20000), 'done');
  const links = trace.traceLinks(parent, all);
  assert.equal(links.children.length, 1);
  const childRun = links.children[0].id;
  assert.equal(trace.traceLinks(childRun, all).parent?.id, parent, 'the called run knows its caller');
  assert.deepEqual(JSON.parse(q.get<any>('select started_by from runs where id = ?', childRun).started_by), { kind: 'run', id: parent });
});

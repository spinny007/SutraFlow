/**
 * Time budgets follow the database. Locally an operation takes well under 50 ms; a database over the
 * internet needs 650 to 750 ms per operation, so when one small transaction takes over 100 ms every
 * budget (and how long a test step holds its place) is stretched 15 times (750 / 50). A slower local
 * store (PGlite while every suite runs) is stretched by its measured speed. An explicit
 * SUTRA_TEST_TIME_FACTOR wins.
 */
let SLOW = Math.max(1, Number(process.env.SUTRA_TEST_TIME_FACTOR) || 1);
const until = async (fn: () => boolean | Promise<boolean>, ms = 10000) => {
  const end = Date.now() + ms * SLOW;
  while (!(await fn())) { if (Date.now() > end) throw new Error('timed out'); await new Promise(r => setTimeout(r, 20)); }
};
let probes = 0;
/** A test activity selecting one connection of the given kind; it records the peak of steps at once. */
function probe(kind: string, ms = 60) {
  const type = `limitProbe${++probes}`;
  const seen = { active: 0, peak: 0, calls: 0 };
  engine.register([{ type, palette: 'test', name: 'Probe', glyph: '.', ports: ['out'], desc: 'Test only', fields: [{ k: 'connection', label: 'Connection', type: 'resource' as const, resourceKind: kind }],
    execute: async () => { seen.active++; seen.calls++; seen.peak = Math.max(seen.peak, seen.active); try { await new Promise(r => setTimeout(r, ms)); return { out: {} }; } finally { seen.active--; } } }] as any);
  return { type, seen };
}
const runAll = async (type: string, connection: string, n: number, o: { name?: string } = {}) => {
  const ids = await Promise.all(Array.from({ length: n }, () => {
    const s = node('start', 'Start', { payload: '{}' }), p = node(type, 'Probe', { connection });
    return engine.startRun({ projectId, doc: { name: o.name || 'Limit check', nodes: [s, p], edges: [edge(s, p)] } });
  }));
  await Promise.all(ids.map(id => engine.waitFor(id, 20000 * SLOW)));
  return ids;
};


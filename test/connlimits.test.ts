test('a lease whose renewals keep failing stops its work before it can run out', async () => {
  const real = asyncDatabase();
  const api = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'Renewal outage', config: { maxConcurrentTasks: 1 } });
  // Taking the lease works; every renewal afterwards fails, as when the engine database goes away.
  let broken = false;
  const flaky = new Proxy(real, { get: (t, k) => (k === 'run' ? (...a: any[]) => (broken ? Promise.reject(new Error('database is away')) : (t as any).run(...a)) : (t as any)[k]) }) as typeof real;
  const t0 = { ...lim.leaseTiming };
  lim.leaseTiming.leaseMs = 2000 * SLOW;
  try {
    const got = await lim.acquireLease(flaky, lim.closureLimits([api.id]), engine.id, 'Listener: outage');
    assert.ok('lease' in got);
    const expires = Number((await real.get<any>(`select expires_at from connection_permits where holder = 'Listener: outage'`)).expires_at);
    broken = true;
    await until(() => (got as any).lease.signal.aborted, 5000);
    assert.ok(Date.now() < expires, 'stopped before the lease could have run out in the database');
    assert.match(String((got as any).lease.signal.reason?.message), /could not be renewed in time/);
    broken = false; await (got as any).lease.release();
  } finally { Object.assign(lim.leaseTiming, t0); }
});

test('in memory and durable Sutras share one limit: an in-memory step takes a lease in the shared engine database and waits for room', async () => {
  // Before 2.1.1 an in-memory step on a limited connection was refused. Now it runs within the same
  // cluster-wide limit as durable steps, counted as a lease (renewed, expiring if its engine stops).
  const db = saveResource({ project_id: projectId, kind: 'database', name: 'Memory DB', config: { driver: 'postgres', host: 'db.invalid', maxConcurrentTasks: 1 } });
  const mem = saveResource({ project_id: projectId, kind: 'aiMemory', name: 'Chats', config: { store: 'database', database: db.id } });
  const { type, seen } = probe('aiMemory', 120);
  const s = node('start', 'Start', { payload: '{}' }), p = node(type, 'Probe', { connection: mem.id });
  const f = saveFlow(undefined, { name: 'In memory with a limit', nodes: [s, p], edges: [edge(s, p)] }, projectId);
  deploy(f.id); setSutraTuning(f.id, { execution: 'in memory' });
  const d = deployedFlows().find(x => x.flowId === f.id)!;
  const memoryRuns = Array.from({ length: 3 }, () => new Promise<string>((resolve, reject) => {
    engine.startRun({ doc: d.doc, flowId: f.id, projectId, version: d.version, source: 'api', onFinish: st => resolve(st) }).catch(reject);
  }));
  let leaseSeen = false;
  const watch = setInterval(() => { if (q.get<any>(`select 1 from connection_permits where kind = 'lease' and holder like 'In-memory step%'`)) leaseSeen = true; }, 10);
  const durable = runAll(type, mem.id, 3, { name: 'Durable beside memory' });
  try {
    assert.deepEqual(await Promise.all(memoryRuns), ['done', 'done', 'done'], 'the in-memory runs finish');
    for (const id of await durable) assert.equal(q.get<any>('select status from runs where id=?', id).status, 'done');
  } finally { clearInterval(watch); }
  assert.equal(seen.calls, 6);
  assert.equal(seen.peak, 1, 'memory and durable steps together never went over the limit of 1');
  assert.ok(leaseSeen, 'the in-memory step held a lease in the shared engine database');
  // The lease goes back as the step's work ends, a moment after the run reports it finished.
  await until(() => Number(q.get<any>(`select count(*) n from connection_permits where kind = 'lease' and holder like 'In-memory step%'`).n) === 0);
});

test('leases: a listener poll or background job shares the limit with steps, and is renewed, released or lost', async () => {
  const db = asyncDatabase();
  const ftp = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'Inbox', config: { maxConcurrentTasks: 1 } });
  const caps = lim.closureLimits([ftp.id]);
  const first = await lim.acquireLease(db, caps, engine.id, 'Listener: poll A');
  assert.ok('lease' in first);
  const second = await lim.acquireLease(db, caps, engine.id, 'Listener: poll B');
  assert.ok('blocked' in second); assert.match((second as any).blocked, /Waiting for Inbox: 1 of 1 in use/);
  const use = await lim.connectionUse(db, [ftp as any]);
  assert.deepEqual([use[0].active, use[0].leases, use[0].holders[0].holder], [1, 1, 'Listener: poll A']);
  await (first as any).lease.release();
  assert.ok('lease' in await lim.acquireLease(db, caps, engine.id, 'Listener: poll C').then(async r => { if ('lease' in r) await r.lease.release(); return r; }));

  // Renewed while held; an expired lease (a crashed engine) frees the place; a lost lease aborts its work.
  const t0 = { ...lim.leaseTiming };
  lim.leaseTiming.leaseMs = 400 * SLOW;
  try {
    const held = await lim.acquireLease(db, caps, engine.id, 'Listener: long poll');
    assert.ok('lease' in held);
    await new Promise(r => setTimeout(r, 900 * SLOW));
    assert.ok('blocked' in await lim.acquireLease(db, caps, engine.id, 'x'), 'renewal kept the lease alive past its length');
    await db.run(`delete from connection_permits where holder = 'Listener: long poll'`);
    await until(() => (held as any).lease.signal.aborted, 3000);
    await (held as any).lease.release();
    await db.run(`insert into connection_permits(resource_id, task_id, owner, claim, kind, holder, since, expires_at) values(?, -42, 'crashed-engine', 0, 'lease', 'Listener: crashed', ?, ?)`, ftp.id, Date.now(), Date.now() - 1);
    const after = await lim.acquireLease(db, caps, engine.id, 'Listener: after crash');
    assert.ok('lease' in after, 'an expired lease no longer counts'); await (after as any).lease.release();
  } finally { Object.assign(lim.leaseTiming, t0); }
});

test('a poll with no room is skipped and the trigger says why; with room again it runs', async () => {
  const db = asyncDatabase();
  const imap = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'Mailbox', config: { maxConcurrentTasks: 1 } });
  const fields = [{ k: 'connection', type: 'resource', showIf: { k: 'mode', in: ['poll'] } }, { k: 'other', type: 'resource' }];
  assert.deepEqual(selectedConnections(fields, { mode: 'poll', connection: imap.id, other: '' }), [imap.id]);
  assert.deepEqual(selectedConnections(fields, { mode: 'push', connection: imap.id }), [], 'a hidden setting is not counted');
  const blocker = await lim.acquireLease(db, lim.closureLimits([imap.id]), engine.id, 'Busy');
  let ran = 0, reason = '';
  assert.equal(await lim.withConnectionLease(db, [imap.id], engine.id, 'Listener: mail', async () => { ran++; return 1; }, { onBlocked: r => { reason = r; } }), undefined);
  assert.equal(ran, 0); assert.match(reason, /Waiting for Mailbox: 1 of 1 in use/);
  // Background work waits a while before giving up (generous): the place frees during the wait.
  setTimeout(() => { if ('lease' in blocker) blocker.lease.release(); }, 300 * SLOW);
  const t0 = lim.leaseTiming.retryMs; lim.leaseTiming.retryMs = 50;
  try { assert.equal(await lim.withConnectionLease(db, [imap.id], engine.id, 'Memory table refresh: Rates', async () => { ran++; return 2; }, { waitMs: 5000 * SLOW }), 2); }
  finally { lim.leaseTiming.retryMs = t0; }
  assert.equal(ran, 1);
});

test('a waiting step keeps its place, says why, backs off, and its timeout starts only when it runs', async () => {
  const api = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'Slow API', config: { maxConcurrentTasks: 1 } });
  const slow = probe('httpConnection', 600 * SLOW);
  const s = node('start', 'Start', { payload: '{}' });
  const p = { ...node(slow.type, 'Probe', { connection: api.id }), settings: { timeoutMs: 450 } };
  const doc = { name: 'Patient', nodes: [s, p], edges: [edge(s, p)] };
  // The first holds the place for 600 ms; the others wait longer than their own 450 ms timeout.
  const longer = { ...p, settings: {} };
  const holder = await engine.startRun({ projectId, doc: { ...doc, nodes: [s, longer], edges: [edge(s, longer)] } });
  await until(() => slow.seen.active === 1);
  const fast = probe('httpConnection', 50);
  const p2 = { ...node(fast.type, 'Quick', { connection: api.id }), settings: { timeoutMs: 450 } };
  const waiting = await engine.startRun({ projectId, doc: { name: 'Patient', nodes: [s, p2], edges: [edge(s, p2)] } });
  await until(async () => !!(await asyncDatabase().get(`select 1 from connection_waits w join tasks t on t.id = w.task_id where t.run_id = ?`, waiting)));
  const w = await asyncDatabase().get<any>(`select w.reason, w.checks from connection_waits w join tasks t on t.id = w.task_id where t.run_id = ?`, waiting);
  assert.match(w.reason, /Waiting for Slow API: 1 of 1 in use/);
  const use = await lim.connectionUse(asyncDatabase(), [api as any]);
  assert.equal(use[0].waiting, 1); assert.equal(use[0].waits[0].sutra, 'Patient');
  await engine.waitFor(holder, 10000 * SLOW); await engine.waitFor(waiting, 10000 * SLOW);
  assert.equal(q.get<any>('select status from runs where id=?', waiting).status, 'done', 'the wait did not count against its 450 ms timeout');
  assert.equal(await asyncDatabase().get(`select 1 from connection_waits w join tasks t on t.id = w.task_id where t.run_id = ?`, waiting), undefined, 'the wait record goes when it runs');
});

test('a step being re-checked keeps its wait record and still counts as waiting', async () => {
  const db = asyncDatabase();
  const api = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'Rechecked', config: { maxConcurrentTasks: 1 } });
  // A re-check claims the waiting step, so for that moment its task is running (no owner: not an orphan).
  await db.run(`insert into tasks(run_id, node_id, input, status, not_before, priority, queued_at) values('recheck-run', 'n', null, 'running', 0, 0, ?)`, Date.now());
  const task = await db.get<any>(`select id from tasks where run_id = 'recheck-run'`);
  await db.run(`insert into connection_waits(task_id, resource_id, reason, since, checks) values(?, ?, 'Waiting for Rechecked: 1 of 1 in use', ?, 4)`, task.id, api.id, Date.now() - 60000);
  await lim.sweepConnections(db);
  assert.equal(Number((await db.get<any>('select checks from connection_waits where task_id = ?', task.id))?.checks), 4, 'the backoff count survives the re-check');
  assert.equal((await lim.connectionUse(db, [api as any]))[0].waiting, 1, 'the Admin Console still shows it waiting');
  await db.run(`update tasks set status = 'done' where id = ?`, task.id);
  await lim.sweepConnections(db);
  assert.equal(await db.get('select 1 from connection_waits where task_id = ?', task.id), undefined, 'a step that left the queue loses its record');
  await db.run('delete from tasks where id = ?', task.id);
});

test('a place that frees goes to a waiting step at once, not after its pause', async () => {
  const api = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'One at a time', config: { maxConcurrentTasks: 1 } });
  const holder = probe('httpConnection', 400 * SLOW), next = probe('httpConnection', 10);
  let nextStarted = 0;
  const watch = setInterval(() => { if (!nextStarted && next.seen.calls) nextStarted = Date.now(); }, 5);
  const s = node('start', 'Start', { payload: '{}' });
  const h = node(holder.type, 'Holder', { connection: api.id }), n = node(next.type, 'Next', { connection: api.id });
  const first = await engine.startRun({ projectId, doc: { name: 'Holder', nodes: [s, h], edges: [edge(s, h)] } });
  await until(() => holder.seen.active === 1);
  const second = await engine.startRun({ projectId, doc: { name: 'Next', nodes: [s, n], edges: [edge(s, n)] } });
  await until(async () => !!(await asyncDatabase().get(`select 1 from connection_waits w join tasks t on t.id = w.task_id where t.run_id = ?`, second)));
  // As if it had waited long: its next check is 5 s away (stretched with the budgets).
  await asyncDatabase().run(`update tasks set not_before = ? where run_id = ? and status = 'pending'`, Date.now() + 5000 * SLOW, second);
  await engine.waitFor(first, 10000 * SLOW);
  const freed = Date.now();
  await engine.waitFor(second, 10000 * SLOW);
  clearInterval(watch);
  assert.equal(q.get<any>('select status from runs where id=?', second).status, 'done');
  assert.ok(nextStarted - freed < 1500 * SLOW, `the waiting step started ${nextStarted - freed} ms after the place was freed; it must be woken, not wait out its 5 s pause`);
});


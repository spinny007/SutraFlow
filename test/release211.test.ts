  reply.config.result = '=object(\'quantity\', 2)';
  const good = await engine.startRun({ doc, projectId, input: { arguments: {} } }); await engine.waitFor(good, 10000); assert.equal(q.get<any>('select status from runs where id=?', good).status, 'done');

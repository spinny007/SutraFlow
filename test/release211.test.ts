test('SOAP strict request/response use actual operation XML; invalid requests never reach the endpoint', async () => {
  const xsd = saveSchema({ project_id: projectId, name: 'SOAP operation', kind: 'xsd', text: '<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema"><xs:element name="Quantity" type="xs:int"/></xs:schema>' }).id;
  const endpoint = await captureServer(() => ({ status: 200, headers: { 'content-type': 'text/xml' }, body: '<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/"><s:Body><Quantity>bad</Quantity></s:Body></s:Envelope>' }));
  try {
    const cfg = { mode: 'raw envelope', endpoint: endpoint.url, bodyXml: '<Quantity>bad</Quantity>', argsSchema: xsd, validateRequest: true, responseSchema: xsd, validateResponse: true };
    assert.equal((await run('soapInvoke', cfg)).status, 'failed'); assert.equal(endpoint.seen.length, 0);
    assert.equal((await run('soapInvoke', { ...cfg, bodyXml: '<Quantity>2</Quantity>' })).status, 'failed'); assert.equal(endpoint.seen.length, 1);
    assert.equal((await run('soapInvoke', { ...cfg, bodyXml: '<Quantity>2</Quantity>', validateResponse: false })).status, 'done');
  } finally { await endpoint.close(); }
  const responseXsd = saveSchema({ project_id: projectId, name: 'Reply operation', kind: 'xsd', text: '<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" targetNamespace="urn:sutra"><xs:element name="QuantityResponse" type="xs:int"/></xs:schema>' }).id;
  const starter = node('soapService', 'SOAP ingress', { namespace: 'urn:sutra' });
  const reply = node('soapReply', 'SOAP reply', { kind: 'response', bodySource: 'template', body: '"bad"', bodySchema: responseXsd, validateSchema: true });
  const doc = { name: 'SOAP reply contract', nodes: [starter, reply], edges: [edge(starter, reply)] };
  const bad = await engine.startRun({ projectId, doc, input: { operation: 'Quantity', body: {} } }); await engine.waitFor(bad, 10000);
  assert.equal(q.get<any>('select status from runs where id=?', bad).status, 'failed');
  reply.config.body = '2';
  const good = await engine.startRun({ projectId, doc, input: { operation: 'Quantity', body: {} } }); await engine.waitFor(good, 10000);
  assert.equal(q.get<any>('select status from runs where id=?', good).status, 'done');
});
test('connection cap is shared by two schedulers, queues excess work and permits another connection', async () => {
  const connection = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'Limited', config: { maxConcurrentTasks: 1 } });
  const other = saveResource({ project_id: projectId, kind: 'httpConnection', name: 'Other', config: { maxConcurrentTasks: 1 } });
  let active = 0, peak = 0, calls = 0;
  const probe = { type: 'capProbe', palette: 'test', name: 'Probe', glyph: '.', ports: ['out'], desc: 'Test only', fields: [{ k: 'connection', label: 'Connection', type: 'resource' as const, resourceKind: 'httpConnection' }], execute: async (c: any) => {
    const limited = c.raw('connection') === connection.id; if (limited) { active++; peak = Math.max(peak, active); }
    calls++; try { await new Promise(r => setTimeout(r, 35)); return { out: {} }; } finally { if (limited) active--; }
  } };
  engine.register([probe]); const previousId = config.engineId; config.engineId = '211-peer'; const peer = new Engine(); config.engineId = previousId;
  peer.register(engine.allActivities()); peer.concurrency = 4; await peer.start();
  // The peer heartbeats like a real engine; otherwise the leader recovers its running steps as orphans
  // and runs them again (at-least-once for a dead engine), which this test would see as an overlap.
  const beat = () => q.run(`insert into engines(id, host, pid, mode, version, started_at, heartbeat_at, workers, active, draining, can_lead) values('211-peer', 'test', 0, 'engine', 'test', ?, ?, 4, 0, 0, 0)
    on conflict(id) do update set heartbeat_at = excluded.heartbeat_at`, new Date().toISOString(), Date.now());
  beat(); const beating = setInterval(beat, 200);
  try {
    const ids = await Promise.all(Array.from({ length: 9 }, async (_, i) => {
      const s = node('start', 'Start', { payload: '{}' }), p = node('capProbe', 'Probe', { connection: i === 8 ? other.id : connection.id });
      return engine.startRun({ projectId, doc: { name: 'Cap check', nodes: [s, p], edges: [edge(s, p)] } });
    }));
    await Promise.all(ids.map(id => engine.waitFor(id, 10000)));
    for (const id of ids) assert.equal(q.get<any>('select status from runs where id=?', id).status, 'done');
    assert.equal(peak, 1); assert.equal(calls, 9);
    assert.equal(Number(q.get<any>(`select count(*) n from tasks where run_id in (${ids.map(() => '?').join(',')}) and attempt<>0`, ...ids).n), 0, 'queueing does not consume retry attempts');
  } finally { clearInterval(beating); await peer.drain(1000); peer.stop(); q.run(`delete from engines where id = '211-peer'`); }
});
test('stale permits are fenced and recovered, and invalid connection limits are refused', async () => {
  for (const cap of [-1, 1.5, true, 'wrong']) assert.throws(() => saveResource({ kind: 'httpConnection', name: 'Invalid cap', config: { maxConcurrentTasks: cap } }), /integer/);
  const s = node('start', 'Start', { payload: '{}' }); const id = await engine.startRun({ projectId, doc: { name: 'Recovery', nodes: [s], edges: [] } }); await engine.waitFor(id, 10000);
  const waitingId = await engine.startRun({ projectId, doc: { name: 'Atomic admission', nodes: [s], edges: [] } }); await engine.waitFor(waitingId, 10000);
  const waiting = q.get<any>('select * from tasks where run_id=?', waitingId);
  const task = q.get<any>('select * from tasks where run_id=?', id);
  q.run('insert into connection_permits(resource_id,task_id,owner,claim) values(?,?,?,?)', 'recovered', task.id, 'dead-engine', 1);
  q.run(`update runs set status='running',finished_at=null where id=?`, id);
  q.run(`update tasks set status='running',owner=?,claim=2 where id=?`, engine.id, task.id);
  assert.equal(await admitConnections(asyncDatabase(), { ...task, claim: 1 }, 'dead-engine', [{ id: 'recovered', limit: 1 }], 100), false);
  assert.equal(await admitConnections(asyncDatabase(), { ...task, claim: 2 }, engine.id, [{ id: 'recovered', limit: 1 }], 100), true);
  assert.equal(Number(q.get<any>('select count(*) n from connection_permits where resource_id=?', 'recovered').n), 1);
  q.run(`update runs set status='running',finished_at=null where id=?`, waitingId);
  q.run(`update tasks set status='running',owner=?,claim=2 where id=?`, engine.id, waiting.id);
  assert.equal(await admitConnections(asyncDatabase(), { ...waiting, claim: 2 }, engine.id, [{ id: 'free', limit: 1 }, { id: 'recovered', limit: 1 }], 100), false);
  assert.equal(Number(q.get<any>('select count(*) n from connection_permits where task_id=?', waiting.id).n), 0, 'blocked multi-resource admission reserves no partial permit');
  assert.equal(q.get<any>('select status from tasks where id=?', waiting.id).status, 'pending');
  q.run(`update tasks set status='done' where id=?`, waiting.id);
  q.run(`update runs set status='done' where id=?`, waitingId);
  q.run(`update tasks set status='done' where id=?`, task.id);
  q.run(`update runs set status='done' where id=?`, id);
});

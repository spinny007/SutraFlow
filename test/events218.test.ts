import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { testEnv, node } from './helpers.js';

/**
 * Purpose: the 2.1.7 audit showed a developer of project A seeing B's schema fields through the designer's
 * shape preview (F5), and B's run ids and statuses on the live event stream (F6). From 2.1.8 the preview reads
 * only the request's project, and each event goes only to someone who may see that run when it is sent.
 */
testEnv(24210);
const { boot } = await import('../server/src/index.js');
const { engine } = await import('../server/src/engine/engine.js');
const { q } = await import('../server/src/db.js');
const schemas = await import('../server/src/schemas.js');
const flows = await import('../server/src/flows.js');

let srv: Awaited<ReturnType<typeof boot>>;
let base = '';
before(async () => {
  srv = await boot({ listenAdmin: false, gateway: false });
  await srv.admin.listen({ port: 0, host: '127.0.0.1' });
  base = `http://127.0.0.1:${(srv.admin.server.address() as any).port}`;
});
after(async () => { await srv.stop(); });

type Who = { cookie?: string };
const call = (who: Who, method: string, url: string, payload?: any) => srv.admin.inject({ method: method as any, url, payload, headers: { 'x-sutra': '1', ...(who.cookie ? { cookie: who.cookie } : {}) } });
const cookieOf = (r: any) => String(r.headers['set-cookie'] || '').split(';')[0];
const admin: Who = {}, dev: Who = {};
let a = '', b = '', bSchema = '', bFlow = '';

/** Opens the live event stream as a person and collects the run ids it receives. */
function stream(who: Who) {
  const seen: string[] = [];
  let req!: http.ClientRequest;
  const ready = new Promise<void>((resolve, reject) => {
    req = http.get(`${base}/api/events`, { headers: { cookie: who.cookie!, 'x-sutra': '1' } }, res => {
      res.setEncoding('utf8');
      res.on('data', (chunk: string) => {
        if (chunk.includes(': connected')) resolve();
        for (const m of chunk.matchAll(/^data: (.*)$/gm)) seen.push(JSON.parse(m[1]).runId);
      });
    });
    req.on('error', reject);
  });
  return { seen, ready, close: () => req.destroy() };
}
/** A finished run row of a project, announced to the event listeners as the engine does. */
const announce = (projectId: string, source = 'manual') => {
  const id = `run-${Math.random().toString(36).slice(2)}`;
  q.run(`insert into runs(id, flow_id, flow_name, version, doc, status, source, state, steps, started_at, project_id) values(?, null, 'Probe', 0, '{}', 'completed', ?, '{}', 0, ?, ?)`, id, source, new Date().toISOString(), projectId);
  for (const fn of engine.listeners) fn(id);
  return id;
};
const settle = () => new Promise(r => setTimeout(r, 150));

test('setup: projects A and B, a developer granted only A, and B\'s schema and Sutra', async () => {
  admin.cookie = cookieOf(await call({}, 'POST', '/api/auth/setup', { username: 'root', password: 'first-admin-pass-1' }));
  a = (await call(admin, 'POST', '/api/projects', { name: 'Alpha' })).json().id;
  b = (await call(admin, 'POST', '/api/projects', { name: 'Bravo' })).json().id;
  bSchema = schemas.saveSchema({ project_id: b, name: 'B order', kind: 'json', text: '{"type":"object","properties":{"bSecretField":{"type":"string"}}}' }).id;
  const start = node('start', 'Start', { schema: bSchema });
  bFlow = flows.saveFlow(undefined, { name: 'B callee', nodes: [start], edges: [] }, b).id;
  await call(admin, 'POST', '/api/access/users', { username: 'dev', password: 'temporary-pass-9', grants: [{ role: 'developer', project: a }] });
  const s = await call({}, 'POST', '/api/auth/login', { username: 'dev', password: 'temporary-pass-9' });
  dev.cookie = cookieOf(await call({ cookie: cookieOf(s) }, 'POST', '/api/auth/password', { current: 'temporary-pass-9', password: 'River-stone-88' }));
  assert.equal((await call(dev, 'GET', `/api/schemas/${bSchema}`)).statusCode, 403, 'control: B\'s schema is closed to the developer');
});

test('F5: the shape preview needs a project, and never shows another project\'s schema or called Sutra', async () => {
  const doc = { name: 'Probe', nodes: [node('start', 'Start', { schema: bSchema })], edges: [] };
  assert.equal((await call(dev, 'POST', '/api/design/schemas', { doc })).statusCode, 400, 'no project');
  assert.equal((await call(dev, 'POST', '/api/design/schemas', { doc, projectId: b })).statusCode, 403, 'B itself');
  const r = await call(dev, 'POST', '/api/design/schemas', { doc, projectId: a });
  assert.equal(r.statusCode, 200, r.body);
  assert.ok(!r.body.includes('bSecretField'), 'B\'s field names are not shown');
  assert.match(r.body, /belongs to another project/);
  const call2 = { name: 'Caller', nodes: [node('callProcess', 'Call B', { process: bFlow, inputContract: true })], edges: [] };
  const c = await call(dev, 'POST', '/api/design/schemas', { doc: call2, projectId: a });
  assert.equal(c.statusCode, 200, c.body);
  assert.ok(!c.body.includes('bSecretField') && !c.body.includes('B order'), 'the called Sutra\'s contract is not read');
  assert.match(c.body, /belongs to another project/);
  // The owner of B still gets the shape.
  const own = await call(admin, 'POST', '/api/design/schemas', { doc, projectId: b });
  assert.ok(own.body.includes('bSecretField'), own.body);
});

test('F6: the live stream sends A\'s events to A\'s developer, not B\'s; design runs need Design', async () => {
  const s = stream(dev), all = stream(admin);
  await Promise.all([s.ready, all.ready]);
  try {
    const ra = announce(a), rb = announce(b), rt = announce(a, 'test');
    await settle();
    assert.ok(s.seen.includes(ra), 'A\'s run');
    assert.ok(!s.seen.includes(rb), 'not B\'s run');
    assert.ok(s.seen.includes(rt), 'a developer has Design on A, so sees A\'s test runs');
    assert.ok(all.seen.includes(rb) && all.seen.includes(ra), 'an administrator sees both');
  } finally { s.close(); all.close(); }
});

test('F6: access taken away while the stream is open stops the events at once', async () => {
  // Grant B too, open the stream, then take B away again without closing it.
  assert.equal((await call(admin, 'PUT', '/api/access/users/dev', { grants: [{ role: 'developer', project: a }, { role: 'developer', project: b }] })).statusCode, 200);
  const s = stream(dev);
  await s.ready;
  try {
    const before = announce(b);
    await settle();
    assert.ok(s.seen.includes(before), 'while granted, B\'s run is sent');
    assert.equal((await call(admin, 'PUT', '/api/access/users/dev', { grants: [{ role: 'developer', project: a }] })).statusCode, 200);
    const afterId = announce(b);
    await settle();
    assert.ok(!s.seen.includes(afterId), 'after the grant is removed, B\'s run is not sent on the open stream');
  } finally { s.close(); }
});

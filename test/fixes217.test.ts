import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { testEnv, node, edge } from './helpers.js';
testEnv(23402);
const { boot } = await import('../server/src/index.js');
const { engine } = await import('../server/src/engine/engine.js');
const { q } = await import('../server/src/db.js');
const { saveProject } = await import('../server/src/projects.js');
const { saveResource } = await import('../server/src/resources.js');
const { saveFlow, getFlow, deploy } = await import('../server/src/flows.js');
const { addSamples } = await import('../server/src/samples.js');
const { sampleInstallHint } = await import('../server/src/sample-hints.js');

let srv: Awaited<ReturnType<typeof boot>>, projectId: string, cookie = '';
before(async () => {
  srv = await boot({ listenAdmin: false, gateway: false });
  projectId = saveProject({ name: 'Fixes 2.1.7', config: { variables: [] } }).id;
  const setup = await srv.admin.inject({ method: 'POST', url: '/api/auth/setup', payload: { username: 'fixes-admin', password: crypto.randomBytes(18).toString('base64url') }, headers: { 'x-sutra': '1' } });
  cookie = String(setup.headers['set-cookie']).split(';')[0];
});
after(async () => { await srv.stop(); });
const api = (url: string) => srv.admin.inject({ method: 'GET', url, headers: { 'x-sutra': '1', cookie } }).then(r => r.json());

test('a Dashboard page trigger: not deployed, then a link to its page, and a note when the draft changes its name', async () => {
  const page = node('dashboardPage', 'Sales page', { name: 'sales-fix', title: 'Sales', policy: '', refreshSeconds: 60, cachePer: 'everyone', columns: 2 });
  const reply = node('dashboardReply', 'Reply', { note: '', charts: [] });
  const f = saveFlow(undefined, { name: 'Page link', nodes: [page, reply], edges: [edge(page, reply)] }, projectId);
  const before = await api(`/api/flows/${f.id}/page-link?node=${page.id}`);
  assert.equal(before.deployed, false);
  assert.equal(before.draftName, 'sales-fix');
  deploy(f.id);
  const after = await api(`/api/flows/${f.id}/page-link?node=${page.id}`);
  assert.equal(after.deployed, true);
  assert.equal(after.version, 1);
  assert.match(after.url, /^http:\/\/[^/]+:\d+\/dash\/sales-fix$/, 'the gateway address of the page');
  const draft = getFlow(f.id)!.doc;
  draft.nodes[0].config.name = 'sales-new';
  saveFlow(f.id, draft, projectId);
  const renamed = await api(`/api/flows/${f.id}/page-link?node=${page.id}`);
  assert.equal(renamed.name, 'sales-fix', 'the deployed page stays where it is');
  assert.equal(renamed.draftName, 'sales-new', 'the designer says to deploy again');
});

test('missing sample data: the error names the install Sutra of the project that makes it', async () => {
  addSamples(projectId, ['dashboarddb']);
  assert.equal(sampleInstallHint(projectId, "Table 'sample_sutraflow.sample_sales_orders' doesn't exist"), " Run 'Sample: Sales orders install' first: it makes sample_sutraflow.");
  assert.equal(sampleInstallHint(projectId, "Unknown database 'sample_sutraflow'"), " Run 'Sample: Sales orders install' first: it makes sample_sutraflow.");
  assert.equal(sampleInstallHint(projectId, 'no such table: orders', 'SELECT * FROM orders'), '', 'not sample data: no hint');
  assert.equal(sampleInstallHint(projectId, 'syntax error near FROM', 'SELECT * FROM sample_sutraflow.sample_sales_orders'), '', 'another error: no hint');
  assert.equal(sampleInstallHint(projectId, 'no such table: sample_other'), '', 'no install Sutra makes it: no hint');
  assert.equal(sampleInstallHint(null, "Table 'sample_sutraflow.sample_sales_orders' doesn't exist"), '');
});

test('a SQL query step on a missing sample table fails with the hint (SQLite)', async () => {
  const db = saveResource({ kind: 'database', name: 'Hint SQLite', project_id: projectId, config: { driver: 'sqlite', file: `hint_${Date.now()}.sqlite` } });
  const s1 = node('start', 'Install', { payload: '{}' });
  const make = node('dbScript', 'Make it', { connection: db.id, onError: 'stop', params: [], sql: 'CREATE TABLE IF NOT EXISTS sample_hint_rows (id TEXT)' });
  saveFlow(undefined, { name: 'Sample: Hint rows install', nodes: [s1, make], edges: [edge(s1, make)] }, projectId);
  const s2 = node('start', 'Go', { payload: '{}' });
  const read = node('dbQuery', 'Read rows', { connection: db.id, params: [], maxRows: 10, sql: 'SELECT id FROM sample_hint_rows' });
  const doc = { name: 'Read sample rows', nodes: [s2, read], edges: [edge(s2, read)] };
  const id = await engine.startRun({ doc, projectId, source: 'test' });
  await engine.waitFor(id, 10000);
  const task = q.get<any>(`select error from tasks where run_id = ? and status = 'failed'`, id);
  assert.match(task.error, /no such table: sample_hint_rows Run 'Sample: Hint rows install' first: it makes sample_hint_rows\./);
});

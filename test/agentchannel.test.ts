test('two callers sending the same session id share no conversation, and a job answers only the caller who started it', async () => {
  setSecret('DESK_A', 'desk-a-key-123456'); setSecret('DESK_B', 'desk-b-key-654321');
  const pol = saveResource({ kind: 'inboundPolicy', name: 'Two desks', project_id: pid, config: { auth: 'apiKey', apiKeyHeader: 'X-API-Key', apiKeySecrets: ['DESK_A', 'DESK_B'], requireHttps: false } }).id;
  const n = flows.getFlow(agentFlow)!.doc;
  const ch = n.nodes.find(x => x.type === 'agentChannel')!;
  const before = { chatPolicy: ch.config.chatPolicy, waitSeconds: ch.config.waitSeconds };
  ch.config.chatPolicy = pol;
  flows.saveFlow(agentFlow, n); flows.deploy(agentFlow);
  const A = { 'x-api-key': 'desk-a-key-123456' }, B = { 'x-api-key': 'desk-b-key-654321' };
  try {
    assert.equal((await (await post('/chat/order-desk/api', { message: 'Alpha secret', sessionId: 'shared-1' }, A)).json()).answer, 'You said "Alpha secret"');
    const b = await (await post('/chat/order-desk/api', { message: 'Beta', sessionId: 'shared-1' }, B)).json();
    assert.equal(b.answer, 'You said "Beta"', 'caller B must not see caller A\'s history under the same session id');
    assert.equal(b.sessionId, 'shared-1', 'the session id people see is unchanged');
    assert.equal((await (await post('/chat/order-desk/api', { message: 'Again', sessionId: 'shared-1' }, A)).json()).answer, 'You said "Again"; before that "Alpha secret"', 'A keeps its own conversation');

    ch.config.waitSeconds = 1; flows.saveFlow(agentFlow, n); flows.deploy(agentFlow);
    delayMs = 1800;
    const started = await (await post('/chat/order-desk/api', { message: 'Slow for A', sessionId: 'job-1' }, A)).json();
    assert.equal(started.status, 'working');
    const asB = await fetch(`${env.http}/chat/order-desk/jobs/${started.job}`, { headers: B });
    assert.equal(asB.status, 404, 'another caller learns nothing from a job id');
    let j: any = {};
    for (let i = 0; i < 40 && j.status !== 'answer'; i++) { await new Promise(res => setTimeout(res, 150)); j = await (await fetch(`${env.http}/chat/order-desk/jobs/${started.job}`, { headers: A })).json(); }
    assert.equal(j.answer, 'You said "Slow for A"');
    assert.equal((await fetch(`${env.http}/chat/order-desk/jobs/${started.job}`, { headers: B })).status, 404, 'still not for B once it is done');
  } finally {
    delayMs = 0;
    ch.config.chatPolicy = before.chatPolicy; ch.config.waitSeconds = before.waitSeconds;
    flows.saveFlow(agentFlow, n); flows.deploy(agentFlow);
  }
});

test('MCP client over a command; Call MCP tool; an agent uses outside tools; hand-off to an agent', async () => {
  const cmd = getResource(saveResource({ kind: 'mcpClient', name: 'Calculator', project_id: pid, config: { transport: 'command', command: `"${process.execPath}" "${path.join(here, 'mcpstdio.mjs')}"` } }).id)!;
  assert.deepEqual((await listMcpTools(cmd, () => '')).map(t => t.name), ['add']);
  const s = node('start', 'Go', { payload: '{}' });
  const call = node('mcpCall', 'Add', { mcp: cmd.id, action: 'call a tool', tool: 'add', arguments: '{"a": 4, "b": 5}' });
  const bad = node('mcpCall', 'Bad add', { mcp: cmd.id, action: 'call a tool', tool: 'add', arguments: '{"a": "x"}' });
  const errLog = node('log', 'Tool error', { message: 'TOOLERR {{input.text}}' });
  let id = await engine.startRun({ doc: { name: 'MCP', nodes: [s, call, bad, errLog], edges: [edge(s, call), edge(call, bad), edge(bad, errLog, 'tool error')] }, projectId: pid });
  await engine.waitFor(id, 20000);
  let st = runState(id)!;
  assert.deepEqual(st.outputs.Add.result, { sum: 9 });
  assert.match(st.logs.map((l: any) => l.msg).join('\n'), /TOOLERR a and b must be numbers/);

  // An agent with the calculator's tools.
  const ag = node('aiAgent', 'Calc agent', { provider: prov, task: 'add two and three', mcp: cmd.id, tools: 'none', maxSteps: 4 });
  id = await engine.startRun({ doc: { name: 'Calc', nodes: [s, ag], edges: [edge(s, ag)] }, projectId: pid });
  await engine.waitFor(id, 20000);
  st = runState(id)!;
  assert.equal(st.outputs['Calc agent'].answer, 'The sum is 5');
  assert.deepEqual(st.outputs['Calc agent'].steps[0].result, { sum: 5 });

  // Hand off: a supervisor Sutra passes the conversation to the order desk agent.
  const h = node('agentHandoff', 'To order desk', { process: agentFlow, use: 'draft', message: 'Handed over', sessionId: 'handoff-1', note: 'customer asks about A-1' });
  id = await engine.startRun({ doc: { name: 'Supervisor', nodes: [s, h], edges: [edge(s, h)] }, projectId: pid });
  await engine.waitFor(id, 20000);
  st = runState(id)!;
  assert.match(st.outputs['To order desk'].answer, /^You said "Handed over/);
});

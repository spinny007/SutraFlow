/* @sutra-file-overview
 * File: server/src/secret-scope.ts
 * Purpose/support: Upgrade checks for 2.1.8. Environment variables projects use with ${env:NAME} that an administrator has not allowed (names and where, never values). Audit F1: connections, Sutra drafts and deployed Sutras that name a stored secret their project can no longer read. Shown on the Admin Console Overview and by sutra secret check; names only.
 * Connects to (static imports): ./db.js, ./projects.js, ./packages.js, ./resources.js
 * Functions/entry points (static scan): envRequests, secretScopeProblems
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import { q } from './db.js';
import { secretVariableReferences, getProject, getOps, envBindings, serverOwnEnv } from './projects.js';
import { secretsOf } from './packages.js';
import { getResource } from './resources.js';

export interface SecretScopeProblem {
  projectId: string | null; project: string;
  /** A connection, a Sutra draft, or the deployed version of a Sutra. */
  item: 'connection' | 'sutra' | 'deployed sutra'; id: string; name: string;
  /** The stored secret's name (a name, never a value). */
  secret: string;
}

/**
 * From 2.1.8 a project's work reads only the stored secrets behind its own Secret properties and the
 * engine's (secrets.ts). This lists every connection, Sutra draft and deployed Sutra that names any other
 * stored secret directly (a secret field, `{{secret.NAME}}`), so an administrator can switch it to a
 * Secret property ({{gv.NAME}} or {{ev.NAME}}) before it fails.
 */
export interface EnvRequest {
  /** The environment variable's name (never its value). */
  name: string;
  /** Where projects ask for it: project properties, deployment config, logging, or a connection (names only). */
  found: string[];
  /** A variable of the SutraFlow server itself (SUTRA_...): it can never be allowed. */
  serverOwn: boolean;
}

/**
 * 2.1.8: every `${env:NAME}` in project content (properties, deployment config, logging, connections) whose
 * NAME an administrator has not allowed. These fail when they are read, until NAME is allowed or the
 * reference is replaced. Nothing is allowed on its own when a server is upgraded.
 */
export function envRequests(): EnvRequest[] {
  const allowed = new Set(envBindings());
  const found = new Map<string, Set<string>>();
  const scan = (value: unknown, where: string) => {
    const text = typeof value === 'string' ? value : JSON.stringify(value ?? '');
    for (const m of text.matchAll(/\$\{env:([A-Za-z_][\w]*)/g)) {
      if (allowed.has(m[1])) continue;
      if (!found.has(m[1])) found.set(m[1], new Set());
      found.get(m[1])!.add(where);
    }
  };
  for (const row of q.all<{ id: string; name: string }>('select id, name from projects order by name')) {
    const p = getProject(row.id);
    if (!p) continue;
    scan(p.config.variables, `${p.name}: Project properties`);
    scan((p.config as any).logging, `${p.name}: logging`);
    try { scan(getOps(p.id), `${p.name}: deployment config`); } catch { /* an unreadable deployment config is reported elsewhere */ }
  }
  for (const row of q.all<{ id: string }>('select id from resources order by name')) {
    const r = getResource(row.id);
    if (r) scan(r.config, `${r.name} (${r.project_id ? getProject(r.project_id)?.name || r.project_id : 'shared'})`);
  }
  return [...found].map(([name, at]) => ({ name, found: [...at], serverOwn: serverOwnEnv(name) })).sort((a, b) => a.name.localeCompare(b.name));
}

export function secretScopeProblems(): SecretScopeProblem[] {
  const usable = new Map<string, Set<string>>();
  const scope = (pid: string | null) => {
    const key = pid ?? '';
    if (!usable.has(key)) { const r = secretVariableReferences(pid); usable.set(key, new Set([...Object.values(r.gv), ...Object.values(r.ev)].map(String))); }
    return usable.get(key)!;
  };
  const projectName = (pid: string | null) => (pid ? getProject(pid)?.name || pid : 'Shared by all projects');
  const out: SecretScopeProblem[] = [];
  const add = (pid: string | null, item: SecretScopeProblem['item'], id: string, name: string, names: string[]) => {
    for (const secret of names) if (!scope(pid).has(secret)) out.push({ projectId: pid, project: projectName(pid), item, id, name, secret });
  };
  for (const row of q.all<{ id: string }>('select id from resources order by name')) {
    const r = getResource(row.id);
    if (r) add(r.project_id ?? null, 'connection', r.id, r.name, secretsOf([r as any], [], []));
  }
  const parse = (s: string) => { try { return JSON.parse(s); } catch { return null; } };
  for (const f of q.all<{ id: string; name: string; project_id: string | null; doc: string }>('select id, name, project_id, doc from flows order by name')) {
    const doc = parse(f.doc);
    if (doc?.nodes) add(f.project_id ?? null, 'sutra', f.id, f.name, secretsOf([], [], [doc]));
  }
  for (const f of q.all<{ id: string; name: string; project_id: string | null; doc: string }>(
    'select f.id, f.name, f.project_id, v.doc from deployments d join flows f on f.id = d.flow_id join flow_versions v on v.flow_id = d.flow_id and v.version = d.version order by f.name')) {
    const doc = parse(f.doc);
    if (doc?.nodes) add(f.project_id ?? null, 'deployed sutra', f.id, f.name, secretsOf([], [], [doc]));
  }
  return out;
}

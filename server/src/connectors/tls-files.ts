import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { config } from '../config.js';

/**
 * Certificates and private keys of connections and security policies (2.1.1). One setting per item,
 * which may be any of:
 *
 *  a file on the server     C:\certs\aiven\ca.pem, or a path with a variable: {{ev.CERTS}}\ca.pem
 *  a variable               {{gv.KAFKA_CA}}: a Certificate-type property holding the PEM text (or a path);
 *                           for a key, a Private key- or Secret-type property (kept in the vault)
 *  the PEM text itself      as pasted into connections before 2.1.1
 *
 * So an administrator renews a certificate by replacing the file or changing one variable per
 * environment, without opening the connections. A relative path is under the data folder.
 */
type Secret = (name: string, purpose?: string) => string;
const PEM = /-----BEGIN [A-Z0-9 ]+-----/;
const looksLikePath = (v: string) => !/[\r\n]/.test(v) && (/[\\/]/.test(v) || /\.(pem|crt|cer|cert|key|ca-bundle)$/i.test(v));

/**
 * A Windows or Linux location: C:\certs\ca.pem, \\server\certs\ca.pem, /etc/ssl/ca.pem, ~/certs/ca.pem,
 * or relative to the data folder. On Linux and macOS backslashes are folder separators too, so a
 * deployment config written on Windows (certs\ca.pem) works there unchanged.
 */
export function certPath(v: string) {
  let p = v.trim();
  if (/^~(?=$|[\\/])/.test(p)) p = path.join(os.homedir(), p.slice(1));
  if (process.platform !== 'win32' && !/^[A-Za-z]:[\\/]/.test(p)) p = p.replace(/\\/g, '/');
  return path.isAbsolute(p) ? path.normalize(p) : path.resolve(config.dataDir, p);
}

function readPem(v: string, what: string) {
  const file = certPath(v);
  let text: string;
  try { text = fs.readFileSync(file, 'utf8'); } catch (e: any) { throw new Error(`${what}: cannot read ${file} (${e?.code === 'ENOENT' ? 'no such file' : e?.code || e?.message})`); }
  if (!PEM.test(text)) throw new Error(`${what}: ${file} is not a PEM file (it has no -----BEGIN ...----- block)`);
  return text;
}

/** A certificate setting: its PEM text, read from the file when the setting is a path. */
export function pemFrom(value: unknown, what: string): string {
  const v = String(value ?? '').trim();
  if (!v || PEM.test(v) || !looksLikePath(v)) return v;
  return readPem(v, what);
}

/** A private key setting: a key file, PEM text from a variable, or a vault secret's name. */
export function keyFrom(value: unknown, secret: Secret, what: string): string {
  const v = String(value ?? '').trim();
  if (!v) return '';
  if (PEM.test(v)) return v;
  if (looksLikePath(v)) return readPem(v, what);
  return secret(v, what);
}

export interface TlsMaterial { ca?: string; cert?: string; key?: string; passphrase?: string }
/** A connection's CA, client certificate, private key and passphrase. */
export function tlsMaterial(c: Record<string, any>, secret: Secret, who: string, names: { passphrase?: string } = {}): TlsMaterial {
  const ca = pemFrom(c.caPem, `${who} CA certificate`);
  const cert = pemFrom(c.clientCertPem, `${who} client certificate`);
  // Both settings or neither, checked before anything is read.
  if (!!cert !== !!String(c.clientKeySecret || '').trim()) throw new Error(`${who} mutual TLS needs both Client certificate and Client private key`);
  const key = cert ? keyFrom(c.clientKeySecret, secret, `${who} client private key`) : '';
  const passName = String(c[names.passphrase || 'clientKeyPassphraseSecret'] || '').trim();
  return { ...(ca ? { ca } : {}), ...(cert ? { cert, key } : {}), ...(passName ? { passphrase: secret(passName, `${who} client key passphrase`) } : {}) };
}


import path from 'node:path';

/**
 * The SQLite database file (2.1.1): always in the data folder, under the name SUTRA_DB gives (sutra.db,
 * shop.db or sqlite:shop.db); without SUTRA_DB it is sutra.db, as before. Only the file name is used, so
 * the database stays with the master key, the backups and the folder's permissions.
 */
export const SQLITE_NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,99}$/;
export function sqliteNameOf(dbSetting: string) {
  const v = String(dbSetting || '').trim();
  if (!v || /^(postgres(ql)?|pglite):/i.test(v)) return 'sutra.db';
  const name = path.basename(v.replace(/^sqlite:(\/\/)?/i, '').replace(/\\/g, '/'));
  return SQLITE_NAME.test(name) ? name : 'sutra.db';
}
export const sqliteFileOf = (dbSetting: string, dataDir: string) => path.join(dataDir, sqliteNameOf(dbSetting));

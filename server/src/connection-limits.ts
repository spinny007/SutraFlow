export interface ConnectionLimit {
  id: string;
  limit: number;
  /** The connection's name, for messages and the Admin Console. */
  name?: string;
  /** Set when the connection is counted through another one: the name of that one. */
  via?: string;
}

const MAX_DEPTH = 6;

/**
 * The limit set on a connection, resolved ({{gv.X}}, deployment overrides); 0 = none. A limit is shown in
 * the Admin Console and in messages, so a Secret property is refused and an invalid value is described,
 * never repeated: the resolved text could be anything a property holds.
 */
export function limitOf(resource: Resource): number {
  const secret = secretInLimit(getResource(resource.id)?.config.maxConcurrentTasks, resource.project_id ?? null);
  if (secret) throw new Error(`${resource.name}: Maximum concurrent activities cannot use the Secret property {{${secret}}}; use a number or a plain property.`);
  const raw = resource.config.maxConcurrentTasks;
  if (raw === undefined || raw === '' || raw === null) return 0;
  if (typeof raw === 'boolean' || !Number.isInteger(Number(raw)) || Number(raw) < 0 || Number(raw) > 100000) {
    throw new Error(`${resource.name}: Maximum concurrent activities must be a whole number from 0 to 100000; check its value or the property it names.`);
  }
  return Number(raw);
}

/** Connections a connection's own settings select (only the settings shown for its choices). */
function referencedIds(r: Resource): string[] {
  const kind = RESOURCE_KINDS.find(k => k.kind === r.kind);
  const value = (key: string) => r.config?.[key];
  const holds = (c: { k: string; in: any[] }) => c.in.includes(value(c.k));
  const out: string[] = [];
  for (const f of kind?.fields || []) {
    if (f.type !== 'resource') continue;
    if ((f.showIf && !holds(f.showIf)) || (f.showIfAny && !f.showIfAny.some(holds))) continue;
    const id = value(f.k);
    if (typeof id === 'string' && id && id !== r.id) out.push(id);
  }
  return out;
}

/**
 * The capped connections behind the given ones: themselves and, transitively, those their settings
 * select. Sorted by id, so atomic admission always takes them in the same order.
 */
export function closureLimits(ids: string[]): ConnectionLimit[] {
  const result = new Map<string, ConnectionLimit>();
  const seen = new Set<string>();
  const walk = (id: string, via: string | undefined, depth: number) => {
    if (seen.has(id) || depth > MAX_DEPTH) return;
    seen.add(id);
    const r = effectiveResource(id);
    if (!r) return;
    const limit = limitOf(r);
    if (limit > 0 && !result.has(id)) result.set(id, { id, limit, name: r.name, ...(via ? { via } : {}) });
    for (const ref of referencedIds(r)) walk(ref, via ?? r.name, depth + 1);
  };
  for (const id of ids) walk(id, undefined, 0);
  return [...result.values()].sort((a, b) => a.id.localeCompare(b.id));
}

/** The capped connections a step uses: those it selects (with this attempt's values) and those behind them. */
export function connectionLimits(node: FlowNode, activity: Activity, scope: Record<string, any>): ConnectionLimit[] {
  if (node.settings?.disabled) return [];
  const ids: string[] = [];
  for (const field of activity.fields.filter(f => f.type === 'resource')) {
    const value = (key: string) => resolveSetting(activity.fields.find(f => f.k === key), node.config?.[key], scope);
    const holds = (c: { k: string; in: any[] }) => c.in.includes(value(c.k));
    if ((field.showIf && !holds(field.showIf)) || (field.showIfAny && !field.showIfAny.some(holds))) continue;
    const id = value(field.k);
    if (id && typeof id === 'string') ids.push(id);
  }
  return closureLimits(ids);
}

/**
 * Locks: one per connection ("connection:<id>"), so work on unrelated connections never queues behind
 * one lock. A transaction takes the first connection's lock with its begin; one that needs several
 * takes the others in the same (id) order, so two can never wait for each other.
 */
const lockKey = (id: string) => `connection:${id}`;
async function lockRest(db: AsyncStore, tx: { get(sql: string, ...a: any[]): Promise<any> }, limits: ConnectionLimit[]) {
  if (db.backend !== 'postgres' || limits.length < 2) return;
  await tx.get(`select ${limits.slice(1).map(() => 'pg_advisory_xact_lock(?)').join(', ')}`, ...limits.slice(1).map(l => lockId(lockKey(l.id))));
}

/**
 * Places in use now, per connection: steps whose claim is still running and leases not yet expired.
 * Rows that no longer count are left for the sweep (the leader, every 30 s): admission reads, never
 * cleans, which keeps it to a few round trips on a distant database.
 */
async function inUse(tx: { all(sql: string, ...a: any[]): Promise<any[]> }, limits: ConnectionLimit[]) {
  const ids = limits.map(l => l.id);
  const rows = await tx.all(`select p.resource_id, count(*) n from connection_permits p
    left join tasks t on p.kind = 'task' and t.id = p.task_id and t.owner = p.owner and t.claim = p.claim and t.status = 'running'
    where p.resource_id in (${ids.map(() => '?').join(', ')}) and ((p.kind = 'task' and t.id is not null) or (p.kind = 'lease' and p.expires_at >= ?))
    group by p.resource_id`, ...ids, Date.now());
  return new Map<string, number>(rows.map((r: any) => [r.resource_id, Number(r.n)]));
}

/** Removes permits whose claim ended, leases that expired and wait records of steps that left the queue. */
export async function sweepConnections(db: AsyncStore) {
  if (db.kind === 'memory') return;
  await db.run(`delete from connection_permits where (kind = 'task' and not exists (select 1 from tasks t where t.id = connection_permits.task_id and t.owner = connection_permits.owner and t.claim = connection_permits.claim and t.status = 'running'))
     or (kind = 'lease' and expires_at < ?)`, Date.now());
  // A waiting step is re-checked by claiming it: for that moment it is running. Only steps that left the
  // queue (done, failed, cancelled, gone) lose their wait record, so the backoff count and the Admin
  // Console view survive the re-checks.
  await db.run(`delete from connection_waits where not exists (select 1 from tasks t where t.id = connection_waits.task_id and t.status in ('pending', 'running'))`);
}

const describe = (cap: ConnectionLimit, used: number) =>
  `Waiting for ${cap.name || cap.id}${cap.via ? ` (used through ${cap.via})` : ''}: ${used} of ${cap.limit} in use`;

const insertPermits = (n: number) => `insert into connection_permits(resource_id, task_id, owner, claim, kind, holder, project, since, expires_at) values${Array.from({ length: n }, () => '(?, ?, ?, ?, ?, ?, ?, ?, ?)').join(', ')}
  on conflict(resource_id, task_id) do update set owner = excluded.owner, claim = excluded.claim, kind = excluded.kind, holder = excluded.holder, project = excluded.project, since = excluded.since, expires_at = excluded.expires_at`;

/**
 * A permit belongs to one durable claim, not a process-local counter. Returns false when the step waits.
 * Four round trips on PostgreSQL whether it is admitted or not: begin with the claim check, the count,
 * the write, and the last write sent with commit (one more for the extra locks of several connections).
 */
export async function admitConnections(db: AsyncStore, task: ClaimedTask, owner: string, limits: ConnectionLimit[], delayMs: number) {
  if (!limits.length) return true;
  if (db.kind === 'memory') return admitInMemory(db, task, owner, limits, delayMs);
  return db.transaction(lockKey(limits[0].id), async (tx, claimed) => {
    if (!claimed) return false;
    await lockRest(db, tx, limits);
    const used = await inUse(tx, limits);
    const full = limits.find(cap => (used.get(cap.id) || 0) >= cap.limit);
    if (full) {
      const n = used.get(full.id) || 0;
      const w = await tx.get(`insert into connection_waits(task_id, resource_id, reason, since, checks) values(?, ?, ?, ?, 1)
        on conflict(task_id) do update set resource_id = excluded.resource_id, reason = excluded.reason, checks = connection_waits.checks + 1
        returning checks`, task.id, full.id, describe(full, n), Date.now());
      // Grows from the poll interval to 5 s, so many waiting steps do not keep the connection's lock
      // busy; a place that frees wakes them at once (releaseConnections).
      const pause = Math.min(5000, Math.max(100, delayMs) * 2 ** Math.min(Number(w?.checks || 1) - 1, 6));
      await tx.commitWith(`update tasks set status='pending', owner=null, started_at=null, not_before=? where id=? and status='running' and owner=? and claim=?`, Date.now() + pause, task.id, owner, task.claim);
      return false;
    }
    const at = Date.now();
    await tx.run(insertPermits(limits.length), ...limits.flatMap(cap => [cap.id, task.id, owner, task.claim, 'task', '', '', at, 0]));
    await tx.commitWith('delete from connection_waits where task_id=?', task.id);
    return true;
  }, { sql: `select id from tasks where id=? and status='running' and owner=? and claim=?`, args: [task.id, owner, task.claim] });
}

/** Steps waiting for any of these connections become due now (a place was just given back). */
async function wakeWaiters(q: { run(sql: string, ...a: any[]): Promise<any> }, ids: string[]) {
  if (!ids.length) return;
  await q.run(`update tasks set not_before = ? where status = 'pending' and id in (select task_id from connection_waits where resource_id in (${ids.map(() => '?').join(', ')}))`, Date.now(), ...ids);
}

/**
 * A step attempt that held places has ended (done, failed, waiting or handed over): its places go back
 * at once and the steps waiting for them are woken, instead of each waiting out its pause. It removes
 * its own rows only, so no lock is needed: two round trips.
 */
export async function releaseConnections(db: AsyncStore, task: ClaimedTask, owner: string, limits: ConnectionLimit[]) {
  if (task.lease) { const l = task.lease; task.lease = undefined; await l.release(); return; }
  if (!limits.length || db.kind === 'memory') return;
  await db.run(`delete from connection_permits where task_id = ? and owner = ? and claim = ? and kind = 'task'`, task.id, owner, task.claim);
  await wakeWaiters(db, limits.map(l => l.id));
}

/** How often each in-memory step found no room, for its growing pause (the memory queue keeps no wait records). */
const memoryWaits = new Map<number, number>();

/**
 * An in-memory step: its places are a lease in the shared engine database, renewed while it runs and
 * expiring if the engine stops, so memory and durable Sutras share the same cluster-wide limit. With no
 * room the step goes back to its (in-memory) queue with a growing pause, like a durable step. When the
 * shared database cannot be reached the step fails with that reason (fail closed, never unlimited).
 */
async function admitInMemory(db: AsyncStore, task: ClaimedTask, owner: string, limits: ConnectionLimit[], delayMs: number) {
  const shared = asyncDatabase();
  if (shared.kind === 'memory') throw new Error('Connection limits need the shared engine database');
  let got: Awaited<ReturnType<typeof acquireLease>>;
  try { got = await acquireLease(shared, limits, owner, `In-memory step ${task.node_id} of run ${String(task.run_id).slice(0, 8)}`); }
  catch (e: any) { throw new Error(`Connection limits need the shared engine database, which could not be reached: ${e?.message || e}`); }
  if ('lease' in got) { memoryWaits.delete(task.id); task.lease = got.lease; return true; }
  const checks = (memoryWaits.get(task.id) || 0) + 1;
  memoryWaits.set(task.id, checks);
  const pause = Math.min(5000, Math.max(100, delayMs) * 2 ** Math.min(checks - 1, 6));
  await db.run(`update tasks set status='pending', owner=null, started_at=null, not_before=? where id=? and status='running' and owner=? and claim=?`, Date.now() + pause, task.id, owner, task.claim);
  return false;
}

interface CallScope {
  db: AsyncStore; owner: string; holder: string; project: string; signal: AbortSignal;
  limits: Map<string, ConnectionLimit>;
  /** Connections whose own place (the step's permit) a call is using now. */
  ownBusy: Set<string>;
  /** Calls waiting for the step's own place of a connection to come free. */
  waiting: Map<string, (() => void)[]>;
}
const stepCalls = new AsyncLocalStorage<CallScope>();
const inCall = new AsyncLocalStorage<Set<string>>();

/** Runs a step's work with its places known, so the calls it makes are counted at the client (admitCall). */
export function runStepCalls<T>(o: { db: AsyncStore; owner: string; holder: string; project?: string; signal: AbortSignal; limits: ConnectionLimit[] }, fn: () => Promise<T>): Promise<T> {
  if (!o.limits.length) return fn();
  return stepCalls.run({ db: o.db, owner: o.owner, holder: o.holder, project: o.project || '', signal: o.signal, limits: new Map(o.limits.map(l => [l.id, l])), ownBusy: new Set(), waiting: new Map() }, fn);
}

/** Timing of a call waiting for a place; tests shorten it. */
export const callTiming = { retryMs: 250 };

/**
 * One call to the given connections (a query, a transaction, an AI request). Outside a step it just runs.
 * Inside one, the first call at a time to a limited connection uses the step's own place; a call made
 * while another is running takes a place of its own (a lease, counted cluster-wide), or, when none is
 * free, waits for the step's own place, so the step's calls take turns and a limit of 1 cannot deadlock.
 * A call nested inside a call to the same connection (a query inside a transaction) is not counted again.
 */
export async function admitCall<T>(ids: string[], fn: () => Promise<T>): Promise<T> {
  const s = stepCalls.getStore();
  if (!s) return fn();
  const nested = inCall.getStore();
  const mine = [...new Set(ids)].filter(id => s.limits.has(id) && !nested?.has(id));
  if (!mine.length) return fn();
  const own: string[] = [], extras: Lease[] = [];
  const freeOwn = (id: string) => { s.ownBusy.delete(id); const w = s.waiting.get(id)?.shift(); w?.(); };
  try {
    // One connection at a time, in id order, as admission does: two calls never hold each other up halfway.
    for (const id of mine.sort()) {
      for (;;) {
        if (s.signal.aborted) throw s.signal.reason ?? new Error('The step was stopped');
        if (!s.ownBusy.has(id)) { s.ownBusy.add(id); own.push(id); break; }
        const got = await acquireLease(s.db, [s.limits.get(id)!], s.owner, `${s.holder} (a call at the same time)`, s.project);
        if ('lease' in got) { extras.push(got.lease); break; }
        await new Promise<void>(resolve => {
          const list = s.waiting.get(id) ?? [];
          s.waiting.set(id, list);
          const t = setTimeout(() => { const i = list.indexOf(go); if (i >= 0) list.splice(i, 1); resolve(); }, callTiming.retryMs);
          const go = () => { clearTimeout(t); resolve(); };
          list.push(go);
        });
      }
    }
    return await inCall.run(new Set([...(nested ?? []), ...mine]), fn);
  } finally {
    for (const id of own) freeOwn(id);
    for (const l of extras) await l.release().catch(() => {});
  }
}

/** Lease timings; tests shorten them. Renewed at a quarter of its length. */
export const leaseTiming = { leaseMs: 120000, retryMs: 1000 };

export interface Lease {
  /** Aborted when the lease is lost (it ran out before a renewal reached the database, or was removed). */
  signal: AbortSignal;
  release(): Promise<void>;
}

/**
 * Takes permits for work that is not a durable step (a listener poll, a background refresh), all or none.
 * Returns the lease, or why there is no room. Three round trips on PostgreSQL.
 */
export async function acquireLease(db: AsyncStore, limits: ConnectionLimit[], owner: string, holder: string, project = ''): Promise<{ lease: Lease } | { blocked: string }> {
  const controller = new AbortController();
  if (!limits.length) return { lease: { signal: controller.signal, release: async () => {} } };
  if (db.kind === 'memory') return { blocked: 'Connection limits need the shared engine database' };
  const id = -crypto.randomInt(1, 2 ** 47);
  let writtenUntil = 0;
  const blocked = await db.transaction(lockKey(limits[0].id), async tx => {
    await lockRest(db, tx, limits);
    const used = await inUse(tx, limits);
    const full = limits.find(cap => (used.get(cap.id) || 0) >= cap.limit);
    if (full) return describe(full, used.get(full.id) || 0);
    const at = Date.now(), until = at + leaseTiming.leaseMs;
    await tx.commitWith(insertPermits(limits.length), ...limits.flatMap(cap => [cap.id, id, owner, 0, 'lease', holder.slice(0, 200), project || '', at, until]));
    writtenUntil = until;
    return '';
  });
  if (blocked) return { blocked };
  let released = false;
  // Until when the database holds this lease, as far as this engine knows: the last renewal that
  // reached it. A renewal only extends a lease that has not run out (one that expired may already be
  // someone else's place). When renewals fail (the database is away), the work is stopped just before
  // that time, so it never goes on after its place could have been given to someone else.
  // The expiry as written in the database, not counted from when the commit came back: on a slow
  // database the two differ, and the engine must never believe in its lease longer than the database.
  let validUntil = writtenUntil;
  // Stops the work a quarter of the lease before the expiry the database holds, unless a renewal moved
  // it on first: renewals run every eighth of the lease, so a healthy lease is renewed six times
  // before its deadline could come.
  const margin = Math.max(25, Math.floor(leaseTiming.leaseMs / 4));
  let deadline: NodeJS.Timeout | undefined;
  const lost = (why: string) => { if (released || controller.signal.aborted) return; clearInterval(renew); clearTimeout(deadline); controller.abort(new Error(why)); };
  const arm = () => {
    clearTimeout(deadline);
    deadline = setTimeout(() => lost('The connection lease could not be renewed in time (the engine database did not answer); the work was stopped'), Math.max(0, validUntil - margin - Date.now()));
    deadline.unref?.();
  };
  const renew = setInterval(() => {
    const asked = Date.now();
    db.run(`update connection_permits set expires_at = ? where task_id = ? and owner = ? and kind = 'lease' and expires_at >= ?`, asked + leaseTiming.leaseMs, id, owner, asked)
      .then(r => { if (r.changes) { validUntil = asked + leaseTiming.leaseMs; if (!released) arm(); } else lost('The connection lease was lost; the work was stopped'); })
      .catch(() => { /* the database is away: the deadline stops the work in time */ });
  }, Math.max(25, Math.floor(leaseTiming.leaseMs / 8)));
  arm();
  renew.unref?.();
  return {
    lease: {
      signal: controller.signal,
      release: async () => {
        if (released) return;
        released = true;
        clearInterval(renew);
        clearTimeout(deadline);
        try {
          await db.run('delete from connection_permits where task_id = ? and owner = ?', id, owner);
          await wakeWaiters(db, limits.map(l => l.id));
        } catch { /* it expires */ }
      },
    },
  };
}

/**
 * Runs fn under a lease of the given connections (and those behind them). With no room it waits up to
 * waitMs, then gives up: onBlocked gets the reason and the result is undefined (the work is skipped).
 */
export async function withConnectionLease<T>(db: AsyncStore, ids: string[], owner: string, holder: string, fn: (signal: AbortSignal) => Promise<T>,
  o: { waitMs?: number; onBlocked?: (reason: string) => void; project?: string } = {}): Promise<T | undefined> {
  const limits = closureLimits(ids);
  if (!limits.length) return fn(new AbortController().signal);
  const until = Date.now() + Math.max(0, o.waitMs || 0);
  for (;;) {
    const got = await acquireLease(db, limits, owner, holder, o.project);
    if ('lease' in got) {
      try { return await fn(got.lease.signal); } finally { await got.lease.release(); }
    }
    if (Date.now() >= until) { o.onBlocked?.(got.blocked); return undefined; }
    await new Promise(r => setTimeout(r, leaseTiming.retryMs));
  }
}

export interface ConnectionUse {
  id: string; name: string; kind: string; project: string | null;
  /** As set (may be {{gv.X}}), and as resolved now. */
  setting: string; limit: number; error?: string;
  active: number; steps: number; leases: number; waiting: number; oldestWaitMs: number;
  holders: { kind: 'step' | 'lease'; owner: string; since: number; run?: string; step?: string; sutra?: string; holder?: string }[];
  waits: { task: number; since: number; reason: string; run?: string; step?: string; sutra?: string }[];
}

/** What each capped connection is doing now, for the Admin Console. */
/**
 * What each capped connection is doing now, for the Admin Console. visible: the projects the viewer may
 * see ('all' for administrators and the leader's samples). Work of other projects on a shared connection
 * is counted (the limit cannot be understood otherwise) but not described: no Sutra, step, run or
 * listener name.
 */
export async function connectionUse(db: AsyncStore, resources: Resource[], visible: 'all' | Set<string> = 'all'): Promise<ConnectionUse[]> {
  const capped = resources.filter(r => { const v = r.config?.maxConcurrentTasks; return v !== undefined && v !== '' && v !== null && v !== 0 && v !== '0'; });
  if (!capped.length) return [];
  await sweepConnections(db);
  const permits = await db.all<any>(`select p.resource_id, p.kind, p.owner, p.since, p.holder, p.project as lease_project, t.run_id, t.node_id, r.flow_name, r.project_id as run_project
    from connection_permits p left join tasks t on p.kind = 'task' and t.id = p.task_id left join runs r on r.id = t.run_id`);
  const waits = await db.all<any>(`select w.task_id, w.resource_id, w.reason, w.since, t.run_id, t.node_id, r.flow_name, r.project_id as run_project
    from connection_waits w join tasks t on t.id = w.task_id and t.status in ('pending', 'running') left join runs r on r.id = t.run_id`);
  const sees = (project: string | null | undefined) => visible === 'all' || (!!project && visible.has(project));
  const now = Date.now();
  return capped.map(raw => {
    const r = effectiveResource(raw.id) || raw;
    let limit = 0, error: string | undefined;
    try { limit = limitOf(r); } catch (e: any) { error = e.message; }
    const mine = permits.filter(p => p.resource_id === raw.id), waiting = waits.filter(w => w.resource_id === raw.id);
    return {
      id: raw.id, name: raw.name, kind: raw.kind, project: raw.project_id ?? null,
      setting: String(raw.config.maxConcurrentTasks), limit, ...(error ? { error } : {}),
      active: mine.length, steps: mine.filter(p => p.kind === 'task').length, leases: mine.filter(p => p.kind === 'lease').length,
      waiting: waiting.length, oldestWaitMs: waiting.length ? now - Math.min(...waiting.map(w => Number(w.since))) : 0,
      holders: mine.map(p => p.kind === 'task'
        ? (sees(p.run_project)
          ? { kind: 'step' as const, owner: p.owner, since: Number(p.since) || 0, run: p.run_id, step: p.node_id, sutra: p.flow_name }
          : { kind: 'step' as const, owner: p.owner, since: Number(p.since) || 0, sutra: OTHER })
        : { kind: 'lease' as const, owner: p.owner, since: Number(p.since) || 0, holder: sees(p.lease_project) ? p.holder : OTHER }),
      waits: waiting.slice(0, 50).map(w => (sees(w.run_project)
        ? { task: Number(w.task_id), since: Number(w.since), reason: w.reason, run: w.run_id, step: w.node_id, sutra: w.flow_name }
        : { task: 0, since: Number(w.since), reason: w.reason, sutra: OTHER })),
    };
  });
}

const OTHER = 'Work of another project';

/** How often the leader samples connection use (tests shorten it). */
export const connectionSampling = { ms: 30000 };

/** One sample per capped connection, kept for the Admin Console graphs (the leader writes it). */
export async function sampleConnectionUse(db: AsyncStore, resources: Resource[]) {
  const use = await connectionUse(db, resources);
  const at = Date.now();
  for (const u of use) {
    await db.run(`insert into connection_usage(at, resource_id, active, waiting, limit_n) values(?, ?, ?, ?, ?) on conflict(at, resource_id) do nothing`, at, u.id, u.active, u.waiting, u.limit);
  }
  return use.length;
}

/**
 * Purpose: one admission service for every piece of work that uses a capped connection, cluster-wide.
 *
 *  What counts    A connection's "Maximum concurrent activities" (maxConcurrentTasks, {{gv.X}} allowed)
 *                 counts work using it at once, in the shared engine database:
 *                 - durable steps that select it, or select a connection that refers to it (a knowledge
 *                   base's vector database and AI provider, an AI memory's database, a memory table's
 *                   database): the behind-the-scenes calls are counted with the step;
 *                 - listener polls and background work (a scheduled memory-table refresh), as leases.
 *                 One step or one poll holds at most one permit per connection, however many requests it
 *                 makes; separate steps and polls each hold their own. Not a pool size, not a rate limit.
 *  Permits        A step's permit belongs to its durable claim (task id, owner, claim, running) and lapses
 *                 when the claim ends, fails, waits or is recovered by another engine. A lease belongs to
 *                 its holder until released or expired; it is renewed while held, and a lost lease aborts
 *                 the holder's signal (a request already sent cannot be called back).
 *  Waiting        A step that finds no room goes back to the queue: no retry attempt used, no worker held,
 *                 its timeout not started. It is checked again with a growing pause (up to 5 s) and the
 *                 reason is kept in connection_waits for the Admin Console. A poll with no room is skipped
 *                 and its trigger says why. Subscriptions (Kafka, RabbitMQ, AMQP, WebSocket, Telegram long
 *                 poll) hold no permit: a limit of 1 never blocks their own Sutra.
 *  In memory      An in-memory step takes its places as a lease in the shared engine database (2.1.1), so
 *                 memory and durable Sutras share one limit; with no room it waits like a durable step, and
 *                 when the engine database cannot be reached it fails with that reason: never unlimited.
 *  Each call      Inside a step, calls are counted where the client makes them (database, AI provider,
 *                 vectors; 2.1.1): the first call at a time uses the step's place, a call made at the same
 *                 time as another takes a place of its own (a lease) or, with none free, waits for the
 *                 step's own place; a call nested in a call to the same connection is not counted again.
 *  Locks          One lock per connection, several taken in id order; admission only reads what counts
 *                 (stale rows are swept by the leader), so it stays a few round trips on a distant database.
 */

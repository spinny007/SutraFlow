/**
 * Purpose: durable activity admission for shared connections across engines.
 * Connects effective resource settings to scheduler claims and connection_permits.
 * Supports atomic multi-resource admission and fenced retry/recovery. Not a pool size
 * or a rate limit on gateway, listener, administrative or implicit nested traffic.
 */
import type { AsyncStore } from './asyncdb.js';
import type { Activity, FlowNode } from './engine/types.js';
import type { ClaimedTask } from './engine/scheduler.js';
import { effectiveResource } from './resources.js';
import { resolveSetting } from './settings.js';
export interface ConnectionLimit { id: string; limit: number }
export function connectionLimits(node: FlowNode, activity: Activity, scope: Record<string, any>): ConnectionLimit[] {
  if (node.settings?.disabled) return [];
  const result = new Map<string, ConnectionLimit>();
  for (const field of activity.fields.filter(f => f.type === 'resource')) {
    const value = (key: string) => resolveSetting(activity.fields.find(f => f.k === key), node.config?.[key], scope);
    const holds = (c: { k: string; in: any[] }) => c.in.includes(value(c.k));
    if ((field.showIf && !holds(field.showIf)) || (field.showIfAny && !field.showIfAny.some(holds))) continue;
    const id = value(field.k); if (!id || typeof id !== 'string') continue;
    const resource = effectiveResource(id); if (!resource) continue;
    const raw = resource.config.maxConcurrentTasks;
    if (raw === undefined || raw === '' || raw === null) continue;
    if (typeof raw === 'boolean' || !Number.isInteger(Number(raw)) || Number(raw) < 0 || Number(raw) > 100000) throw new Error('Connection maximum concurrent activities must be an integer from 0 to 100000.');
    if (Number(raw) > 0) result.set(id, { id, limit: Number(raw) });
  }
  return [...result.values()].sort((a, b) => a.id.localeCompare(b.id));
}
/** A permit belongs to one durable claim, not a process-local counter. */
export async function admitConnections(db: AsyncStore, task: ClaimedTask, owner: string, limits: ConnectionLimit[], delayMs: number) {
  if (!limits.length) return true;
  if (db.kind === 'memory') throw new Error('Connection concurrency limits require durable execution; change this Sutra from in-memory to durable mode.');
  return db.transaction('connection-admission', async tx => {
    if (!await tx.get(`select id from tasks where id=? and status='running' and owner=? and claim=?`, task.id, owner, task.claim)) return false;
    await tx.run(`delete from connection_permits where not exists (select 1 from tasks t where t.id=connection_permits.task_id and t.owner=connection_permits.owner and t.claim=connection_permits.claim and t.status='running')`);
    for (const cap of limits) {
      const count = await tx.get<{ n: number }>('select count(*) n from connection_permits where resource_id=?', cap.id);
      if (Number(count?.n || 0) >= cap.limit) {
        await tx.run(`update tasks set status='pending', owner=null, started_at=null, not_before=? where id=? and status='running' and owner=? and claim=?`, Date.now() + Math.max(100, delayMs), task.id, owner, task.claim);
        return false;
      }
    }
    for (const cap of limits) await tx.run('insert into connection_permits(resource_id,task_id,owner,claim) values(?,?,?,?)', cap.id, task.id, owner, task.claim);
    return true;
  });
}

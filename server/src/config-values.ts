/**
 * Config file values on the machine that runs sutra config (2.1.6), before anything is sent: the
 * environment file merged in, ${env:NAME} read from this machine's environment (CI/CD secret
 * variables), file:/path read for secret, certificate and private key properties (Kubernetes and
 * Docker secrets), and $${env:NAME} kept as the reference ${env:NAME}, read on the server at run time.
 * No database here, so a check against a remote server opens nothing locally.
 */
import fs from 'node:fs';
import YAML from 'yaml';

/** A config or environment file: YAML or JSON (JSON is YAML too). */
export function parseConfigText(text: string, file = 'config file') {
  try { return YAML.parse(text); } catch (e: any) { throw new Error(`${file}: ${e.message}`); }
}

const isObj = (v: unknown): v is Record<string, any> => !!v && typeof v === 'object' && !Array.isArray(v);
const named = (l: unknown[]) => l.length > 0 && l.every(x => isObj(x) && typeof x.name === 'string');

/**
 * The environment file over the config file: objects merged key by key, lists of named items merged
 * by name (an item only in the environment file is added), other values replaced.
 */
export function mergeConfig(base: any, over: any): any {
  if (over === undefined) return base;
  if (isObj(base) && isObj(over)) {
    const out: Record<string, any> = { ...base };
    for (const [k, v] of Object.entries(over)) out[k] = mergeConfig(base[k], v);
    return out;
  }
  if (Array.isArray(base) && Array.isArray(over) && named(base) && named(over)) {
    const out = base.map(b => { const o = over.find((x: any) => x.name.toLowerCase() === b.name.toLowerCase()); return o ? { ...mergeConfig(b, o), name: b.name } : b; });
    for (const o of over) if (!base.some((b: any) => b.name.toLowerCase() === o.name.toLowerCase())) out.push(o);
    return out;
  }
  return over;
}

const FILE_TYPES = new Set(['secret', 'private key', 'certificate']);
const SECRET_TYPES = new Set(['secret', 'private key']);
const ESCAPED = '\u0000SUTRA_ENV\u0000';

export interface Resolved { doc: any; missing: string[]; plainSecrets: string[] }

/**
 * Resolves a merged config document: values never leave this function in a message, only names.
 * missing: environment variables or files that are not there; plainSecrets: secret properties written
 * directly in the file (a warning unless --allow-plain-secrets).
 */
export function resolveConfigValues(input: any, env: Record<string, string | undefined> = process.env): Resolved {
  const missing: string[] = [], plainSecrets: string[] = [];
  const str = (v: string, where: string) => v.split('$${env:').join(ESCAPED).replace(/\$\{env:([A-Za-z_][A-Za-z0-9_]*)\}/g, (_m, n) => {
    if (env[n] === undefined) { missing.push(`environment variable ${n} (${where})`); return ''; }
    return env[n]!;
  }).split(ESCAPED).join('${env:');
  const walk = (v: any, where: string): any => {
    if (typeof v === 'string') return str(v, where);
    if (Array.isArray(v)) return v.map((x, i) => walk(x, `${where}[${isObj(x) && x.name ? x.name : i}]`));
    if (isObj(v)) return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x, where ? `${where}.${k}` : k)]));
    return v;
  };
  // Every property list in the file, with a label for messages.
  const lists = (d: any): [any[], string, (l: any[]) => void][] => [
    ...(isObj(d?.server) && Array.isArray(d.server.engineProperties) ? [[d.server.engineProperties, 'engine property', (l: any[]) => { d.server = { ...d.server, engineProperties: l }; }] as [any[], string, (l: any[]) => void]] : []),
    ...(Array.isArray(d?.projects) ? d.projects.map((p: any, i: number) => [isObj(p) && Array.isArray(p.properties) ? p.properties : [], `${p?.name}: property`, (l: any[]) => { d.projects = d.projects.map((x: any, j: number) => j === i ? { ...x, properties: l } : x); }]) : []),
  ];
  // Secrets written directly, judged on the file as written.
  for (const [l, where] of lists(input)) for (const p of l) {
    if (isObj(p) && typeof p.value === 'string' && SECRET_TYPES.has(String(p.type || 'string')) && p.value && !p.value.includes('${env:') && !p.value.startsWith('file:')) plainSecrets.push(`${where} ${p.name}`);
  }
  const doc = walk(input, '');
  // Then file: values (the path may itself come from ${env:}); the file's text is taken as it is.
  for (const [l, where, set] of lists(doc)) set(l.map(p => {
    if (!isObj(p) || typeof p.value !== 'string' || !FILE_TYPES.has(String(p.type || 'string')) || !p.value.startsWith('file:')) return p;
    const f = p.value.slice(5);
    if (!fs.existsSync(f)) { missing.push(`file ${f} (${where} ${p.name})`); return { ...p, value: '' }; }
    return { ...p, value: fs.readFileSync(f, 'utf8').replace(/\r?\n$/, '') };
  }));
  return { doc, missing, plainSecrets };
}

/* @sutra-file-overview
 * File: server/src/sample-hints.ts
 * Purpose/support: The hint added to a database error when sample data is missing (2.1.7): a query on a sample_ database or table that does not exist names the install Sutra of the project that makes it, such as "Run 'Sample: Sales orders install' first."
 * Connects to (static imports): ./flows.js, ./projects.js
 * Functions/entry points (static scan): sampleInstallHint
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import { getFlow, listFlows } from './flows.js';
import { effectiveVariables } from './projects.js';

/** Errors of SQLite, MySQL, PostgreSQL and SQL Server for a database or table that is not there. */
const MISSING = /no such table|doesn't exist|does not exist|unknown database|unknown table|invalid object name/i;

/**
 * " Run 'Sample: …' first." when the error is about missing sample data (names start with sample_, as all
 * sample data does) and a Sutra of the project with "install" in its name makes it; otherwise ''.
 */
export function sampleInstallHint(projectId: string | null | undefined, message: string, sql = ''): string {
  if (!projectId || !MISSING.test(message)) return '';
  const names = [...new Set([...`${message} ${sql}`.matchAll(/\bsample_\w+/gi)].map(m => m[0].toLowerCase()))];
  if (!names.length) return '';
  let values: Record<string, string> = {};
  try { values = effectiveVariables(projectId).values as Record<string, string>; } catch { /* properties are optional here */ }
  for (const f of listFlows(projectId)) {
    if (!/install/i.test(f.name)) continue;
    const doc = getFlow(f.id)?.doc;
    const text = (doc?.nodes || []).map(n => String(n.config?.sql ?? '')).join('\n')
      .replace(/\{\{\s*gv\.(\w+)\s*\}\}/g, (all, k) => (k in values ? String(values[k]) : all)).toLowerCase();
    const makes = names.find(n => new RegExp(`create\\s+(?:table|database|schema)\\s+(?:if\\s+not\\s+exists\\s+)?[\\w.\`"\\[\\]]*\\b${n}\\b`).test(text));
    if (makes) return ` Run '${f.name}' first: it makes ${makes}.`;
  }
  return '';
}

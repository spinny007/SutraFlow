/**
 * Database work of the installer and upgrader, run as a child process with the target installation's
 * settings in its environment (SUTRA_DATA_DIR, SUTRA_DB, SUTRA_DB_PASSWORD), so one installer can work
 * on another folder without mixing their settings. One operation per process; the answer is one line of
 * JSON on stdout ({ ok, ... } or { ok: false, error }).
 *
 *   init      opens the database (making its tables), the master key, and the first administrator when
 *             there is none; records the installed version
 *   backup    copies the whole database to a SQLite file (any engine database: SQLite or PostgreSQL)
 *   restore   copies such a file back over the database (way back after a failed upgrade)
 *   migrate   opens the database, which applies the changes of this version
 */
const op = process.argv[2];
const args = JSON.parse(process.argv[3] || '{}');

async function main() {
  const db = await import('../db.js');
  const { version } = await import('../config.js');
  switch (op) {
    case 'init': {
      db.openDb();
      // The master key is made with the data folder (secrets.ts) the first time something is encrypted.
      (await import('../secrets.js')).encrypt('installer check');
      const access = await import('../access.js');
      // The built-in roles (Administrator, Developer...), as the server makes them when it starts.
      access.ensureBuiltins();
      const people = access.listUsers('user');
      let created = '';
      if (!people.length && args.admin?.username) {
        access.createAccount({ username: args.admin.username, password: args.admin.password, email: args.admin.email || '', displayName: args.admin.displayName || 'Administrator', mustChange: false, grants: [{ role: 'administrator', project: '' } as any] });
        created = args.admin.username;
      }
      db.setSetting('installedVersion', version);
      db.setSetting('installedAt', new Date().toISOString());
      // The cluster (2.1.1): its name, and the engines that never lead (the Admin Console changes both later).
      if (typeof args.clusterName === 'string') db.setSetting('clusterName', args.clusterName.trim().slice(0, 60));
      if (Array.isArray(args.neverLead)) db.setSetting('leadersDenied', Object.fromEntries(args.neverLead.map((id: string) => [String(id), true])));
      return { version, users: access.listUsers('user').length, created };
    }
    case 'backup': {
      db.openDb();
      const log: string[] = [];
      db.copyDatabase(String(args.to), { replace: true, log: m => log.push(m) });
      return { to: args.to, log };
    }
    case 'restore': {
      // Opens the backup file as the database, then copies it over the installation's own database.
      const target = (await import('../config.js')).config.dbUrl;
      db.openDb(String(args.from));
      const log: string[] = [];
      db.copyDatabase(target, { replace: true, log: m => log.push(m) });
      return { log };
    }
    case 'migrate': {
      db.openDb();
      db.setSetting('installedVersion', version);
      db.setSetting('upgradedAt', new Date().toISOString());
      return { version, kind: db.dbKind() };
    }
    default: throw new Error(`Unknown installer task: ${op}`);
  }
}

main().then(r => { console.log(JSON.stringify({ ok: true, ...r })); process.exit(0); },
  e => { console.log(JSON.stringify({ ok: false, error: e?.message || String(e) })); process.exit(1); });

/* @sutra-file-overview
 * File: server/src/install/cli.ts
 * Purpose/support: Silent install and upgrade from a JSON file (2.1.1): passwords only as environment variables or files, every problem reported before anything changes, a dry run that prints the plan, progress to the terminal and data/logs/installer.log.
 * Connects to (static imports): node:fs, node:path, ./core.js
 * Functions/entry points (static scan): secretOf, main, writeLog, flag, opt, say
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import fs from 'node:fs';
import path from 'node:path';
import { HOME, install, upgrade, samples, validateInstall, checkPorts, testDatabase, systemCheck, type InstallConfig, type UpgradeConfig } from './core.js';

/**
 * Silent install and upgrade from a config file (2.1.1), the same steps as the web installer:
 *   sutraflow install --config install.json [--dry-run]
 *   sutraflow upgrade --config upgrade.json [--dry-run]   ("reinstall": true for the same version, 2.1.6)
 *   sutraflow samples list|add|remove [--folder <installation>] [--no-start]   (2.1.5)
 * Passwords are never written in the file: give them as { "env": "NAME" } (an environment variable) or
 * { "file": "path" } (a file holding only the password). The whole file is checked first and every
 * problem reported before anything changes; --dry-run prints the plan. Progress and the result go to the
 * terminal and to <data>/logs/installer.log; the exit code is 0 on success, 1 on failure, 2 on a bad file.
 */
const [command, ...rest] = process.argv.slice(2);
const flag = (f: string) => rest.includes(f);
const opt = (f: string) => { const i = rest.indexOf(f); return i >= 0 ? rest[i + 1] : undefined; };
const log: string[] = [];
const say = (m: string) => { const line = `${new Date().toISOString()} ${m}`; log.push(line); console.log(m); };

/** A password field: from an environment variable or a file, never written in the config file. */
function secretOf(v: unknown, where: string, problems: string[]): string | undefined {
  if (v === undefined || v === null || v === '') return undefined;
  if (typeof v === 'string') { problems.push(`${where}: write it as {"env": "NAME"} or {"file": "path"}, not in the config file`); return undefined; }
  const o = v as { env?: string; file?: string };
  if (o.env) { const x = process.env[o.env]; if (!x) problems.push(`${where}: the environment variable ${o.env} is not set`); return x; }
  if (o.file) { try { return fs.readFileSync(path.resolve(o.file), 'utf8').trim(); } catch { problems.push(`${where}: the file ${o.file} cannot be read`); return undefined; } }
  problems.push(`${where}: give {"env": "NAME"} or {"file": "path"}`);
  return undefined;
}

async function main(): Promise<number> {
  // sutraflow samples list|add|remove [--folder <installation>] [--no-start] (2.1.5).
  if (command === 'samples') {
    const action = rest.find(a => !a.startsWith('--') && a !== opt('--folder'));
    if (!['list', 'add', 'remove'].includes(String(action))) { console.error('sutraflow samples: list, add or remove'); return 2; }
    const what = action === 'list' ? 'remove' : action as 'add' | 'remove';
    const r: any = await samples({ folder: opt('--folder') || HOME, action: what, start: !flag('--no-start') }, (step, state, detail) => say(`${state === 'run' ? '…' : state === 'ok' ? '✓' : state === 'fail' ? '✗' : '-'} ${step}${detail ? `: ${detail}` : ''}`), { dryRun: action === 'list' });
    if (action === 'add') { say(r.already ? `The project ${r.project} already has ${r.already} sample Sutras: remove them first to add them fresh.` : r.dryRun ? `${r.samples} samples would be added to the project ${r.project}.` : `Added ${r.added} sample Sutras to the project ${r.project}.`); return 0; }
    const line = (i: any) => `  - ${i.where}: ${i.what} ${i.name}${i.old ? ' (earlier version)' : ''}${i.note ? ` (${i.note})` : ''}`;
    say(`${action === 'list' ? 'Samples and their data' : 'Removed'} in ${r.folder}: ${r.items.length}${r.items.length ? `\n${r.items.map(line).join('\n')}` : ''}`);
    if (r.kept?.length) say(`Kept (used by your own Sutras):\n${r.kept.map(line).join('\n')}`);
    for (const p of r.problems || []) say(`Could not reach or remove: ${p}`);
    for (const n of r.notes || []) say(n);
    return r.problems?.length && action === 'remove' ? 1 : 0;
  }
  const file = opt('--config');
  if (!file) { console.error(`sutraflow ${command}: --config <file.json or file.yaml> is needed for a silent ${command} (without it, the web installer opens)`); return 2; }
  let raw: any;
  // JSON, or YAML for a file ending in .yaml or .yml (2.1.5): the same fields either way.
  try { const text = fs.readFileSync(path.resolve(file), 'utf8'); raw = /\.ya?ml$/i.test(file) ? (await import('yaml')).parse(text) : JSON.parse(text); } catch (e: any) { console.error(`${file}: ${e.message}`); return 2; }
  const problems: string[] = [];
  if (command === 'install') {
    const c: InstallConfig = { ...raw, admin: { ...raw.admin, password: secretOf(raw.admin?.password, 'admin.password', problems) },
      database: { kind: 'sqlite', ...raw.database, ...(raw.database?.kind === 'postgres' ? { password: secretOf(raw.database?.password, 'database.password', problems) } : {}) } };
    if (!c.admin.password && !problems.some(p => p.startsWith('admin.password'))) problems.push('admin.password: needed');
    problems.push(...validateInstall(c));
    if (!problems.length) {
      const s = c.server;
      const busy = (await checkPorts(s.host || '127.0.0.1', [s.studioPort, s.gatewayHttp, s.gatewayHttps])).filter(p => !p.free);
      for (const p of busy) problems.push(`server: port ${p.port} is in use${p.suggest ? ` (${p.suggest} is free)` : ''}`);
      for (const x of systemCheck(HOME)) if (x.required && !x.ok) problems.push(`system: ${x.detail}`);
      if (!flag('--dry-run')) { const t = await testDatabase(c.database, HOME); if (!t.ok) problems.push(`database: ${t.message}`); }
    }
    if (problems.length) { console.error(`The config file is not ready (nothing was changed):\n${problems.map(p => `  - ${p}`).join('\n')}`); return 2; }
    const r = await install(c, HOME, (step, state, detail) => say(`${state === 'run' ? '…' : state === 'ok' ? '✓' : state === 'fail' ? '✗' : '-'} ${step}${detail ? `: ${detail}` : ''}`), { dryRun: flag('--dry-run') });
    if ((r as any).dryRun) { say(`Plan:\n${(r as any).plan.map((p: string) => `  - ${p}`).join('\n')}`); return 0; }
    say(`Installed ${(r as any).installed} in ${(r as any).folder}; open ${(r as any).address}`);
    // The values are not printed (a silent install's output often ends up in a build log): only where they are.
    say(`Keep a copy of the master key (${(r as any).keyFiles.masterKey}) and the admin token (${(r as any).keyFiles.adminToken}) in a safe place: the master key unlocks the vault, and without it the stored passwords cannot be read.`);
    for (const e of (r as any).cluster || []) { const f = path.join(HOME, `sutraflow-engine-${e.name}.env`); fs.writeFileSync(f, e.env, { mode: 0o600 }); say(`Settings for engine ${e.name}: ${f}`); }
    return 0;
  }
  if (command === 'upgrade') {
    const c: UpgradeConfig = raw;
    if (!c.from) { console.error('The config file is not ready (nothing was changed):\n  - from: the folder of the installation to upgrade'); return 2; }
    if (c.samples && !['keep', 'add', 'remove', 'refresh'].includes(c.samples)) { console.error('The config file is not ready (nothing was changed):\n  - samples: keep, add, remove or refresh'); return 2; }
    if (c.reinstall !== undefined && typeof c.reinstall !== 'boolean') { console.error('The config file is not ready (nothing was changed):\n  - reinstall: true (the same version again, a repair) or false'); return 2; }
    const r = await upgrade(c, (step, state, detail) => say(`${state === 'run' ? '…' : state === 'ok' ? '✓' : state === 'fail' ? '✗' : '-'} ${step}${detail ? `: ${detail}` : ''}`), { dryRun: flag('--dry-run') });
    if ((r as any).dryRun) { say(`Plan:\n${(r as any).plan.map((p: string) => `  - ${p}`).join('\n')}`); return 0; }
    say(`${(r as any).reinstalled ? 'Reinstalled' : 'Upgraded'} ${(r as any).upgraded.replace(/ reinstalled$/, '')} in ${(r as any).folder}; backup in ${(r as any).backup}`);
    for (const n of (r as any).sampleNotes || []) say(`Samples: ${n}`);
    return 0;
  }
  console.error(`Unknown command: ${command}`);
  return 2;
}

main().then(code => { writeLog(); process.exit(code); }, e => { say(`Failed: ${e?.message || e}`); writeLog(); process.exit(1); });

function writeLog() {
  try { const dir = path.join(HOME, 'data', 'logs'); fs.mkdirSync(dir, { recursive: true }); fs.appendFileSync(path.join(dir, 'installer.log'), log.join('\n') + '\n'); } catch { /* the terminal has it */ }
}

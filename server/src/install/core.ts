export function systemCheck(folder = HOME): Check[] {
  const [maj, min] = process.versions.node.split('.').map(Number);
  const nodeOk = maj > 22 || (maj === 22 && min >= 13);
  const writable = (dir: string) => { try { fs.mkdirSync(dir, { recursive: true }); const f = path.join(dir, `.write-${process.pid}`); fs.writeFileSync(f, 'x'); fs.rmSync(f); return true; } catch { return false; } };
  const free = (() => { try { const s = fs.statfsSync(folder); return Number(s.bavail) * Number(s.bsize); } catch { return -1; } })();
  return [
    { name: 'Node.js 22.13 or later', ok: nodeOk, detail: `Node.js ${process.versions.node}${nodeOk ? '' : ': install Node.js 22.13 or later (24 recommended)'}`, required: true },
    { name: 'The SutraFlow folder can be written', ok: writable(folder), detail: folder, required: true },
    { name: 'Runtime packages present', ok: fs.existsSync(path.join(folder, 'node_modules')), detail: fs.existsSync(path.join(folder, 'node_modules')) ? 'node_modules is there' : 'run "sutraflow setup" first (or use the offline package)', required: true },
    { name: 'Free disk space', ok: free < 0 || free > 1024 ** 3, detail: free < 0 ? 'not known' : `${(free / 1024 ** 3).toFixed(1)} GB free${free > 1024 ** 3 ? '' : ': at least 1 GB is recommended'}`, required: false },
    { name: 'Operating system', ok: true, detail: `${os.type()} ${os.release()} (${process.arch}), ${os.cpus().length} processors, ${Math.round(os.totalmem() / 1024 ** 3)} GB memory`, required: false },
  ];
}

/** Whether each port can be listened on at the host; a busy one gets the next free port as a suggestion. */
export async function checkPorts(host: string, ports: number[]): Promise<{ port: number; free: boolean; suggest?: number }[]> {
  const tryPort = (port: number) => new Promise<boolean>(resolve => {
    const s = net.createServer();
    s.once('error', () => resolve(false));
    s.listen({ port, host: host === '0.0.0.0' ? '0.0.0.0' : host, exclusive: true }, () => s.close(() => resolve(true)));
  });
  const taken = new Set<number>(), out = [];
  for (const port of ports) {
    const ok = Number.isInteger(port) && port > 0 && port < 65536 && !taken.has(port) && await tryPort(port);
    let suggest: number | undefined;
    if (!ok) for (let p = Math.max(1024, port + 1); p < 65536; p++) if (!taken.has(p) && !ports.includes(p) && await tryPort(p)) { suggest = p; break; }
    taken.add(ok ? port : suggest ?? port);
    out.push({ port, free: ok, ...(suggest ? { suggest } : {}) });
  }
  return out;
}

// ---------- sutraflow.env ----------

export function readEnv(file: string): Record<string, string> {
  const vals: Record<string, string> = {};
  if (!fs.existsSync(file)) return vals;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (m && !line.trimStart().startsWith('#')) vals[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return vals;
}

/** Sets values in an env file, keeping its comments and order; new names go at the end, with a note. */
export function writeEnv(file: string, values: Record<string, string>, note = 'Set by the SutraFlow installer') {
  const base = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : fs.existsSync(path.join(path.dirname(file), 'sutraflow.env.example')) ? fs.readFileSync(path.join(path.dirname(file), 'sutraflow.env.example'), 'utf8') : '';
  const lines = base.split(/\r?\n/);
  const done = new Set<string>();
  const out = lines.map(line => {
    const m = /^\s*#?\s*([A-Z_][A-Z0-9_]*)\s*=/.exec(line);
    if (!m || !(m[1] in values) || done.has(m[1])) return line;
    // A commented example line becomes the setting only for the first time the name appears.
    done.add(m[1]);
    return `${m[1]}=${values[m[1]]}`;
  });
  const extra = Object.keys(values).filter(k => !done.has(k));
  if (extra.length) out.push('', `# ${note}`, ...extra.map(k => `${k}=${values[k]}`));
  fs.writeFileSync(file, out.join(os.EOL).replace(/(\r?\n)*$/, os.EOL), { mode: 0o600 });
}


export function validateInstall(c: InstallConfig): string[] {
  const errors: string[] = [];
  if (!/^[A-Za-z0-9._@-]{2,64}$/.test(String(c.admin?.username || ''))) errors.push('Administrator user name: 2 to 64 letters, digits, . _ @ -');
  const pw = String(c.admin?.password || '');
  if (pw.length < 12) errors.push('Administrator password: at least 12 characters');
  else if (!(/[a-z]/.test(pw) && /[A-Z]/.test(pw) && /\d/.test(pw))) errors.push('Administrator password: use upper and lower case letters and digits');
  if (c.admin?.email && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(c.admin.email)) errors.push('Administrator email: not an email address');
  if (!c.database || !['sqlite', 'postgres'].includes(c.database.kind)) errors.push('Database: choose SQLite or PostgreSQL');
  if (c.database?.kind === 'postgres') {
    if (!c.database.host) errors.push('Database: the PostgreSQL host is empty');
    if (!c.database.database) errors.push('Database: the database name is empty');
    if (!c.database.user) errors.push('Database: the user is empty');
    if (c.database.pgvector && !['required', 'optional'].includes(c.database.pgvector)) errors.push('Database: pgvector is required or optional');
  }
  if (c.database?.kind === 'sqlite' && c.database.file && !SQLITE_NAME.test(c.database.file)) {
    errors.push('Database: the SQLite file is a file name in the data folder (letters, digits, . _ -), not a path');
  }
  const s = c.server || ({} as InstallConfig['server']);
  const ports = [s.studioPort, s.gatewayHttp, s.gatewayHttps, ...(s.enginePort ? [s.enginePort, s.engineHttp, s.engineHttps] : [])].map(Number);
  for (const p of ports) if (!Number.isInteger(p) || p < 1 || p > 65535) errors.push(`Ports: ${p} is not a port (1 to 65535)`);
  if (new Set(ports).size !== ports.length) errors.push('Ports: each port must be different');
  if (s.environment && !['development', 'test', 'production'].includes(s.environment)) errors.push('Environment: development, test or production');
  if (c.cluster?.engines?.length && c.database?.kind !== 'postgres') errors.push('Cluster: several engines need PostgreSQL (SQLite serves one engine)');
  errors.push(...memoryProblems(c));
  const engines = engineList(c);
  for (const e of engines) if (!ENGINE_ID.test(e.id)) errors.push(`Cluster: "${e.id}" (${e.where}) is not an engine name: letters, digits, . _ - and at most 60`);
  const ids = engines.map(e => e.id.toLowerCase());
  if (new Set(ids).size !== ids.length) errors.push('Cluster: each engine needs a name of its own');
  if (!engines.some(e => e.mayLead)) errors.push('Cluster: at least one engine must be allowed to lead (timers, listeners and recovery need a leader)');
  if (c.cluster?.name && c.cluster.name.length > 60) errors.push('Cluster: the name is at most 60 characters');
  return errors;
}

export const lockFile = (folder: string) => path.join(path.resolve(folder, readEnv(path.join(folder, 'sutraflow.env')).SUTRA_DATA_DIR || 'data'), 'install.lock');
export const isLocked = (folder = HOME) => fs.existsSync(lockFile(folder));

export async function install(c: InstallConfig, folder = HOME, progress: Progress = () => {}, o: { dryRun?: boolean } = {}) {
  const errors = validateInstall(c);
  if (errors.length) throw new Error(errors.join('; '));
  if (isLocked(folder)) throw new Error(`SutraFlow is already installed here (${lockFile(folder)}). To install again, remove that file first; to upgrade, use the upgrade.`);
  const step = async <T>(name: string, fn: () => Promise<T> | T): Promise<T> => {
    progress(name, 'run');
    try { const r = await fn(); progress(name, 'ok', typeof r === 'string' ? r : undefined); return r; } catch (e: any) { progress(name, 'fail', e?.message || String(e)); throw e; }
  };
  const s = c.server;
  const plan = [`write ${path.join(folder, 'sutraflow.env')}`, `make the data folder ${path.resolve(folder, c.dataDir || 'data')}`, c.database.kind === 'postgres' ? `use PostgreSQL ${databaseUrl(c.database)}, pgvector ${c.database.pgvector === 'optional' ? 'when available' : 'required (enabled in the database when it is not yet)'}` : `use SQLite: ${c.database.file || 'sutra.db'} in the data folder`, `create the administrator ${c.admin.username}`, `listen on ${s.host || '127.0.0.1'}:${s.studioPort} (gateway ${s.gatewayHttp}/${s.gatewayHttps})`, `Node memory: studio ${Number(s.studioMemoryMb) > 0 ? `${s.studioMemoryMb} MB` : 'Node.js decides'}${s.enginePort ? `, engine ${Number(s.engineMemoryMb) > 0 ? `${s.engineMemoryMb} MB` : 'Node.js decides'}` : ''}`];
  if (o.dryRun) return { dryRun: true, plan };
  await step('System check', () => {
    const bad = systemCheck(folder).filter(x => x.required && !x.ok);
    if (bad.length) throw new Error(bad.map(x => x.detail).join('; '));
    return 'ready';
  });
  await step('Ports', async () => {
    const busy = (await checkPorts(s.host || '127.0.0.1', [s.studioPort, s.gatewayHttp, s.gatewayHttps])).filter(p => !p.free);
    if (busy.length) throw new Error(busy.map(p => `${p.port} is in use${p.suggest ? ` (${p.suggest} is free)` : ''}`).join('; '));
    return 'free';
  });
  await step('Database', async () => { const t = await testDatabase(c.database, folder); if (!t.ok) throw new Error(t.message); return t.message; });
  await step('Settings file', () => {
    writeEnv(path.join(folder, 'sutraflow.env'), {
      SUTRA_DATA_DIR: c.dataDir || 'data', SUTRA_ADMIN_HOST: s.host || '127.0.0.1',
      STUDIO_PORT: String(s.studioPort), STUDIO_GATEWAY_HTTP: String(s.gatewayHttp), STUDIO_GATEWAY_HTTPS: String(s.gatewayHttps),
      ...(s.enginePort ? { ENGINE_PORT: String(s.enginePort), ENGINE_GATEWAY_HTTP: String(s.engineHttp), ENGINE_GATEWAY_HTTPS: String(s.engineHttps) } : {}),
      SUTRA_ENVIRONMENT: s.environment || 'development',
      ...(s.engineId ? { STUDIO_ENGINE_ID: s.engineId } : {}),
      ...(s.enginePort && s.engineName ? { ENGINE_ENGINE_ID: s.engineName } : {}),
      ...(Number(s.studioMemoryMb) > 0 ? { STUDIO_MEMORY_MB: String(s.studioMemoryMb) } : {}),
      ...(s.enginePort && Number(s.engineMemoryMb) > 0 ? { ENGINE_MEMORY_MB: String(s.engineMemoryMb) } : {}),
      // The address without the password; the password apart (the server joins them).
      SUTRA_DB: c.database.kind === 'postgres' ? databaseUrl(c.database) : (c.database.file && c.database.file !== 'sutra.db' ? c.database.file : ''), ...(c.database.kind === 'postgres' && c.database.password ? { SUTRA_DB_PASSWORD: c.database.password } : {}),
    });
    return 'sutraflow.env';
  });
  const tables = await step('Tables and administrator', async () => {
    const r = await runTask(HOME, 'init', { admin: c.admin, clusterName: c.cluster?.name || '', neverLead: engineList(c).filter(e => !e.mayLead).map(e => e.id) }, targetEnv(folder));
    return r.created ? `tables ready, administrator ${r.created} created` : `tables ready; ${r.users} administrator account(s) already there`;
  });
  await step('Admin token', () => {
    const f = path.join(targetEnv(folder).SUTRA_DATA_DIR, 'admin-token.txt');
    if (!fs.existsSync(f)) fs.writeFileSync(f, crypto.randomBytes(24).toString('hex'), { mode: 0o600 });
    return 'made';
  });
  fs.writeFileSync(lockFile(folder), JSON.stringify({ version: thisVersion(), at: new Date().toISOString(), by: 'installer' }, null, 2));
  if (c.start) await step('Start', () => startAll(folder, !!c.server.enginePort));
  return { installed: thisVersion(), folder, address: `http://${(s.host || '127.0.0.1') === '0.0.0.0' ? '127.0.0.1' : s.host || '127.0.0.1'}:${s.studioPort}`, detail: tables, cluster: clusterFiles(c) };
}


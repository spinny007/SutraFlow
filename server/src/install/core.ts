export const databaseUrl = (d: DatabaseChoice, withPassword = false) => {
  if (d.kind !== 'postgres') return '';
  const auth = encodeURIComponent(d.user || 'postgres') + (withPassword && d.password ? `:${encodeURIComponent(d.password)}` : '');
  const host = String(d.host || '127.0.0.1');
  const mode = d.sslMode || 'off';
  return `postgres://${auth}@${host.includes(':') ? `[${host}]` : host}:${Number(d.port) || 5432}/${encodeURIComponent(d.database || 'sutraflow')}${mode === 'require' ? '?sslmode=no-verify' : mode === 'verify' ? '?sslmode=verify-full' : ''}`;
};

/** Tests the chosen database: reachable, the database there (or allowed to make it), rights, pgvector. */
export async function testDatabase(d: DatabaseChoice, folder = HOME): Promise<{ ok: boolean; message: string; notes: string[]; exists?: boolean; pgvector?: PgvectorState }> {
  if (d.kind === 'sqlite') {
    if (d.file && !SQLITE_NAME.test(d.file)) return { ok: false, message: `SQLite: "${d.file}" is not a file name. Use letters, digits, . _ - only (for example sutra.db); the file is always in the data folder.`, notes: [] };
    return { ok: true, message: `SQLite: ${d.file || 'sutra.db'} in the data folder; nothing to set up.`, notes: ['Good for one engine. For several engines, or large volumes, choose PostgreSQL.', 'SQLite has no user names or passwords: the file is protected by the data folder\'s permissions, and passwords and keys inside SutraFlow are encrypted with master.key. For a database with its own logins, choose PostgreSQL.'] };
  }
  const pg = require('pg');
  const ssl = d.sslMode === 'off' || !d.sslMode ? undefined : { rejectUnauthorized: d.sslMode === 'verify' };
  const conn = (database: string) => new pg.Client({ host: d.host || '127.0.0.1', port: Number(d.port) || 5432, user: d.user || 'postgres', password: d.password || undefined, database, ssl, connectionTimeoutMillis: 10000 });
  const notes: string[] = [];
  const name = d.database || 'sutraflow';
  let c = conn(name);
  try {
    await c.connect();
  } catch (e: any) {
    if (e?.code !== '3D000') return { ok: false, message: pgProblem(e, d), notes };
    // The database is not there: make it when asked, through the maintenance database.
    if (!d.create) return { ok: false, exists: false, message: `The database ${name} does not exist on ${d.host}. Tick "Create it" (the user needs CREATEDB), or create it first.`, notes };
    const admin = conn('postgres');
    try {
      await admin.connect();
      await admin.query(`CREATE DATABASE "${name.replace(/"/g, '""')}"`);
      notes.push(`Created the database ${name}.`);
    } catch (e2: any) { return { ok: false, exists: false, message: `The database ${name} could not be created: ${e2.message}`, notes }; }
    finally { await admin.end().catch(() => {}); }
    c = conn(name);
    await c.connect();
  }
  try {
    const v = (await c.query('select version() as v')).rows[0].v as string;
    notes.push(String(v).split(',')[0]);
    const major = Number(/PostgreSQL (\d+)/.exec(v)?.[1] || 0);
    if (major && major < 14) notes.push(`PostgreSQL ${major} is old; 15 or later is recommended.`);
    const rights = (await c.query(`select has_database_privilege(current_user, current_database(), 'CREATE') as can`)).rows[0].can;
    if (!rights) return { ok: false, exists: true, message: `${d.user} may not create tables in ${name}; grant CREATE on the database (or use its owner).`, notes };
    const tables = Number((await c.query(`select count(*) as n from information_schema.tables where table_schema = current_schema() and table_name in ('runs', 'flows', 'users')`)).rows[0].n);
    if (tables) notes.push('This database already holds SutraFlow data: it will be used as it is (an upgrade keeps it).');
    // pgvector (knowledge bases, AI memory search): enabled in this database, or enabled here, before going on.
    const vector = await pgvectorIn(c, name, d.user || 'postgres');
    if (!vector.ok && d.pgvector !== 'optional') return { ok: false, exists: true, pgvector: vector, message: vector.message, notes };
    notes.push(vector.ok ? vector.message : `${vector.message} Going on without it: knowledge bases use the built-in store or another vector database.`);
    return { ok: true, exists: true, pgvector: vector, message: `Connected to ${name} on ${d.host}:${Number(d.port) || 5432} as ${d.user}.`, notes };
  } finally { await c.end().catch(() => {}); }
}

export interface PgvectorState { ok: boolean; state: 'enabled' | 'enabled now' | 'not enabled' | 'not installed'; version?: string; message: string }
/**
 * pgvector in the database: already enabled, enabled now (CREATE EXTENSION, when the user may), or what an
 * administrator has to do: install it on the server, or enable it in this database as a superuser.
 */
export async function pgvectorIn(c: any, database: string, user: string): Promise<PgvectorState> {
  const enabled = (await c.query(`select extversion from pg_extension where extname = 'vector'`)).rows[0]?.extversion;
  if (enabled) return { ok: true, state: 'enabled', version: enabled, message: `pgvector ${enabled} is enabled in ${database}.` };
  const available = (await c.query(`select default_version from pg_available_extensions where name = 'vector'`)).rows[0]?.default_version;
  if (!available) return { ok: false, state: 'not installed', message: `pgvector is not installed on this PostgreSQL server. Install it, then test again: Windows, the pgvector build for your PostgreSQL version (Laragon's PostgreSQL 18 has it); Linux, the package postgresql-<version>-pgvector (apt) or pgvector_<version> (dnf); a managed service (Azure, AWS RDS, Google Cloud SQL, Supabase, Neon), allow the "vector" extension in its settings. Or choose "Continue without pgvector".` };
  try {
    await c.query('CREATE EXTENSION IF NOT EXISTS vector');
    const v = (await c.query(`select extversion from pg_extension where extname = 'vector'`)).rows[0]?.extversion || available;
    return { ok: true, state: 'enabled now', version: v, message: `pgvector ${v} was enabled in ${database}.` };
  } catch (e: any) {
    return { ok: false, state: 'not enabled', version: available, message: `pgvector ${available} is installed on the server but ${user} may not enable it in ${database} (${String(e?.message || e).split('\n')[0]}). Ask a superuser to run, in ${database}: CREATE EXTENSION vector; then test again. Or choose "Continue without pgvector".` };
  }
}

function pgProblem(e: any, d: DatabaseChoice) {
  const m = String(e?.message || e);
  const at = `${d.host}:${Number(d.port) || 5432}`;
  if (e?.code === '28P01') return `PostgreSQL refused the password of ${d.user}.`;
  if (e?.code === '28000') return `The server does not accept ${d.user} from this machine (pg_hba.conf)${d.sslMode === 'off' ? ', or it accepts only SSL' : ''}.`;
  if (e?.code === 'ENOTFOUND' || e?.code === 'EAI_AGAIN') return `The name ${d.host} cannot be found.`;
  if (e?.code === 'ECONNREFUSED') return `Nothing answers at ${at}: is PostgreSQL running and listening there, and is the port open?`;
  if (/timeout/i.test(m)) return `No answer from ${at} in time: a firewall probably blocks the port.`;
  if (/SSL/i.test(m)) return `SSL: ${m}. Try SSL "require", or "off" on a trusted network.`;
  return `PostgreSQL at ${at}: ${m}`;
}


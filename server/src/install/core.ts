/**
 * Node memory (2.1.1): this machine's memory, what Node.js takes by itself here, and the size the sizing
 * profile suggests. Each engine is its own process with its own memory (--max-old-space-size).
 */
export function memoryInfo() {
  const MB = 1024 * 1024;
  return { machineMb: Math.round(os.totalmem() / MB), freeMb: Math.round(os.freemem() / MB), nodeDefaultMb: Math.round(v8.getHeapStatistics().heap_size_limit / MB), suggestedMb: profileFor().nodeMemoryMb };
}
/** Problems with the memory sizes: 0 (Node decides) or 256 MB and more; the engines on this machine fit in it. */
export function memoryProblems(c: InstallConfig, machineMb = memoryInfo().machineMb): string[] {
  const errors: string[] = [];
  const s = c.server || ({} as InstallConfig['server']);
  const check = (what: string, v: unknown, local = true) => {
    if (v === undefined || v === null || v === '') return 0;
    const n = Number(v);
    if (!Number.isInteger(n) || n < 0 || (n > 0 && n < 256)) { errors.push(`${what}: 0 (Node.js decides) or a whole number of MB from 256`); return 0; }
    if (local && n > machineMb) errors.push(`${what}: ${n} MB is more than the machine has (${machineMb} MB)`);
    return n;
  };
  const here = check('Studio memory', s.studioMemoryMb) + (s.enginePort ? check('Engine memory', s.engineMemoryMb) : 0);
  // The system, the database and Node's own memory outside the heap need room too.
  if (here > machineMb * 0.85) errors.push(`Memory: the processes on this machine would take ${here} MB of ${machineMb} MB; leave at least 15% for the system`);
  // Further engines run on their own machines: only the size itself is checked here.
  for (const e of c.cluster?.engines || []) check(`Engine ${e.name} memory`, e.memoryMb, false);
  return errors;
}

/** Every engine the install sets up, with its id (the name it has in the cluster) and whether it may lead. */
export function engineList(c: InstallConfig) {
  const s = c.server || ({} as InstallConfig['server']);
  return [
    { id: s.engineId || `${os.hostname()}-studio`, where: 'this server (studio)', mayLead: s.studioMayLead !== false },
    ...(s.enginePort ? [{ id: s.engineName || `${os.hostname()}-engine`, where: 'the engine beside it', mayLead: s.engineMayLead !== false }] : []),
    ...(c.cluster?.engines || []).map(e => ({ id: e.name, where: 'a further engine', mayLead: e.canLead !== false })),
  ];
}
const ENGINE_ID = /^[A-Za-z0-9][A-Za-z0-9._-]{0,59}$/;


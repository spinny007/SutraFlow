export async function upgrade(c: UpgradeConfig, progress: Progress = () => {}, o: { dryRun?: boolean } = {}) {
  const from = path.resolve(c.from);
  const found = await detectInstall(from);
  if (!found.exists) throw new Error(`No SutraFlow installation in ${from}`);
  if (!found.upgradable) throw new Error(found.note);
  if (path.resolve(HOME) === from) throw new Error('Unpack the new release in a folder of its own and run its upgrader from there; it upgrades the installation you name.');
  const stamp = new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '');
  const backup = path.resolve(c.backupDir || path.join(from, 'backups', `${found.version}-${stamp}`));
  const dataInside = path.relative(from, found.dataDir).split(path.sep)[0];
  const plan = [`stop SutraFlow ${found.version} in ${from}`, `back up its data folder, settings and database to ${backup}`, `move the ${found.version} runtime to ${path.join(backup, 'runtime')}`, `install ${thisVersion()} from ${HOME}`, 'add new settings with their defaults', 'apply the database changes and compare the data', c.start === false ? 'leave it stopped' : 'start it and check its address'];
  if (o.dryRun) return { dryRun: true, plan, found };
  const env = targetEnv(from);
  const done: string[] = [];
  const step = async <T>(name: string, fn: () => Promise<T> | T): Promise<T> => {
    progress(name, 'run');
    try { const r = await fn(); progress(name, 'ok', typeof r === 'string' ? r : undefined); done.push(name); return r; } catch (e: any) { progress(name, 'fail', e?.message || String(e)); throw e; }
  };
  const moved: string[] = [], copied: string[] = [], inPlace: string[] = [];
  // The old program: everything in the folder but the settings, the data folder, backups and a site's own files.
  const runtime = fs.readdirSync(from).filter(f => !KEEP_IN_FOLDER.has(f) && f !== dataInside);
  const engineUp = engineRunning(from);
  let before: any;
  try {
    before = await step('Snapshot of the data', () => snapshotDb(from));
    await step('Stop', () => launcher(from, 'stop', 'all'));
    await step('Program files free', () => {
      // A file another program has open without sharing cannot be replaced: found here, before anything
      // changes, with the program that holds it (2.1.2). A folder that is only open (a web server such as
      // Apache or IIS, a terminal or Explorer in it) does not stop the upgrade: it is updated in place.
      const files = runtime.flatMap(f => filesUnder(path.join(from, f)));
      const locked = lockedFiles(files);
      if (!locked.length) return `${files.length} files can be replaced`;
      const who = whoHolds(locked);
      const shown = locked.slice(0, 5).map(f => path.relative(from, f)).join(', ') + (locked.length > 5 ? ` and ${locked.length - 5} more` : '');
      throw new Error(`Open in another program, so they cannot be replaced: ${shown}${who.length ? `. Held by process ${who.join(', ')}` : ''}. Stop that program or let it close them, then run the upgrade again; nothing was changed`);
    });
    await step('Backup', async () => {
      fs.mkdirSync(backup, { recursive: true });
      fs.cpSync(found.dataDir, path.join(backup, 'data'), { recursive: true });
      for (const f of ['sutraflow.env', '.htaccess', 'web.config']) if (fs.existsSync(path.join(from, f))) fs.copyFileSync(path.join(from, f), path.join(backup, f));
      if (!isPostgres(env)) return `${backup} (the SQLite database is in the data folder copy)`;
      // PostgreSQL: pg_dump changes nothing; without it, SutraFlow's own copy, which first applies this
      // version's additive database changes (the old version runs with them, as 2.1.0 did with 2.0.11's).
      const dump = pgTool('pg_dump');
      if (dump) {
        const a = pgArgs(env);
        const file = path.join(backup, 'database.dump');
        await runTool(dump, ['-Fc', '-f', file, a.url], a.env);
        // The dump is read back before anything changes: a backup that cannot be restored stops the upgrade here.
        const restore = pgTool('pg_restore');
        if (!restore) return `${backup} (pg_dump database.dump; pg_restore not found to check it)`;
        const tables = await dumpTables(restore, file);
        if (!tables) throw new Error(`The database backup ${file} holds no table data: nothing was changed`);
        return `${backup} (pg_dump database.dump, checked: ${tables} tables)`;
      }
      const r = await runTask(HOME, 'backup', { to: path.join(backup, 'database.db') }, env);
      return `${backup} (database.db: ${(r.log || []).length} tables; pg_dump not found, so the database changes were applied before the copy)`;
    });
    await step('Move the old runtime aside', () => {
      fs.mkdirSync(path.join(backup, 'runtime'), { recursive: true });
      for (const f of runtime) {
        const src = path.join(from, f), dst = path.join(backup, 'runtime', f);
        try { fs.renameSync(src, dst); moved.push(f); } catch (e: any) {
          // A folder another program is in cannot be moved: it is copied into the backup and updated in place.
          if (!IN_USE.has(e?.code) || !fs.statSync(src).isDirectory()) throw e;
          fs.cpSync(src, dst, { recursive: true });
          inPlace.push(f);
        }
      }
      return `${moved.length} entries${inPlace.length ? `; ${inPlace.join(', ')} open in another program as a folder, so copied and updated in place` : ''}`;
    });
    await step(`Install ${thisVersion()}`, () => {
      for (const f of fs.readdirSync(HOME)) {
        // A site's own .htaccess or web.config stays; an installation without one gets the release's.
        if (KEEP_IN_FOLDER.has(f) && !(['.htaccess', 'web.config'].includes(f) && !fs.existsSync(path.join(from, f)))) continue;
        if (f === 'data' || f === 'release') continue;
        const dst = path.join(from, f);
        if (inPlace.includes(f) && fs.statSync(path.join(HOME, f)).isDirectory()) emptyDir(dst);
        else copied.push(f);
        fs.cpSync(path.join(HOME, f), dst, { recursive: true });
      }
      // A folder updated in place that the new version no longer has is emptied.
      for (const f of inPlace) if (!fs.existsSync(path.join(HOME, f))) emptyDir(path.join(from, f));
      return `${copied.length + inPlace.length} entries`;
    });
    await step('New settings', () => {
      const have = readEnv(path.join(from, 'sutraflow.env'));
      const example = readEnv(path.join(from, 'sutraflow.env.example'));
      const add = Object.fromEntries(Object.entries(example).filter(([k]) => !(k in have)));
      if (Object.keys(add).length) writeEnv(path.join(from, 'sutraflow.env'), add, `Added by the ${thisVersion()} upgrade with their defaults`);
      return Object.keys(add).length ? `added ${Object.keys(add).join(', ')}` : 'none needed';
    });
    await step('Database changes', async () => `${(await runTask(from, 'migrate', {}, env)).version}`);
    await step('Compare the data', async () => {
      const after = await snapshotDb(from);
      const diff = Object.keys(before).filter(t => before[t].rows !== after[t]?.rows || before[t].hash !== after[t]?.hash);
      if (diff.length) throw new Error(`Changed by the upgrade: ${diff.join(', ')}`);
      return 'unchanged';
    });
    fs.writeFileSync(lockFile(from), JSON.stringify({ version: thisVersion(), at: new Date().toISOString(), by: 'upgrade', from: found.version }, null, 2));
    if (c.start !== false) {
      await step('Start', () => startAll(from, engineUp));
      await step('Check', async () => { const v = await health(from); if (v !== thisVersion()) throw new Error(`It answers ${v}, not ${thisVersion()}`); return `answers ${v}`; });
    }
    return { upgraded: `${found.version} to ${thisVersion()}`, folder: from, backup, steps: done };
  } catch (e: any) {
    // The way back: the old runtime, data and database as they were, then the old version started.
    progress('Putting the previous version back', 'run');
    // Each part is tried on its own, and the old version is started whatever happened before, so one
    // problem never leaves the installation stopped (2.1.2). What could not be put back is reported.
    const problems: string[] = [];
    const attempt = async (what: string, fn: () => unknown) => { try { await fn(); } catch (x: any) { problems.push(`${what}: ${x?.message || x}`); } };
    await launcher(from, 'stop', 'all').catch(() => {});
    await attempt('the new runtime', () => { for (const f of copied) fs.rmSync(path.join(from, f), { recursive: true, force: true }); });
    await attempt('the old runtime', () => {
      for (const f of moved) if (fs.existsSync(path.join(backup, 'runtime', f))) fs.renameSync(path.join(backup, 'runtime', f), path.join(from, f));
      // Folders updated in place get their old files back from the backup copy.
      for (const f of inPlace) {
        const dst = path.join(from, f);
        if (fs.existsSync(dst)) emptyDir(dst); else fs.mkdirSync(dst, { recursive: true });
        fs.cpSync(path.join(backup, 'runtime', f), dst, { recursive: true });
      }
    });
    if (done.includes('Backup')) {
      // Only what an upgrade changes in the data folder comes back: the SQLite database and the installer
      // lock. Logs, project files and Git workspaces (whose objects are read-only) stay as they are.
      await attempt('the data folder', () => {
        const db = isPostgres(env) ? [] : [sqliteNameOf(env.SUTRA_DB || '')].flatMap(n => [n, `${n}-wal`, `${n}-shm`]);
        for (const n of [...db, 'install.lock']) {
          const src = path.join(backup, 'data', n), dst = path.join(found.dataDir, n);
          if (fs.existsSync(src)) fs.copyFileSync(src, dst); else fs.rmSync(dst, { force: true });
        }
      });
      // A table held by a process still connected (an engine on another machine) makes the restore fail
      // after a minute instead of waiting for ever.
      if (isPostgres(env) && fs.existsSync(path.join(backup, 'database.dump'))) await attempt('the database', () => { const a = pgArgs(env); return runTool(pgTool('pg_restore'), ['--clean', '--if-exists', '-d', a.url, path.join(backup, 'database.dump')], { ...a.env, PGOPTIONS: '-c lock_timeout=60000' }); });
      else if (isPostgres(env) && fs.existsSync(path.join(backup, 'database.db'))) await attempt('the database', () => runTask(HOME, 'restore', { from: path.join(backup, 'database.db') }, env));
      await attempt('the settings', () => fs.copyFileSync(path.join(backup, 'sutraflow.env'), path.join(from, 'sutraflow.env')));
    }
    let started = '';
    if (done.includes('Stop')) started = await startAll(from, engineUp).then(() => ' and started', (x: any) => { problems.push(`start: ${x?.message || x}`); return ''; });
    progress('Putting the previous version back', problems.length ? 'fail' : 'ok', `${found.version} restored${started}${problems.length ? `; not put back: ${problems.join('; ')}. The backup is in ${backup}` : ''}`);
    throw e;
  }
}

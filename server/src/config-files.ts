/**
 * Configuration as files (2.1.6): sutra config export, check and apply.
 *
 * A config file (YAML or JSON) holds the server's settings (engine properties, roles, system accounts
 * without tokens, connections shared by all projects, gateway options, firewall and trusted proxies,
 * release and script policies, gateway plans and apps without keys, alert channels and rules, server
 * knowledge bases and their grants) and projects (properties, logging, connections). People are never
 * in it.
 *
 * Applying a file only creates what is missing. Everything to create is created in one transaction:
 * one item that cannot be created stops the apply with an error and nothing is created. An item that
 * is already on the server is never changed: it goes into a checklist (name, type, where it points,
 * the fields whose values differ, never the values) for the operations team to verify by hand.
 *
 * Secret values in a file are plain by the time they reach here (the command line resolves ${env:NAME}
 * and file:/path before sending); they go into the vault, encrypted, and are never returned. A value
 * written $${env:NAME} in the file arrives as ${env:NAME} and stays a reference read at run time.
 */

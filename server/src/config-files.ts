export interface ConfigItem { name: string; [k: string]: any }
export interface ConfigProject { name: string; description?: string; properties?: ConfigItem[]; logging?: Record<string, any>; connections?: ConfigItem[] }
export interface ConfigServer {
  engineProperties?: ConfigItem[];
  roles?: ConfigItem[];
  systemAccounts?: ConfigItem[];
  connections?: ConfigItem[];
  gateway?: { options?: Record<string, any>; firewall?: { allow?: string[]; deny?: string[] }; trustedProxies?: string[] };
  policies?: { scriptsAllowed?: boolean; releasesAllowed?: boolean; aiCli?: { allowed?: boolean; commands?: string[]; env?: string[] }; envBindings?: string[] };
  plans?: ConfigItem[];
  apps?: ConfigItem[];
  alerts?: { channels?: ConfigItem[]; rules?: ConfigItem[] };
  knowledge?: ConfigItem[];
}
export interface ConfigDoc { sutraflow?: string; version?: number; server?: ConfigServer; projects?: ConfigProject[] }

export interface ConfigReport {
  /** What was (apply) or would be (check) created. */
  creates: { what: string; name: string; kind?: string; project?: string }[];
  /** Already on the server and kept as it is: verify by hand. */
  checklist: (ChecklistItem & { project?: string })[];
  errors: string[];
  warnings: string[];
  applied: boolean;
}

const SERVER_KEYS = ['engineProperties', 'roles', 'systemAccounts', 'connections', 'gateway', 'policies', 'plans', 'apps', 'alerts', 'knowledge'];
const lower = (s: unknown) => String(s ?? '').trim().toLowerCase();
const byName = <T extends { name: string }>(list: T[], name: unknown) => list.find(x => lower(x.name) === lower(name));
const envName = (...parts: string[]) => parts.join('_').toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
/** A placeholder for a secret in an exported file: never the value. */
const placeholder = (...parts: string[]) => `\${env:${envName('SUTRA', ...parts)}}`;
/** A value that is a reference read at run time stays one in an exported file ($${env:} is read back as ${env:}). */
const keepRef = (v: string) => v.replace(/\$\{env:/g, () => '$${env:');
const resourceFields = (kind: string) => RESOURCE_KINDS.find(k => k.kind === kind)?.fields.filter(f => f.type === 'resource').map(f => f.k) || [];
const isRef = (v: unknown) => typeof v === 'string' && !!v && !v.includes('{{') && !v.startsWith('=') && !v.includes('${');

// ---------------------------------------------------------------- export

/** Connections as they go into a file: other connections named, not by id. */
function exportConnection(r: Resource) {
  const settings: Record<string, any> = { ...r.config };
  for (const k of resourceFields(r.kind)) if (isRef(settings[k])) settings[k] = getResource(settings[k])?.name ?? settings[k];
  return { name: r.name, kind: r.kind, settings };
}

function exportProject(p: Project): ConfigProject {
  return {
    name: p.name,
    ...(p.description ? { description: p.description } : {}),
    properties: p.config.variables.map(v => ({
      name: v.name, type: v.type || 'string',
      value: isVaultType(v.type) ? (v.value.includes('${env:') ? keepRef(v.value) : v.value ? placeholder(p.name, v.name) : '') : keepRef(String(v.value ?? '')),
      ...(v.description ? { description: v.description } : {}),
    })),
    logging: p.config.logging,
    connections: listResources(undefined, p.id).map(exportConnection),
  };
}

const sutraRef = (id: unknown) => {
  if (!id) return undefined;
  const f = listFlows().find(x => x.id === id);
  return f ? { project: getProject(f.projectId)?.name || '', name: f.name } : undefined;
};

function exportServer(): ConfigServer {
  const roles = listRoles();
  const roleName = (id: string) => roles.find(r => r.id === id)?.name || id;
  const projName = (id: string) => (id ? getProject(id)?.name || id : '*');
  const channels = listChannels();
  const plans = listPlans();
  return {
    engineProperties: listEngineVariables().map(v => ({
      name: v.name, type: v.type || 'string',
      value: isVaultType(v.type) ? (v.value.includes('${env:') ? keepRef(v.value) : v.value ? placeholder('ENGINE', v.name) : '') : keepRef(v.value),
      ...(v.description ? { description: v.description } : {}),
    })),
    roles: roles.filter(r => !r.builtin).map(r => ({ name: r.name, description: r.description, permissions: r.perms })),
    systemAccounts: listUsers('system').map(u => ({ name: u.username, displayName: u.displayName, disabled: u.disabled, roles: u.grants.map(g => ({ role: roleName(g.role), project: projName(g.project) })) })),
    connections: listResources().filter(r => !r.project_id).map(exportConnection),
    gateway: { options: getGatewayOptions(), firewall: getFirewall(), trustedProxies: getProxies().trusted },
    policies: { scriptsAllowed: scriptsAllowed(), releasesAllowed: releasesAllowed(), aiCli: (({ pending: _p, ...x }) => x)(cliPolicy()), envBindings: envBindings() },
    plans: plans.map(p => ({ name: p.name, description: p.description, perMinute: p.perMinute, perHour: p.perHour, perDay: p.perDay, perMonth: p.perMonth })),
    apps: listApps().map(a => ({ name: a.name, description: a.description, contact: a.contact, plan: plans.find(p => p.id === a.planId)?.name || '', scopes: a.scopes, disabled: a.disabled })),
    alerts: {
      channels: channels.map(c => {
        const settings: Record<string, any> = { ...c.config };
        if (c.kind === 'email' && settings.connection) settings.connection = getResource(settings.connection)?.name ?? settings.connection;
        if (c.kind === 'sutra') { settings.sutra = sutraRef(settings.flowId); delete settings.flowId; }
        return { name: c.name, kind: c.kind, enabled: c.enabled, settings };
      }),
      rules: listRules().map(r => {
        const params: Record<string, any> = { ...r.params };
        if ('flowId' in params) { if (params.flowId) params.sutra = sutraRef(params.flowId); delete params.flowId; }
        return { name: r.name, kind: r.kind, severity: r.severity, params, channels: r.channels.map(id => channels.find(c => c.id === id)?.name || id), enabled: r.enabled, notifyResolved: r.notifyResolved, repeatMin: r.repeatMin };
      }),
    },
    knowledge: knowledgeOverview().filter(k => k.server).map(k => ({
      name: k.name, project: k.projectName || '', access: k.access,
      ...(k.mcp ? { mcp: { server: k.mcp.serverName, tool: k.mcp.tool, description: k.mcp.description, area: k.mcp.area } } : {}),
      grants: k.grants.map(g => ({ project: g.projectName || g.projectId, area: g.area, write: g.write })),
    })),
  };
}

/** What is set now, as a config file: the server part, some projects, or both. Secrets as ${env:} placeholders. */
export function exportConfig(o: { server?: boolean; projects?: string[]; allProjects?: boolean }): ConfigDoc {
  const doc: ConfigDoc = { sutraflow: 'config', version: 1 };
  if (o.server) doc.server = exportServer();
  const team = listProjects().filter(p => !p.owner);
  const chosen = o.allProjects ? team : (o.projects || []).map(n => { const p = byName(team, n); if (!p) throw new Error(`No project named "${n}"`); return p; });
  if (chosen.length) doc.projects = chosen.map(p => exportProject(getProject(p.id)!));
  return doc;
}

// ---------------------------------------------------------------- check and apply

/** Reads a file's text (YAML or JSON) into a config document, with its shape checked. */
export function readConfigDoc(input: unknown): ConfigDoc {
  const d: any = input;
  if (!d || typeof d !== 'object' || Array.isArray(d)) throw new Error('A config file holds an object with server and/or projects');
  if (d.sutraflow !== undefined && d.sutraflow !== 'config') throw new Error('Not a SutraFlow config file (sutraflow: config)');
  if (d.version !== undefined && Number(d.version) !== 1) throw new Error(`Config file version ${d.version} is newer than this server reads (1)`);
  if (d.server !== undefined && (typeof d.server !== 'object' || Array.isArray(d.server))) throw new Error('server: an object');
  if (d.projects !== undefined && !Array.isArray(d.projects)) throw new Error('projects: a list');
  for (const p of d.projects || []) if (!p || typeof p.name !== 'string' || !p.name.trim()) throw new Error('Every project in the file needs a name');
  return d;
}

/** Permissions a caller needs for a file: [permission, project id or '' for all projects]. */
export function configNeeds(doc: ConfigDoc): [string, string][] {
  const s = doc.server || {};
  const need: [string, string][] = [];
  if (s.engineProperties || s.connections || s.policies || (s.gateway && (s.gateway.options || s.gateway.trustedProxies)) || s.knowledge) need.push(['server', '']);
  if (s.roles || s.systemAccounts) need.push(['users', '']);
  if (s.plans || s.apps || s.gateway?.firewall) need.push(['gateway', '']);
  if (s.alerts) need.push(['alerts', '']);
  for (const p of doc.projects || []) { const have = byName(listProjects(), p.name); need.push(['deploy', have ? have.id : '']); }
  return need;
}

/** Used to stop a dry run: everything done inside the transaction is rolled back. */
class DryRun extends Error {}

/**
 * Checks (apply false) or applies a config file. Both run the same code inside one transaction, so a
 * check finds every error an apply would; a check, or an apply with an error, rolls it all back.
 */
export function runConfig(input: unknown, o: { apply: boolean; by?: string }): ConfigReport {
  const doc = readConfigDoc(input);
  const rep: ConfigReport = { creates: [], checklist: [], errors: [], warnings: [], applied: false };
  for (const k of Object.keys(doc.server || {})) if (!SERVER_KEYS.includes(k)) rep.warnings.push(`server.${k} is not something a config file sets: left out`);
  const touchedResources = new Set<string>(), touchedProjects = new Set<string>();
  const created: { what: string; name: string; kind?: string; project?: string; projectId?: string }[] = [];
  const attempt = (what: string, name: string, kind: string | undefined, project: string | undefined, fn: () => void) => {
    try { fn(); created.push({ what, name, kind, project }); rep.creates.push({ what, name, ...(kind ? { kind } : {}), ...(project ? { project } : {}) }); }
    catch (e: any) { rep.errors.push(`${what} ${name}${kind ? ` (${kind})` : ''}${project ? ` in ${project}` : ''} cannot be created: ${e.message}`); }
  };
  const keep = (item: ChecklistItem & { project?: string }) => rep.checklist.push(item);

  try {
    tx(() => {
      const s = doc.server || {};
      // Roles before accounts, connections before what uses them, projects before their grants.
      for (const r of s.roles || []) {
        const have = byName(listRoles(), r.name);
        if (!have) { attempt('role', r.name, undefined, undefined, () => saveRole({ name: r.name, description: r.description, perms: r.permissions || r.perms || [] })); continue; }
        const fields = differing({ description: r.description ?? have.description, permissions: [...(r.permissions || r.perms || [])].sort() }, { description: have.description, permissions: [...have.perms].sort() });
        keep({ what: 'role', name: have.name, fields, note: noteOf(fields) });
      }
      engineProperties(s.engineProperties || [], attempt, keep);
      connections(null, '', s.connections || [], attempt, keep, touchedResources);
      for (const p of doc.projects || []) project(p, attempt, keep, touchedResources, touchedProjects);
      gateway(s, attempt, keep);
      for (const pl of s.plans || []) {
        const have = byName(listPlans(), pl.name);
        const want = { description: pl.description ?? '', perMinute: pl.perMinute ?? 0, perHour: pl.perHour ?? 0, perDay: pl.perDay ?? 0, perMonth: pl.perMonth ?? 0 };
        if (!have) { attempt('gateway plan', pl.name, undefined, undefined, () => savePlan({ name: pl.name, ...want })); continue; }
        const fields = differing(want, have as any);
        keep({ what: 'gateway plan', name: have.name, fields, note: noteOf(fields) });
      }
      for (const a of s.apps || []) {
        const have = byName(listApps(), a.name);
        if (!have) {
          attempt('gateway app', a.name, undefined, undefined, () => {
            const plan = a.plan ? byName(listPlans(), a.plan) : undefined;
            if (a.plan && !plan) throw new Error(`no gateway plan named "${a.plan}"`);
            saveApp({ name: a.name, description: a.description || '', contact: a.contact || '', planId: plan?.id || '', scopes: a.scopes || [], disabled: !!a.disabled });
          });
          continue;
        }
        const planName = listPlans().find(p => p.id === have.planId)?.name || '';
        const fields = differing({ description: a.description ?? have.description, contact: a.contact ?? have.contact, plan: a.plan ?? planName, scopes: [...(a.scopes || have.scopes)].sort(), disabled: a.disabled ?? have.disabled }, { description: have.description, contact: have.contact, plan: planName, scopes: [...have.scopes].sort(), disabled: have.disabled });
        keep({ what: 'gateway app', name: have.name, fields, note: noteOf(fields, 'its keys are never in a config file') });
      }
      alerts(s.alerts || {}, attempt, keep);
      for (const acc of s.systemAccounts || []) {
        const have = listUsers().find(u => lower(u.username) === lower(acc.name));
        const grants = () => (acc.roles || []).map((g: any) => {
          const role = listRoles().find(r => lower(r.id) === lower(g.role) || lower(r.name) === lower(g.role));
          if (!role) throw new Error(`no role named "${g.role}"`);
          const all = !g.project || g.project === '*';
          const proj = all ? undefined : byName(listProjects(), g.project);
          if (!all && !proj) throw new Error(`no project named "${g.project}"`);
          return { role: role.id, project: proj?.id || '' };
        });
        if (!have) { attempt('system account', acc.name, undefined, undefined, () => createAccount({ username: acc.name, kind: 'system', displayName: acc.displayName || '', grants: grants() })); continue; }
        if (have.kind !== 'system') { rep.errors.push(`system account ${acc.name}: a person's account has this name; people are never set by a config file`); continue; }
        let fields: string[] = [];
        try {
          const key = (l: { role: string; project: string }[]) => l.map(g => `${g.role}@${g.project}`).sort();
          fields = differing({ displayName: acc.displayName ?? have.displayName, roles: key(grants()) }, { displayName: have.displayName, roles: key(have.grants) });
        } catch (e: any) { rep.errors.push(`system account ${acc.name}: ${e.message}`); }
        keep({ what: 'system account', name: have.username, fields, note: noteOf(fields, 'tokens are made on the server, never in a config file') });
      }
      knowledge(s.knowledge || [], attempt, keep, rep, o.by || 'config file');
      if (rep.errors.length || !o.apply) throw new DryRun();
    });
    rep.applied = true;
  } catch (e) {
    if (!(e instanceof DryRun)) throw e;
    // Rolled back: what reacted to a change inside the transaction (routes, listeners, caches) reads the saved state again.
    for (const id of touchedResources) onResourceChange.forEach(fn => fn(id));
    for (const id of touchedProjects) onProjectChange.forEach(fn => fn(id));
  }
  if (rep.applied) {
    for (const c of created) audit({ actor: o.by || 'config file', actorKind: 'user', action: `Config apply: created ${c.what} ${c.name}`, outcome: 'ok', status: 200, target: c.name, projectName: c.project, details: { what: c.what, name: c.name, kind: c.kind } });
    audit({ actor: o.by || 'config file', actorKind: 'user', action: 'Config apply', outcome: 'ok', status: 200, details: { created: created.length, checklist: rep.checklist.map(c => `${c.what} ${c.name}${c.project ? ` (${c.project})` : ''}`).slice(0, 100) } });
  }
  return rep;
}

const noteOf = (fields: string[] = [], extra?: string) =>
  (fields.length ? `already on this server and kept as it is; the file has other values for ${fields.join(', ')}: check it by hand` : 'already on this server and kept as it is; the file has the same values')
  + (extra ? ` (${extra})` : '');

type Attempt = (what: string, name: string, kind: string | undefined, project: string | undefined, fn: () => void) => void;
type Keep = (item: ChecklistItem & { project?: string }) => void;

/** A property value from a file: plain values of secret types go into the vault under ref. */
function propertyValue(type: string, value: unknown, ref: () => string) {
  const v = value === undefined || value === null ? '' : String(value);
  if (!isVaultType(type) || !v || v.includes('${env:')) return v;
  const name = ref();
  setSecret(name, v);
  return name;
}
/** Whether a value from a file differs from the one here; secrets are compared in memory, never shown. */
function sameValue(type: string, want: unknown, have: string) {
  const w = want === undefined || want === null ? '' : String(want);
  if (isVaultType(type) && have && !have.includes('${env:') && !w.includes('${env:')) return (getSecret(have) ?? '') === w;
  return w === have;
}

function engineProperties(list: ConfigItem[], attempt: Attempt, keep: Keep) {
  for (const p of list) {
    const all = listEngineVariables(), have = byName(all, p.name), type = p.type || 'string';
    if (!have) {
      attempt('engine property', p.name, type, undefined, () => {
        const value = propertyValue(type, p.value, () => `ev_${crypto.createHash('sha256').update(`engine\0${p.name}`).digest('hex').slice(0, 16)}_${String(p.name).slice(0, 24)}`);
        saveEngineVariables([...all, { name: p.name, value, type, ...(p.description ? { description: p.description } : {}) }]);
      });
      continue;
    }
    const fields = [...(sameValue(have.type || 'string', p.value, have.value) ? [] : ['value']), ...((have.type || 'string') !== type ? ['type'] : [])];
    keep({ what: 'engine property', name: have.name, kind: have.type || 'string', fields, note: noteOf(fields) });
  }
}

/** Connections of a project (or shared by all, projectId null): missing ones created, others listed. */
function connections(projectId: string | null, projectName: string, list: ConfigItem[], attempt: Attempt, keep: Keep, touched: Set<string>) {
  const here = listResources().filter(r => (r.project_id ?? null) === projectId);
  // Ids first, so connections created together can name each other.
  const planned = new Map<string, string>();
  for (const c of list) if (!byName(here, c.name)) planned.set(lower(c.name), crypto.randomUUID());
  const idOf = (name: string) => {
    const mine = planned.get(lower(name)) || byName(here, name)?.id;
    if (mine) return mine;
    const shared = listResources().find(r => !r.project_id && lower(r.name) === lower(name));
    if (shared) return shared.id;
    throw new Error(`no connection named "${name}" in ${projectName || 'the connections shared by all projects'}`);
  };
  const named = (c: ConfigItem) => {
    const settings: Record<string, any> = { ...(c.settings || c.config || {}) };
    for (const k of resourceFields(c.kind)) if (isRef(settings[k])) settings[k] = idOf(settings[k]);
    return settings;
  };
  for (const c of list) {
    const have = byName(here, c.name);
    if (!have) {
      attempt('connection', c.name, c.kind, projectName || undefined, () => {
        if (!c.kind) throw new Error('kind is required');
        const id = planned.get(lower(c.name))!;
        saveResource({ id, kind: c.kind, name: c.name, project_id: projectId, config: named(c) });
        touched.add(id);
      });
      continue;
    }
    let fields: string[] = [];
    try { fields = differing(named(c), have.config); } catch { fields = differing(c.settings || c.config || {}, have.config); }
    if (c.kind && c.kind !== have.kind) fields = ['kind', ...fields];
    keep({ what: 'connection', name: have.name, kind: have.kind, where: whereOf(have.config), fields, note: noteOf(fields), ...(projectName ? { project: projectName } : {}) });
  }
}

function project(p: ConfigProject, attempt: Attempt, keep: Keep, touchedRes: Set<string>, touchedProj: Set<string>) {
  let found = byName(listProjects(), p.name);
  const props = p.properties || [];
  const secretRef = (pid: string, name: string) => `gv_${crypto.createHash('sha256').update(`${pid}\0${name}`).digest('hex').slice(0, 32)}_${name.slice(0, 24)}`;
  if (!found) {
    let ok = false;
    attempt('project', p.name, undefined, undefined, () => {
      const id = crypto.randomUUID();
      const variables: ProjectVariable[] = props.map(v => ({ name: v.name, type: v.type || 'string', value: propertyValue(v.type || 'string', v.value, () => secretRef(id, v.name)), description: v.description || '' }));
      saveProject({ id, name: p.name, description: p.description || '', config: { variables, logging: { ...defaultLogging, ...(p.logging || {}) } } });
      touchedProj.add(id);
      ok = true;
    });
    if (!ok) return;
    found = byName(listProjects(), p.name)!;
    for (const v of props) attempt('project property', v.name, v.type || 'string', p.name, () => {});
  } else {
    const current = getProject(found.id)!;
    const added: ProjectVariable[] = [];
    for (const v of props) {
      const type = v.type || 'string';
      const have = current.config.variables.find(x => x.name === v.name);
      if (!have) {
        attempt('project property', v.name, type, current.name, () => {
          added.push({ name: v.name, type, value: propertyValue(type, v.value, () => secretRef(current.id, v.name)), description: v.description || '' });
          saveProject({ id: current.id, name: current.name, config: { variables: [...current.config.variables, ...added] } });
          touchedProj.add(current.id);
        });
        continue;
      }
      const fields = [...(sameValue(have.type, v.value, have.value) ? [] : ['value']), ...(have.type !== type ? ['type'] : [])];
      keep({ what: 'project property', name: have.name, kind: have.type, fields, note: noteOf(fields), project: current.name });
    }
    if (p.logging) {
      const fields = differing(p.logging, current.config.logging as any);
      if (fields.length) keep({ what: 'logging', name: current.name, fields, note: noteOf(fields), project: current.name });
    }
  }
  connections(found.id, found.name, p.connections || [], attempt, keep, touchedRes);
}

function gateway(s: ConfigServer, attempt: Attempt, keep: Keep) {
  // A setting is "missing" when it was never saved on this server (the defaults are in use).
  const setting = (key: string, what: string, want: Record<string, any> | undefined, have: Record<string, any>, set: () => void) => {
    if (want === undefined) return;
    if (getSetting<any>(key, undefined) === undefined) { attempt('setting', what, undefined, undefined, set); return; }
    const fields = differing(want, have);
    keep({ what: 'setting', name: what, fields, note: noteOf(fields) });
  };
  const g = s.gateway || {};
  setting('gateway.options', 'gateway options', g.options, getGatewayOptions() as any, () => setGatewayOptions(g.options!));
  setting('gateway.firewall', 'gateway firewall', g.firewall && { allow: g.firewall.allow || [], deny: g.firewall.deny || [] }, getFirewall() as any, () => setFirewall(g.firewall!));
  setting('gateway.proxies', 'trusted proxies', g.trustedProxies && { trusted: g.trustedProxies }, getProxies() as any, () => setProxies({ trusted: g.trustedProxies }));
  const pol = s.policies || {};
  if (pol.scriptsAllowed !== undefined) setting('scriptsAllowed', 'scripts allowed', { value: !!pol.scriptsAllowed }, { value: scriptsAllowed() }, () => setScriptsAllowed(!!pol.scriptsAllowed));
  if (pol.releasesAllowed !== undefined) setting('releasesAllowed', 'releases allowed', { value: !!pol.releasesAllowed }, { value: releasesAllowed() }, () => setReleasesAllowed(!!pol.releasesAllowed));
  // 2.1.8 (audit F2): saved on every server at its first start, so a file only reports a difference here; change it in the Admin Console.
  if (pol.envBindings !== undefined) setting('envBindings', 'environment variables for projects', { value: [...pol.envBindings].sort() }, { value: envBindings().sort() } as any, () => setEnvBindings(pol.envBindings));
  if (pol.aiCli !== undefined) setting('aiCliPolicy', 'AI command-line tools', { ...cliPolicy(), ...pol.aiCli }, cliPolicy() as any, () => setCliPolicy(pol.aiCli!));
}

const sutraId = (ref: any) => {
  if (!ref) return '';
  const proj = ref.project ? byName(listProjects(), ref.project) : undefined;
  if (ref.project && !proj) throw new Error(`no project named "${ref.project}"`);
  const f = listFlows(proj?.id).find(x => lower(x.name) === lower(ref.name));
  if (!f) throw new Error(`no Sutra named "${ref.name}"${ref.project ? ` in ${ref.project}` : ''}: deploy its release first`);
  return f.id;
};

function alerts(a: NonNullable<ConfigServer['alerts']>, attempt: Attempt, keep: Keep) {
  for (const c of a.channels || []) {
    const have = byName(listChannels(), c.name);
    const settings = () => {
      const st: Record<string, any> = { ...(c.settings || {}) };
      if (c.kind === 'email' && st.connection) { const r = listResources('smtp').find(x => lower(x.name) === lower(st.connection) || x.id === st.connection); if (!r) throw new Error(`no Email (SMTP) connection named "${st.connection}"`); st.connection = r.id; }
      if (c.kind === 'sutra') { st.flowId = sutraId(st.sutra); delete st.sutra; }
      return st;
    };
    if (!have) { attempt('alert channel', c.name, c.kind, undefined, () => saveChannel({ name: c.name, kind: c.kind, enabled: c.enabled !== false, config: settings() })); continue; }
    let fields: string[] = [];
    try { fields = differing({ kind: c.kind, ...settings() }, { kind: have.kind, ...have.config }); } catch { fields = ['settings']; }
    keep({ what: 'alert channel', name: have.name, kind: have.kind, fields, note: noteOf(fields) });
  }
  for (const r of a.rules || []) {
    const have = byName(listRules(), r.name);
    const resolved = () => {
      const params: Record<string, any> = { ...(r.params || {}) };
      if ('sutra' in params) { params.flowId = sutraId(params.sutra); delete params.sutra; }
      const channels = (r.channels || []).map((n: string) => { const ch = byName(listChannels(), n); if (!ch) throw new Error(`no alert channel named "${n}"`); return ch.id; });
      return { params, channels };
    };
    if (!have) {
      attempt('alert rule', r.name, r.kind, undefined, () => saveRule({ name: r.name, kind: r.kind, severity: r.severity, ...resolved(), enabled: r.enabled !== false, notifyResolved: r.notifyResolved !== false, repeatMin: r.repeatMin ?? 0 } as any));
      continue;
    }
    let fields: string[] = [];
    try { const x = resolved(); fields = differing({ kind: r.kind, severity: r.severity ?? have.severity, params: x.params, channels: [...x.channels].sort() }, { kind: have.kind, severity: have.severity, params: have.params, channels: [...have.channels].sort() }); } catch { fields = ['settings']; }
    keep({ what: 'alert rule', name: have.name, kind: have.kind, fields, note: noteOf(fields) });
  }
}

function knowledge(list: ConfigItem[], attempt: Attempt, keep: Keep, rep: ConfigReport, by: string) {
  for (const k of list) {
    const all = knowledgeOverview();
    const kb = all.find(x => lower(x.name) === lower(k.name) && (!k.project || lower(x.projectName) === lower(k.project)));
    const label = `${k.name}${k.project ? ` (${k.project})` : ''}`;
    if (!kb) { rep.errors.push(`knowledge base ${label}: no such knowledge base connection; it comes with its project's connections or release`); continue; }
    if (!kb.server) {
      attempt('server knowledge base', label, undefined, undefined, () => {
        let mcpServer = '';
        if (k.mcp?.server) { const s = listResources('mcpServer').find(r => lower(r.name) === lower(k.mcp.server)); if (!s) throw new Error(`no MCP server connection named "${k.mcp.server}"`); mcpServer = s.id; }
        setKnowledgeAdmin(kb.id, { server: true, access: k.access, mcpServer, mcpTool: k.mcp?.tool, mcpDescription: k.mcp?.description, mcpArea: k.mcp?.area }, by);
      });
    } else {
      const fields = differing({ access: k.access ?? kb.access, mcp: k.mcp ? { server: k.mcp.server, tool: k.mcp.tool } : null }, { access: kb.access, mcp: kb.mcp ? { server: kb.mcp.serverName, tool: kb.mcp.tool } : null });
      keep({ what: 'server knowledge base', name: label, fields, note: noteOf(fields) });
    }
    for (const g of k.grants || []) {
      const proj = byName(listProjects(), g.project);
      const area = String(g.area || '');
      const glabel = `${label} for ${g.project}${area ? `, area ${area}` : ''}`;
      const have = kb.grants.find(x => proj && x.projectId === proj.id && x.area === area);
      if (!have) { attempt('knowledge grant', glabel, g.write ? 'write' : 'read', undefined, () => { if (!proj) throw new Error(`no project named "${g.project}"`); setGrant(kb.id, { projectId: proj.id, area, write: !!g.write }, by); }); continue; }
      const fields = have.write === !!g.write ? [] : ['write'];
      keep({ what: 'knowledge grant', name: glabel, kind: have.write ? 'write' : 'read', fields, note: noteOf(fields) });
    }
  }
}


import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import v8 from 'node:v8';
import { config } from './config.js';
import { HOME, writeEnv } from './install/core.js';

/**
 * Node memory per engine (2.1.1). Every engine is its own Node.js process with its own heap; the limit
 * (--max-old-space-size) is fixed when the process starts, so a change in the Admin Console cannot apply
 * while it runs:
 *
 *  Report    each heartbeat records the heap used and its limit, the process and the machine's memory.
 *  Change    when the tuned value differs from the one this engine started with, the engine writes it
 *            to its own settings file (STUDIO_MEMORY_MB or ENGINE_MEMORY_MB), which the launcher reads
 *            on the next start. Engines in another folder or on another machine each write their own.
 *  Restart   the Admin Console asks; an engine the launcher started in the background starts
 *            "sutraflow restart" beside it, which drains it (running steps finish) and starts it again.
 *            Engines started in the foreground (a service manager, Docker) are restarted by that manager.
 */
export interface EngineMemory {
  heapUsedMb: number; heapLimitMb: number; rssMb: number; machineMb: number; machineFreeMb: number;
  startedMb: number; wantedMb: number; restartable: boolean; settingsFile: string; note: string;
}

const MB = 1024 * 1024;
const envKey = () => (config.launch.role === 'engine' ? 'ENGINE_MEMORY_MB' : 'STUDIO_MEMORY_MB');
/** Started by the launcher in the background, with its settings file: it can restart itself. */
export const restartable = () => config.launch.how === 'background' && !!config.launch.envFile && fs.existsSync(config.launch.envFile);
let written = -1;

/** This engine's memory now, and the tuned value waiting for a restart (wantedMb = startedMb when none). */
export function memoryNow(wantedMb: number): EngineMemory {
  const h = v8.getHeapStatistics();
  const settingsFile = config.launch.envFile && fs.existsSync(config.launch.envFile) ? config.launch.envFile : '';
  let note = '';
  if (wantedMb !== config.memoryMb) {
    if (settingsFile) note = `${envKey()}=${wantedMb || ''} is in ${settingsFile}; it applies when the engine restarts.`;
    else note = `This engine was not started with sutraflow, so set node --max-old-space-size=${wantedMb || '(default)'} where it is started (NODE_OPTIONS in Docker or a service).`;
  }
  return {
    heapUsedMb: Math.round(h.used_heap_size / MB), heapLimitMb: Math.round(h.heap_size_limit / MB), rssMb: Math.round(process.memoryUsage.rss() / MB),
    machineMb: Math.round(os.totalmem() / MB), machineFreeMb: Math.round(os.freemem() / MB),
    startedMb: config.memoryMb, wantedMb, restartable: restartable(), settingsFile, note,
  };
}

/** Writes a changed value to this engine's settings file once (empty = Node's own). */
export function keepWanted(wantedMb: number) {
  if (wantedMb === written || !config.launch.envFile || !fs.existsSync(config.launch.envFile)) return;
  if (wantedMb === config.memoryMb && written === -1) { written = wantedMb; return; }
  try {
    writeEnv(config.launch.envFile, { [envKey()]: wantedMb ? String(wantedMb) : '' }, 'Node memory, set in the Admin Console (Engines, Tuning)');
    written = wantedMb;
  } catch (e: any) { console.error(`Node memory: could not write ${config.launch.envFile}:`, e?.message || e); }
}

/** Restarts this engine through the launcher: it drains, stops and starts again with the settings file. */
export function restartHere() {
  if (!restartable()) throw new Error('This engine was not started in the background with sutraflow: restart it where it is started (its service, Docker or terminal).');
  const home = config.launch.home || HOME;
  const env = { ...process.env };
  delete env.SUTRA_MEMORY_MB;
  const p = spawn(process.execPath, [path.join(home, 'bin', 'sutraflow.mjs'), 'restart', ...(config.launch.role === 'engine' ? ['engine'] : [])],
    { cwd: home, env, detached: true, stdio: 'ignore', windowsHide: true });
  p.unref();
  return { restarting: true };
}

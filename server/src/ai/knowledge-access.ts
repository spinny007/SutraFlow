import { q } from '../db.js';
import { inProject, runningFlow, runningProject, type Resource } from '../resources.js';

/**
 * What the running work may do with a knowledge base (Knowledge admin, 2.1.5). A knowledge base of a
 * project is that project's own, as before. An administrator makes it a server knowledge base and
 * grants it: to every project (search everything), or to listed projects, each for the whole base or
 * areas of it (a folder of sources such as products), to search or also to add and remove. The home
 * project keeps full use. Work outside a project (the Admin Console, managed sync) is not limited here.
 */
export interface KbAccess {
  /** Areas the work may search ('' = everything). */
  read: string[];
  /** Areas it may add to and remove from (empty = none, '' = everything). */
  write: string[];
  /** Whole-base changes: remove everything, rebuild vectors, build the search index. */
  whole: boolean;
}

/** "/Products/" -> "Products": an area is a folder of source names. */
export const areaOf = (s: unknown) => String(s ?? '').trim().replace(/\\/g, '/').replace(/^\/+|\/+$/g, '').replace(/\/{2,}/g, '/');
/** A source (or folder of sources) inside an area; every source is inside the area ''. */
export const within = (source: string, area: string) => !area || source === area || source.startsWith(area + '/');
export const overlaps = (a: string, b: string) => within(a, b) || within(b, a);

const FULL: KbAccess = { read: [''], write: [''], whole: true };
const cache = new Map<string, { at: number; a: KbAccess | string }>();
export const forgetKbAccess = () => cache.clear();

export function kbAccess(kb: Resource): KbAccess {
  const pid = runningProject();
  if (!pid) return FULL;
  // A Sutra exported from a managed source (Knowledge admin) writes only that source's area, in any project.
  const flow = runningFlow();
  if (flow) {
    const fk = `${kb.id}|flow|${flow}`, fc = cache.get(fk);
    let fa = fc && Date.now() - fc.at < 5000 ? fc.a : undefined;
    if (fa === undefined) {
      const src = q.get<{ area: string }>('select area from kb_sources where kb_id = ? and exported_flow = ?', kb.id, flow);
      fa = src ? { read: [''], write: [areaOf(src.area)], whole: false } : '';
      cache.set(fk, { at: Date.now(), a: fa });
    }
    if (fa) return fa as KbAccess;
  }
  if (!kb.project_id || pid === kb.project_id) return FULL;
  const key = `${kb.id}|${pid}`, c = cache.get(key);
  let a = c && Date.now() - c.at < 5000 ? c.a : undefined;
  if (a === undefined) {
    const admin = q.get<{ access: string }>('select access from kb_admin where kb_id = ?', kb.id);
    if (!admin) a = `The knowledge base ${kb.name} belongs to another project. An administrator can grant it to this project in the Admin Console, Knowledge admin.`;
    else if (admin.access === 'all') a = { read: [''], write: [], whole: false };
    else {
      const g = q.all<{ area: string; can_write: number }>('select area, can_write from kb_grants where kb_id = ? and project_id = ?', kb.id, pid);
      a = g.length ? { read: g.map(x => areaOf(x.area)), write: g.filter(x => Number(x.can_write)).map(x => areaOf(x.area)), whole: false }
        : `The knowledge base ${kb.name} is not granted to this project. An administrator grants it in the Admin Console, Knowledge admin.`;
    }
    cache.set(key, { at: Date.now(), a });
  }
  if (typeof a === 'string') throw new Error(a);
  return a;
}

/**
 * The folders a search or listing may look in: the one asked for when it lies inside a granted area,
 * the granted areas inside it, or every granted area. undefined = no limit.
 */
export function readScopes(kb: Resource, source?: string): (string | undefined)[] {
  const a = kbAccess(kb);
  const s = areaOf(source);
  if (a.read.includes('')) return [s || undefined];
  if (!s) return a.read;
  if (a.read.some(x => within(s, x))) return [s];
  const inside = a.read.filter(x => within(x, s));
  if (!inside.length) throw new Error(`${s} is outside the areas of ${kb.name} granted to this project (${a.read.join(', ')})`);
  return inside;
}

export function assertWrite(kb: Resource, source: string) {
  const a = kbAccess(kb);
  const s = areaOf(source);
  if (a.write.includes('') || (s && a.write.some(x => within(s, x)))) return;
  throw new Error(a.write.length
    ? `This project may change only ${a.write.map(x => `${x}/`).join(', ')} in the knowledge base ${kb.name}; ${s || 'the whole knowledge base'} is outside`
    : `This project may search the knowledge base ${kb.name} but not change it. An administrator can grant changes to an area in Knowledge admin.`);
}

export function assertWhole(kb: Resource, what: string) {
  if (!kbAccess(kb).whole) throw new Error(`Only the home project and administrators may ${what} of the knowledge base ${kb.name} (Admin Console, Knowledge admin)`);
}

/**
 * The knowledge base's own connections (a pgvector database, an AI provider for vectors) belong to its
 * home project: a granted project reaches them through the knowledge base only.
 */
export function asHome<T>(kb: Resource, fn: () => T): T {
  const pid = runningProject();
  return kb.project_id && pid !== undefined && pid !== kb.project_id ? inProject(kb.project_id, fn) : fn();
}

/**
 * The personal-data finder of the AI guard, on its own so the logger and run traces can use it without the
 * AI code: e-mail addresses, card numbers (with their checksum), IBANs, Aadhaar, PAN, SSN, phone numbers and
 * IP addresses are replaced by [EMAIL], [CARD] and so on.
 */
const luhn = (digits: string) => {
  let sum = 0;
  for (let i = 0; i < digits.length; i++) { let d = Number(digits[digits.length - 1 - i]); if (i % 2) { d *= 2; if (d > 9) d -= 9; } sum += d; }
  return sum % 10 === 0;
};

/** Personal data patterns, most specific first. */
const PII: { kind: string; label: string; re: RegExp; ok?: (m: string) => boolean }[] = [
  { kind: 'email', label: '[EMAIL]', re: /\b[\w.+-]+@[\w-]+(\.[\w-]+)+\b/g },
  { kind: 'card', label: '[CARD]', re: /\b(?:\d[ -]?){13,19}\b/g, ok: m => luhn(m.replace(/\D/g, '')) },
  { kind: 'iban', label: '[IBAN]', re: /\b[A-Z]{2}\d{2}(?: ?[A-Z0-9]{4}){2,7}(?: ?[A-Z0-9]{1,4})?\b/g },
  { kind: 'aadhaar', label: '[AADHAAR]', re: /\b[2-9]\d{3}[ -]?\d{4}[ -]?\d{4}\b/g },
  { kind: 'pan', label: '[PAN]', re: /\b[A-Z]{5}\d{4}[A-Z]\b/g },
  { kind: 'ssn', label: '[SSN]', re: /\b\d{3}-\d{2}-\d{4}\b/g },
  { kind: 'phone', label: '[PHONE]', re: /(?:\+\d{1,3}[ -]?)?(?:\(\d{2,4}\)[ -]?)?\d{3,5}[ -]?\d{3,5}(?:[ -]?\d{2,4})?\b/g, ok: m => m.replace(/\D/g, '').length >= 9 },
  { kind: 'ip address', label: '[IP]', re: /\b(?:\d{1,3}\.){3}\d{1,3}\b/g },
];

export function hidePersonalData(text: string) {
  let out = text;
  const hidden: { kind: string; count: number }[] = [];
  for (const p of PII) {
    let n = 0;
    out = out.replace(p.re, m => { if (p.ok && !p.ok(m)) return m; n++; return p.label; });
    if (n) hidden.push({ kind: p.kind, count: n });
  }
  return { text: out, hidden };
}

/**
 * The same finder over any value: every string inside it is masked, keys, numbers and the shape stay. For
 * what a run shows in traces and writes to logs (2.1.8); the data the steps pass on is never changed.
 */
export function maskPersonalData<T>(value: T, depth = 0): T {
  if (typeof value === 'string') return hidePersonalData(value).text as T;
  if (!value || typeof value !== 'object' || depth > 40) return value;
  if (Array.isArray(value)) return value.map(v => maskPersonalData(v, depth + 1)) as T;
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(value as Record<string, unknown>)) out[k] = maskPersonalData(v, depth + 1);
  return out as T;
}

/* AI execution policy.
 * Shares validated request timeouts and per-step overrides across providers, vectors and CLI calls.
 * Async context carries only the current activity's override/log callback, never credentials.
 */
import { AsyncLocalStorage } from 'node:async_hooks';

const execution = new AsyncLocalStorage<{ timeoutMs?: number; log?: (message: string) => void }>();
export const DEFAULT_AI_TIMEOUT_MS = 120000;
export function withAiExecution<T>(settings: { timeoutMs?: number; log?: (message: string) => void }, fn: () => T): T {
  return execution.run(settings, fn);
}
/** Blank means the documented default; invalid settings fail rather than disable the deadline. */
export function aiTimeoutMs(r: { config: Record<string, any> }): number {
  const value = execution.getStore()?.timeoutMs ?? r.config.timeoutMs;
  const ms = value === undefined || value === '' ? DEFAULT_AI_TIMEOUT_MS : Number(value);
  if (!Number.isSafeInteger(ms) || ms < 1 || ms > 86400000) throw new Error('AI timeout must be a whole number from 1 to 86400000 ms.');
  return ms;
}
export function aiLog(message: string) { execution.getStore()?.log?.(message); }
/** An outer activity cancellation always wins; all discovery/repair work shares this request deadline. */
export async function withinAiTimeout<T>(r: { name: string; config: Record<string, any> }, signal: AbortSignal | undefined, fn: (signal: AbortSignal, ms: number) => Promise<T>): Promise<T> {
  signal?.throwIfAborted();
  const ms = aiTimeoutMs(r), controller = new AbortController();
  const timer = setTimeout(() => controller.abort(new Error(`AI provider ${r.name} timed out after ${ms} ms.`)), ms);
  timer.unref?.();
  const combined = signal ? AbortSignal.any([signal, controller.signal]) : controller.signal;
  try { return await fn(combined, ms); }
  catch (error) { if (controller.signal.aborted && !signal?.aborted) throw controller.signal.reason; throw error; }
  finally { clearTimeout(timer); }
}

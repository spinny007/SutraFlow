import os from 'node:os';
import { q, getSetting, setSetting } from '../db.js';

/**
 * Programs on the server (2.1.8, audit F2). An AI provider that uses a command-line tool (Claude, Gemini,
 * Codex CLI) and an MCP server started by a command both run a program as the SutraFlow server user. They
 * run only when an administrator has switched on *AI command-line tools* (Admin Console > Server > Runtime)
 * and the command line starts with one of the administrator's allowed commands. The connection cannot
 * choose the working folder, and the program gets a small environment, not the server's.
 */
export interface CliPolicy {
  allowed: boolean;
  /** Allowed command lines; a connection's command line must start with one of them, word for word ("quotes" keep a path with spaces together). */
  commands: string[];
  /** Names of further environment variables the programs get (for example a tool's own sign-in token). */
  env: string[];
  /**
   * Command lines found in existing connections when the server was upgraded to 2.1.8. They are not
   * trusted until an administrator approves them (moved to commands) or dismisses them.
   */
  pending: PendingCommand[];
}

export interface PendingCommand {
  command: string;
  /** Where it was found: connection names with their projects (names only). */
  found: string[];
}

export const DEFAULT_CLI_COMMANDS = ['claude', 'gemini', 'codex'];
const KEY = 'aiCliPolicy';

/** Environment variables every program gets: finding programs, the user's home and temp folders, the locale. */
const BASE_ENV = ['PATH', 'PATHEXT', 'SystemRoot', 'SYSTEMROOT', 'windir', 'WINDIR', 'ComSpec', 'COMSPEC', 'HOME', 'USERPROFILE', 'HOMEDRIVE', 'HOMEPATH', 'APPDATA', 'LOCALAPPDATA', 'TEMP', 'TMP', 'TMPDIR', 'LANG', 'LC_ALL', 'TERM', 'XDG_CONFIG_HOME', 'XDG_DATA_HOME', 'XDG_CACHE_HOME'];
const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,127}$/;

/**
 * Flags of the known AI command-line tools that let the tool act without asking (edit files, run commands,
 * reach other folders). Refused even for an allowed tool: an AI step answers text, it does not act.
 */
const UNSAFE_FLAGS = /^(--dangerously-skip-permissions|--dangerously-bypass-approvals-and-sandbox|--yolo|-y|--full-auto|--allowedTools|--allowed-tools|--add-dir|--include-directories|--permission-mode|--approval-mode|--config|-c|danger-full-access|--sandbox=danger-full-access)(=.*)?$/;

const clean = (list: unknown, max: number) => [...new Set((Array.isArray(list) ? list : []).map(x => String(x ?? '').trim().replace(/\s+/g, ' ')).filter(Boolean))].slice(0, max);

const cleanPending = (list: unknown): PendingCommand[] => (Array.isArray(list) ? list : [])
  .map((x: any) => ({ command: String(x?.command ?? '').trim(), found: clean(x?.found, 20) }))
  .filter(x => x.command).slice(0, 50);

export function cliPolicy(): CliPolicy {
  const p = getSetting<Partial<CliPolicy> | null>(KEY, null);
  return { allowed: !!p?.allowed, commands: p ? clean(p.commands, 50) : [...DEFAULT_CLI_COMMANDS], env: p ? clean(p.env, 50) : [], pending: cleanPending(p?.pending) };
}

export interface CliPolicyChange extends Partial<Omit<CliPolicy, 'pending'>> {
  /** Pending command lines the administrator approves: added to the allowed commands. */
  approve?: string[];
  /** Pending command lines the administrator does not want: removed from the list, never allowed. */
  dismiss?: string[];
}

export function setCliPolicy(input: CliPolicyChange): CliPolicy {
  const now = cliPolicy();
  const approve = clean(input.approve, 50);
  const dismiss = clean(input.dismiss, 50);
  const unknown = [...approve, ...dismiss].find(c => !now.pending.some(x => x.command === c));
  if (unknown) throw new Error(`Not a command waiting for approval: ${unknown}`);
  const env = input.env === undefined ? now.env : clean(input.env, 50);
  const bad = env.find(n => !ENV_NAME.test(n));
  if (bad) throw new Error(`Environment variable names use letters, digits and _: ${bad}`);
  const commands = clean([...(input.commands === undefined ? now.commands : clean(input.commands, 50)), ...approve], 50);
  const unsafe = commands.find(c => /[%^&|<>]/.test(c) || (c.match(/"/g) || []).length % 2 === 1);
  if (unsafe) throw new Error(`Allowed commands cannot contain % ^ & | < > or an unclosed double quote: ${unsafe}`);
  const pending = now.pending.filter(x => !approve.includes(x.command) && !dismiss.includes(x.command));
  setSetting(KEY, { allowed: input.allowed === undefined ? now.allowed : !!input.allowed, commands, env, pending });
  return cliPolicy();
}

/** Splits a command line on spaces; "double quotes" keep a path with spaces together (as connections do). */
const words = (s: string) => { const out: string[] = []; const re = /"([^"]*)"|(\S+)/g; let m: RegExpExecArray | null; while ((m = re.exec(s))) out.push(m[1] ?? m[2]); return out; };
const same = (a: string, b: string) => (os.platform() === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b);

/**
 * Throws unless the program may start: the switch is on, the command line starts with an allowed command,
 * and (for an AI tool) no flag lets the tool act on its own. `line` is the command followed by its arguments.
 */
export function checkCliCommand(what: 'AI provider' | 'MCP server', line: string[], aiTool: boolean) {
  const p = cliPolicy();
  if (!p.allowed) throw new Error(p.pending.length
    ? `${what}: AI command-line tools are switched off on this server until an administrator approves the commands found when it was upgraded (Admin Console > Server > Runtime, AI command-line tools).`
    : `${what}: AI command-line tools are switched off on this server, so no program is started. An administrator can allow them in Admin Console > Server > Runtime.`);
  if (!line.length || !line[0]) throw new Error(`${what}: no command is set.`);
  const ok = p.commands.some(c => { const w = words(c); return w.length <= line.length && w.every((x, i) => same(x, line[i])); });
  if (!ok) throw new Error(`${what}: "${line[0]}" is not one of the commands an administrator allowed on this server (Admin Console > Server > Runtime, AI command-line tools).`);
  if (aiTool) {
    const unsafe = line.slice(1).find(a => UNSAFE_FLAGS.test(a));
    if (unsafe) throw new Error(`${what}: the argument ${unsafe.split('=')[0]} lets the tool act without asking and is not allowed. An AI step only answers with text.`);
  }
}

/** The environment of a started program: the base variables and the ones the administrator named. */
export function cliEnv(): NodeJS.ProcessEnv {
  const names = new Set([...BASE_ENV, ...cliPolicy().env]);
  const out: NodeJS.ProcessEnv = {};
  for (const [k, v] of Object.entries(process.env)) if (names.has(k) && v !== undefined) out[k] = v;
  return out;
}

/**
 * First start of 2.1.8: every server starts with the switch off. The command lines of existing AI
 * command-line and MCP command connections are listed as waiting for approval, with where they were found;
 * none is trusted until an administrator approves it, because whoever could edit a connection chose it.
 */
const quoted = (w: string) => (/\s/.test(w) ? `"${w}"` : w);
export function upgradeCliPolicy() {
  if (getSetting<unknown>(KEY, null) !== null) return;
  const found = new Map<string, Set<string>>();
  const lines = { add: (line: string) => { if (line) { if (!found.has(line)) found.set(line, new Set()); found.get(line)!.add(where); } } };
  let where = '';
  for (const r of q.all<{ kind: string; name: string; config: string; project: string | null }>(
    `select r.kind, r.name, r.config, p.name as project from resources r left join projects p on p.id = r.project_id where r.kind in ('aiProvider', 'mcpClient') order by r.name`)) {
    let c: any; try { c = JSON.parse(r.config); } catch { continue; }
    where = `${r.name} (${r.project || 'shared'})`;
    if (r.kind === 'aiProvider' && /CLI$/.test(String(c?.engine || ''))) {
      const cmd = String(c.command || '').trim();
      // The command of an AI tool is one program path (cliCall does not split it), spaces and all.
      lines.add(cmd ? quoted(cmd.replace(/^"(.*)"$/, '$1')) : ({ 'Claude CLI': 'claude', 'Gemini CLI': 'gemini', 'OpenAI Codex CLI': 'codex' } as Record<string, string>)[c.engine] || '');
    }
    if (r.kind === 'mcpClient' && c?.transport === 'command' && String(c.command || '').trim()) lines.add(words(`${c.command} ${c.args || ''}`).map(quoted).join(' '));
  }
  const pending = [...found].map(([command, at]) => ({ command, found: [...at] }));
  setSetting(KEY, { allowed: false, commands: [...DEFAULT_CLI_COMMANDS], env: [], pending });
}

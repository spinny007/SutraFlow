/** Makes a knowledge base a server knowledge base (or a project's own again), with its access and MCP tool. */
export function setKnowledgeAdmin(kbId: string, body: { server: boolean; access?: string; mcpServer?: string; mcpTool?: string; mcpDescription?: string; mcpArea?: string }, by: string) {
  const kb = kbOf(kbId);
  if (!body.server) {
    if (q.get('select 1 from kb_grants where kb_id = ?', kbId)) throw new Error('Remove its grants first: projects using it would stop working');
    q.run('delete from kb_admin where kb_id = ?', kbId);
    changed();
    return { server: false };
  }
  if (!kb.project_id) throw new Error('A knowledge base shared by all projects is already server-wide');
  const access = body.access === 'all' ? 'all' : 'granted';
  let srv = '', tool = '', area = '';
  if (body.mcpServer) {
    const s = getResource(String(body.mcpServer));
    if (!s || s.kind !== 'mcpServer') throw new Error('Choose an MCP server connection');
    if (!s.config.policy) throw new Error(`The MCP server ${s.name} has no security policy: a knowledge base is searched only by callers a policy lets in`);
    tool = String(body.mcpTool || '').trim();
    if (!TOOL_NAME.test(tool)) throw new Error('The tool name may use letters, digits, _ and - (up to 64)');
    if (q.get('select 1 from kb_admin where mcp_server = ? and mcp_tool = ? and kb_id != ?', s.id, tool, kbId)) throw new Error(`Another knowledge base already offers the tool ${tool} on ${s.name}`);
    srv = s.id; area = areaOf(body.mcpArea);
  }
  const t = now();
  q.run(`insert into kb_admin(kb_id, access, mcp_server, mcp_tool, mcp_description, mcp_area, updated_at, updated_by) values(?, ?, ?, ?, ?, ?, ?, ?)
    on conflict(kb_id) do update set access = excluded.access, mcp_server = excluded.mcp_server, mcp_tool = excluded.mcp_tool, mcp_description = excluded.mcp_description, mcp_area = excluded.mcp_area, updated_at = excluded.updated_at, updated_by = excluded.updated_by`,
    kbId, access, srv || null, tool || null, srv ? String(body.mcpDescription || '').trim() || null : null, srv ? area : null, t, by);
  changed();
  return { server: true, access };
}

/** Who already writes in an area of a knowledge base: a managed source or a project granted changes. */
function writersOf(kbId: string, area: string, except: { source?: string; project?: string } = {}) {
  const out: string[] = [];
  for (const s of q.all<SourceRow>('select * from kb_sources where kb_id = ?', kbId)) {
    if (s.id === except.source || !overlaps(areaOf(s.area), area)) continue;
    if (s.kind === 'sutra') { if (json(s.config).project !== except.project) out.push(`the source ${s.name} (Sutras of ${projectName(json(s.config).project)})`); }
    else if (Number(s.enabled) || s.exported_flow) out.push(`the source ${s.name}`);
  }
  for (const g of q.all<Grant>('select * from kb_grants where kb_id = ? and can_write = 1', kbId)) {
    if (g.project_id === except.project || g.created_by === `source:${except.source}` || !overlaps(areaOf(g.area), area)) continue;
    if (!String(g.created_by || '').startsWith('source:')) out.push(`the project ${projectName(g.project_id)} (${g.area || 'whole base'})`);
  }
  return out;
}

export function setGrant(kbId: string, body: { projectId: string; area?: string; write?: boolean }, by: string) {
  const kb = kbOf(kbId);
  if (!q.get('select 1 from kb_admin where kb_id = ?', kbId)) throw new Error('Make it a server knowledge base first');
  const p = getProject(String(body.projectId || ''));
  if (!p) throw new Error('No such project');
  if (p.id === kb.project_id) throw new Error(`${p.name} is the home project of ${kb.name}: it always has full use`);
  const area = areaOf(body.area);
  if (body.write) {
    const w = writersOf(kbId, area, { project: p.id });
    if (w.length) throw new Error(`One writer per area: ${area || 'the whole base'} is already written by ${w.join(', ')}`);
  }
  q.run(`insert into kb_grants(kb_id, project_id, area, can_write, created_at, created_by) values(?, ?, ?, ?, ?, ?)
    on conflict(kb_id, project_id, area) do update set can_write = excluded.can_write, created_at = excluded.created_at, created_by = excluded.created_by`, kbId, p.id, area, body.write ? 1 : 0, now(), by);
  changed();
  return { projectId: p.id, area, write: !!body.write };
}

export function removeGrant(kbId: string, projectId: string, area: string) {
  const g = q.get<Grant>('select * from kb_grants where kb_id = ? and project_id = ? and area = ?', kbId, projectId, areaOf(area));
  if (!g) throw new Error('No such grant');
  if (String(g.created_by || '').startsWith('source:')) throw new Error('This grant belongs to a "Sutra of a project" source: remove the source instead');
  q.run('delete from kb_grants where kb_id = ? and project_id = ? and area = ?', kbId, projectId, areaOf(area));
  changed();
  return { removed: true };
}


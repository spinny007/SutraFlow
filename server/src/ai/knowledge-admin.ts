/** When a schedule fires next: minutes ("60") or a cron expression (seconds first, as Timer triggers). 0 = only Sync now. */
export function nextRunOf(schedule: string | null | undefined, from = Date.now()) {
  const s = String(schedule || '').trim();
  if (!s) return 0;
  if (/^\d+$/.test(s)) return from + Math.max(5, Number(s)) * 60000;
  const next = new Cron(s, { paused: true }).nextRun(new Date(from));
  return next ? next.getTime() : 0;
}

export function saveSource(kbId: string, body: any, by: string) {
  const kb = kbOf(kbId);
  const kind = String(body.kind || '') as SourceKind;
  if (!SOURCE_KINDS.includes(kind)) throw new Error(`Choose what the source reads: ${SOURCE_KINDS.join(', ')}`);
  const prev = body.id ? q.get<SourceRow>('select * from kb_sources where id = ? and kb_id = ?', body.id, kbId) : undefined;
  if (body.id && !prev) throw new Error('No such source');
  const name = String(body.name || '').trim();
  if (!name) throw new Error('Give the source a name');
  const area = areaOf(body.area);
  const cfg = body.config && typeof body.config === 'object' ? body.config : {};
  let connection: string | null = null;
  if (CONNECTION_OF[kind].length) {
    const c = getResource(String(body.connectionId || ''));
    if (!c && kind !== 'http') throw new Error(`Choose the ${SOURCE_LABELS[kind]} connection`);
    if (c) {
      if (!CONNECTION_OF[kind].includes(c.kind)) throw new Error(`${c.name} is not a ${CONNECTION_OF[kind].join(' or ')} connection`);
      if (c.project_id && c.project_id !== kb.project_id) throw new Error(`${c.name} belongs to another project: a source reads through connections of ${projectName(kb.project_id)}, the home project of the knowledge base`);
      connection = c.id;
    }
  }
  if (kind === 'folder' && !path.isAbsolute(String(cfg.path || ''))) throw new Error('Give the full path of the folder on the server');
  if (kind === 'web' && !String(cfg.urls || '').split(/\s+/).some(u => /^https?:\/\//i.test(u))) throw new Error('List the web pages, one address per line');
  if (kind === 'database' && (!String(cfg.sql || '').trim() || !String(cfg.idColumn || '').trim() || !String(cfg.text || '').trim())) throw new Error('A database source needs the query, the key column and the text');
  if (kind === 'http' && (!String(cfg.url || '').trim() || !String(cfg.idField || '').trim() || !String(cfg.text || '').trim())) throw new Error('An HTTP source needs the address, the key field and the text');
  if (kind === 'sutra') {
    const p = getProject(String(cfg.project || ''));
    if (!p) throw new Error('Choose the project whose Sutras write the area');
    if (!area) throw new Error('A Sutra of a project writes an area: name it, for example hr');
  }
  const schedule = kind === 'sutra' ? '' : String(body.schedule ?? '').trim();
  if (schedule && !/^\d+$/.test(schedule)) { try { new Cron(schedule, { paused: true }); } catch (e: any) { throw new Error(`Schedule: ${e.message}`); } }
  const enabled = body.enabled === false ? 0 : 1;
  if (enabled || kind === 'sutra') {
    const w = writersOf(kbId, area, { source: prev?.id, project: kind === 'sutra' ? cfg.project : undefined });
    if (w.length) throw new Error(`One writer per area: ${area || 'the whole base'} is already written by ${w.join(', ')}`);
  }
  if (prev && prev.area !== area && Number(q.get<any>('select count(*) n from kb_source_items where source_id = ?', prev.id)?.n)) throw new Error('The area of a source that has added passages cannot change: remove the source with its passages, then add it again');
  const id = prev?.id || crypto.randomUUID(), t = now();
  q.run(`insert into kb_sources(id, kb_id, name, description, kind, connection_id, config, area, schedule, enabled, next_at, requested, created_at, updated_at, updated_by)
    values(?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, ?, ?, ?)
    on conflict(id) do update set name = excluded.name, description = excluded.description, kind = excluded.kind, connection_id = excluded.connection_id, config = excluded.config, area = excluded.area,
    schedule = excluded.schedule, enabled = excluded.enabled, next_at = excluded.next_at, updated_at = excluded.updated_at, updated_by = excluded.updated_by`,
    id, kbId, name, String(body.description || '').trim() || null, kind, connection, JSON.stringify(cfg), area, schedule || null, enabled, nextRunOf(schedule), t, t, by);
  // A Sutra of a project: that project may change this area (and search the base), nothing else.
  q.run(`delete from kb_grants where kb_id = ? and created_by = ?`, kbId, `source:${id}`);
  if (kind === 'sutra') {
    if (!q.get('select 1 from kb_admin where kb_id = ?', kbId)) q.run(`insert into kb_admin(kb_id, access, updated_at, updated_by) values(?, 'granted', ?, ?)`, kbId, t, by);
    if (cfg.project !== kb.project_id) q.run(`insert into kb_grants(kb_id, project_id, area, can_write, created_at, created_by) values(?, ?, ?, 1, ?, ?) on conflict(kb_id, project_id, area) do update set can_write = 1, created_by = excluded.created_by`, kbId, cfg.project, area, t, `source:${id}`);
  }
  changed();
  return sourceView(q.get<SourceRow>('select * from kb_sources where id = ?', id)!);
}


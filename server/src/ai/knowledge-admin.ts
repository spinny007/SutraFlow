const running = new Map<string, AbortController>();
export const syncing = () => [...running.keys()];

/**
 * Reads a source and brings its area in step: new and changed items are added (vectors made only for
 * them), unchanged ones skipped, items gone from the source removed. An item that cannot be read keeps
 * its passages. A listing that comes back empty while passages exist removes nothing.
 */
export async function runSource(id: string, startedBy = 'schedule') {
  const s = sourceOf(id);
  const kbRow = getResource(s.kb_id);
  if (!kbRow) throw new Error('The knowledge base of the source no longer exists');
  if (running.has(id)) throw new Error('Already syncing');
  const ctl = new AbortController();
  running.set(id, ctl);
  const runId = crypto.randomUUID();
  const n = { found: 0, added: 0, changed: 0, unchanged: 0, removed: 0, failed: 0 };
  const notes: string[] = [];
  const note = (m: string) => { if (notes.length < 50) notes.push(m); };
  q.run(`insert into kb_sync_runs(id, source_id, kb_id, engine, started_at, status, started_by) values(?, ?, ?, ?, ?, 'running', ?)`, runId, id, s.kb_id, config.engineId, now(), startedBy);
  const progress = () => q.run(`update kb_sync_runs set found = ?, added = ?, changed = ?, unchanged = ?, removed = ?, failed = ? where id = ?`, n.found, n.added, n.changed, n.unchanged, n.removed, n.failed, runId);
  let status = 'done', error: string | null = null;
  try {
    // Work of the home project: its connections, its properties, its connection limits.
    await inProject(kbRow.project_id ?? null, async () => {
      const kb = effectiveResource(s.kb_id)!;
      const before = new Map(q.all<{ item: string; hash: string }>('select item, hash from kb_source_items where source_id = ?', id).map(r => [r.item, r.hash]));
      await withItems(s, ctl.signal, async items => {
        const seen = new Set<string>();
        for (const it of items) {
          if (ctl.signal.aborted) throw new Error('Stopped');
          if (seen.has(it.key)) continue;
          seen.add(it.key);
          n.found++;
          const prev = before.get(it.key);
          if (prev && it.fp && prev === it.fp) { n.unchanged++; continue; }
          try {
            const { text, meta } = await it.load();
            const fp = it.fp || hashOf(text, meta);
            if (prev === fp) { n.unchanged++; continue; }
            if (!String(text).trim()) { note(`${it.key}: no text`); n.failed++; continue; }
            await addKnowledge(kb, secret, sourceName(s, it.key), text, { ...meta, managedSource: s.name }, ctl.signal);
            q.run(`insert into kb_source_items(source_id, item, hash, at) values(?, ?, ?, ?) on conflict(source_id, item) do update set hash = excluded.hash, at = excluded.at`, id, it.key, fp, now());
            if (prev) n.changed++; else n.added++;
          } catch (e: any) {
            if (ctl.signal.aborted) throw e;
            n.failed++; note(`${it.key}: ${e?.message || e}`);
          }
          if (n.found % 25 === 0) progress();
        }
        const gone = [...before.keys()].filter(k => !seen.has(k));
        if (!n.found && before.size) { note(`The source listed nothing while ${before.size} items were added before: nothing removed (a missing folder or a lost connection must not empty the knowledge base). Re-index clears and reads it again.`); return; }
        for (const k of gone) {
          await removeKnowledge(kb, sourceName(s, k), false, secret);
          q.run('delete from kb_source_items where source_id = ? and item = ?', id, k);
          n.removed++;
        }
      });
    });
    if (n.failed) status = 'done with problems';
  } catch (e: any) {
    status = ctl.signal.aborted ? 'stopped' : 'failed';
    error = String(e?.message || e).slice(0, 2000);
  } finally {
    running.delete(id);
    q.run(`update kb_sync_runs set status = ?, finished_at = ?, found = ?, added = ?, changed = ?, unchanged = ?, removed = ?, failed = ?, error = ?, notes = ? where id = ?`,
      status, now(), n.found, n.added, n.changed, n.unchanged, n.removed, n.failed, error, JSON.stringify(notes), runId);
    // Housekeeping: the last 50 runs of each source.
    q.run(`delete from kb_sync_runs where source_id = ? and id not in (select id from kb_sync_runs where source_id = ? order by started_at desc limit 50)`, id, id);
  }
  return { runId, status, ...n, error, notes };
}

let ticking = false;
/** The leader's check (every 15 seconds): sources asked for or due run one after another. */
export async function knowledgeSyncTick(alive: () => boolean = () => true) {
  if (ticking) return;
  ticking = true;
  try {
    // Runs of an engine that stopped, or of this one before a restart, did not finish.
    const engines = new Set(q.all<{ id: string }>('select id from engines where heartbeat_at > ?', Date.now() - 60000).map(r => r.id));
    for (const r of q.all<{ id: string; source_id: string; engine: string }>(`select id, source_id, engine from kb_sync_runs where status = 'running'`)) {
      if ((r.engine === config.engineId && !running.has(r.source_id)) || (r.engine !== config.engineId && !engines.has(r.engine))) q.run(`update kb_sync_runs set status = 'interrupted', finished_at = ? where id = ?`, now(), r.id);
    }
    const t = Date.now();
    const due = q.all<SourceRow>(`select * from kb_sources where enabled = 1 and exported_flow is null and kind != 'sutra' and (requested = 1 or (next_at > 0 and next_at <= ?)) order by next_at`, t);
    for (const s of due) {
      if (!alive()) break;
      if (running.has(s.id)) continue;
      const by = Number(s.requested) ? 'Sync now' : 'schedule';
      q.run('update kb_sources set requested = 0, next_at = ? where id = ?', nextRunOf(s.schedule), s.id);
      await runSource(s.id, by).catch(e => console.error(`Knowledge source ${s.name}:`, e?.message || e));
    }
  } finally { ticking = false; }
}
/** Leadership lost or the engine stops: running syncs stop (the next leader starts them again when due). */
export function stopKnowledgeSync() { for (const c of running.values()) c.abort(); }


/** Removes a source; with its passages, the sources it added leave the knowledge base too. */
export async function deleteSource(id: string, withPassages: boolean) {
  const s = sourceOf(id);
  if (running.has(id)) throw new Error('The source is syncing: wait for it to finish');
  let removed = 0;
  if (withPassages) {
    const kb = effectiveResource(s.kb_id);
    if (kb) for (const it of q.all<{ item: string }>('select item from kb_source_items where source_id = ?', id)) removed += await removeKnowledge(kb, sourceName(s, it.item), false, secret).catch(() => 0) ? 1 : 0;
  }
  q.run('delete from kb_source_items where source_id = ?', id);
  q.run('delete from kb_sync_runs where source_id = ?', id);
  q.run('delete from kb_grants where kb_id = ? and created_by = ?', s.kb_id, `source:${id}`);
  q.run('delete from kb_sources where id = ?', id);
  changed();
  return { removed: true, passagesRemovedFor: removed };
}

/** Sync now: the leader starts it within its next check (15 seconds). */
export function requestSync(id: string, reindex = false) {
  const s = sourceOf(id);
  if (s.kind === 'sutra') throw new Error('A Sutra of a project is not synced here: its Sutras write the area');
  if (s.exported_flow) throw new Error(`This source was exported as a Sutra in ${projectName(s.exported_project)}: that Sutra keeps the area in step now`);
  // Re-index: forget what was read, so every item is read and added again.
  if (reindex) q.run('delete from kb_source_items where source_id = ?', id);
  q.run('update kb_sources set requested = 1 where id = ?', id);
  return { requested: true, reindex, note: 'The leader engine starts the sync within 15 seconds.' };
}


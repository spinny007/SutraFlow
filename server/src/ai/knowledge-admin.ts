/** One thing a source holds: its key (the source name below the area), a cheap fingerprint when it has one, and how to read it. */
interface Item { key: string; fp?: string; load(): Promise<{ text: string; meta: Record<string, any> }> }
const MAX_ITEMS = 20000;
const sourceName = (s: { area: string }, key: string) => [areaOf(s.area), String(key).replace(/^\/+/, '')].filter(Boolean).join('/');
/** "{name}. {description}" filled from a row; {a.b} reaches into objects. */
export function fillTemplate(tpl: string, row: Record<string, any>) {
  return String(tpl).replace(/\{([^{}]+)\}/g, (_m, k) => {
    const v = String(k).trim().split('.').reduce<any>((o, p) => (o == null ? o : o[p]), row);
    return v == null ? '' : typeof v === 'object' ? JSON.stringify(v) : String(v);
  });
}
const detailsOf = (list: unknown, row: Record<string, any>) => Object.fromEntries(String(list || '').split(',').map(s => s.trim()).filter(Boolean).map(k => [k, row[k] == null ? '' : String(row[k])]));
const maxBytes = (c: any) => (Number(c.maxMb) || 25) * 1048576;
const tooBig = (name: string, n: number, c: any) => { if (n > maxBytes(c)) throw new Error(`${name} is ${(n / 1048576).toFixed(1)} MB, more than ${Number(c.maxMb) || 25} MB`); };

/** Reads the items of a source and hands them to use; connections stay open while use runs. */
async function withItems<R>(s: SourceRow, signal: AbortSignal, use: (items: Item[]) => Promise<R>): Promise<R> {
  const c = json(s.config);
  const conn = s.connection_id ? effectiveResource(s.connection_id) : undefined;
  if (s.connection_id && !conn) throw new Error('The connection of the source no longer exists');
  switch (s.kind) {
    case 'folder': {
      const root = String(c.path);
      const files = await listFiles(root, String(c.pattern || '*'), c.recursive !== false);
      return use(files.slice(0, MAX_ITEMS).map(f => ({
        key: f.name, fp: `${f.size}|${f.modifiedAt}`,
        load: async () => { tooBig(f.name, f.size, c); const r = await documentText(await fsp.readFile(f.path), { name: f.name }); return { text: r.text, meta: { file: f.name, modified: f.modifiedAt, ...(r.title ? { title: r.title } : {}) } }; },
      })));
    }
    case 'remote':
      return withRemote(conn!, secret, async x => {
        const start = remotePath(x.base, String(c.folder || ''));
        const pattern = msWildcard(String(c.pattern || '*'));
        const out: Item[] = [];
        const walk = async (dir: string, depth: number) => {
          for (const e of await x.list(dir)) {
            if (out.length >= MAX_ITEMS || signal.aborted) return;
            if (e.isDir) { if (c.recursive && depth < 10 && !/^\.\.?$/.test(e.name)) await walk(e.path, depth + 1); continue; }
            if (pattern && !pattern.test(e.name)) continue;
            const rel = path.posix.relative(start, e.path) || e.name;
            out.push({ key: rel, fp: `${e.size}|${e.modifiedAt}`, load: async () => { tooBig(rel, e.size, c); const r = await documentText(await x.get(e.path), { name: e.name }); return { text: r.text, meta: { file: rel, modified: e.modifiedAt } }; } });
          }
        };
        await walk(start, 0);
        return use(out);
      });
    case 'sharepoint': {
      const call = callerFor(conn!.id, signal);
      const { drive } = await driveOf(call, c);
      const files = await listFolder(call, drive, String(c.folder || '').replace(/^\/+|\/+$/g, ''), !!c.recursive, msWildcard(String(c.pattern || '*')));
      return use(files.slice(0, MAX_ITEMS).map(f => ({
        key: f.path, fp: `${f.size}|${f.modifiedAt}`,
        load: async () => { tooBig(f.path, f.size, c); const d = await download(call, drive, f.path, signal); const r = await documentText(d.data, { name: f.name, contentType: f.mimeType }); return { text: r.text, meta: { file: f.path, url: f.webUrl, modified: f.modifiedAt } }; },
      })));
    }
    case 'gdrive': {
      const G = 'https://www.googleapis.com/drive/v3/files';
      const files: any[] = [];
      let token = '';
      for (let page = 0; page < 100; page++) {
        const query: Record<string, string> = { q: `'${String(c.folderId || 'root').replace(/'/g, "\\'")}' in parents and trashed = false`, fields: 'nextPageToken, files(id, name, mimeType, modifiedTime, size, webViewLink)', pageSize: '200' };
        if (token) query.pageToken = token;
        const b = (await apiCall(conn!.id, { method: 'GET', url: G, query, signal })).body;
        files.push(...(b.files || []));
        token = b.nextPageToken || '';
        if (!token || files.length >= MAX_ITEMS) break;
      }
      const pattern = msWildcard(String(c.pattern || '*'));
      return use(files.filter(f => f.mimeType !== 'application/vnd.google-apps.folder' && (!pattern || pattern.test(f.name))).slice(0, MAX_ITEMS).map(f => ({
        key: f.name, fp: `${f.id}|${f.modifiedTime}`,
        load: async () => {
          // Google Docs, Sheets and Slides are exported as text; other files are downloaded and read.
          const native = String(f.mimeType).startsWith('application/vnd.google-apps.');
          const res = native ? await apiCall(conn!.id, { method: 'GET', url: `${G}/${f.id}/export`, query: { mimeType: f.mimeType.endsWith('spreadsheet') ? 'text/csv' : 'text/plain' }, parse: 'buffer', signal })
            : await apiCall(conn!.id, { method: 'GET', url: `${G}/${f.id}`, query: { alt: 'media' }, parse: 'buffer', signal });
          if (res.status >= 400) throw new Error(`${f.name}: Google Drive answered ${res.status}`);
          tooBig(f.name, res.buffer!.length, c);
          const r = native ? { text: res.buffer!.toString('utf8') } : await documentText(res.buffer!, { name: f.name, contentType: f.mimeType });
          return { text: r.text, meta: { file: f.name, url: f.webViewLink || '', modified: f.modifiedTime } };
        },
      })));
    }
    case 'web':
      return use(String(c.urls || '').split(/\s+/).filter(u => /^https?:\/\//i.test(u)).slice(0, 2000).map(url => ({
        key: url,
        load: async () => {
          const res = await httpCall({ method: 'GET', url, headers: { accept: 'text/html,application/pdf,*/*', 'user-agent': 'SutraFlow' }, timeoutMs: 120000, signal, parse: 'buffer' });
          if (res.status >= 400) throw new Error(`${url} answered ${res.status}`);
          tooBig(url, res.buffer!.length, c);
          const r = await documentText(res.buffer!, { name: url.split(/[?#]/)[0].split('/').pop() || url, contentType: res.headers['content-type'] || '' });
          return { text: r.text, meta: { url, ...(r.title ? { title: r.title } : {}) } };
        },
      })));
    case 'database': {
      const db = await dbConnection(conn!, secret);
      const rows = (await db.query(String(c.sql), {})).rows.slice(0, MAX_ITEMS);
      return use(rowItems(rows, c));
    }
    case 'http': {
      const tls = tlsFromConnection(conn, secret);
      const dispatcher = dispatcherFor(conn, tls);
      const auth = await applyAuth(c.auth ? effectiveResource(String(c.auth)) : undefined, secret, (v: unknown) => v, { signal, dispatcher });
      const url = new URL(joinUrl(conn?.config.baseUrl, String(c.url)));
      for (const [k, v] of Object.entries(auth.query)) url.searchParams.set(k, v);
      const res = await httpCall({ method: 'GET', url: url.toString(), headers: { accept: 'application/json', ...auth.headers }, dispatcher, timeoutMs: 120000, signal, parse: 'json' });
      if (res.status >= 400) throw new Error(`${url.origin}${url.pathname} answered ${res.status}`);
      const list = String(c.itemsPath || '').trim() ? String(c.itemsPath).split('.').reduce<any>((o, p) => (o == null ? o : o[p]), res.body) : res.body;
      if (!Array.isArray(list)) throw new Error(`The answer has no list${c.itemsPath ? ` at ${c.itemsPath}` : ''}`);
      return use(rowItems(list.slice(0, MAX_ITEMS), { ...c, idColumn: c.idField }));
    }
    default: throw new Error(`${SOURCE_LABELS[s.kind] || s.kind} is not synced here`);
  }
}
function rowItems(rows: Record<string, any>[], c: any): Item[] {
  const key = String(c.idColumn);
  return rows.filter(r => r && r[key] != null && String(r[key]) !== '').map(r => {
    const text = fillTemplate(String(c.text), r), meta = detailsOf(c.details, r);
    return { key: String(r[key]), fp: hashOf(text, meta), load: async () => ({ text, meta }) };
  });
}
const hashOf = (text: string, meta: Record<string, any>) => crypto.createHash('sha256').update(JSON.stringify([text, meta])).digest('hex').slice(0, 32);


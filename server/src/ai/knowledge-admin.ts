/**
 * Knowledge admin (2.1.5). An administrator makes a project's knowledge base a server knowledge base:
 * grants it to every project (to search) or to listed projects, for the whole base or areas of it (a
 * folder of sources such as products), to search or also to change. Managed sources keep an area in
 * step with files, SFTP, SharePoint, Google Drive, web pages, a database query or an HTTP API: on a
 * schedule or Sync now, on the leader engine only, reading each item and making vectors only for what
 * changed, removing what went away. One writer per area: a managed source, an exported Sutra or one
 * granted project. A knowledge base can also be an MCP tool that outside assistants search.
 */

export const SOURCE_KINDS = ['folder', 'remote', 'sharepoint', 'gdrive', 'web', 'database', 'http', 'sutra'] as const;
export type SourceKind = typeof SOURCE_KINDS[number];
/** The connection kinds each source reads through; folder and web need none. */
const CONNECTION_OF: Record<SourceKind, string[]> = { folder: [], remote: ['sftp', 'ftp'], sharepoint: ['oauthApp'], gdrive: ['oauthApp'], web: [], database: ['database'], http: ['httpConnection'], sutra: [] };
export const SOURCE_LABELS: Record<SourceKind, string> = {
  folder: 'Files in a server folder', remote: 'SFTP or FTP folder', sharepoint: 'SharePoint or OneDrive', gdrive: 'Google Drive folder',
  web: 'Web pages', database: 'Database query', http: 'HTTP API (JSON)', sutra: 'Sutra of a project',
};
/** Kinds whose managed sync can be exported as a Sutra built from ordinary steps. */
export const EXPORTABLE: SourceKind[] = ['database', 'folder', 'web'];


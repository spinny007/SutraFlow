let e = 0;
const N = (id: string, type: string, name: string, x: number, y: number, cfg: Record<string, any>, description: string): FlowNode => ({ id, type, name, x, y, config: cfg, description } as FlowNode);
const E = (from: string, to: string, port = 'out') => ({ id: `e${++e}`, from, port, to });
const jsonataString = (s: string) => JSON.stringify(s);
const jsonataField = (k: string) => (/^[A-Za-z_]\w*$/.test(k) ? k : `\`${k.replace(/`/g, '')}\``);

/**
 * Exports a managed source as a Sutra of ordinary steps in the home project, for a designer to change:
 * the managed sync stops, and the exported Sutra may write only the source's area (knowledge-access.ts).
 * Database, folder and web page sources can be exported.
 */
export function exportSource(id: string, by: string) {
  const s = sourceOf(id);
  if (s.exported_flow) throw new Error('Already exported');
  if (!EXPORTABLE.includes(s.kind)) throw new Error(`${SOURCE_LABELS[s.kind]} sources are not exported; start from the knowledge feed samples (New Sutra, Samples) and grant the project the area`);
  const kb = kbOf(s.kb_id);
  const projectId = kb.project_id;
  if (!projectId) throw new Error('The knowledge base has no home project');
  const c = json(s.config), area = areaOf(s.area);
  const prefix = area ? `${area}/` : '';
  const sched = String(s.schedule || '').trim();
  const timer = N('t', 'timer', /^\d+$/.test(sched) ? `Every ${sched} minutes` : sched ? 'On schedule' : 'Every hour', 60, 240,
    /^\d+$/.test(sched) ? { mode: 'interval', every: Number(sched) * 60, payload: '{}' } : { mode: 'cron', cron: sched || '0 0 * * * *', timezone: '', payload: '{}' },
    'The schedule of the managed source. A test run starts at once.');
  const add = (x: number, y: number, sourceTpl: string, text: string, meta: { k: string; v: string }[]) => N('k', 'knowledgeAdd', 'Add to knowledge', x, y,
    { knowledge: kb.id, source: sourceTpl, text, unchanged: 'skip', meta: [...meta, { k: 'managedSource', v: s.name }] },
    `Adds or replaces the item under ${prefix || 'its own name'}; an unchanged item is skipped, so vectors are made only for what changed.`);
  const keep = (x: number, y: number) => N('r', 'knowledgeRemove', 'Remove what went away', x, y, { knowledge: kb.id, action: 'keep only these sources', keep: '{{nodes.Current items.sources}}', under: area },
    `Items no longer in the source leave the knowledge base. Only sources under ${area || 'the whole base'} are touched.`);
  const log = (x: number, y: number) => N('l', 'log', 'Log the feed', x, y, { level: 'info', message: `${s.name}: {{input.removed}} removed` }, 'One line per feed.');
  let nodes: FlowNode[], edges: any[];
  e = 0;
  if (s.kind === 'database') {
    const idc = String(c.idColumn);
    const details = String(c.details || '').split(',').map(x => x.trim()).filter(Boolean);
    nodes = [timer,
      N('q', 'dbQuery', 'Read the rows', 300, 240, { connection: s.connection_id, params: [], maxRows: MAX_ITEMS, sql: String(c.sql) }, 'The query of the managed source.'),
      N('c', 'jsonata', 'Current items', 540, 240, { source: '{{input}}', expression: `{ "rows": rows, "sources": rows.(${jsonataString(prefix)} & $string(${jsonataField(idc)})) }` }, 'The source name of every row, for the clean-up at the end.'),
      N('f', 'forEach', 'Each row', 780, 240, { list: '{{input.rows}}', max: MAX_ITEMS }, 'One row at a time on the item output; then done once.'),
      add(1020, 140, `${prefix}{{input.${idc}}}`, String(c.text).replace(/\{([^{}]+)\}/g, (_m, k) => `{{input.${String(k).trim()}}}`), details.map(k => ({ k, v: `{{input.${k}}}` }))),
      keep(1020, 340), log(1260, 340)];
    edges = [E('t', 'q'), E('q', 'c'), E('c', 'f'), E('f', 'k', 'item'), E('f', 'r', 'done'), E('r', 'l')];
  } else if (s.kind === 'folder') {
    nodes = [timer,
      N('d', 'fileList', 'List the files', 300, 240, { location: String(c.path), pattern: String(c.pattern || '*'), recursive: c.recursive !== false, sort: 'name', max: MAX_ITEMS, format: 'do not read' }, 'Every file of the folder, without reading it.'),
      N('c', 'jsonata', 'Current items', 540, 240, { source: '{{input}}', expression: `{ "files": files, "sources": files.(${jsonataString(prefix)} & name) }` }, 'The source name of every file, for the clean-up at the end.'),
      N('f', 'forEach', 'Each file', 780, 240, { list: '{{input.files}}', max: MAX_ITEMS }, 'One file at a time on the item output; then done once.'),
      N('o', 'fileRead', 'Read the file', 1020, 140, { folder: String(c.path), path: '{{input.name}}', format: 'base64 (binary)', maxMb: Number(c.maxMb) || 25 }, 'The file as bytes.'),
      N('x', 'docText', 'Take the text', 1260, 140, { from: 'earlier step', content: '{{input.content}}', encoding: 'base64', name: '{{input.name}}', type: 'auto', maxMb: Number(c.maxMb) || 25 }, 'PDF, Word, PowerPoint, Excel, OpenDocument, HTML or text.'),
      add(1500, 140, `${prefix}{{input.name}}`, '{{input.text}}', [{ k: 'file', v: '{{input.name}}' }]),
      N('w', 'log', 'File not read', 1260, 20, { level: 'warn', message: 'Not added: {{input.error.message}}' }, 'A file that cannot be read keeps its passages; the feed goes on.'),
      keep(1020, 340), log(1260, 340)];
    edges = [E('t', 'd'), E('d', 'c'), E('c', 'f'), E('f', 'o', 'item'), E('o', 'x'), E('x', 'k'), E('o', 'w', 'error'), E('x', 'w', 'error'), E('f', 'r', 'done'), E('r', 'l')];
  } else {
    const urls = String(c.urls || '').split(/\s+/).filter(u => /^https?:\/\//i.test(u));
    nodes = [timer,
      N('c', 'jsonata', 'Current items', 300, 240, { source: '{}', expression: `{ "pages": ${JSON.stringify(urls)}, "sources": ${JSON.stringify(urls.map(u => prefix + u))} }` }, 'The pages of the managed source.'),
      N('f', 'forEach', 'Each page', 540, 240, { list: '{{input.pages}}', max: 2000 }, 'One page at a time on the item output; then done once.'),
      N('x', 'docText', 'Read the page', 780, 140, { from: 'web address', url: '{{input}}', type: 'auto', maxMb: Number(c.maxMb) || 25 }, 'HTML or PDF, as text.'),
      add(1020, 140, `${prefix}{{input.url}}`, '{{input.text}}', [{ k: 'url', v: '{{input.url}}' }, { k: 'title', v: '{{input.title}}' }]),
      N('w', 'log', 'Page not read', 1020, 20, { level: 'warn', message: 'Not added: {{input.error.message}}' }, 'A page that cannot be read keeps its passages; the feed goes on.'),
      keep(780, 340), log(1020, 340)];
    edges = [E('t', 'c'), E('c', 'f'), E('f', 'x', 'item'), E('x', 'k'), E('x', 'w', 'error'), E('f', 'r', 'done'), E('r', 'l')];
  }
  const flow = saveFlow(undefined, {
    name: `Knowledge feed: ${s.name}`,
    description: `Exported from Knowledge admin (${kb.name}${area ? `, area ${area}` : ''}) on ${now().slice(0, 10)} by ${by}. Keeps the area in step with its source; it may change only ${area ? `${area}/` : 'the whole base'} of the knowledge base. Deploy it to run on its schedule: the managed sync of the source has stopped.`,
    nodes, edges,
  }, projectId);
  q.run('update kb_sources set exported_project = ?, exported_flow = ?, requested = 0, updated_at = ?, updated_by = ? where id = ?', projectId, flow.id, now(), by, id);
  changed();
  return { flowId: flow.id, projectId, projectName: projectName(projectId), name: flow.name };
}


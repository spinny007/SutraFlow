/**
 * Everything a sample stores is named sample_<objective> (sample_sutraflow.sample_sales_orders, the counter
 * sample_channel_orders, the folder ${files}/sample_csv), so it can be told apart from a site's own data.
 * Sutras keep "Sample: ..." and connections "Sample ..." names; outside SutraFlow only what is reached through
 * a "Sample ..." connection is touched.
 */
export const isSampleName = (n: unknown) => /^sample_/i.test(String(n ?? ''));

/** Exact names of the sample data of versions before 2.1.5, recognised when removing. */
export const OLD_SAMPLE_DATA = {
  mysqlDatabase: 'sutraflow_samples',
  mysqlTables: ['sales_orders', 'products', 'customers', 'orders'],
  mysqlProcedures: ['customer_orders'],
  sqliteFiles: ['samples.sqlite'],
  mongoCollections: ['sutraflow_sample_orders'],
  counters: /^sample-(channel-orders|notifications|poll-.+|orders-.+)$/,
  folders: ['validation-samples'],
  filesIn: { documents: () => sampleDocuments().map(([n]) => n), scripts: () => ['sales_report.py'] } as Record<string, () => string[]>,
  windowsFolders: ['C:/sutra/samples', 'C:/sutra/inbox', 'C:/sutra/outbox'],
  remoteFiles: [/^outbox\/orders\.csv$/, /^archive\/orders-.*\.csv$/],
};

/** Project properties the samples add; removed with them when nothing left in the project uses them. */
const SAMPLE_PROPERTIES = ['CHAT_SITE_SECRET', 'DOCS_FOLDER', 'DOWNLOADS', 'MONGODB_URI', 'ORDERS_TABLE', 'PRODUCTS_TABLE', 'SAMPLE_CSV_FOLDER', 'SAMPLE_INBOX_FOLDER', 'SAMPLE_OUTBOX_FOLDER', 'SCRIPTS_FOLDER', 'VALIDATION_FOLDER'];

export interface SampleItem { where: string; what: string; name: string; old?: boolean; note?: string }
export interface SampleReport { items: SampleItem[]; kept: SampleItem[]; problems: string[]; notes: string[]; removed: boolean }

const isSampleSutra = (f: { name: string; folder?: string }) => /^Sample:/i.test(f.name) || (/^Skill:/i.test(f.name) && /^Samples(\/|$)/.test(f.folder || ''));
const isSampleConnection = (name: string) => /^Sample /.test(name);
const safeId = (n: unknown) => typeof n === 'string' && /^[\w$]{1,128}$/.test(n);
const secretOf = (name: string, what = 'Secret') => {
  if (!name) throw new Error(`${what} is not set`);
  const v = getSecret(name);
  if (v === undefined) throw missingSecretError(name, what);
  return v;
};

/**
 * Lists the samples and their data, and removes them when remove is true. SutraFlow should be stopped for a
 * removal (the installer stops it): running engines keep the Sutras they have loaded.
 */
export async function sampleData(o: { remove: boolean }): Promise<SampleReport> {
  const items: SampleItem[] = [], kept: SampleItem[] = [], problems: string[] = [];
  const notes = ['Messages in sample_ queues and topics on brokers, and sample data in cloud services (Firebase, Dropbox, Google, YouTube), stay there: remove them in those services if you used those samples.'];
  const add = (i: SampleItem) => { items.push(i); };

  // SutraFlow: Sutras, then the connections nothing else uses.
  const flows = q.all<{ id: string; name: string; project_id: string; folder: string; doc: string }>('select id, name, project_id, folder, doc from flows');
  const sutras = flows.filter(isSampleSutra);
  const gone = new Set(sutras.map(f => f.id));
  const others = flows.filter(f => !gone.has(f.id));
  const resources = q.all<{ id: string; name: string; kind: string; project_id: string | null; config: string }>('select id, name, kind, project_id, config from resources');
  const sampleConns = resources.filter(r => isSampleConnection(r.name));
  const otherConns = resources.filter(r => !isSampleConnection(r.name));
  const projectName = (id: string | null) => (id && getProject(id)?.name) || 'server-wide';
  for (const f of sutras) add({ where: projectName(f.project_id), what: 'Sutra', name: f.name });
  const conns: typeof sampleConns = [];
  for (const r of sampleConns) {
    const user = others.find(f => f.doc.includes(r.id)) || otherConns.find(x => x.config.includes(r.id));
    if (user) kept.push({ where: projectName(r.project_id), what: 'connection', name: r.name, note: `used by ${user.name}` });
    else { conns.push(r); add({ where: projectName(r.project_id), what: 'connection', name: r.name }); }
  }

  // Outside SutraFlow: through every "Sample ..." connection, kept or not.
  // A placeholder never filled in (an example.com host, no password) can hold no data: it is not tried.
  const sqliteFiles = new Set<string>(), notSetUp: string[] = [];
  for (const r of sampleConns) {
    if (!['database', 'mongodb', 'sftp', 'ftp'].includes(r.kind)) continue;
    const res = (() => { try { return effectiveResource(r.id); } catch { return undefined; } })();
    if (!res) continue;
    if (/(^|\.)example\.(com|org|net)$/i.test(String(res.config.host || ''))) { notSetUp.push(r.name); continue; }
    try {
      if (r.kind === 'database') await databaseData(res, o.remove, add, sqliteFiles);
      if (r.kind === 'mongodb') await mongoData(res, o.remove, add);
      if (r.kind === 'sftp' || r.kind === 'ftp') await remoteData(res, o.remove, add);
    } catch (e: any) {
      const m = String(e?.message || e);
      if (/is not set|stored value is unavailable|not selected/i.test(m)) notSetUp.push(r.name);
      else problems.push(`${r.name}: ${m.slice(0, 300)}`);
    }
  }
  if (notSetUp.length) notes.push(`Not set up, so there was nothing to check: ${[...new Set(notSetUp)].join(', ')}.`);

  // What the removed connections hold in SutraFlow's database: knowledge, AI memory, memory tables.
  const stores: [string, string[]][] = [['knowledge', ['ai_knowledge:kb_id']], ['AI memory', ['ai_memory:store_id', 'ai_sessions:store_id', 'ai_session_queue:store_id']], ['memory table', ['mem_rows:store_id', 'mem_meta:store_id']]];
  for (const r of conns) for (const [what, tables] of stores) {
    const [t, col] = tables[0].split(':');
    const n = q.get<{ n: number }>(`select count(*) n from ${t} where ${col} = ?`, r.id)?.n || 0;
    if (n) add({ where: projectName(r.project_id), what, name: `${r.name}: ${n} ${what === 'knowledge' ? 'pieces' : 'rows'}` });
  }
  const schemas = q.all<{ id: string; name: string; project_id: string }>('select id, name, project_id from schemas').filter(s => /^Sample:/i.test(s.name));
  for (const s of schemas) add({ where: projectName(s.project_id), what: 'schema', name: s.name });
  const counters = q.all<{ project_id: string; name: string }>('select project_id, name from counters').filter(c => isSampleName(c.name) || OLD_SAMPLE_DATA.counters.test(c.name));
  for (const c of counters) add({ where: projectName(c.project_id), what: 'counter', name: c.name, old: !isSampleName(c.name) });

  // Project properties the samples added and nothing left uses.
  const props: { projectId: string; name: string; secretRef?: string }[] = [];
  for (const p of listProjects()) {
    const left = [...others.filter(f => f.project_id === p.id).map(f => f.doc), ...otherConns.filter(r => r.project_id === p.id).map(r => r.config)].join('\n');
    for (const v of p.config.variables || []) {
      if (!SAMPLE_PROPERTIES.includes(v.name) || left.includes(`gv.${v.name}`)) continue;
      props.push({ projectId: p.id, name: v.name, secretRef: isVaultType(v.type) && /^gv_/.test(v.value) ? v.value : undefined });
      add({ where: p.name, what: 'project property', name: v.name });
    }
  }

  // Files: sample_ files and folders in each project's files folder and in the data folder.
  const paths: string[] = [];
  const file = (where: string, full: string, old = false) => { if (fs.existsSync(full) && !paths.includes(full)) { paths.push(full); add({ where, what: fs.statSync(full).isDirectory() ? 'folder' : 'file', name: full.split(path.sep).join('/'), old }); } };
  for (const p of listProjects()) {
    const dir = projectFilesDir(p.name);
    if (!fs.existsSync(dir)) continue;
    for (const e of fs.readdirSync(dir)) {
      if (isSampleName(e)) file(p.name, path.join(dir, e));
      else if (OLD_SAMPLE_DATA.folders.includes(e)) file(p.name, path.join(dir, e), true);
      else if (OLD_SAMPLE_DATA.filesIn[e]) for (const n of OLD_SAMPLE_DATA.filesIn[e]()) file(p.name, path.join(dir, e, n), true);
    }
  }
  for (const e of fs.existsSync(config.dataDir) ? fs.readdirSync(config.dataDir) : []) {
    const full = path.join(config.dataDir, e);
    if ((isSampleName(e) || OLD_SAMPLE_DATA.sqliteFiles.includes(e)) && fs.statSync(full).isFile()) { sqliteFiles.delete(path.resolve(full)); file('data folder', full, !isSampleName(e)); }
  }
  for (const f of sqliteFiles) file('data folder', f);
  if (process.platform === 'win32') for (const d of OLD_SAMPLE_DATA.windowsFolders) file('this computer', path.resolve(d), true);

  // The Samples project goes only when nothing else is left in it: deleting a project takes all its
  // connections, schemas and folders, so a connection, schema or property someone added there, which
  // this list does not name, keeps the project (2.1.6).
  const samplesProject = listProjects().find(p => p.name === 'Samples');
  let projectGoes = !!samplesProject && !others.some(f => f.project_id === samplesProject.id);
  if (samplesProject && projectGoes) {
    const goneConns = new Set(conns.map(r => r.id)), goneSchemas = new Set(schemas.map(s => s.id));
    const goneProps = new Set(props.filter(x => x.projectId === samplesProject.id).map(x => x.name));
    const own = [
      ...resources.filter(r => r.project_id === samplesProject.id && !goneConns.has(r.id)).map(r => `connection ${r.name}`),
      ...q.all<{ id: string; name: string }>('select id, name from schemas where project_id = ?', samplesProject.id).filter(s => !goneSchemas.has(s.id)).map(s => `schema ${s.name}`),
      ...(samplesProject.config.variables || []).filter(v => !goneProps.has(v.name)).map(v => `project property ${v.name}`),
    ];
    if (own.length) {
      projectGoes = false;
      kept.push({ where: 'Samples', what: 'project', name: 'Samples', note: `holds ${own.slice(0, 5).join(', ')}${own.length > 5 ? ` and ${own.length - 5} more` : ''}` });
    }
  }
  if (projectGoes) add({ where: 'Samples', what: 'project', name: 'Samples' });

  if (!o.remove) return { items, kept, problems, notes, removed: false };

  tx(() => {
    for (const f of sutras) deleteFlow(f.id);
    for (const r of conns) {
      for (const [, tables] of stores) for (const tc of tables) { const [t, col] = tc.split(':'); q.run(`delete from ${t} where ${col} = ?`, r.id); }
      deleteResource(r.id);
    }
    for (const s of schemas) deleteSchema(s.id);
    for (const c of counters) q.run('delete from counters where project_id = ? and name = ?', c.project_id, c.name);
    // Designer folders under Samples that are now empty.
    for (const fo of q.all<{ project_id: string; area: string; path: string }>("select project_id, area, path from folders where path = 'Samples' or path like 'Samples/%'")) {
      const table = fo.area === 'resources' ? 'resources' : fo.area === 'sutras' ? 'flows' : 'schemas';
      const used = q.get(`select 1 from ${table} where project_id = ? and (folder = ? or folder like ?)`, fo.project_id, fo.path, `${fo.path}/%`);
      if (!used) q.run('delete from folders where project_id = ? and area = ? and path = ?', fo.project_id, fo.area, fo.path);
    }
  });
  for (const pr of [...new Set(props.map(x => x.projectId))]) {
    const p = getProject(pr);
    if (!p) continue;
    const names = props.filter(x => x.projectId === pr).map(x => x.name);
    saveProject({ id: p.id, name: p.name, description: p.description, config: { ...p.config, variables: p.config.variables.filter(v => !names.includes(v.name)) } });
  }
  for (const x of props) if (x.secretRef) deleteSecret(x.secretRef);
  if (projectGoes && samplesProject) deleteProject(samplesProject.id);
  // Database pools hold SQLite files open: closed before the files go.
  await (await import('./connectors/db.js')).closeDbPools().catch(() => {});
  await (await import('./connectors/mongodb.js')).closeMongoPools().catch(() => {});
  for (const f of paths) {
    try { fs.rmSync(f, { recursive: true, force: true }); } catch (e: any) { problems.push(`${f}: ${e?.message || e}`); }
  }
  for (const d of process.platform === 'win32' ? ['C:/sutra'] : []) try { if (fs.existsSync(d) && !fs.readdirSync(d).length) fs.rmdirSync(d); } catch { /* left */ }
  return { items, kept, problems, notes, removed: true };
}

/** sample_ databases, schemas, tables, views and procedures behind a "Sample ..." database connection. */
async function databaseData(r: Resource, remove: boolean, add: (i: SampleItem) => void, sqliteFiles: Set<string>) {
  const c = r.config, where = r.name;
  if (c.driver === 'sqlite') {
    const full = path.resolve(path.isAbsolute(c.file) ? c.file : path.join(config.dataDir, c.file || 'app.sqlite'));
    // A file named as sample data is removed whole (with the data folder's files).
    if (isSampleName(path.basename(full)) || OLD_SAMPLE_DATA.sqliteFiles.includes(path.basename(full))) { sqliteFiles.add(full); return; }
    if (!fs.existsSync(full)) return;
  }
  const { dbConnection } = await import('./connectors/db.js');
  const db = await dbConnection(r, secretOf);
  const rows = async (sql: string) => (await db.query(sql, {})).rows as any[];
  const run = async (sql: string) => { if (remove) await db.query(sql, {}); };
  const lower = (x: any) => Object.fromEntries(Object.entries(x).map(([k, v]) => [k.toLowerCase(), v]));
  if (c.driver === 'mysql') {
    // A connection that names its database works in that database only; one that names none (the samples'
    // "Sample MySQL") reaches the server's sample_ databases and the old sample database.
    const own = String(c.database || '');
    if (own && isSampleName(own)) {
      if (!safeId(own)) return;
      add({ where, what: 'database', name: own });
      await run(`DROP DATABASE IF EXISTS \`${own}\``);
      return;
    }
    const dbs = own ? [] : (await rows('SELECT schema_name AS n FROM information_schema.schemata')).map(x => String(lower(x).n));
    for (const d of dbs.filter(isSampleName).filter(safeId)) { add({ where, what: 'database', name: d }); await run(`DROP DATABASE \`${d}\``); }
    const old = OLD_SAMPLE_DATA.mysqlDatabase;
    if (dbs.includes(old) || own === old) {
      const tables = (await rows(`SELECT table_name AS n FROM information_schema.tables WHERE table_schema = '${old}'`)).map(x => String(lower(x).n));
      const procs = (await rows(`SELECT routine_name AS n FROM information_schema.routines WHERE routine_schema = '${old}'`)).map(x => String(lower(x).n));
      const tGo = tables.filter(t => OLD_SAMPLE_DATA.mysqlTables.includes(t)), pGo = procs.filter(p => OLD_SAMPLE_DATA.mysqlProcedures.includes(p));
      for (const p of pGo) { add({ where, what: 'procedure', name: `${old}.${p}`, old: true }); await run(`DROP PROCEDURE IF EXISTS \`${old}\`.\`${p}\``); }
      for (const t of tGo) { add({ where, what: 'table', name: `${old}.${t}`, old: true }); await run(`DROP TABLE IF EXISTS \`${old}\`.\`${t}\``); }
      if (tables.length === tGo.length && procs.length === pGo.length) { add({ where, what: 'database', name: old, old: true }); await run(`DROP DATABASE \`${old}\``); }
    }
    if (own && own !== old && safeId(own)) {
      for (const x of await rows(`SELECT table_name AS n, table_type AS t FROM information_schema.tables WHERE table_schema = '${own}'`)) {
        const { n, t } = lower(x) as any;
        if (!isSampleName(n) || !safeId(n)) continue;
        add({ where, what: /VIEW/i.test(t) ? 'view' : 'table', name: `${own}.${n}` });
        await run(`DROP ${/VIEW/i.test(t) ? 'VIEW' : 'TABLE'} IF EXISTS \`${own}\`.\`${n}\``);
      }
      for (const x of await rows(`SELECT routine_name AS n, routine_type AS t FROM information_schema.routines WHERE routine_schema = '${own}'`)) {
        const { n, t } = lower(x) as any;
        if (!isSampleName(n) || !safeId(n)) continue;
        add({ where, what: String(t).toLowerCase(), name: `${own}.${n}` });
        await run(`DROP ${/FUNCTION/i.test(t) ? 'FUNCTION' : 'PROCEDURE'} IF EXISTS \`${own}\`.\`${n}\``);
      }
    }
    return;
  }
  if (c.driver === 'postgres') {
    const schemas = (await rows('SELECT schema_name AS n FROM information_schema.schemata')).map(x => String(lower(x).n));
    for (const s of schemas.filter(isSampleName).filter(safeId)) { add({ where, what: 'schema', name: s }); await run(`DROP SCHEMA "${s}" CASCADE`); }
    for (const x of await rows("SELECT table_schema AS s, table_name AS n, table_type AS t FROM information_schema.tables WHERE table_schema NOT IN ('pg_catalog', 'information_schema')")) {
      const { s, n, t } = lower(x) as any;
      if (isSampleName(s) || !isSampleName(n) || !safeId(n) || !safeId(s)) continue;
      add({ where, what: /VIEW/i.test(t) ? 'view' : 'table', name: `${s}.${n}` });
      await run(`DROP ${/VIEW/i.test(t) ? 'VIEW' : 'TABLE'} IF EXISTS "${s}"."${n}"`);
    }
    return;
  }
  if (c.driver === 'mssql') {
    for (const x of await rows("SELECT s.name AS s, o.name AS n, o.type AS t FROM sys.objects o JOIN sys.schemas s ON s.schema_id = o.schema_id WHERE o.type IN ('U', 'V', 'P')")) {
      const { s, n, t } = lower(x) as any;
      if (!isSampleName(n) || !safeId(n) || !safeId(s)) continue;
      const kind = String(t).trim() === 'V' ? 'VIEW' : String(t).trim() === 'P' ? 'PROCEDURE' : 'TABLE';
      add({ where, what: kind.toLowerCase(), name: `${s}.${n}` });
      await run(`DROP ${kind} [${s}].[${n}]`);
    }
    return;
  }
  if (c.driver === 'oracle') {
    for (const x of await rows("SELECT object_name AS n, object_type AS t FROM user_objects WHERE object_type IN ('TABLE', 'VIEW', 'PROCEDURE')")) {
      const { n, t } = lower(x) as any;
      if (!isSampleName(n) || !safeId(n)) continue;
      add({ where, what: String(t).toLowerCase(), name: n });
      await run(`DROP ${t} "${n}"${t === 'TABLE' ? ' PURGE' : ''}`);
    }
    return;
  }
  if (c.driver === 'sqlite') {
    for (const x of await rows("SELECT name AS n, type AS t FROM sqlite_master WHERE type IN ('table', 'view')")) {
      const { n, t } = lower(x) as any;
      if (!isSampleName(n) || !safeId(n)) continue;
      add({ where, what: t, name: n });
      await run(`DROP ${t === 'view' ? 'VIEW' : 'TABLE'} IF EXISTS "${n}"`);
    }
  }
}

/** sample_ collections (and the old sample collection) behind a "Sample ..." MongoDB connection. */
async function mongoData(r: Resource, remove: boolean, add: (i: SampleItem) => void) {
  const { mongoConnection } = await import('./connectors/mongodb.js');
  const { db } = await mongoConnection(r, secretOf);
  const names = (await db.listCollections({}, { nameOnly: true }).toArray()).map((x: any) => String(x.name));
  for (const n of names) {
    const old = OLD_SAMPLE_DATA.mongoCollections.includes(n);
    if (!isSampleName(n) && !old) continue;
    add({ where: r.name, what: 'collection', name: `${db.databaseName}.${n}`, old });
    if (remove) await db.collection(n).drop();
  }
}

/** sample_ files and folders in the base folder of a "Sample ..." SFTP or FTP connection, and the old sample files. */
async function remoteData(r: Resource, remove: boolean, add: (i: SampleItem) => void) {
  const { withRemote, remotePath } = await import('./connectors/remote.js');
  await withRemote(r, secretOf, async x => {
    const list = async (rel: string) => { try { return await x.list(remotePath(x.base, rel)); } catch { return []; } };
    for (const e of await list('')) {
      if (!isSampleName(e.name)) continue;
      add({ where: r.name, what: e.isDir ? 'folder' : 'file', name: e.name });
      if (remove) await (e.isDir ? x.removeDir(e.path) : x.remove(e.path));
    }
    for (const dir of ['outbox', 'archive']) for (const e of await list(dir)) {
      if (e.isDir || !OLD_SAMPLE_DATA.remoteFiles.some(re => re.test(`${dir}/${e.name}`))) continue;
      add({ where: r.name, what: 'file', name: `${dir}/${e.name}`, old: true });
      if (remove) await x.remove(e.path);
    }
  });
}

/* @sutra-file-overview
 * File: server/src/call-contract.ts
 * Purpose/support: The input contract of a called Sutra (2.1.7): the payload schema of its Manual start, for the version a Call Sutra step uses (draft or deployed), with a fingerprint so the designer can say when the called Sutra changed it. Feeds the Call Sutra mapping targets, its notes and the contract API.
 * Connects to (static imports): node:crypto, ./flows.js, ./schemas.js, ./engine/types.js
 * Functions/entry points (static scan): manualStartOf, contractFingerprint, calledContract, isContract
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import crypto from 'node:crypto';
import { getFlow, versionDoc } from './flows.js';
import { getSchema, schemaTree } from './schemas.js';
import type { FlowDoc, FlowNode } from './engine/types.js';

/** What a Call Sutra step offers as its input contract. */
export interface CallContract {
  /** The called Sutra's name. */
  sutra: string;
  /** The version the step uses: 0 = draft. */
  version: number;
  /** The Manual start of the called Sutra. */
  trigger: string;
  /** Its payload schema (id, or id::root for an XSD), empty when it has none. */
  ref: string;
  schemaName: string;
  kind: 'json' | 'xsd' | '';
  /** Strict schema validation of the Manual start: the called Sutra refuses input that does not match. */
  strict: boolean;
  /** Changes when the schema or its shape changes (not when strict validation is switched). */
  fingerprint: string;
}

/** The Version choices of Call Sutra. */
export const CALL_VERSIONS = ['deployed (draft while testing)', 'deployed', 'draft'] as const;

/** The trigger of a Sutra document, when it is a Manual start. */
export function manualStartOf(doc: FlowDoc | undefined): FlowNode | undefined {
  return doc?.nodes.find(n => n.type === 'start');
}

/** A fingerprint of a payload schema: its reference and the shape it describes. */
export function contractFingerprint(ref: string) {
  let tree: unknown = null;
  try { tree = ref ? schemaTree(ref) : null; } catch (e: any) { tree = { error: e.message }; }
  const text = ref ? getSchema(ref.split('::')[0])?.text ?? '' : '';
  return crypto.createHash('sha256').update(JSON.stringify({ ref, tree, text })).digest('hex').slice(0, 12);
}

/**
 * The contract of the Sutra a Call Sutra step calls. The designer uses the draft unless Version is
 * "deployed" (test runs call the draft); a run passes the version it really calls.
 */
export function calledContract(flowId: unknown, use: unknown = CALL_VERSIONS[0], projectId?: string | null): CallContract | { problem: string } {
  const f = typeof flowId === 'string' && flowId ? getFlow(flowId) : undefined;
  if (!f) return { problem: flowId ? 'The called Sutra no longer exists.' : 'Choose the Sutra to call.' };
  if (projectId && f.project_id !== projectId) return { problem: `${f.name} belongs to another project.` };
  let doc: FlowDoc | undefined = f.doc, version = 0;
  if (use === 'deployed') {
    if (!f.deployed) return { problem: `${f.name} is not deployed. Deploy it, or set Version to draft.` };
    doc = versionDoc(f.id, f.deployed.version); version = f.deployed.version;
  }
  const start = manualStartOf(doc);
  if (!start) return { problem: `${f.name} does not start with a Manual start, so it has no input contract.` };
  const ref = typeof start.config?.schema === 'string' ? start.config.schema : '';
  const schema = ref ? getSchema(ref.split('::')[0]) : undefined;
  return {
    sutra: f.name, version, trigger: start.name, ref: schema ? ref : '',
    schemaName: schema ? schema.name + (ref.includes('::') ? ` (${ref.split('::')[1]})` : '') : '',
    kind: schema?.kind === 'json' || schema?.kind === 'xsd' ? schema.kind : '',
    strict: start.config?.validateSchema === true || start.config?.validateSchema === 'true',
    fingerprint: contractFingerprint(schema ? ref : ''),
  };
}

export const isContract = (c: CallContract | { problem: string } | null | undefined): c is CallContract => !!c && !('problem' in c);

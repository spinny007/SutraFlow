import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { config, ensureDataDir } from './config.js';
import { q, now } from './db.js';

/**
 * Secret vault. Values are encrypted with AES-256-GCM using a master key from
 * SUTRA_MASTER_KEY (base64, 32 bytes) or data/master.key, created on first start.
 * Values are never returned by the API. A project reaches them through its Secret properties ({{gv.NAME}})
 * and the engine's ({{ev.NAME}}); {{secret.NAME}} works only for a name behind one of those (2.1.8).
 */
let masterKey: Buffer | null = null;

function key(): Buffer {
  if (masterKey) return masterKey;
  if (process.env.SUTRA_MASTER_KEY) {
    masterKey = Buffer.from(process.env.SUTRA_MASTER_KEY, 'base64');
  } else {
    ensureDataDir();
    const file = path.join(config.dataDir, 'master.key');
    if (!fs.existsSync(file)) fs.writeFileSync(file, crypto.randomBytes(32).toString('base64'), { mode: 0o600 });
    masterKey = Buffer.from(fs.readFileSync(file, 'utf8').trim(), 'base64');
  }
  if (masterKey.length !== 32) throw new Error('The master key must be 32 bytes, base64 encoded');
  return masterKey;
}

/**
 * A key for one purpose (signing visitor tokens, say), derived from the master key: the master key itself
 * never leaves this module, and a key made for one purpose cannot be used for another.
 */
export function purposeKey(purpose: string): Buffer {
  return crypto.createHmac('sha256', key()).update(`sutraflow:${purpose}`).digest();
}

export function encrypt(plain: string) {
  const iv = crypto.randomBytes(12);
  const c = crypto.createCipheriv('aes-256-gcm', key(), iv);
  const data = Buffer.concat([c.update(plain, 'utf8'), c.final()]);
  return { iv: iv.toString('base64'), tag: c.getAuthTag().toString('base64'), data: data.toString('base64') };
}

export function decrypt(e: { iv: string; tag: string; data: string }) {
  const d = crypto.createDecipheriv('aes-256-gcm', key(), Buffer.from(e.iv, 'base64'));
  d.setAuthTag(Buffer.from(e.tag, 'base64'));
  return Buffer.concat([d.update(Buffer.from(e.data, 'base64')), d.final()]).toString('utf8');
}

export const SECRET_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,63}$/;
/** A mistaken secret reference can itself contain a complete credential-bearing URI. */
export const missingSecretError = (_name: string, what = 'Secret') => new Error(`${what}: the selected stored secret is missing or the reference is invalid (value withheld). Enter an encrypted value in the connection or select a stored secret.`);

/**
 * Stores a secret. `owner` is the project a new secret belongs to (a Secret property's value stored from
 * the project); without one it is a server-level secret. Changing a value never changes its owner.
 */
export function setSecret(name: string, value: string, owner?: string | null) {
  if (!SECRET_NAME.test(name)) throw new Error('Secret names use letters, digits and _ and start with a letter or _');
  const e = encrypt(value);
  q.run(
    `insert into secrets(name, iv, tag, data, updated_at, project_id) values(?, ?, ?, ?, ?, ?)
     on conflict(name) do update set iv = excluded.iv, tag = excluded.tag, data = excluded.data, updated_at = excluded.updated_at,
       project_id = coalesce(secrets.project_id, excluded.project_id)`,
    name, e.iv, e.tag, e.data, now(), owner || null,
  );
}

/** Whether a stored secret exists and the project it belongs to (null: server-level). Never the value. */
export function secretOwner(name: string): { exists: boolean; project: string | null } {
  const r = q.get<{ project_id: string | null }>('select project_id from secrets where name = ?', name);
  return { exists: !!r, project: r?.project_id || null };
}

/** Of these names, the ones stored for a project other than `projectId` (2.1.8). */
export function ownedElsewhere(names: string[], projectId: string | null): Set<string> {
  const out = new Set<string>();
  if (!names.length) return out;
  for (let i = 0; i < names.length; i += 200) {
    const part = names.slice(i, i + 200);
    for (const r of q.all<{ name: string; project_id: string | null }>(`select name, project_id from secrets where project_id is not null and name in (${part.map(() => '?').join(', ')})`, ...part)) {
      if (r.project_id && r.project_id !== projectId) out.add(r.name);
    }
  }
  return out;
}

/**
 * Which stored secrets the work that is running may read (2.1.8, audit F1). While a project's work runs
 * (a step, a listener, Test connection, model discovery, a preview: resources.ts `inProject`), only the
 * secrets behind that project's Secret properties (GV) and the engine's Secret properties (EV) can be
 * read, whichever way the name arrived (a connection field, `{{secret.NAME}}`, run data). Outside such
 * work (sign-in, the gateway's own policies, the Admin Console) there is no scope and the caller checks
 * permissions itself.
 */
type SecretScope = () => Set<string> | undefined;
let secretScope: SecretScope = () => undefined;
export function onSecretScope(fn: SecretScope) { secretScope = fn; }

/** The running project may not read this secret. The name is not repeated: a mistaken reference can itself be sensitive. */
export class SecretOutOfScope extends Error {}
export const outOfScopeError = (what = 'Secret') => new SecretOutOfScope(`${what}: the selected stored secret is not behind a Secret property of this project or of the engine, so it cannot be used here. Choose a Secret property of this project ({{gv.NAME}}) or an engine Secret property ({{ev.NAME}}).`);

/** May the work that is running read this stored secret? */
export function secretInScope(name: string) {
  const names = secretScope();
  return !names || names.has(name);
}

/** Reads a stored secret without the project check: only for server-level work (database move, sign-in, Secret properties themselves). */
export function readSecretUnscoped(name: string): string | undefined {
  const r = q.get<{ iv: string; tag: string; data: string }>('select iv, tag, data from secrets where name = ?', name);
  return r ? decrypt(r) : undefined;
}

export function getSecret(name: string): string | undefined {
  if (!secretInScope(name)) throw outOfScopeError();
  return readSecretUnscoped(name);
}

export function requireSecret(name: string, what = 'Secret'): string {
  if (!name) throw new Error(`${what} is not set`);
  if (!secretInScope(name)) throw outOfScopeError(what);
  const v = readSecretUnscoped(name);
  if (v === undefined) throw missingSecretError(name, what);
  return v;
}

export function listSecrets() {
  return q.all<{ name: string; updated_at: string }>('select name, updated_at from secrets order by name');
}

export function deleteSecret(name: string) {
  q.run('delete from secrets where name = ?', name);
}

/** Replaces any revealed secret values in a JSON-able value with a mask, so run history never stores them. */
export function maskSecrets<T>(value: T, revealed: Set<string>): T {
  if (!revealed.size || value === undefined) return value;
  let s = JSON.stringify(value);
  if (s === undefined) return value;
  for (const v of [...revealed].sort((a, b) => b.length - a.length)) {
    if (v.length < 4) continue;
    const enc = JSON.stringify(v).slice(1, -1);
    s = s.split(enc).join('••••••');
  }
  return JSON.parse(s);
}

/**
 * Tables a feature makes for itself (a knowledge base's pgvector table, an AI memory table), made once
 * (2.1.1). Steps running at the same time all asked PostgreSQL for the same CREATE TABLE IF NOT EXISTS,
 * and all but one failed with "duplicate key value violates unique constraint pg_type_typname_nsp_index"
 * (the 8-hour soak: the first 50 MB document learned in parallel batches). Within an engine every caller
 * now waits for the one creation; another engine that loses the same race tries again, finding the table.
 */
const made = new Map<string, Promise<void>>();
const LOST_RACE = /duplicate key value|already exists/i;

export function createOnce(key: string, create: () => Promise<unknown>): Promise<void> {
  let p = made.get(key);
  if (!p) {
    p = (async () => {
      for (let i = 0; ; i++) {
        try { await create(); return; } catch (e: any) {
          if (i < 4 && LOST_RACE.test(String(e?.message))) { await new Promise(r => setTimeout(r, 100 * (i + 1))); continue; }
          throw e;
        }
      }
    })();
    made.set(key, p);
    // A creation that failed for good is tried again by the next caller (the cause may be fixed by then).
    p.catch(() => { if (made.get(key) === p) made.delete(key); });
  }
  return p;
}

/** For tests: forget what was made. */
export const forgetCreated = () => made.clear();

/** The /mcp/studio route on the studio (admin) server. */
export function registerStudioMcp(app: FastifyInstance) {
  app.route({ method: ['GET', 'POST', 'DELETE', 'OPTIONS'], url: '/mcp/studio', handler: (req, reply) => handleStudioMcp(app, req, reply) });
}

async function handleStudioMcp(app: FastifyInstance, req: FastifyRequest, reply: FastifyReply) {
  const method = req.method.toUpperCase();
  if (method === 'GET') return reply.code(405).header('allow', 'POST, DELETE').send({ error: 'This MCP server answers POST requests; it does not open an event stream' });
  if (method === 'DELETE' || method === 'OPTIONS') return reply.code(204).send();
  const token = /^Bearer\s+(.+)$/i.exec(str(req.headers.authorization))?.[1];
  const unauthorized = (message: string) => reply.code(401).header('www-authenticate', 'Bearer realm="SutraFlow studio"').send({ jsonrpc: '2.0', id: null, error: { code: -32001, message } });
  if (!token) return unauthorized('Sign in with an API token (Admin Console > Access): Authorization: Bearer <token>');

  const api: Api = async (m, url, payload) => {
    const r = await app.inject({
      method: m as any, url, remoteAddress: req.ip,
      headers: { authorization: `Bearer ${token}`, 'x-sutra': '1', 'x-sutra-client': 'mcp', ...(payload !== undefined ? { 'content-type': 'application/json' } : {}) },
      ...(payload !== undefined ? { payload: JSON.stringify(payload) } : {}),
    });
    let body: any = null;
    try { body = r.body ? JSON.parse(r.body) : null; } catch { body = r.body; }
    if (r.statusCode >= 400) throw new ToolError(r.statusCode, (body && typeof body === 'object' ? body.error : body) || `Request failed (${r.statusCode})`);
    return body;
  };
  let who: { username: string; kind: string };
  try { who = await api('GET', '/api/access/me'); } catch (e: any) { return e.status === 401 ? unauthorized('The token is not valid') : reply.code(e.status || 500).send({ jsonrpc: '2.0', id: null, error: { code: -32001, message: e.message } }); }

  let msg: any;
  try { msg = typeof req.body === 'string' ? JSON.parse(req.body) : req.body; } catch { return reply.code(400).send({ jsonrpc: '2.0', id: null, error: { code: -32700, message: 'Request is not valid JSON' } }); }
  const batch = Array.isArray(msg) ? msg : [msg];
  const out: any[] = [];
  for (const m of batch) {
    if (!m || m.jsonrpc !== '2.0' || typeof m.method !== 'string') { out.push({ jsonrpc: '2.0', id: m?.id ?? null, error: { code: -32600, message: 'Invalid request' } }); continue; }
    if (m.id === undefined || m.id === null) continue;
    const ok = (result: any) => out.push({ jsonrpc: '2.0', id: m.id, result });
    if (m.method === 'initialize') {
      const asked = str(m.params?.protocolVersion);
      reply.header('mcp-session-id', crypto.randomUUID());
      ok({ protocolVersion: MCP_PROTOCOLS.includes(asked) ? asked : MCP_PROTOCOLS[0], capabilities: { tools: { listChanged: false } }, serverInfo: { name: 'SutraFlow studio', title: 'SutraFlow studio', version: sutraVersion }, instructions: INSTRUCTIONS });
    } else if (m.method === 'ping') ok({});
    else if (m.method === 'tools/list') {
      ok({ tools: STUDIO_TOOLS.map(t => ({ name: t.name, title: t.title, description: t.description, inputSchema: t.inputSchema, annotations: { title: t.title, readOnlyHint: !!t.readOnly, destructiveHint: t.name === 'deploy_release', openWorldHint: false } })) });
    } else if (m.method === 'tools/call') {
      const name = str(m.params?.name);
      const t = STUDIO_TOOLS.find(x => x.name === name);
      if (!t) { out.push({ jsonrpc: '2.0', id: m.id, error: { code: -32602, message: `Unknown tool: ${name}` } }); continue; }
      const args = m.params?.arguments && typeof m.params.arguments === 'object' ? m.params.arguments : {};
      let status = 200, result: unknown, failure = '';
      try { result = await t.run(args, api, who); } catch (e: any) { status = e instanceof ToolError ? e.status : 500; failure = e.message || String(e); }
      // Every call is recorded: who, which tool, in which project, and how it ended (2.1.8). Docs and inputs are not.
      audit({
        actor: who.username, actorKind: who.kind, ip: req.ip, action: `MCP studio ${name}`, method: 'MCP', path: '/mcp/studio',
        target: [args.sutraId, args.runId, args.releaseId].filter(Boolean).map(str).join(' '), projectId: str(args.projectId), status,
        outcome: status < 400 ? 'ok' : status === 401 || status === 403 ? 'denied' : 'failed',
        details: { client: 'mcp', ...(t.changes ? { generated: true } : {}), tool: name, ...(failure ? { reason: failure.slice(0, 500) } : {}) },
      });
      ok(failure ? toolResult(`${status === 403 ? 'Refused' : status === 404 ? 'Not found' : 'Failed'} (${status}): ${failure}`, true) : toolResult(result));
    } else if (m.method === 'resources/list') ok({ resources: [] });
    else if (m.method === 'prompts/list') ok({ prompts: [] });
    else out.push({ jsonrpc: '2.0', id: m.id, error: { code: -32601, message: `Method not found: ${m.method}` } });
  }
  if (!out.length) return reply.code(202).send();
  return reply.code(200).type('application/json').send(JSON.stringify(Array.isArray(msg) ? out : out[0]));
}

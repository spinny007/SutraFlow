const str = (v: unknown) => (typeof v === 'string' ? v : v == null ? '' : String(v));
const need = (args: any, ...keys: string[]) => {
  const missing = keys.filter(k => args?.[k] === undefined || args[k] === null || args[k] === '');
  if (missing.length) throw new ToolError(400, `Missing argument${missing.length > 1 ? 's' : ''}: ${missing.join(', ')}`);
};
const enc = encodeURIComponent;
const hash = (v: unknown) => crypto.createHash('sha256').update(JSON.stringify(v)).digest('hex').slice(0, 16);

/** A generated Sutra reads secrets through Secret properties only (2.1.8 F1); {{secret.NAME}} is refused. */
function refuseDirectSecrets(doc: any) {
  const m = /\{\{\s*secret\.([^}\s]+)\s*\}\}/.exec(JSON.stringify(doc ?? null));
  if (m) throw new ToolError(400, `{{secret.${m[1]}}} reads the vault directly. Use a project Secret property (list_properties) and pick it by its name, such as {{env.NAME}} or the connection's property field.`);
}

/**
 * The Sutra a model wrote, made ready to save: connections may name steps by their names instead of ids,
 * steps without a position are laid out left to right.
 */
function prepareDoc(raw: any) {
  if (!raw || typeof raw !== 'object' || !Array.isArray(raw.nodes)) throw new ToolError(400, 'Give the Sutra as { name, nodes: [{ id, type, name, config }], edges: [{ from, port, to }] }.');
  const nodes = raw.nodes.map((n: any, i: number) => ({ ...n, id: str(n?.id) || `s${i + 1}`, x: Number(n?.x) || 60 + (i % 6) * 300, y: Number(n?.y) || 220 + Math.floor(i / 6) * 200, config: n?.config && typeof n.config === 'object' ? n.config : {} }));
  const byName = new Map(nodes.map((n: any) => [str(n.name).toLowerCase(), n.id]));
  const ids = new Set(nodes.map((n: any) => n.id));
  const ref = (v: unknown) => { const s = str(v); return ids.has(s) ? s : byName.get(s.toLowerCase()) ?? s; };
  const edges = (Array.isArray(raw.edges) ? raw.edges : []).map((e: any, i: number) => ({ ...e, id: str(e?.id) || `c${i + 1}`, from: ref(e?.from), to: ref(e?.to), port: str(e?.port) || 'out' }));
  const unknown = edges.filter((e: any) => !ids.has(e.from) || !ids.has(e.to)).map((e: any) => `${e.from} -> ${e.to}`);
  if (unknown.length) throw new ToolError(400, `Connections name steps that are not in the Sutra: ${unknown.join(', ')}`);
  const doc = { ...raw, nodes, edges };
  refuseDirectSecrets(doc);
  return doc;
}

/** What a change does to a Sutra: steps added, removed and changed (field by field), connections added and removed. */
export function sutraDifference(before: any, after: any) {
  const b = new Map<string, any>((before?.nodes || []).map((n: any) => [n.id, n]));
  const a = new Map<string, any>((after?.nodes || []).map((n: any) => [n.id, n]));
  const label = (n: any) => `${n.name} (${n.type})`;
  const changed: { step: string; changes: { field: string; from: unknown; to: unknown }[] }[] = [];
  for (const [id, n] of a) {
    const o = b.get(id);
    if (!o) continue;
    const changes: { field: string; from: unknown; to: unknown }[] = [];
    for (const k of ['name', 'type', 'description']) if (JSON.stringify(o[k] ?? null) !== JSON.stringify(n[k] ?? null)) changes.push({ field: k, from: o[k] ?? null, to: n[k] ?? null });
    for (const k of new Set([...Object.keys(o.config || {}), ...Object.keys(n.config || {})])) {
      const from = o.config?.[k], to = n.config?.[k];
      if (JSON.stringify(from ?? null) !== JSON.stringify(to ?? null)) changes.push({ field: `config.${k}`, from: from ?? null, to: to ?? null });
    }
    if (JSON.stringify(o.settings ?? null) !== JSON.stringify(n.settings ?? null)) changes.push({ field: 'settings', from: o.settings ?? null, to: n.settings ?? null });
    if (changes.length) changed.push({ step: label(n), changes });
  }
  const name = (m: Map<string, any>, id: string) => m.get(id)?.name ?? id;
  const key = (m: Map<string, any>) => (e: any) => `${name(m, e.from)} -[${e.port}${e.when === 'when' && e.condition ? ` when ${e.condition}` : e.when === 'otherwise' ? ' otherwise' : ''}]-> ${name(m, e.to)}`;
  const be = new Set<string>((before?.edges || []).map(key(b))), ae = new Set<string>((after?.edges || []).map(key(a)));
  return {
    ...(str(before?.name) !== str(after?.name) ? { renamed: { from: before?.name, to: after?.name } } : {}),
    ...(str(before?.description) !== str(after?.description) ? { description: { from: before?.description ?? null, to: after?.description ?? null } } : {}),
    ...(JSON.stringify(before?.variables ?? []) !== JSON.stringify(after?.variables ?? []) ? { variables: { from: before?.variables ?? [], to: after?.variables ?? [] } } : {}),
    stepsAdded: [...a.values()].filter(n => !b.has(n.id)).map(label),
    stepsRemoved: [...b.values()].filter(n => !a.has(n.id)).map(label),
    stepsChanged: changed,
    connectionsAdded: [...ae].filter(x => !be.has(x)),
    connectionsRemoved: [...be].filter(x => !ae.has(x)),
  };
}
const nothingChanged = (d: ReturnType<typeof sutraDifference>) =>
  !('renamed' in d) && !('description' in d) && !('variables' in d) && !d.stepsAdded.length && !d.stepsRemoved.length && !d.stepsChanged.length && !d.connectionsAdded.length && !d.connectionsRemoved.length;

/** A run as an assistant needs it to repair a Sutra: each step's status, input, output and error, and the log. */
function runSummary(r: any) {
  const names = new Map<string, string>((r.doc?.nodes || []).map((n: any) => [n.id, n.name]));
  const cut = (v: unknown) => { const s = JSON.stringify(v ?? null); return s.length > 4000 ? `${s.slice(0, 4000)}... (cut, ${s.length} characters)` : v; };
  return {
    runId: r.id, status: r.status, error: r.error || null, stage: r.stage, startedAt: r.startedAt, finishedAt: r.finishedAt,
    steps: (r.tasks || []).map((t: any) => ({ step: names.get(t.node_id) || t.node_id, status: t.status, port: t.port, ms: t.ms, input: cut(t.input), output: cut(t.output), ...(t.error ? { error: t.error } : {}) })),
    logs: (r.logs || []).slice(-100).map((l: any) => `${l.level} ${l.step ? `[${l.step}] ` : ''}${l.msg}`),
  };
}
const finished = (s: string) => !['running', 'queued', 'waiting', 'pending', 'paused'].includes(s);


import crypto from 'node:crypto';
import { purposeKey } from '../secrets.js';

/**
 * Visitor tokens: each caller of an agent channel without a security policy gets an identity of its own
 * (before 2.1.1 they were all one anonymous caller, protected only by unguessable session and job ids).
 * A token is a random id and the time it was issued, signed with a key derived from the server's master
 * key: "v2.<id>.<issued>.<signature>". It travels in the X-Sutra-Visitor header (the chat page and widget
 * keep it in the browser); a missing, forged or foreign token gets a new identity, never another visitor's.
 * Since 2.1.5 a token expires SUTRA_VISITOR_DAYS (30) after it was issued, and is renewed (same id, new
 * time) once half of that has passed while the visitor keeps coming back. Tokens of 2.1.1 to 2.1.4 ("v1",
 * no time) are accepted once and renewed. The id is not secret on its own: only the signed token proves it,
 * so it may show in logs and Started by.
 */
export const VISITOR_HEADER = 'x-sutra-visitor';

const days = () => Math.max(1, Number(process.env.SUTRA_VISITOR_DAYS) || 30);
const mac = (text: string, purpose: string) => crypto.createHmac('sha256', purposeKey(purpose)).update(text).digest('base64url').slice(0, 32);
const same = (a: string, b: string) => { const x = Buffer.from(a), y = Buffer.from(b); return x.length === y.length && crypto.timingSafeEqual(x, y); };
const nowSec = () => Math.floor(Date.now() / 1000);
const tokenOf = (id: string, issued: number) => `v2.${id}.${issued}.${mac(`${id}.${issued}`, 'visitor-token-v2')}`;

/** A new visitor: its id and the token that proves it. */
export function newVisitor() {
  const id = crypto.randomBytes(12).toString('base64url');
  return { id, token: tokenOf(id, nowSec()) };
}

/** What a token proves: the visitor id and when the token was issued (0 for a 2.1.4 token), or null. */
function read(token: unknown): { id: string; issued: number } | null {
  const t = String(token ?? '').trim();
  let m = /^v2\.([A-Za-z0-9_-]{16})\.(\d{9,11})\.([A-Za-z0-9_-]{32})$/.exec(t);
  if (m) return same(mac(`${m[1]}.${m[2]}`, 'visitor-token-v2'), m[3]) ? { id: m[1], issued: Number(m[2]) } : null;
  m = /^v1\.([A-Za-z0-9_-]{16})\.([A-Za-z0-9_-]{32})$/.exec(t);
  if (m) return same(mac(m[1], 'visitor-token-v1'), m[2]) ? { id: m[1], issued: 0 } : null;
  return null;
}

/** The visitor id a token proves while it has not expired, or '' when it is missing, foreign or expired. */
export function visitorOf(token: unknown): string {
  const v = read(token);
  return v && (v.issued === 0 || nowSec() - v.issued < days() * 86400) ? v.id : '';
}

/**
 * The visitor of a request: the one its token proves (renewed once half its time has passed, or when it is
 * a 2.1.4 token), or a new one when there is none or it expired. fresh: the visitor is new.
 */
export function visitorFor(token: unknown): { id: string; token: string; fresh: boolean } {
  const raw = String(token ?? '').trim();
  const v = read(raw);
  const age = v ? nowSec() - v.issued : 0;
  if (v && v.issued && age < days() * 86400) return { id: v.id, token: age > (days() * 86400) / 2 ? tokenOf(v.id, nowSec()) : raw, fresh: false };
  if (v && !v.issued) return { id: v.id, token: tokenOf(v.id, nowSec()), fresh: false };
  return { ...newVisitor(), fresh: true };
}

import crypto from 'node:crypto';
import { purposeKey } from '../secrets.js';

/**
 * Visitor tokens: each caller of an agent channel without a security policy gets an identity of its own
 * (before 2.1.1 they were all one anonymous caller, protected only by unguessable session and job ids).
 * A token is a random id signed with a key derived from the server's master key: "v1.<id>.<signature>".
 * It travels in the X-Sutra-Visitor header (the chat page and widget keep it in the browser); a missing,
 * forged or foreign token gets a new identity, never another visitor's. The id is not secret on its own:
 * only the signed token proves it, so it may show in logs and Started by.
 */
export const VISITOR_HEADER = 'x-sutra-visitor';

const sign = (id: string) => crypto.createHmac('sha256', purposeKey('visitor-token-v1')).update(id).digest('base64url').slice(0, 32);

/** A new visitor: its id and the token that proves it. */
export function newVisitor() {
  const id = crypto.randomBytes(12).toString('base64url');
  return { id, token: `v1.${id}.${sign(id)}` };
}

/** The visitor id a token proves, or '' when it is missing or not signed by this server. */
export function visitorOf(token: unknown): string {
  const m = /^v1\.([A-Za-z0-9_-]{16})\.([A-Za-z0-9_-]{32})$/.exec(String(token ?? '').trim());
  if (!m) return '';
  const want = Buffer.from(sign(m[1])), got = Buffer.from(m[2]);
  return want.length === got.length && crypto.timingSafeEqual(want, got) ? m[1] : '';
}

/** The visitor of a request: the one its token proves, or a new one (fresh: true, so the token is handed out). */
export function visitorFor(token: unknown): { id: string; token: string; fresh: boolean } {
  const raw = String(token ?? '').trim();
  const id = visitorOf(raw);
  if (id) return { id, token: raw, fresh: false };
  return { ...newVisitor(), fresh: true };
}

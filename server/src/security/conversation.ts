import crypto from 'node:crypto';
import { asyncDatabase } from '../asyncdb.js';
import { purposeKey, requireSecret } from '../secrets.js';
import { effectiveResource } from '../resources.js';

/**
 * Conversation tokens (2.1.5): a published agent's conversation id is issued by the server, never chosen by
 * the caller. A token "c1.<id>.<expires>.<signature>" is signed with a key derived from the master key over
 * the id, its expiry and its owner: the agent and the caller (realm: policy and token issuer; method,
 * subject, gateway app). It continues a conversation only for the caller who started it, with that agent,
 * until it expires. A missing, forged, foreign or expired token, or a session id the caller made up, starts
 * a new conversation: knowing a token or an id gives nothing to anyone else.
 *
 * agent_conversations records every conversation (no message text), so administrators can see them and
 * clear expired ones with their memory (Admin Console, Agent conversations; sutra agents clear-expired).
 */
export const DEFAULT_CONVERSATION_HOURS = 24;

/** The identity a conversation belongs to: as stored with an agent run's caller. */
export interface ConversationOwner { realm?: string; method?: string; subject?: string; appId?: string }
export interface Conversation { id: string; token: string; expiresAt: number; fresh: boolean; expired: boolean }

const ownerOf = (agent: string, who: ConversationOwner) => crypto.createHash('sha256')
  .update(JSON.stringify([agent, String(who.realm ?? ''), String(who.method ?? ''), String(who.subject ?? ''), String(who.appId ?? '')]))
  .digest('hex').slice(0, 24);
const sign = (id: string, exp: number, owner: string) => crypto.createHmac('sha256', purposeKey('conversation-token-v1')).update(`${id}.${exp}.${owner}`).digest('base64url').slice(0, 32);
const tokenOf = (id: string, exp: number, owner: string) => `c1.${id}.${exp}.${sign(id, exp, owner)}`;
const nowSec = () => Math.floor(Date.now() / 1000);
const hoursOf = (h: unknown) => Math.min(24 * 365, Math.max(1 / 3600, Number(h) || DEFAULT_CONVERSATION_HOURS));

/** The id a token proves for this agent and caller: { id, expired } when signed by this server for them, else null. */
export function readConversation(token: unknown, agent: string, who: ConversationOwner): { id: string; exp: number; expired: boolean } | null {
  const m = /^c1\.([A-Za-z0-9_-]{8,64})\.(\d{9,11})\.([A-Za-z0-9_-]{32})$/.exec(String(token ?? '').trim());
  if (!m) return null;
  const exp = Number(m[2]);
  const want = Buffer.from(sign(m[1], exp, ownerOf(agent, who))), got = Buffer.from(m[3]);
  if (want.length !== got.length || !crypto.timingSafeEqual(want, got)) return null;
  return { id: m[1], exp, expired: exp <= nowSec() };
}

async function record(id: string, agent: string, projectId: string, owner: string, exp: number) {
  const at = new Date().toISOString();
  await asyncDatabase().run(`insert into agent_conversations(id, agent, project_id, owner, created_at, last_at, expires_at, messages) values(?, ?, ?, ?, ?, ?, ?, 1)
    on conflict(id) do update set last_at = excluded.last_at, messages = agent_conversations.messages + 1`, id, agent, projectId, owner, at, at, exp);
}

/**
 * The conversation of a message: the one its token continues, or a new one. hours: how long a new
 * conversation lasts (the agent channel's setting). A derived seed (OpenAI-compatible callers, which send
 * the whole history with every request) gives the same conversation for the same first message until it
 * expires, then a new one.
 */
export async function conversationFor(token: unknown, agent: string, projectId: string, who: ConversationOwner, hours: unknown, seed?: string): Promise<Conversation> {
  const owner = ownerOf(agent, who);
  const known = readConversation(token, agent, who);
  if (known && !known.expired) {
    await record(known.id, agent, projectId, owner, known.exp);
    return { id: known.id, token: tokenOf(known.id, known.exp, owner), expiresAt: known.exp * 1000, fresh: false, expired: false };
  }
  const exp = nowSec() + Math.round(hoursOf(hours) * 3600);
  let id = crypto.randomBytes(12).toString('base64url');
  if (seed) {
    // The same seed continues one conversation; once it has expired the next generation starts a new one.
    for (let gen = 0; gen < 50; gen++) {
      const cand = `oa${crypto.createHash('sha256').update(`${owner}|${seed}|${gen}`).digest('base64url').slice(0, 20)}`;
      const row = await asyncDatabase().get<{ expires_at: number }>('select expires_at from agent_conversations where id = ?', cand);
      if (!row) { id = cand; break; }
      if (Number(row.expires_at) > nowSec()) {
        await record(cand, agent, projectId, owner, Number(row.expires_at));
        return { id: cand, token: tokenOf(cand, Number(row.expires_at), owner), expiresAt: Number(row.expires_at) * 1000, fresh: false, expired: false };
      }
    }
  }
  await record(id, agent, projectId, owner, exp);
  return { id, token: tokenOf(id, exp, owner), expiresAt: exp * 1000, fresh: true, expired: !!known?.expired };
}

/** The token of a known conversation for its owner (a job's answer names its conversation again). */
export async function tokenFor(id: string, agent: string, who: ConversationOwner): Promise<string> {
  const row = await asyncDatabase().get<{ expires_at: number; owner: string }>('select expires_at, owner from agent_conversations where id = ? and agent = ?', id, agent);
  const owner = ownerOf(agent, who);
  return row && row.owner === owner ? tokenOf(id, Number(row.expires_at), owner) : '';
}

/** Conversations by agent: active and expired, with their messages, for the Admin Console. */
export async function conversationSummary() {
  const t = nowSec();
  const rows = await asyncDatabase().all<any>(`select agent, project_id,
      sum(case when expires_at > ? then 1 else 0 end) active, sum(case when expires_at <= ? then 1 else 0 end) expired,
      sum(messages) messages, min(created_at) first_at, max(last_at) last_at
    from agent_conversations group by agent, project_id order by agent`, t, t);
  return rows.map(r => ({ agent: r.agent, projectId: r.project_id, active: Number(r.active || 0), expired: Number(r.expired || 0), messages: Number(r.messages || 0), firstAt: r.first_at, lastAt: r.last_at }));
}

/**
 * Clears expired conversations: their AI memory (turns, summaries, queued places, in every memory store
 * that holds them) and their records. agent: only this agent's. Returns what was cleared.
 */
export async function clearExpiredConversations(agent?: string) {
  const db = asyncDatabase();
  const ids = (await db.all<{ id: string }>(`select id from agent_conversations where expires_at <= ?${agent ? ' and agent = ?' : ''}`, nowSec(), ...(agent ? [agent] : []))).map(r => r.id);
  let sessions = 0;
  const { clearSession } = await import('../ai/memory.js');
  for (const id of ids) {
    // Agent memory keeps a conversation under "caller:<owner>:<id>" (ai/memory.ts memoryKey).
    // ("_" in an id is a LIKE wildcard: the suffix is checked exactly.)
    const found = (await db.all<{ store_id: string; session: string }>(`select store_id, session from ai_sessions where session = ? or session like ?`, id, `caller:%${id}`))
      .filter(s => s.session === id || (s.session.startsWith('caller:') && s.session.endsWith(`:${id}`)));
    for (const s of found) {
      const store = effectiveResource(s.store_id);
      if (store) { await clearSession(store, (n: string, what?: string) => requireSecret(n, what), s.session); sessions++; }
      else await db.run('delete from ai_sessions where store_id = ? and session = ?', s.store_id, s.session);
      await db.run('delete from ai_session_queue where store_id = ? and session = ?', s.store_id, s.session);
    }
  }
  for (let i = 0; i < ids.length; i += 200) {
    const part = ids.slice(i, i + 200);
    await db.run(`delete from agent_conversations where id in (${part.map(() => '?').join(', ')})`, ...part);
  }
  return { conversations: ids.length, memorySessions: sessions };
}

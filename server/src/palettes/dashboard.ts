/** A field by name or by a dotted path into nested objects (customer.city). */
export const fieldOf = (row: any, f: string): any => {
  if (!row || typeof row !== 'object') return undefined;
  if (f in row) return row[f];
  return f.split('.').reduce((o, k) => (o && typeof o === 'object' ? o[k] : undefined), row);
};
/** Field names of the rows, nested objects as dotted paths (three levels). */
export const fieldsOf = (rows: any[]) => {
  const out = new Set<string>();
  const walk = (o: any, pre: string, depth: number) => { for (const [k, v] of Object.entries(o)) { if (v && typeof v === 'object' && !Array.isArray(v) && depth < 3) walk(v, `${pre}${k}.`, depth + 1); else out.add(pre + k); } };
  for (const r of rows.slice(0, 50)) if (r && typeof r === 'object') walk(r, '', 1);
  return [...out];
};

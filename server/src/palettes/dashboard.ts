/** Rows from a step: a list, JSON text, or an object (an API answer) holding the list at a path or as its first list. */
export function rowsFrom(value: unknown, listPath = ''): any[] {
  let v: any = value;
  if (typeof v === 'string' && /^\s*[[{]/.test(v)) { try { v = JSON.parse(v); } catch { /* not JSON: refused below */ } }
  if (listPath && v && typeof v === 'object' && !Array.isArray(v)) v = fieldOf(v, listPath);
  if (v && typeof v === 'object' && !Array.isArray(v)) v = Object.values(v).find(Array.isArray) ?? [v];
  if (!Array.isArray(v)) throw new Error('Rows must be a list of objects, such as {{input.rows}} of an SQL query, or an object holding one (set "List inside")');
  return v.filter(r => r && typeof r === 'object' && !Array.isArray(r));
}

/** A date as its group: 2026-10-07 by month is 2026-10, by quarter 2026-Q4, by week 2026-W41. */
export function dateBucket(v: unknown, g: string): string {
  if (g === 'none' || v === null || v === undefined || v === '') return String(v ?? '');
  const d = typeof v === 'number' ? new Date(v < 1e11 ? v * 1000 : v) : new Date(String(v).length === 10 ? `${v}T00:00:00Z` : String(v));
  if (Number.isNaN(d.getTime())) return String(v);
  const y = d.getUTCFullYear(), m = d.getUTCMonth() + 1, p = (n: number) => String(n).padStart(2, '0');
  if (g === 'year') return String(y);
  if (g === 'quarter') return `${y}-Q${Math.ceil(m / 3)}`;
  if (g === 'month') return `${y}-${p(m)}`;
  if (g === 'day') return `${y}-${p(m)}-${p(d.getUTCDate())}`;
  const t = new Date(Date.UTC(y, m - 1, d.getUTCDate())), day = t.getUTCDay() || 7;
  t.setUTCDate(t.getUTCDate() + 4 - day);
  const y0 = new Date(Date.UTC(t.getUTCFullYear(), 0, 1));
  return `${t.getUTCFullYear()}-W${p(Math.ceil(((t.getTime() - y0.getTime()) / 86400000 + 1) / 7))}`;
}

function aggregate(list: unknown[], how: string): number {
  if (how === 'count') return list.length;
  if (how === 'distinct count') return new Set(list.map(v => String(v))).size;
  const ns = list.filter(isNum).map(Number);
  if (!ns.length) return 0;
  if (how === 'average') return Math.round((ns.reduce((a, b) => a + b, 0) / ns.length) * 100) / 100;
  if (how === 'min') return Math.min(...ns);
  if (how === 'max') return Math.max(...ns);
  return Math.round(ns.reduce((a, b) => a + b, 0) * 100) / 100;
}

/**
 * The page filters, applied to rows that have the filter's field (rows already filtered by SQL pass as they are).
 * A text is one value, a list is any of them, {from, to} a range (dates as text, or numbers), {contains} a search.
 */
export function applyFilters(rows: any[], filters: unknown): any[] {
  if (!filters || typeof filters !== 'object' || Array.isArray(filters)) return rows;
  const active = Object.entries(filters as Record<string, any>).filter(([, v]) => v !== '' && v !== null && v !== undefined && !(Array.isArray(v) && !v.length)
    && !(typeof v === 'object' && !Array.isArray(v) && !v.from && !v.to && !v.contains));
  if (!active.length || !rows.length) return rows;
  const fields = new Set(fieldsOf(rows));
  const usable = active.filter(([f]) => fields.has(f));
  return rows.filter(r => usable.every(([f, want]) => {
    const got = fieldOf(r, f);
    if (Array.isArray(want)) return want.map(w => String(w).toLowerCase()).includes(String(got ?? '').toLowerCase());
    if (typeof want === 'object') {
      if (want.contains !== undefined) return String(got ?? '').toLowerCase().includes(String(want.contains).toLowerCase());
      const numeric = (want.from === '' || want.from === undefined || isNum(want.from)) && (want.to === '' || want.to === undefined || isNum(want.to)) && isNum(got);
      const g = numeric ? Number(got) : String(got ?? '').slice(0, String(want.to || want.from || '').length || 10);
      if (want.from !== undefined && want.from !== '' && (numeric ? (g as number) < Number(want.from) : (g as string) < String(want.from))) return false;
      if (want.to !== undefined && want.to !== '' && (numeric ? (g as number) > Number(want.to) : (g as string) > String(want.to))) return false;
      return true;
    }
    return String(got ?? '').toLowerCase() === String(want).toLowerCase();
  }));
}

/** Rows grouped by the category (by date group), and by the split field: one value per group, added up as asked. */
function grouped(rows: any[], s: ChartSettings): { rows: any[]; values: string[] } {
  const how = s.aggregate && s.aggregate !== 'none' ? s.aggregate : 'sum';
  const g = s.dateGroup || 'none';
  const values = how === 'count' || !s.values.length ? (how === 'count' ? ['count'] : s.values) : s.values;
  const keyOf = (r: any) => (s.category ? dateBucket(fieldOf(r, s.category), g) : 'all');
  const groups = new Map<string, any[]>();
  for (const r of rows) { const k = keyOf(r); (groups.get(k) || groups.set(k, []).get(k)!).push(r); }
  if (s.splitBy) {
    const totals = new Map<string, number>();
    for (const r of rows) { const sv = String(fieldOf(r, s.splitBy) ?? ''); totals.set(sv, (totals.get(sv) || 0) + (how === 'count' ? 1 : num(fieldOf(r, values[0])))); }
    // The 12 largest, in name order: a series keeps its colour when filters change.
    const series = [...totals.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12).map(([k]) => k).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
    const out = [...groups.entries()].map(([k, list]) => Object.fromEntries([[s.category || 'group', k], ...series.map(sv => {
      const part = list.filter(r => String(fieldOf(r, s.splitBy!) ?? '') === sv);
      return [sv, how === 'count' ? part.length : aggregate(part.map(r => fieldOf(r, values[0])), how)];
    })]));
    return { rows: out, values: series };
  }
  const out = [...groups.entries()].map(([k, list]) => Object.fromEntries([[s.category || 'group', k], ...values.map(v => [v, aggregate(v === 'count' ? list : list.map(r => fieldOf(r, v)), how)])]));
  return { rows: out, values };
}

const ALLOWED = new Set(['type', 'title', 'category', 'values', 'stack', 'palette', 'unit', 'limit', 'sort', 'aggregate', 'dateGroup', 'splitBy', 'kpi', 'better']);
/**
 * The allow-list for chart settings that come from a step (an AI suggestion): known keys only, a known chart
 * type, palette, grouping and date group, field names that exist in the rows, short plain titles. Returns the
 * settings to use and what was refused; anything refused falls back to the step's own settings.
 */
export function checkChartSettings(raw: unknown, rows: any[], fallback: ChartSettings): { settings: ChartSettings; problems: string[] } {
  const problems: string[] = [];
  let s: any = raw;
  if (typeof s === 'string') { try { s = JSON.parse(s); } catch { return { settings: fallback, problems: ['The suggested chart is not JSON'] }; } }
  if (!s || typeof s !== 'object' || Array.isArray(s)) return { settings: fallback, problems: ['The suggested chart is not an object'] };
  for (const k of Object.keys(s)) if (!ALLOWED.has(k)) problems.push(`"${k}" is not a chart setting (ignored)`);
  const fields = fieldsOf(rows);
  const out: ChartSettings = { ...fallback };
  const pick = <T extends string>(k: string, list: readonly T[], label: string) => { if (s[k] === undefined) return; if (list.includes(s[k])) (out as any)[k] = s[k]; else problems.push(`${label} "${plainText(s[k], 30)}" is not one of ${list.join(', ')}`); };
  pick('type', CHART_TYPES, 'Chart type');
  pick('aggregate', AGGREGATES, 'Grouping');
  pick('dateGroup', DATE_GROUPS, 'Date group');
  pick('sort', ['none', 'descending', 'ascending'] as const, 'Sort');
  pick('kpi', ['total', 'latest'] as const, 'KPI shows');
  pick('better', ['higher', 'lower'] as const, 'Better is');
  if (s.title !== undefined) out.title = plainText(s.title);
  for (const k of ['category', 'splitBy'] as const) {
    if (s[k] === undefined || s[k] === '') continue;
    if (fields.includes(String(s[k]))) out[k] = String(s[k]); else problems.push(`Field "${plainText(s[k], 40)}" is not in the data`);
  }
  if (s.values !== undefined) {
    const v: string[] = (Array.isArray(s.values) ? s.values : [s.values]).map(String).filter((x: string) => x !== 'count');
    const bad = v.filter((x: string) => !fields.includes(x));
    if (bad.length || v.length > 8 || (!v.length && out.aggregate !== 'count')) problems.push(bad.length ? `Fields ${bad.map((b: string) => `"${plainText(b, 40)}"`).join(', ')} are not in the data` : 'Give 1 to 8 value fields');
    else out.values = v;
  }
  if (s.stack !== undefined) out.stack = !!s.stack;
  if (s.palette !== undefined) { if (CHART_PALETTES[s.palette]) out.palette = s.palette; else problems.push(`Palette "${plainText(s.palette, 30)}" is not one of ${Object.keys(CHART_PALETTES).join(', ')}`); }
  if (s.unit !== undefined) out.unit = plainText(s.unit, 12);
  if (s.limit !== undefined) { const n = Number(s.limit); if (Number.isInteger(n) && n > 0 && n <= 1000) out.limit = n; else problems.push('limit is a whole number from 1 to 1000'); }
  return { settings: out, problems };
}

/** An ECharts chart from rows: only plain JSON (series, axes, dataset), never functions or links. */
export function chartFrom(input: any[], s: ChartSettings): ChartSpec {
  let rows = (Array.isArray(input) ? input : []).filter(r => r && typeof r === 'object');
  let values = s.values.length ? s.values : s.aggregate === 'count' ? [] : fieldsOf(rows).filter(f => f !== s.category && rows.some(r => isNum(fieldOf(r, f)))).slice(0, 1);
  const title = plainText(s.title) || 'Chart', id = slug(title), colors = CHART_PALETTES[s.palette] || CHART_PALETTES.SutraFlow;
  const how = s.aggregate && s.aggregate !== 'none' ? s.aggregate : '';
  if (s.type === 'number') {
    const list = how === 'count' ? rows : rows.map(r => fieldOf(r, values[0]));
    return { id, title, type: 'number', value: aggregate(list, how || 'sum'), label: how === 'count' ? 'count' : values[0] || '', unit: s.unit };
  }
  if (s.type === 'kpi') {
    const one = { ...s, values: values.slice(0, 1) };
    const series = s.category ? grouped(rows, one).rows.sort((a, b) => String(a[s.category]).localeCompare(String(b[s.category]))) : [];
    const key = how === 'count' ? 'count' : values[0];
    const trend = series.map(r => num(r[key])).slice(-60);
    const latest = s.kpi === 'latest' && trend.length;
    const value = latest ? trend[trend.length - 1] : aggregate(how === 'count' ? rows : rows.map(r => fieldOf(r, values[0])), how || 'sum');
    const previous = s.previous ?? (latest && trend.length > 1 ? trend[trend.length - 2] : null);
    return { id, title, type: 'kpi', value, label: latest ? `${series[series.length - 1]?.[s.category] ?? ''}` : (how === 'count' ? 'count' : values[0] || ''), unit: s.unit, previous, target: s.target ?? null, trend, better: s.better || 'higher', field: s.category || undefined };
  }
  if (how || (s.dateGroup && s.dateGroup !== 'none') || s.splitBy) {
    const g = grouped(rows, { ...s, values });
    rows = g.rows; values = g.values;
    if (s.sort === 'none' && s.dateGroup && s.dateGroup !== 'none') rows.sort((a, b) => String(a[s.category]).localeCompare(String(b[s.category])));
  }
  const get = (r: any, f: string) => fieldOf(r, f);
  if (s.sort !== 'none' && values[0]) rows = [...rows].sort((a, b) => (s.sort === 'descending' ? num(get(b, values[0])) - num(get(a, values[0])) : num(get(a, values[0])) - num(get(b, values[0]))));
  rows = rows.slice(0, Math.max(1, Math.min(1000, s.limit || 1000)));
  const field = s.category || undefined;
  const base = { color: colors, tooltip: { trigger: ['pie', 'donut'].includes(s.type) ? 'item' : 'axis' }, grid: { left: 8, right: 16, top: values.length > 1 ? 36 : 16, bottom: 8, containLabel: true }, ...(values.length > 1 || ['pie', 'donut'].includes(s.type) ? { legend: { type: 'scroll', top: 0 } } : {}) };
  if (s.type === 'table') { const columns = [s.category, ...values].filter(Boolean); const cols = columns.length ? columns : fieldsOf(rows); return { id, title, type: 'table', columns: cols, rows: rows.slice(0, 200).map(r => Object.fromEntries(cols.map(c => [c, get(r, c)]))), field }; }
  if (s.type === 'gauge') return { id, title, type: 'gauge', option: { ...base, legend: undefined, series: [{ type: 'gauge', detail: { valueAnimation: true }, data: [{ name: values[0] || '', value: num(get(rows[0], values[0])) }] }] } };
  if (s.type === 'pie' || s.type === 'donut') {
    return { id, title, type: s.type, field, option: { ...base, series: [{ type: 'pie', radius: s.type === 'donut' ? ['45%', '72%'] : '72%', top: 28, label: { position: 'inside', formatter: '{d}%', fontSize: 11 }, labelLine: { show: false }, data: rows.map(r => ({ name: String(get(r, s.category) ?? ''), value: num(get(r, values[0])) })) }] } };
  }
  const source = rows.map(r => Object.fromEntries([[s.category, String(get(r, s.category) ?? '')], ...values.map(v => [v, num(get(r, v))])]));
  const horizontal = s.type === 'horizontal bar';
  // Horizontal bars read top to bottom: the first row (the largest when sorted descending) at the top.
  const cat = { type: 'category', ...(horizontal ? { inverse: true } : {}) }, val = { type: 'value', ...(s.unit ? { name: s.unit } : {}) };
  const seriesType = s.type === 'line' || s.type === 'area' ? 'line' : s.type === 'scatter' ? 'scatter' : 'bar';
  return {
    id, title, type: s.type, field,
    option: { ...base, dataset: { source }, xAxis: horizontal ? val : cat, yAxis: horizontal ? cat : val,
      series: values.map(v => ({ type: seriesType, name: v, encode: horizontal ? { y: s.category, x: v } : { x: s.category, y: v }, ...(s.type === 'area' ? { areaStyle: {} } : {}), ...(s.stack && seriesType !== 'scatter' ? { stack: 'all' } : {}), ...(seriesType === 'line' ? { smooth: true } : {}) })) },
  };
}

/** Page filters from the Dashboard page's rows: field, then the kind and optional fixed choices ("list: North, South"). */
export function pageFilters(rows: unknown): PageFilter[] {
  return (Array.isArray(rows) ? rows : []).filter((r: any) => r && /^[\w.-]{1,40}$/.test(String(r.k || '').trim())).slice(0, 12).map((r: any) => {
    const [kindText, ...rest] = String(r.v || 'list').split(':');
    const kind = (FILTER_KINDS as readonly string[]).includes(kindText.trim().toLowerCase()) ? kindText.trim().toLowerCase() as PageFilter['kind'] : 'list';
    return { field: String(r.k).trim(), label: humanize(String(r.k).trim()), kind, choices: rest.join(':').split(',').map(x => x.trim()).filter(Boolean).slice(0, 200) };
  });
}

/**
 * The values of the page filters from the page address: params as text for SQL (every filter present, empty
 * when not set; a multi list joined by commas; ranges as <field>_from and <field>_to) and filters typed for
 * Chart steps (text, list, {from, to}, {contains}).
 */
export function filterValues(defs: PageFilter[], get: (k: string) => string[]): { params: Record<string, string>; filters: Record<string, any> } {
  const params: Record<string, string> = {}, filters: Record<string, any> = {};
  const clean = (v: string | undefined) => String(v ?? '').slice(0, 200);
  for (const f of defs) {
    if (f.kind === 'date range' || f.kind === 'number range') {
      const from = clean(get(`${f.field}_from`)[0]), to = clean(get(`${f.field}_to`)[0]);
      const ok = (v: string) => !v || (f.kind === 'date range' ? /^\d{4}-\d{2}-\d{2}$/.test(v) : isNum(v));
      params[`${f.field}_from`] = ok(from) ? from : ''; params[`${f.field}_to`] = ok(to) ? to : '';
      filters[f.field] = { from: params[`${f.field}_from`], to: params[`${f.field}_to`] };
    } else if (f.kind === 'multi list') {
      const list = get(f.field).flatMap(v => v.split(',')).map(v => clean(v).trim()).filter(Boolean).slice(0, 50);
      params[f.field] = list.join(','); filters[f.field] = list;
    } else if (f.kind === 'search') {
      params[f.field] = clean(get(f.field)[0]); filters[f.field] = { contains: params[f.field] };
    } else { params[f.field] = clean(get(f.field)[0]); filters[f.field] = params[f.field]; }
  }
  return { params, filters };
}

const settingsOfStep = (c: ExecCtx): ChartSettings => {
  const n = (k: string) => { const v = c.v(k); return v === '' || v === null || v === undefined || !isNum(v) ? null : Number(v); };
  return {
    type: (CHART_TYPES as readonly string[]).includes(c.raw('type')) ? c.raw('type') : 'bar', title: plainText(c.v('title')), category: String(c.raw('category') || '').trim(),
    values: String(c.raw('values') || '').split(/[\s,]+/).filter(Boolean), stack: !!c.raw('stack'), palette: String(c.raw('palette') || 'SutraFlow'),
    unit: plainText(c.raw('unit'), 12), limit: Number(c.raw('limit')) || 1000, sort: (['none', 'descending', 'ascending'].includes(c.raw('sort')) ? c.raw('sort') : 'none') as ChartSettings['sort'],
    aggregate: (AGGREGATES as readonly string[]).includes(c.raw('aggregate')) ? c.raw('aggregate') : 'none', dateGroup: (DATE_GROUPS as readonly string[]).includes(c.raw('dateGroup')) ? c.raw('dateGroup') : 'none',
    splitBy: String(c.raw('splitBy') || '').trim(), kpi: c.raw('kpi') === 'latest' ? 'latest' : 'total', better: c.raw('better') === 'lower' ? 'lower' : 'higher', target: n('target'), previous: n('previous'),
  };
};

/** What a model is told about the rows: field names, kinds and a few values; rows only when asked. */
function profile(rows: any[]) {
  return fieldsOf(rows).slice(0, 40).map(f => {
    const vals = rows.slice(0, 500).map(r => fieldOf(r, f)).filter(v => v !== null && v !== undefined && v !== '');
    const kind = vals.length && vals.every(isNum) ? 'number' : vals.length && vals.every(v => DATE_RE.test(String(v))) ? 'date' : 'text';
    return { field: f, kind, distinct: new Set(vals.map(String)).size };
  });
}

/** Charts chosen by rules from the kinds of fields: KPIs, a trend over time, a ranking, a share and a table. */
export function suggestCharts(rows: any[], most = 6): ChartSettings[] {
  const p = profile(rows), nums = p.filter(f => f.kind === 'number' && !/(^|_)(id|code|no|number|year)$/i.test(f.field)), dates = p.filter(f => f.kind === 'date'), texts = p.filter(f => f.kind === 'text' && f.distinct > 1 && f.distinct <= 30);
  const base = { stack: false, palette: 'SutraFlow', unit: '', limit: 1000, sort: 'none' as const, aggregate: 'sum' as const, dateGroup: 'none' as const, splitBy: '', kpi: 'total' as const, better: 'higher' as const, target: null, previous: null };
  const out: ChartSettings[] = [];
  const v = nums[0]?.field;
  if (v) out.push({ ...base, type: 'kpi', title: /^(total|sum|amount)/i.test(humanize(v)) ? humanize(v) : `Total ${humanize(v).toLowerCase()}`, category: dates[0]?.field || '', values: [v], dateGroup: dates[0] ? 'month' : 'none' });
  out.push({ ...base, type: 'kpi', title: 'Records', category: '', values: [], aggregate: 'count' });
  if (v && dates[0]) out.push({ ...base, type: 'area', title: `${humanize(v)} by month`, category: dates[0].field, values: [v], dateGroup: 'month' });
  if (texts[0]) out.push({ ...base, type: 'horizontal bar', title: v ? `${humanize(v)} by ${humanize(texts[0].field).toLowerCase()}` : `Records by ${humanize(texts[0].field).toLowerCase()}`, category: texts[0].field, values: v ? [v] : [], aggregate: v ? 'sum' : 'count', sort: 'descending', limit: 10 });
  const share = texts.find(t => t !== texts[0] && t.distinct <= 8) || (texts[0] && texts[0].distinct <= 8 ? texts[0] : undefined);
  if (share) out.push({ ...base, type: 'donut', title: `Share by ${humanize(share.field).toLowerCase()}`, category: share.field, values: v ? [v] : [], aggregate: v ? 'sum' : 'count' });
  out.push({ ...base, type: 'table', title: 'Details', category: '', values: p.slice(0, 6).map(f => f.field), aggregate: 'none', limit: 50 });
  return out.slice(0, most);
}


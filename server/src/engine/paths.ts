/* @sutra-file-overview
 * File: server/src/engine/paths.ts
 * Purpose/support: The path rule (2.1.7): a step may use the outputs of the steps before it on a connected path only. Finds the steps before a step, the step names a configuration refers to, and the references to steps that are not on the path; used by the design check, the engine and the designer.
 * Connects to (static imports): ./types.js
 * Functions/entry points (static scan): stepsBefore, stepRefs, walk, offPathRefs, edgeOffPathRefs, fieldLabel, pathMessage, edgePathMessage, allowedOutputs
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import type { Activity, FlowDoc, FlowEdge, FlowNode } from './types.js';

/**
 * The path rule. A step may use the trigger, properties, Sutra variables, and the outputs of the steps
 * that come before it on a connected path: every step from which a chain of connections leads to it.
 * After a join (two lanes into one step) both lanes are before it; a step in another lane is not.
 * The Error handler starts after any step, so it may use every step's output.
 */
export function stepsBefore(doc: Pick<FlowDoc, 'edges'>, nodeId: string): Set<string> {
  const before = new Set<string>();
  const pending = doc.edges.filter(e => e.to === nodeId).map(e => e.from);
  while (pending.length) {
    const id = pending.pop()!;
    if (before.has(id)) continue;
    before.add(id);
    for (const e of doc.edges) if (e.to === id && !before.has(e.from)) pending.push(e.from);
  }
  return before;
}

/** Configuration keys that hold the designer's own words, never data references. */
const PROSE_KEYS = new Set(['description', 'note', 'notes', 'help']);

/** What may follow a step name in a reference: a field, an index, the end of a template or formula. */
const NAME_END = /^(?:$|[.[\]}"'`|),;\s+*/=<>!&?:-])/;

/**
 * The step names a text refers to as nodes.<name>, nodes["<name>"], $nodes.<name> (JSONata) or
 * nodes.`<name>`. Step names may contain spaces, so each reference is matched against the known
 * names, longest first ("Orders by category" before "Orders").
 */
export function stepRefs(text: unknown, names: readonly string[]): string[] {
  if (typeof text !== 'string' || !text.includes('nodes')) return [];
  const sorted = [...new Set(names)].filter(Boolean).sort((a, b) => b.length - a.length);
  const found = new Set<string>();
  const re = /(?<![\w])nodes\s*(?:\.|\[)\s*([`"']?)/g;
  for (let m = re.exec(text); m; m = re.exec(text)) {
    const at = m.index + m[0].length, quote = m[1];
    for (const name of sorted) {
      if (!text.startsWith(name, at)) continue;
      const next = text.slice(at + name.length, at + name.length + 1);
      if (quote ? next === quote : NAME_END.test(next)) { found.add(name); break; }
    }
  }
  return [...found];
}

function walk(value: unknown, visit: (text: string) => void, key = '') {
  if (PROSE_KEYS.has(key)) return;
  if (typeof value === 'string') visit(value);
  else if (Array.isArray(value)) value.forEach(v => walk(v, visit));
  else if (value && typeof value === 'object') for (const [k, v] of Object.entries(value)) walk(v, visit, k);
}

export interface OffPathRef { field: string; step: string }

const cache = new WeakMap<FlowDoc, Map<string, OffPathRef[]>>();

/**
 * References of a step's configuration and settings to steps that are not before it on a connected
 * path (field = the configuration key, or "settings.<key>"). Empty for the Error handler, which may
 * use every step. `noInput` tells whether the step is the Error handler (it has no incoming connection).
 */
export function offPathRefs(doc: FlowDoc, node: FlowNode, noInput = false): OffPathRef[] {
  if (noInput) return [];
  let byNode = cache.get(doc);
  if (!byNode) cache.set(doc, byNode = new Map());
  const known = byNode.get(node.id);
  if (known) return known;
  const before = stepsBefore(doc, node.id);
  const allowed = new Set(doc.nodes.filter(n => before.has(n.id)).map(n => n.name));
  const names = doc.nodes.map(n => n.name);
  const out: OffPathRef[] = [];
  const seen = new Set<string>();
  const check = (field: string) => (text: string) => {
    for (const step of stepRefs(text, names)) {
      if (allowed.has(step) || seen.has(`${field}\u0000${step}`)) continue;
      seen.add(`${field}\u0000${step}`);
      out.push({ field, step });
    }
  };
  for (const [k, v] of Object.entries(node.config || {})) walk(v, check(k), k);
  for (const [k, v] of Object.entries(node.settings || {})) walk(v, check(`settings.${k}`), k);
  byNode.set(node.id, out);
  return out;
}

/** Step names a connection's condition uses that are neither its source step nor before it. */
export function edgeOffPathRefs(doc: FlowDoc, edge: FlowEdge): string[] {
  if (!edge.condition) return [];
  const before = stepsBefore(doc, edge.from);
  before.add(edge.from);
  const allowed = new Set(doc.nodes.filter(n => before.has(n.id)).map(n => n.name));
  return stepRefs(edge.condition, doc.nodes.map(n => n.name)).filter(step => !allowed.has(step));
}

/** The label a person sees for a configuration key ("the setting loopOver" for step settings). */
export function fieldLabel(activity: Pick<Activity, 'fields'> | undefined, key: string) {
  if (key.startsWith('settings.')) return `the setting ${key.slice(9)}`;
  const label = activity?.fields.find(f => f.k === key)?.label;
  return `the field ${label ? `"${label}"` : key}`;
}

/** The message for a step that uses a step off its path (design check and run time say the same). */
export function pathMessage(stepName: string, fieldLabel: string, used: string, prefix = true) {
  return `${prefix ? `${stepName}: ` : ''}${fieldLabel[0].toUpperCase()}${fieldLabel.slice(1)} uses the step "${used}", which is not on its path. A step can use only the steps before it on a connected path; connect "${used}" before ${stepName}, or move ${stepName} after the step where the lanes meet (for example a Merge).`;
}

export function edgePathMessage(connection: string, used: string) {
  return `Connection ${connection}: its condition uses the step "${used}", which is not on its path. A condition can use only the step it leaves and the steps before it.`;
}

/**
 * The outputs a step may see at run time: only the steps before it on its path (all of them for the
 * Error handler). Built per step, so a template, formula or code step cannot read another lane.
 */
export function allowedOutputs(doc: FlowDoc, nodeId: string, outputs: Record<string, any>, all = false): Record<string, any> {
  if (all) return outputs;
  const before = stepsBefore(doc, nodeId);
  const out: Record<string, any> = {};
  for (const n of doc.nodes) if (before.has(n.id) && n.name in outputs) out[n.name] = outputs[n.name];
  return out;
}

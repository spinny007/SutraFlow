/* @sutra-file-overview
 * File: server/src/engine/stage.ts
 * Purpose/support: The stage of a run (2.1.7): design (a test or debug run, or a draft) or runtime (a deployed version), decided in one place when a run starts; a called Sutra takes its caller's stage. Also the client that started it (studio, api, cli) and the SQL every runtime figure uses.
 * Connects to (static imports): No static module imports; use purpose/entry points and adjacent contracts for external interactions.
 * Functions/entry points (static scan): runStage, runClient
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */

export type RunStage = 'design' | 'runtime';
export type RunClient = 'studio' | 'api' | 'cli' | 'mcp';
export const RUN_STAGES: RunStage[] = ['design', 'runtime'];

/**
 * design: a test or debug run, or a run of a draft (version 0), from the studio (later also VS Code
 * and generated Sutras). runtime: a deployed version, from any trigger or the Run API. A Call Sutra
 * child takes the stage of the run that called it, so a test never counts as production work.
 */
export function runStage(o: { source?: string; version?: number | null; parentStage?: string | null }): RunStage {
  if (o.parentStage === 'design' || o.parentStage === 'runtime') return o.parentStage;
  if (o.source === 'test' || o.source === 'debug' || !Number(o.version)) return 'design';
  return 'runtime';
}

/** The client that started a run by hand or by API; automatic starts (timers, listeners, gateway calls) have none. */
export function runClient(o: { source?: string; client?: string | null }): RunClient | null {
  if (o.client === 'studio' || o.client === 'api' || o.client === 'cli' || o.client === 'mcp') return o.client;
  if (o.source === 'test' || o.source === 'debug') return 'studio';
  if (o.source === 'api') return 'api';
  return null;
}

/** The condition every production figure uses (overview, alerts, traces, run limits). */
export const RUNTIME_SQL = `stage = 'runtime'`;
/** Same, for SQL that names the runs table r. */
export const RUNTIME_SQL_R = `r.stage = 'runtime'`;

/** The SQL that fills the stage of runs made before 2.1.7 (and by an engine not yet upgraded in a rolling upgrade). */
export const STAGE_FROM_SOURCE_SQL = `case when source in ('test', 'debug') or coalesce(version, 0) = 0 then 'design' else 'runtime' end`;

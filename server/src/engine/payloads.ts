import crypto from 'node:crypto';
import { config } from '../config.js';

/**
 * Large values stored once (2.1.1). A run's input part over the threshold (a 2 MB broker message body,
 * its text, a file's content) is kept once in the payloads table of the engine database, shared by every
 * engine; run data (the run's input, step inputs and outputs, the run state, step data) carries a small
 * reference { "$payload": id, "size": bytes } instead. Before, such a value was written about five times
 * per run (found with the 2.1.0 soak: 2 MB messages raised engine event-loop delays tenfold).
 *
 *  Reading    A step gets the whole value back (internalize), each step its own copy, through a cache
 *             bounded by size; mappings and activities see no difference.
 *  Writing    storedJson writes a value that came from a payload as its reference again (by identity for
 *             objects, by content for long strings), so passing it on does not copy it.
 *  Replies    A run's answer to its caller is always the whole value (callers never see a reference).
 *  Lifetime   A payload belongs to its run and is removed with it (retention).
 */
export interface PayloadRef { $payload: string; size: number }
export const payloadSettings = { thresholdBytes: config.payloadStoreKb ? config.payloadStoreKb * 1024 : Infinity, cacheBytes: config.payloadCacheMb * 1024 * 1024 };

/** The minimal store this module needs: the engine database or a transaction of it. */
interface Q { run(sql: string, ...a: any[]): Promise<any>; get<T = any>(sql: string, ...a: any[]): Promise<T | undefined> }

export const isPayloadRef = (v: unknown): v is PayloadRef =>
  !!v && typeof v === 'object' && !Array.isArray(v) && typeof (v as any).$payload === 'string' && Object.keys(v as object).length === 2 && 'size' in (v as object);

/** Values that came from a payload (copies handed to steps), so they are written as the reference again. */
const refOfObject = new WeakMap<object, PayloadRef>();
const refOfString = new Map<string, PayloadRef>();
/** Loaded payloads, most recently used last, bounded by cacheBytes. */
const cache = new Map<string, { text: string; value: unknown }>();
let cached = 0;

function remember(id: string, text: string, value: unknown) {
  if (cache.has(id)) { const e = cache.get(id)!; cache.delete(id); cache.set(id, e); return e; }
  const e = { text, value };
  cache.set(id, e); cached += text.length;
  if (typeof value === 'string') refOfString.set(value, { $payload: id, size: text.length });
  while (cached > payloadSettings.cacheBytes && cache.size > 1) {
    const [old, v] = cache.entries().next().value as [string, { text: string; value: unknown }];
    cache.delete(old); cached -= v.text.length;
    if (typeof v.value === 'string') refOfString.delete(v.value);
  }
  return e;
}

/** A copy of a payload's value for one step, known to be that payload when written back. */
function copyOf(id: string, e: { text: string; value: unknown }): unknown {
  const ref = { $payload: id, size: e.text.length };
  if (e.value === null || typeof e.value !== 'object') return e.value;
  const copy = JSON.parse(e.text);
  refOfObject.set(copy, ref);
  return copy;
}

/** JSON for run data: values that came from a payload become their reference. */
export function storedJson(value: unknown): string {
  return JSON.stringify(value, (_k, v) => {
    if (v && typeof v === 'object') { const r = refOfObject.get(v); if (r) return r; }
    else if (typeof v === 'string' && v.length >= payloadSettings.thresholdBytes) { const r = refOfString.get(v); if (r) return r; }
    return v;
  });
}

/**
 * A run's input with each part over the threshold stored once and replaced by its reference, up to three
 * levels down (a message's body and its text, a file's content). Small inputs are returned as they are.
 */
export async function externalize(db: Q, runId: string, input: unknown): Promise<unknown> {
  if (input === null || input === undefined || typeof input !== 'object') return input;
  const whole = JSON.stringify(input);
  if (whole === undefined || whole.length < payloadSettings.thresholdBytes) return input;
  const store = async (value: unknown, text: string): Promise<PayloadRef> => {
    const id = crypto.randomUUID();
    await db.run('insert into payloads(id, run_id, size, data, created_at) values(?, ?, ?, ?, ?)', id, runId, text.length, text, Date.now());
    remember(id, text, typeof value === 'string' ? value : JSON.parse(text));
    return { $payload: id, size: text.length };
  };
  const walk = async (v: unknown, depth: number): Promise<unknown> => {
    if (typeof v === 'string') return v.length >= payloadSettings.thresholdBytes ? store(v, JSON.stringify(v)) : v;
    if (!v || typeof v !== 'object' || isPayloadRef(v)) return v;
    const text = JSON.stringify(v);
    if (text === undefined || text.length < payloadSettings.thresholdBytes) return v;
    if (depth >= 3) return store(v, text);
    const out: any = Array.isArray(v) ? [] : {};
    for (const [k, x] of Object.entries(v)) out[k] = await walk(x, depth + 1);
    // Many small parts adding up: the object as a whole.
    const rest = storedJson(out);
    return rest.length >= payloadSettings.thresholdBytes && !Object.values(out).some(isPayloadRef) ? store(v, text) : out;
  };
  return walk(input, 0);
}

/** The value with every payload reference replaced by (a copy of) its value. */
export async function internalize<T = unknown>(db: Q, value: T): Promise<T> {
  const walk = async (v: any): Promise<any> => {
    if (!v || typeof v !== 'object') return v;
    if (isPayloadRef(v)) {
      let e = cache.get(v.$payload);
      if (e) remember(v.$payload, e.text, e.value);
      else {
        const row = await db.get<{ data: string }>('select data from payloads where id = ?', v.$payload);
        if (!row) throw new Error(`A stored part of this run's data (${Math.round(v.size / 1024)} KB) is no longer there; it was removed with retention or by hand`);
        e = remember(v.$payload, row.data, JSON.parse(row.data));
      }
      return copyOf(v.$payload, e);
    }
    if (Array.isArray(v)) { let changed = false; const out = await Promise.all(v.map(async x => { const y = await walk(x); if (y !== x) changed = true; return y; })); return changed ? out : v; }
    let out: any = null;
    for (const [k, x] of Object.entries(v)) { const y = await walk(x); if (y !== x) { out ??= { ...v }; out[k] = y; } }
    return out ?? v;
  };
  return walk(value);
}

/** Whether a stored JSON text carries a reference (cheap check before parsing for internalize). */
export const hasPayloadRef = (text: string | null | undefined) => !!text && text.includes('"$payload"');

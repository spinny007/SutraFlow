/**
 * Runtime check of a release archive (2.1.1), as an administrator would use it: unpack, sutraflow setup,
 * silent install with a Node memory, start, health, a Sutra run, a memory change applied by Restart from
 * the Admin Console API; then, given the previous release's archive, an upgrade of a running installation
 * with its data. Used by CI on Linux; runs the same on Windows.
 *
 *   node tools/runtime-check.mjs --archive release/sutraflow-2.1.1-linux.tar.gz [--from old.tar.gz] [--work dir] [--port 47600]
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const arg = (name, dflt) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : dflt; };
const archive = path.resolve(arg('archive', ''));
const from = arg('from') ? path.resolve(arg('from')) : '';
const work = path.resolve(arg('work', fs.mkdtempSync(path.join(os.tmpdir(), 'sutra-runtime-'))));
const base = Number(arg('port', 47600));
const password = `Rt-${crypto.randomBytes(9).toString('base64url')}-9a`;
const sleep = ms => new Promise(r => setTimeout(r, ms));
let failed = 0;
const ok = (cond, what) => { console.log(`${cond ? 'ok  ' : 'FAIL'} ${what}`); if (!cond) failed++; return cond; };

function unpack(file, into) {
  fs.mkdirSync(into, { recursive: true });
  // Windows: its own tar (bsdtar) reads .zip and .tar.gz; another tar on the PATH may take C: for a host.
  const tar = process.platform === 'win32' ? path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe') : 'tar';
  const r = spawnSync(tar, ['-xf', file, '-C', into], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`could not unpack ${file}`);
  const dir = fs.readdirSync(into).find(d => d.startsWith('sutraflow-'));
  if (!dir) throw new Error(`no sutraflow folder in ${file}`);
  return path.join(into, dir);
}
function sutraflow(folder, args, env = {}) {
  const r = spawnSync(process.execPath, [path.join(folder, 'bin', 'sutraflow.mjs'), ...args], { cwd: folder, env: { ...process.env, ...env }, encoding: 'utf8', timeout: 600000 });
  process.stdout.write((r.stdout || '').split('\n').map(l => (l ? `     ${l}` : l)).join('\n'));
  if (r.stderr) process.stdout.write(r.stderr.split('\n').map(l => (l ? `     ${l}` : l)).join('\n'));
  return r.status;
}
const setPorts = (folder, port) => {
  const f = path.join(folder, 'sutraflow.env');
  const s = fs.readFileSync(f, 'utf8').replace(/^STUDIO_PORT=.*$/m, `STUDIO_PORT=${port}`).replace(/^STUDIO_GATEWAY_HTTP=.*$/m, `STUDIO_GATEWAY_HTTP=${port + 1}`)
    .replace(/^STUDIO_GATEWAY_HTTPS=.*$/m, `STUDIO_GATEWAY_HTTPS=${port + 2}`).replace(/^ENGINE_PORT=.*$/m, `ENGINE_PORT=${port + 3}`)
    .replace(/^ENGINE_GATEWAY_HTTP=.*$/m, `ENGINE_GATEWAY_HTTP=${port + 4}`).replace(/^ENGINE_GATEWAY_HTTPS=.*$/m, `ENGINE_GATEWAY_HTTPS=${port + 5}`);
  fs.writeFileSync(f, s);
};

/** The studio's API with the local admin token. */
function api(folder, port) {
  const tok = fs.readFileSync(path.join(folder, 'data', 'admin-token.txt'), 'utf8').trim();
  const call = async (m, p, b) => {
    const r = await fetch(`http://127.0.0.1:${port}${p}`, { method: m, headers: { authorization: `Bearer ${tok}`, 'content-type': 'application/json' }, body: m === 'GET' ? undefined : JSON.stringify(b ?? {}) });
    const t = await r.text();
    if (!r.ok) throw new Error(`${m} ${p}: ${r.status} ${t.slice(0, 200)}`);
    return t ? JSON.parse(t) : null;
  };
  return call;
}
/** The health answer, waiting up to 30 s for it. */
const health = async port => {
  let last = '';
  for (let i = 0; i < 30; i++) {
    try { const r = await fetch(`http://127.0.0.1:${port}/health`, { signal: AbortSignal.timeout(3000) }); if (r.ok) return await r.json(); last = `HTTP ${r.status}`; } catch (e) { last = e?.cause?.code || e?.message || String(e); }
    await sleep(1000);
  }
  console.log(`     health on ${port}: ${last}`);
  return null;
};
async function runOnce(call, label) {
  const n = (id, type, name, config, x) => ({ id, type, name, x, y: 100, config });
  const doc = { name: `Runtime check ${label}`, nodes: [n('s', 'start', 'Start', { payload: '{}' }, 0), n('j', 'jsonata', 'Double', { source: '{{input}}', expression: '{ "n": n * 2 }' }, 200)], edges: [{ id: 'e1', from: 's', to: 'j' }] };
  const f = await call('POST', '/api/flows', doc);
  await call('POST', `/api/flows/${f.id}/deploy`, {});
  const r = await call('POST', `/api/flows/${f.id}/run?wait=20000`, { input: { n: 21 } });
  return { flow: f.id, status: r.run?.status || r.status };
}

async function main() {
  if (!fs.existsSync(archive)) throw new Error(`No archive: ${archive}`);
  console.log(`Runtime check of ${path.basename(archive)} in ${work}`);

  // 1. A new installation: setup, silent install with a Node memory, start.
  const folder = unpack(archive, path.join(work, 'new'));
  ok(sutraflow(folder, ['setup']) === 0, 'sutraflow setup');
  const port = base;
  fs.writeFileSync(path.join(work, 'install.json'), JSON.stringify({
    admin: { username: 'runtime', password: { env: 'RUNTIME_ADMIN_PASSWORD' } }, database: { kind: 'sqlite' },
    server: { studioPort: port, gatewayHttp: port + 1, gatewayHttps: port + 2, environment: 'test', studioMemoryMb: 512 }, start: true,
  }, null, 2));
  ok(sutraflow(folder, ['install', '--config', path.join(work, 'install.json')], { RUNTIME_ADMIN_PASSWORD: password }) === 0, 'silent install with start');
  const h = await health(port);
  ok(!!h && h.ok, `health answers ${h?.version}`);
  const call = api(folder, port);
  ok((await runOnce(call, 'new')).status === 'done', 'a Sutra runs');
  const signIn = await fetch(`http://127.0.0.1:${port}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-sutra': '1' }, body: JSON.stringify({ username: 'runtime', password }) });
  ok(signIn.status === 200, 'the administrator signs in');

  // 2. Node memory: started with 512 MB; changed to 640 MB and applied by Restart.
  let me = (await call('GET', '/api/engine/status')).engines[0];
  ok(me.memory?.startedMb === 512 && me.memory.restartable, `started with 512 MB, restartable (heap limit ${me.memory?.heapLimitMb} MB)`);
  await call('PUT', `/api/console/tuning/engines/${encodeURIComponent(me.id)}`, { values: { memoryMb: 640 } });
  for (let i = 0; i < 20 && !/^STUDIO_MEMORY_MB=640$/m.test(fs.readFileSync(path.join(folder, 'sutraflow.env'), 'utf8')); i++) await sleep(1000);
  ok(/^STUDIO_MEMORY_MB=640$/m.test(fs.readFileSync(path.join(folder, 'sutraflow.env'), 'utf8')), 'the new value is in sutraflow.env');
  const oldPid = me.pid;
  await call('POST', `/api/console/engines/${encodeURIComponent(me.id)}/restart`, {});
  for (let i = 0; i < 90; i++) { await sleep(1000); try { me = (await call('GET', '/api/engine/status')).engines[0]; if (me.pid !== oldPid && me.memory) break; } catch { /* restarting */ } }
  ok(me.pid !== oldPid && me.memory?.startedMb === 640, `restarted with 640 MB (process ${oldPid} -> ${me.pid}, heap limit ${me.memory?.heapLimitMb} MB)`);
  ok(sutraflow(folder, ['stop']) === 0, 'graceful stop');

  // 3. An upgrade of a running previous release, with its data.
  if (from && fs.existsSync(from)) {
    const old = unpack(from, path.join(work, 'old'));
    const oldPort = base + 10;
    ok(sutraflow(old, ['setup']) === 0, `setup of ${path.basename(old)}`);
    setPorts(old, oldPort);
    ok(sutraflow(old, ['start']) === 0, 'the previous release starts');
    const before = await runOnce(api(old, oldPort), 'old');
    ok(before.status === 'done', 'a Sutra runs on the previous release');
    fs.writeFileSync(path.join(work, 'upgrade.json'), JSON.stringify({ from: old, start: true }));
    ok(sutraflow(folder, ['upgrade', '--config', path.join(work, 'upgrade.json')]) === 0, 'silent upgrade');
    const h2 = await health(oldPort);
    ok(h2?.version === h?.version, `the upgraded installation answers ${h2?.version}`);
    const c2 = api(old, oldPort);
    const r = await c2('POST', `/api/flows/${before.flow}/run?wait=20000`, { input: { n: 4 } });
    ok((r.run?.status || r.status) === 'done', 'the Sutra from before the upgrade still runs');
    const runs = await c2('GET', '/api/runs');
    ok((runs.runs || runs).length >= 2, 'the runs from before are kept');
    sutraflow(old, ['stop']);
  } else console.log('skip upgrade: no --from archive of the previous release');

  console.log(failed ? `${failed} check(s) failed` : 'All runtime checks passed');
  process.exit(failed ? 1 : 0);
}
main().catch(e => { console.error(e?.stack || e); process.exit(1); });

const CORE_LOAD = /^(REST |SOAP |WebSocket |PostgreSQL DB Ops|MySQL DB Ops|SQLite DB Ops|Channel publish|Error handler|Called Sutra|MCP tool|Bus message|RAG search)/;
function every(name, ms, fn, parallel = 4) {
  if (!CORE && CORE_LOAD.test(name)) return;
  let running = 0;
  const tick = async () => {
    if (stopping || Date.now() > END || running >= parallel) return;
    running++;
    const t = performance.now();
    try { await fn(); note(name, true, performance.now() - t); } catch (e) { note(name, false, 0, e?.message || e); } finally { running--; }
  };
  // Gentle scenarios (free-tier services over the internet) keep their pace whatever --scale says.
  const h = setInterval(tick, Math.max(50, name.includes('(gentle)') ? ms : ms / SCALE));
  timers.push(h);
  stat(name);
}

async function retry(what, fn, tries = 10, waitMs = 3000) {
  for (let i = 1; ; i++) {
    try { return await fn(); } catch (e) {
      if (e.final || i >= tries) throw new Error(`${what}: gave up after ${tries} tries: ${e.message}`);
      event('retry', `${what} (${i}/${tries}): ${e.message}`);
      await sleep(waitMs);
    }
  }
}

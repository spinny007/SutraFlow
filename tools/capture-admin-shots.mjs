async function pg(sql) {
  const { default: pgLib } = await import('pg');
  const c = new pgLib.Client({ connectionString: `${pgServer}/postgres` });
  await c.connect();
  try { return await c.query(sql); } finally { await c.end(); }
}

async function main() {
  if (!fs.existsSync(archive)) throw new Error(`${archive} is missing: run node tools/build-release.mjs --offline first`);
  if (pgServer && (await pg(`select 1 from pg_database where datname = '${dbName}'`)).rowCount) throw new Error(`${dbName} already exists`);
  const A = unpack('SutraFlow');
  const B = unpack(`sutraflow-${version}`);
  const page = await open({ width: 1280, height: 1000 });
  if (only) { const shot = page.shot; page.shot = (name, o) => (only.has(name) ? shot(name, o) : Promise.resolve()); }
  let inst;
  try {
    // ---------- the web installer, page by page ----------
    inst = await startInstaller(A);
    await page.go(inst.url, 2500);
    await page.shot('install-welcome');
    await page.js(`${I} await next();
      set(fld('Email'), 'operations@example.com'); set(fld('Password'), ${JSON.stringify(adminPassword)}); set(fld('Password again'), ${JSON.stringify(adminPassword)}); await wait(300);`);
    await page.shot('install-admin');
    await page.js(`${I} await next();`);
    if (pgServer) {
      const u = new URL(pgServer);
      await page.js(`${I} choice('PostgreSQL').click(); await wait(300);
        set(fld('Host'), ${JSON.stringify(u.hostname)}); set(fld('Port'), ${JSON.stringify(u.port || '5432')}); set(fld('Database'), ${JSON.stringify(dbName)}); set(fld('User'), ${JSON.stringify(decodeURIComponent(u.username) || 'postgres')});
        await wait(200); btn('Test connection').click(); await until('pgvector', 20000); await wait(500);`);
    }
    await page.shot('install-database');
    await page.js(`${I} await next();
      set(fld('Designer and Admin Console port'), ${ports.studio}); set(fld('Gateway HTTP port'), ${ports.http}); set(fld('Gateway HTTPS port'), ${ports.https});
      set(fld('A headless engine beside it'), 'yes'); await wait(300);
      set(fld('Engine port'), ${ports.engine}); set(fld('Engine gateway HTTP'), ${ports.engineHttp}); set(fld('Engine gateway HTTPS'), ${ports.engineHttps});
      btn('Check ports').click(); await wait(1500);`);
    await page.shot('install-server');
    await page.js(`${I} await next(); set(fld('Cluster name'), 'Shop cluster'); set(aria("This server's engine name"), 'shop-studio'); set(aria('The engine beside it: name'), 'shop-engine'); await wait(200);
      ${pgServer ? `btn('Add an engine on another machine').click(); await wait(300); set(aria('Engine 1 name'), 'shop-engine-3'); set(aria('Engine 1 host'), '0.0.0.0'); set(aria('Engine 1 memoryMb'), '2048');` : ''} await wait(400);`);
    await page.shot('install-cluster');
    await page.js(`${I} await next();`);
    await page.shot('install-review');
    await page.js(`${I} await next(); await wait(1500);`);
    await page.shot('install-progress');
    await page.js(`${I} await until('SutraFlow is installed', 240000); await wait(500);`);
    await page.shot('install-done');
    await page.js(`${I} btn('Close the installer')?.click(); await wait(500);`);
    await sleep(800);
    inst.proc.kill();

    // ---------- the Admin Console of the new installation ----------
    for (let i = 0; i < 120; i++) { try { if ((await fetch(`${studio}/ready`)).ok) break; } catch { /* starting */ } await sleep(1000); }
    const login = await fetch(`${studio}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-sutra': '1' }, body: JSON.stringify({ username: 'admin', password: adminPassword }) });
    if (login.status !== 200) throw new Error(`Sign-in failed: ${login.status}`);
    const session = /sutra_session=([^;]+)/.exec(login.headers.get('set-cookie'))[1];
    const api = async (m, u, b) => {
      const r = await fetch(studio + u, { method: m, headers: { 'content-type': 'application/json', 'x-sutra': '1', cookie: `sutra_session=${session}` }, body: b === undefined ? undefined : JSON.stringify(b) });
      const t = await r.text();
      if (!r.ok) throw new Error(`${m} ${u}: ${r.status} ${t.slice(0, 200)}`);
      return t ? JSON.parse(t) : null;
    };
    await seed(api);
    await page.size(1440, 900);
    await page.cookie(studio, 'sutra_session', session);
    const C = `const wait = ms => new Promise(r => setTimeout(r, ms)); const btn = t => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === t);`;
    const at = async (hash, name, extra = '') => { await page.go(`${studio}/admin#${hash}`, 2800); if (extra) await page.js(`${C} ${extra}`); await page.shot(name); };
    await page.js(`localStorage.setItem('sutra.theme', 'light');`);
    await at('overview', 'console-overview');
    await at('apps', 'console-apps');
    await at('apps', 'console-tuning', `btn('Tuning')?.click(); await wait(1200);`);
    await at('apps', 'console-command', `btn('Stop')?.click(); await wait(800); [...document.querySelectorAll('summary, button')].find(b => /shell/i.test(b.textContent))?.click(); await wait(800);`);
    await at('trace', 'console-trace', `[...document.querySelectorAll('button, a, tr')].find(b => b.textContent.includes('Shop'))?.click(); await wait(1500);`);
    await at('releases', 'console-releases');
    await at('engines', 'console-engines');
    await at('engines', 'console-machine', `const m = document.querySelector('.c-machine'); m?.scrollIntoView({ block: 'start' }); await wait(600);`);
    await at('alerts', 'alerts-open', `[...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Details')?.click(); await wait(800);`);
    await at('rules', 'alerts-rule', `[...document.querySelectorAll('button, tr')].find(b => b.textContent.includes('Failed payments'))?.click(); await wait(1000);`);
    await at('traffic', 'gateway-traffic');
    await at('gwapps', 'gateway-apps');
    await at('apis', 'gateway-apis');
    await at('people', 'console-users');
    await at('roles', 'console-roles');
    await at('audit', 'console-audit');
    await at('runtime', 'console-runtime');
    await at('database', 'console-database');
    await at('overview', 'console-panel', `btn('Console')?.click(); await wait(1000);`);
    spawnSync(process.execPath, [path.join(A, 'bin', 'sutraflow.mjs'), 'stop', 'all'], { cwd: A, stdio: 'inherit' });

    // ---------- the upgrade pages: a real upgrade of the installation named, from the new release beside it ----------
    if (upgradeFrom) {
      let target = path.resolve(upgradeFrom);
      if (upgradeFrom === 'installed') {
        // The throwaway installation, marked older so it can be upgraded: its program is this build.
        target = A;
        const pj = path.join(A, 'package.json');
        fs.writeFileSync(pj, fs.readFileSync(pj, 'utf8').replace(`"version": "${version}"`, '"version": "2.1.1"'));
      }
      await page.size(1280, 1000);
      inst = await startInstaller(B);
      await page.go(inst.url, 2500);
      await page.js(`${I} choice('Upgrade').click(); await wait(400);`);
      await page.shot('upgrade-welcome');
      await page.js(`${I} await next(); set(document.querySelector('.i-row input'), ${JSON.stringify(target)}); await wait(200); btn('Check').click(); await until('can be upgraded', 20000); await wait(400);`);
      await page.shot('upgrade-installation');
      await page.js(`${I} await next();`);
      await page.shot('upgrade-review');
      // The progress page with most steps done: taken once the database changes are made, before Done.
      await page.js(`${I} await next(); await until('Compare the data', 600000);`);
      await page.shot('upgrade-progress');
      await page.js(`${I} await until('SutraFlow is upgraded', 600000); await wait(500);`);
      await page.shot('upgrade-done');
      await page.js(`${I} btn('Close the installer')?.click();`);
      await sleep(800);
    }
  } finally {
    await page.close();
    inst?.proc.kill();
    spawnSync(process.execPath, [path.join(A, 'bin', 'sutraflow.mjs'), 'stop', 'all', '--force'], { cwd: A, stdio: 'inherit' });
    await sleep(2000);
    for (const f of fs.readdirSync(work)) try { fs.rmSync(path.join(work, f), { recursive: true, force: true }); } catch (e) { console.error(`Remove ${path.join(work, f)} by hand: ${e.message}`); }
    if (pgServer) await pg(`drop database if exists ${dbName} with (force)`).catch(e => console.error(`Drop ${dbName} by hand: ${e.message}`));
  }
}

/** Something to show: a shop project with samples and runs, a failing Sutra with an alert, gateway apps, people. */
async function seed(api) {
  const shop = await api('POST', '/api/projects', { name: 'Shop' });
  await api('POST', `/api/projects/${shop.id}/samples`, { ids: ['rest', 'microservices', 'trycatch', 'timer'] });
  const flows = await api('GET', `/api/flows?projectId=${shop.id}`);
  for (const f of flows.filter(f => /REST API|Microservice|Timer|Try and catch/.test(f.name))) await api('POST', `/api/flows/${f.id}/deploy`, {}).catch(() => {});
  const payments = await api('POST', '/api/flows', { projectId: shop.id, doc: { name: 'Payment check', nodes: [
    { id: 't', type: 'restService', name: 'Payment API', x: 80, y: 200, config: { method: 'POST', path: '/shop/payments', policy: '' } },
    { id: 'f', type: 'throw', name: 'Card declined', x: 380, y: 200, config: { message: 'Card declined by the bank' } }],
    edges: [{ id: 'e', from: 't', port: 'out', to: 'f' }] } });
  await api('POST', `/api/flows/${payments.id}/deploy`, {});
  const handler = await api('POST', '/api/flows', { projectId: shop.id, doc: { name: 'Alert to operations', nodes: [
    { id: 's', type: 'start', name: 'Start', x: 80, y: 200, config: {} },
    { id: 'l', type: 'log', name: 'Log the alert', x: 380, y: 200, config: { message: 'Alert: {{input.text}}' } }],
    edges: [{ id: 'e', from: 's', port: 'out', to: 'l' }] } });
  await api('POST', `/api/flows/${handler.id}/deploy`, {});
  await sleep(6000);
  for (let i = 0; i < 40; i++) await fetch(`${gateway}/samples/orders/${i % 7 === 0 ? 'x' : 1000 + i}`).catch(() => {});
  for (let i = 0; i < 3; i++) await fetch(`${gateway}/shop/payments`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{"order":"A-1001","amount":49.9}' }).catch(() => {});
  const channel = await api('POST', '/api/alerts/channels', { name: 'Operations team', kind: 'sutra', config: { flowId: handler.id }, enabled: true });
  await api('POST', '/api/alerts/rules', { name: 'Failed payments', kind: 'runFailures', params: { count: 1, minutes: 15, flowId: payments.id }, severity: 'critical', channels: [channel.id], enabled: true, notifyResolved: true, repeatMin: 30 });
  await api('POST', '/api/alerts/check', {}).catch(() => {});
  const plan = await api('POST', '/api/gateway/plans', { name: 'Partner', description: 'Partners and their shops', perMinute: 120, perHour: 0, perDay: 50000, perMonth: 0 });
  const app = await api('POST', '/api/gateway/apps', { name: 'Acme shop', description: 'Web shop of Acme Ltd', contact: 'it@acme.example', planId: plan.id, scopes: ['orders:read'], disabled: false });
  await api('POST', `/api/gateway/apps/${app.id}/keys`, { name: 'production', expiresDays: 365 });
  await api('POST', '/api/access/users', { username: 'meera', displayName: 'Meera Rao', email: 'meera@example.com', password: `Dev-${crypto.randomBytes(8).toString('hex')}A1`, grants: [{ role: 'developer', project: shop.id }] });
  await api('POST', '/api/access/users', { username: 'ci-shop', kind: 'system', displayName: 'Release pipeline', grants: [{ role: 'deployer', project: shop.id }] });
  const engines = (await api('GET', '/api/engine/status')).engines || [];
  for (const e of engines) await api('PUT', `/api/console/engines/${encodeURIComponent(e.id)}/name`, { name: /engine$/.test(e.id) ? 'Shop engine (beside the studio)' : 'Shop studio' }).catch(() => {});
  await sleep(2000);
}

main().catch(e => { console.error(e); process.exitCode = 1; });

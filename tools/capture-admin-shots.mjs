// Captures the Administration Guide screenshots on a throwaway installation, never on a real server:
//   1. unpacks this version's offline release archive (node tools/build-release.mjs --offline) twice into
//      temporary folders, exactly as an administrator would (SUTRA_SHOTS_PACKAGE names another archive);
//   2. installs the first with the real web installer, page by page, in headless Edge (PostgreSQL when
//      SUTRA_SHOTS_PG gives a server, else SQLite);
//   3. seeds the running server through its API (samples, runs, a failing Sutra, an alert, gateway apps,
//      people) and captures the Admin Console pages, then stops it;
//   4. with SUTRA_SHOTS_UPGRADE naming an older installation (2.1.0 or later) that may really be upgraded,
//      upgrades it with the second copy through the upgrade pages: a real upgrade, with its backup.
//      SUTRA_SHOTS_UPGRADE=installed upgrades the throwaway installation instead, marked 2.1.1 (its
//      program is this build);
//   5. removes the folders and the database it made.
//   SUTRA_SHOTS_ONLY=upgrade-progress,... saves only the pictures named.
//
//   node tools/build-release.mjs --offline && node tools/capture-admin-shots.mjs
//   SUTRA_SHOTS_PG=postgres://postgres@127.0.0.1:5432 SUTRA_SHOTS_UPGRADE=C:\laragon\www\sutra node tools/capture-admin-shots.mjs
import { spawn, spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { open, sleep } from './guide/headless.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
// A plain folder, as on a server: the pictures show its path, so not a temporary folder under a user's profile.
const work = process.env.SUTRA_SHOTS_DIR || (process.platform === 'win32' ? 'C:\\SutraFlow-docs' : '/tmp/sutraflow-docs');
if (fs.existsSync(work) && fs.readdirSync(work).length) throw new Error(`${work} is not empty: empty it, or set SUTRA_SHOTS_DIR to a new folder`);
fs.mkdirSync(work, { recursive: true });
const upgradeFrom = process.env.SUTRA_SHOTS_UPGRADE || '';
const only = process.env.SUTRA_SHOTS_ONLY ? new Set(process.env.SUTRA_SHOTS_ONLY.split(',').map(s => s.trim())) : null;
const pgServer = process.env.SUTRA_SHOTS_PG || '';
const dbName = `sutraflow_shots_${process.pid}`;
const ports = { studio: 47301, http: 47302, https: 47303, engine: 47304, engineHttp: 47305, engineHttps: 47306 };
const adminPassword = `Shots-${crypto.randomBytes(9).toString('base64url')}9a`;
const studio = `http://127.0.0.1:${ports.studio}`;
const gateway = `http://127.0.0.1:${ports.http}`;

const archive = process.env.SUTRA_SHOTS_PACKAGE || path.join(root, 'release', process.platform === 'win32'
  ? `sutraflow-${version}-windows-${process.arch}-offline.zip` : `sutraflow-${version}-${process.platform === 'darwin' ? 'macos' : 'linux'}-${process.arch}-offline.tar.gz`);
/** The release unpacked into a folder of its own, as an administrator would (tar reads zip files too). */
function unpack(name) {
  const into = path.join(work, `.unpack-${name}`);
  fs.mkdirSync(into, { recursive: true });
  // Windows' own tar refuses some long entries of the zip; 7-Zip reads it whole.
  const sevenZip = 'C:/Program Files/7-Zip/7z.exe';
  const r = process.platform === 'win32' && fs.existsSync(sevenZip)
    ? spawnSync(sevenZip, ['x', '-y', `-o${into}`, archive], { stdio: 'ignore' })
    : spawnSync('tar', ['-xf', archive, '-C', into], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`Could not unpack ${archive}`);
  const [top] = fs.readdirSync(into);
  fs.renameSync(path.join(into, top), path.join(work, name));
  fs.rmSync(into, { recursive: true, force: true });
  return path.join(work, name);
}

/** Starts the web installer of a folder and returns its one-time address. */
async function startInstaller(dir) {
  const p = spawn(process.execPath, ['--disable-warning=ExperimentalWarning', path.join(dir, 'dist', 'server', 'install', 'server.js'), '--no-open'], { cwd: dir, stdio: ['ignore', 'pipe', 'inherit'] });
  let out = '';
  p.stdout.on('data', d => { out += d; });
  for (let i = 0; i < 60 && !/installer: (http\S+)/.test(out); i++) await sleep(250);
  const m = /installer: (http\S+)/.exec(out);
  if (!m) { p.kill(); throw new Error('The installer did not start'); }
  return { url: m[1], proc: p };
}


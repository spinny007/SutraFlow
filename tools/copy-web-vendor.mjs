// Copies Apache ECharts (its built file, licence and notice) into dist/web/vendor/echarts, so the gateway
// serves dashboards with ECharts from SutraFlow itself, never a CDN (2.1.5). Run by npm run build after Vite.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const from = path.join(root, 'node_modules', 'echarts');
const to = path.join(root, 'dist', 'web', 'vendor', 'echarts');
fs.mkdirSync(to, { recursive: true });
for (const [src, dst] of [['dist/echarts.min.js', 'echarts.min.js'], ['LICENSE', 'LICENSE'], ['NOTICE', 'NOTICE']]) {
  const f = path.join(from, src);
  if (fs.existsSync(f)) fs.copyFileSync(f, path.join(to, dst));
  else if (src.endsWith('.js')) { console.error(`Missing ${f}: run npm ci`); process.exit(1); }
}
const version = JSON.parse(fs.readFileSync(path.join(from, 'package.json'), 'utf8')).version;
console.log(`Apache ECharts ${version} copied to dist/web/vendor/echarts`);

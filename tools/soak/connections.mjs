/**
 * The soak test's connections, read from a plain notes file kept outside the repository (2.1.1):
 *
 *   node tools/soak.mjs --connections C:\Users\me\Documents\Sutra-connections.txt ...
 *
 * The file is written for people, so this reads it by its section headings and "Key: value" lines:
 *
 *   Mongo DB                 User: (the name on the next line), password:, Cluster: name.mongodb.net
 *   MySQL Remote             DB:, username:, pwd:, Host: (the first host name on the line), Port: (3306)
 *   Kafka remote             host:port lines; the first block is the client certificate method
 *                            (Service Key:, Access Certificate:, CA Cert: file paths), the block after
 *                            "Authentication" is SASL (user:, Password:, CA cert:)
 *   Remote Postgre(s) DB     a postgres://user:password@host:port/db?sslmode=require address
 *   RabbitMQ local           optional: url: amqp://user:password@127.0.0.1:5672/, home: C:\rabbitmq_server-4.4.0
 *   ActiveMQ local           optional: url: amqp://user:password@127.0.0.1:5673, home: C:\apache-activemq-6.3.2
 *
 * Nothing here is printed or written anywhere: describe() gives a masked summary for the log.
 */
import fs from 'node:fs';

const SECTIONS = [
  ['mongo', /^mongo/i], ['mysql', /^(mysql\s*remote|remote\s*mysql)/i], ['kafka', /^kafka/i],
  ['postgres', /^(remote\s*postgre|postgre\w*\s*remote)/i], ['rabbitmq', /^rabbit/i], ['activemq', /^active\s*mq/i],
];
const unquote = v => v.trim().replace(/^["']|["']$/g, '');
const HOST_PORT = /\b([a-z0-9-]+(?:\.[a-z0-9-]+)+):(\d{2,5})\b/i;

/** Splits the notes into sections: the heading line (which may carry a value) and the lines under it. */
function sections(text) {
  const out = {};
  let cur = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    // A heading is a short title: a host name such as kafka-1.example.com under it is not one.
    const hit = !/^[\w-]+\.[\w-]+\./.test(line) && SECTIONS.find(([, re]) => re.test(line));
    // A heading met again (a second Kafka block, such as its REST service) starts a section of its own:
    // the first block stays the connection.
    if (hit) { cur = out[hit[0]] ? `${hit[0]}#${Object.keys(out).length}` : hit[0]; out[cur] = { heading: line, lines: [] }; continue; }
    // "Local rabbit MQ C:\rabbitmq_server-4.4.0" and "Local Active MQ C:\apache-activemq-6.3.2": the brokers' folders.
    const home = /^local\s+(rabbit|active)\s*mq\s*:?\s*(.+)$/i.exec(line);
    if (home) { out[`${home[1].toLowerCase()}Home`] = { heading: line, lines: [home[2].trim()] }; continue; }
    if (cur && line) out[cur].lines.push(line);
  }
  return out;
}
/** "Key: value" (the first colon, unless the line is a host:port or an address). */
const keyValue = line => {
  if (/^\w+:\/\//.test(line) || /^[\w.-]+:\d+$/.test(line.replace(/\s/g, ''))) return null;
  const m = /^([A-Za-z][A-Za-z ]{0,40}?)\s*:\s*(.*)$/.exec(line);
  return m ? [m[1].trim().toLowerCase(), m[2].trim()] : null;
};
const pick = (pairs, ...keys) => { for (const k of keys) { const p = pairs.find(([x]) => x === k); if (p && p[1]) return unquote(p[1]); } return ''; };

export function readConnections(file) {
  const s = sections(fs.readFileSync(file, 'utf8'));
  const c = {};
  if (s.mongo) {
    const pairs = s.mongo.lines.map(keyValue).filter(Boolean);
    // "User:" may be followed by the name on its own line.
    const userAt = s.mongo.lines.findIndex(l => /^user\s*:/i.test(l));
    const user = pick(pairs, 'user', 'username') || (userAt >= 0 ? s.mongo.lines[userAt + 1] : '');
    const cluster = pick(pairs, 'cluster', 'host', 'uri', 'srv', 'connection string');
    c.mongo = { user: unquote(user || ''), password: pick(pairs, 'password', 'pwd'), cluster, database: pick(pairs, 'database', 'db') || 'amaron' };
  }
  if (s.mysql) {
    const pairs = s.mysql.lines.map(keyValue).filter(Boolean);
    const hostLine = pick(pairs, 'host');
    const host = (/[a-z0-9-]+(?:\.[a-z0-9-]+){2,}/i.exec(hostLine) || [hostLine.split(/\s+/)[0]])[0];
    c.mysql = { host, port: Number(pick(pairs, 'port')) || 3306, database: pick(pairs, 'db', 'database'), user: pick(pairs, 'username', 'user'), password: pick(pairs, 'pwd', 'password') };
  }
  if (s.kafka) {
    const lines = s.kafka.lines;
    const saslAt = lines.findIndex(l => /^authentication\b/i.test(l));
    const blocks = [saslAt > 0 ? lines.slice(0, saslAt) : lines, saslAt > 0 ? lines.slice(saslAt) : []];
    const hostOf = b => { for (const l of b) { const m = HOST_PORT.exec(l.replace(/\s+/g, '')); if (m) return `${m[1]}:${m[2]}`; } return ''; };
    const [cert, sasl] = blocks.map(b => b.map(keyValue).filter(Boolean));
    c.kafka = {
      cert: { broker: hostOf(blocks[0]), key: pick(cert, 'service key'), cert: pick(cert, 'access certificate'), ca: pick(cert, 'ca cert') },
      sasl: { broker: hostOf(blocks[1]), user: pick(sasl, 'user', 'username'), password: pick(sasl, 'password'), ca: pick(sasl, 'ca cert'), mechanism: (pick(sasl, 'mechanism') || 'scram-sha-256').toLowerCase() },
    };
  }
  if (s.postgres) {
    const all = [s.postgres.heading, ...s.postgres.lines].join(' ');
    const m = /postgres(?:ql)?:\/\/\S+/i.exec(all);
    if (m) c.postgres = { url: m[0].replace(/^postgresql:/i, 'postgres:') };
  }
  for (const [k, port, user] of [['rabbitmq', 5672, 'guest'], ['activemq', 5673, 'admin']]) {
    const pairs = s[k] ? s[k].lines.map(keyValue).filter(Boolean) : [];
    const url = pick(pairs, 'url', 'uri') || (s[k] && /amqps?:\/\/\S+/.exec(s[k].lines.join(' '))?.[0]) || `amqp://${user}:${user}@127.0.0.1:${port}${k === 'rabbitmq' ? '/' : ''}`;
    const homeLine = s[k === 'rabbitmq' ? 'rabbitHome' : 'activeHome']?.lines[0];
    c[k] = { url, home: pick(pairs, 'home', 'folder') || (homeLine ? unquote(homeLine) : '') || (k === 'rabbitmq' ? 'C:\\rabbitmq_server-4.4.0' : 'C:\\apache-activemq-6.3.2'), fromFile: !!s[k] || !!homeLine };
  }
  return c;
}

/** What was found, for the log: names and places, no passwords, keys or full addresses. */
export function describe(c) {
  const host = u => { try { return new URL(u).host; } catch { return '?'; } };
  const has = v => (v ? 'yes' : 'no');
  return [
    c.postgres ? `remote PostgreSQL ${host(c.postgres.url)}` : 'remote PostgreSQL: none',
    c.mysql ? `remote MySQL ${c.mysql.host}:${c.mysql.port}/${c.mysql.database ? '<db>' : '?'} password ${has(c.mysql.password)}` : 'remote MySQL: none',
    c.kafka ? `Kafka SASL ${c.kafka.sasl.broker || '?'} (password ${has(c.kafka.sasl.password)}, CA ${has(c.kafka.sasl.ca && fs.existsSync(c.kafka.sasl.ca))}); client certificate ${c.kafka.cert.broker || '?'} (files ${has([c.kafka.cert.key, c.kafka.cert.cert, c.kafka.cert.ca].every(f => f && fs.existsSync(f)))})` : 'Kafka: none',
    c.mongo ? `MongoDB user ${has(c.mongo.user)}, password ${has(c.mongo.password)}, cluster ${c.mongo.cluster ? c.mongo.cluster.replace(/^.*@/, '').replace(/^mongodb(\+srv)?:\/\//, '') : 'missing (add "Cluster: <name>.mongodb.net" under Mongo DB)'}` : 'MongoDB: none',
    `RabbitMQ ${host(c.rabbitmq.url)}${c.rabbitmq.fromFile ? '' : ' (default local)'}`,
    `ActiveMQ ${host(c.activemq.url)}${c.activemq.fromFile ? '' : ' (default local)'}`,
  ];
}

/** The MongoDB address from the notes, when they have a cluster name. */
export function mongoUri(m) {
  if (!m?.cluster || !m.user) return '';
  if (/^mongodb(\+srv)?:\/\//.test(m.cluster)) {
    const u = new URL(m.cluster.replace(/<(?:db_)?password>/g, encodeURIComponent(m.password)).replace(/<username>/g, encodeURIComponent(m.user)));
    if (!u.username) u.username = encodeURIComponent(m.user);
    if (!u.password) u.password = encodeURIComponent(m.password);
    return u.href;
  }
  return `mongodb+srv://${encodeURIComponent(m.user)}:${encodeURIComponent(m.password)}@${m.cluster.replace(/\/.*$/, '')}/?retryWrites=true&w=majority`;
}

/**
 * Local RabbitMQ and ActiveMQ for the soak test (2.1.1): installed from their zip folders (for example
 * C:\rabbitmq_server-4.4.0 and C:\apache-activemq-6.3.2), not as services. A broker already listening is
 * used as it is; one that is not is started from its folder, and only brokers started here are stopped
 * at the end, so a broker someone runs by hand is never touched.
 */
import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';

const WIN = process.platform === 'win32';
// Windows runs .bat files through the shell: one quoted command line (the folder may have spaces).
const line = (cmd, args) => (WIN ? [`"${cmd}" ${args.join(' ')}`, []] : [cmd, args]);
const sleep = ms => new Promise(r => setTimeout(r, ms));
export const listening = (port, host = '127.0.0.1') => new Promise(resolve => {
  const s = net.connect({ port, host });
  s.once('connect', () => { s.destroy(); resolve(true); });
  s.once('error', () => resolve(false));
  s.setTimeout(1500, () => { s.destroy(); resolve(false); });
});

const KINDS = {
  rabbitmq: {
    name: 'RabbitMQ', port: 5672,
    start: home => [path.join(home, 'sbin', WIN ? 'rabbitmq-server.bat' : 'rabbitmq-server'), []],
    stop: home => [path.join(home, 'sbin', WIN ? 'rabbitmqctl.bat' : 'rabbitmqctl'), ['stop']],
  },
  activemq: {
    name: 'ActiveMQ', port: 5673,
    start: home => [path.join(home, 'bin', WIN ? 'activemq.bat' : 'activemq'), [WIN ? 'start' : 'console']],
    stop: home => [path.join(home, 'bin', WIN ? 'activemq.bat' : 'activemq'), ['stop']],
  },
};

/**
 * Makes sure the broker answers on its port: { started } says whether this call started it.
 * The broker's own output goes to <log folder>/<kind>.log.
 */
export async function ensureBroker(kind, { url, home, logDir, waitMs = 120000 }, note = () => {}) {
  const k = KINDS[kind];
  const u = new URL(url);
  const port = Number(u.port) || k.port;
  if (await listening(port, u.hostname)) { note(`${k.name} is already running on ${u.hostname}:${port}`); return { started: false, port }; }
  if (!['127.0.0.1', 'localhost'].includes(u.hostname)) throw new Error(`${k.name} at ${u.host} does not answer (only a local broker is started here)`);
  const [cmd, args] = k.start(home);
  if (!fs.existsSync(cmd)) throw new Error(`${k.name} is not running and ${cmd} is not there`);
  fs.mkdirSync(logDir, { recursive: true });
  const log = fs.openSync(path.join(logDir, `${kind}.log`), 'a');
  const p = spawn(...line(cmd, args), { cwd: home, detached: true, stdio: ['ignore', log, log], windowsHide: true, shell: WIN });
  p.unref();
  note(`${k.name} is starting from ${home}`);
  for (const t = Date.now(); Date.now() - t < waitMs; await sleep(2000)) {
    if (await listening(port, u.hostname)) {
      // A port answers before the broker accepts logins: a moment more.
      await sleep(kind === 'rabbitmq' ? 5000 : 3000);
      note(`${k.name} is running on ${u.hostname}:${port}`);
      return { started: true, port, home };
    }
  }
  throw new Error(`${k.name} did not start within ${Math.round(waitMs / 1000)} s; see ${path.join(logDir, `${kind}.log`)}`);
}

/** Stops a broker this soak started; leaves one that was already running. */
export async function stopBroker(kind, state, note = () => {}) {
  if (!state?.started) return;
  const k = KINDS[kind];
  const [cmd, args] = k.stop(state.home);
  spawnSync(...line(cmd, args), { cwd: state.home, stdio: 'ignore', windowsHide: true, shell: WIN, timeout: 60000 });
  for (let i = 0; i < 30 && await listening(state.port); i++) await sleep(1000);
  note(`${k.name} ${await listening(state.port) ? 'did not stop; stop it by hand' : 'stopped (it was started by this soak)'}`);
}

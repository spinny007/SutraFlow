/** A small seeded random generator, so the base data is the same on every machine. */
export function rng(seed = 42) {
  let s = seed >>> 0;
  const next = () => { s = (s + 0x6d2b79f5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  return { next, int: (a, b) => a + Math.floor(next() * (b - a + 1)), pick: arr => arr[Math.floor(next() * arr.length)] };
}

export function makeCustomers(n, r = rng(7)) {
  const out = [];
  for (let i = 1; i <= n; i++) {
    const [city, state, pin] = r.pick(CITIES), first = r.pick(FIRST), last = r.pick(LAST);
    out.push({ code: `C${String(i).padStart(6, '0')}`, name: `${first} ${last}`, email: `${first}.${last}${i}@example.in`.toLowerCase(), phone: `+91 ${r.int(70000, 99999)} ${r.int(10000, 99999)}`, city, state, pincode: `${pin}${String(r.int(1, 99)).padStart(3, '0')}`, tier: r.next() < 0.3 ? 'Prime' : 'Regular' });
  }
  return out;
}
export function makeProducts(n, r = rng(11)) {
  const out = [];
  for (let i = 1; i <= n; i++) {
    const [cat, brands, items, [lo, hi], [wlo, whi]] = CATALOG[i % CATALOG.length];
    const brand = r.pick(brands), item = r.pick(items);
    const price = Math.round((lo + (hi - lo) * r.next() ** 2) / 10) * 10 - 1;
    out.push({ sku: `AMR-${cat.slice(0, 3).toUpperCase()}-${String(i).padStart(5, '0')}`, name: `${brand} ${item}`, category: cat, brand, price: Math.max(lo, price), weight: r.int(wlo, whi) });
  }
  return out;
}

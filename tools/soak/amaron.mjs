/** The amaron database on the soak's PostgreSQL: made with its tables and base data when missing. */
export async function ensureAmaron(pg, adminUrl, { password, customers = 5000, products = 1200, history = 20000, note = () => {} } = {}) {
  const admin = new pg.Client({ connectionString: adminUrl, ...(password ? { password } : {}) });
  admin.on('error', () => {});
  await admin.connect();
  const exists = (await admin.query('select 1 from pg_database where datname = $1', [DB])).rowCount > 0;
  if (!exists) { await admin.query(`CREATE DATABASE ${DB}`); note(`made the ${DB} database`); }
  await admin.end();
  const url = new URL(adminUrl); url.pathname = `/${DB}`;
  const db = new pg.Client({ connectionString: url.toString(), ...(password ? { password } : {}) });
  db.on('error', () => {});
  await db.connect();
  await db.query(SCHEMA);
  const [{ n }] = (await db.query('select count(*)::int n from customers')).rows;
  if (!n) await seed(db, { customers, products, history, note });
  return { db, url: url.toString() };
}

async function seed(db, { customers, products, history, note }) {
  const t = Date.now();
  await db.query('BEGIN');
  const ins = async (table, cols, rows) => {
    for (let i = 0; i < rows.length; i += 1000) {
      const part = rows.slice(i, i + 1000), args = [];
      const values = part.map(r => `(${cols.map(c => { args.push(r[c]); return `$${args.length}`; }).join(', ')})`).join(', ');
      await db.query(`INSERT INTO ${table}(${cols.join(', ')}) VALUES ${values}`, args);
    }
  };
  await ins('warehouses', ['code', 'name', 'city', 'state', 'capacity', 'soak_run'], WAREHOUSES.map(([code, name, city, state, capacity]) => ({ code, name, city, state, capacity, soak_run: SEED })));
  await ins('customers', ['code', 'name', 'email', 'phone', 'city', 'state', 'pincode', 'tier', 'soak_run'], makeCustomers(customers).map(c => ({ ...c, soak_run: SEED })));
  await ins('products', ['sku', 'name', 'category', 'brand', 'price', 'weight_g', 'soak_run'], makeProducts(products).map(p => ({ ...p, weight_g: p.weight, soak_run: SEED })));
  await db.query(`INSERT INTO inventory(warehouse_id, product_id, on_hand) SELECT w.id, p.id, 50 + (abs(hashtext(w.code || p.sku)) % 950) FROM warehouses w CROSS JOIN products p`);
  // Order history: the last 180 days, mostly delivered, with lines, shipments and some care tickets.
  await db.query(`
    WITH o AS (
      INSERT INTO orders(order_no, customer_id, warehouse_id, status, total, payment, placed_at, updated_at, soak_run)
      SELECT 'AMR-H' || lpad(g::text, 7, '0'), c.id, w.id,
        (ARRAY['delivered','delivered','delivered','delivered','delivered','shipped','cancelled','returned'])[1 + abs(hashtext('s' || g)) % 8],
        0, (ARRAY['UPI','UPI','UPI','Card','Card','Cash on delivery','Net banking','Amaron Pay'])[1 + abs(hashtext('p' || g)) % 8],
        now() - ((abs(hashtext('t' || g)) % 259200) || ' minutes')::interval, now(), $2
      FROM generate_series(1, $1::int) g
      JOIN customers c ON c.id = 1 + abs(hashtext('c' || g)) % (SELECT count(*) FROM customers)
      JOIN warehouses w ON w.id = 1 + abs(hashtext('w' || g)) % (SELECT count(*) FROM warehouses)
      RETURNING id, order_no, placed_at)
    INSERT INTO order_items(order_id, line, product_id, qty, price, soak_run)
    SELECT o.id, l, p.id, 1 + abs(hashtext(o.order_no || l)) % 3, p.price, $2
    FROM o CROSS JOIN generate_series(1, 1 + abs(hashtext(o.order_no)) % 4) l
    JOIN products p ON p.id = 1 + abs(hashtext(o.order_no || 'p' || l)) % (SELECT count(*) FROM products)`, [history, SEED]);
  await db.query(`UPDATE orders o SET total = s.total FROM (SELECT order_id, sum(qty * price) total FROM order_items GROUP BY order_id) s WHERE s.order_id = o.id AND o.soak_run = $1`, [SEED]);
  await db.query(`INSERT INTO shipments(order_id, warehouse_id, carrier, tracking_no, status, created_at, soak_run)
    SELECT o.id, o.warehouse_id, (ARRAY['Amaron Logistics','Delhivery','Blue Dart','Ekart','DTDC','Xpressbees'])[1 + abs(hashtext(o.order_no)) % 6],
      'TRK' || upper(substr(md5(o.order_no), 1, 10)), CASE WHEN o.status = 'delivered' THEN 'delivered' ELSE 'in transit' END, o.placed_at + interval '6 hours', $1
    FROM orders o WHERE o.soak_run = $1 AND o.status IN ('delivered', 'shipped', 'returned')`, [SEED]);
  await db.query('COMMIT');
  const counts = (await db.query(`select (select count(*) from customers)::int c, (select count(*) from products)::int p, (select count(*) from orders)::int o, (select count(*) from order_items)::int i, (select count(*) from inventory)::int s`)).rows[0];
  note(`seeded ${DB} in ${Math.round((Date.now() - t) / 1000)} s: ${counts.c} customers, ${counts.p} products, ${WAREHOUSES.length} warehouses, ${counts.s} stock rows, ${counts.o} past orders with ${counts.i} lines (soak_run ${SEED})`);
}

export async function startRun(db, { id, version, scenarios, options }) {
  await db.query('INSERT INTO soak_runs(id, version, host, scenarios, options) VALUES ($1, $2, $3, $4, $5)', [id, version, (await import('node:os')).hostname(), scenarios, options]);
}
export async function endRun(db, id, { status, passed, total, summary }) {
  await db.query('UPDATE soak_runs SET ended_at = now(), status = $2, checks_passed = $3, checks_total = $4, summary = $5 WHERE id = $1', [id, status, passed, total, summary]);
}

/** Picks what a shopper would: a customer, one to four products, a payment; the warehouse that serves the city. */
export async function shop(db) {
  const customers = (await db.query('select code, name, city from customers')).rows;
  const products = (await db.query('select sku, name, price::float price from products where active')).rows;
  const r = rng(Date.now() % 100000);
  return {
    customers, products,
    order() {
      const c = r.pick(customers), lines = r.int(1, 4), seen = new Set(), items = [];
      while (items.length < lines) { const p = r.pick(products); if (seen.has(p.sku)) continue; seen.add(p.sku); items.push({ line: items.length + 1, sku: p.sku, qty: r.int(1, 3) }); }
      return { customer: c.code, city: c.city, warehouse: warehouseFor(c.city), payment: r.pick(PAYMENTS), items };
    },
    care(orderNo, itemName) {
      const [subject, body, expected] = r.pick(CARE);
      return { subject, body: body.replace('{item}', itemName).replace('{order}', orderNo), channel: r.pick(CHANNELS), expected };
    },
    review(product) {
      const rating = r.next() < 0.7 ? r.int(4, 5) : r.int(1, 3);
      const text = rating >= 4 ? r.pick(['Value for money, works as described.', 'Fast delivery and well packed.', 'Good quality, would buy again.', 'Exactly as shown in the pictures.']) : r.pick(['Stopped working within a week.', 'Packaging was damaged.', 'Smaller than expected.', 'Not worth the price.']);
      return { sku: product.sku, product: product.name, rating, text, verified: r.next() < 0.85 };
    },
    pick: r.pick,
  };
}

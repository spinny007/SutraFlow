// A headless Edge (or Chrome) for the guide screenshots, driven through the DevTools protocol with a
// temporary profile of its own: open() starts it, and the page object navigates, runs code in the page
// and saves screenshots to docs/guide-images.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT = path.join(root, 'docs', 'guide-images');
export const sleep = ms => new Promise(r => setTimeout(r, ms));

const browsers = [
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/usr/bin/microsoft-edge', '/usr/bin/google-chrome', '/usr/bin/chromium',
];

/** Starts the browser at a window size; close() ends it and removes its profile. */
export async function open({ width = 1440, height = 900 } = {}) {
  const exe = browsers.find(b => fs.existsSync(b));
  if (!exe) throw new Error('No Edge or Chrome found');
  fs.mkdirSync(OUT, { recursive: true });
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'sutra-shots-'));
  const port = 9300 + Math.floor(Math.random() * 500);
  const proc = spawn(exe, ['--headless=new', `--remote-debugging-port=${port}`, `--user-data-dir=${profile}`, '--no-first-run', '--disable-extensions', '--hide-scrollbars', 'about:blank'], { stdio: 'ignore' });
  let target;
  for (let i = 0; i < 50 && !target; i++) {
    await sleep(200);
    try { target = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find(t => t.type === 'page'); } catch { /* starting */ }
  }
  if (!target) { proc.kill(); throw new Error('The browser did not start'); }
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
  let id = 0;
  const waiting = new Map();
  ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && waiting.has(m.id)) { waiting.get(m.id)(m); waiting.delete(m.id); } };
  const cdp = (method, params = {}) => new Promise((res, rej) => {
    const n = ++id;
    waiting.set(n, m => (m.error ? rej(new Error(`${method}: ${m.error.message}`)) : res(m.result)));
    ws.send(JSON.stringify({ id: n, method, params }));
  });
  await cdp('Page.enable');
  await cdp('Network.enable');
  await cdp('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile: false });
  const page = {
    cdp,
    /** Runs an async function body in the page and returns its value. */
    async js(body) {
      const r = await cdp('Runtime.evaluate', { expression: `(async () => { ${body} })()`, awaitPromise: true, returnByValue: true });
      if (r.exceptionDetails) throw new Error(r.exceptionDetails.exception?.description || r.exceptionDetails.text);
      return r.result.value;
    },
    async go(url, wait = 2200) { await cdp('Page.navigate', { url }); await sleep(wait); },
    async size(w, h) { await cdp('Emulation.setDeviceMetricsOverride', { width: w, height: h, deviceScaleFactor: 1, mobile: false }); await sleep(300); },
    async cookie(url, name, value) { await cdp('Network.setCookie', { name, value, domain: new URL(url).hostname, path: '/', httpOnly: true }); },
    /** Saves the window, or the whole page height when full is set, as docs/guide-images/<name>.jpg. */
    async shot(name, { full = false } = {}) {
      await sleep(500);
      const r = await cdp('Page.captureScreenshot', { format: 'jpeg', quality: 84, captureBeyondViewport: full });
      fs.writeFileSync(path.join(OUT, `${name}.jpg`), Buffer.from(r.data, 'base64'));
      console.log('saved', name);
    },
    async close() {
      try { ws.close(); } catch { /* closed */ }
      proc.kill();
      await sleep(500);
      try { fs.rmSync(profile, { recursive: true, force: true }); } catch { /* still in use */ }
    },
  };
  return page;
}

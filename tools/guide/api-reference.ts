function routeTable(keys: string[]) {
  const rows = keys.map(k => {
    const d = API_DOCS[k];
    const [m, p] = k.split(' ');
    return `<tr><td><code>${m}&nbsp;${esc(p)}</code></td><td>${text(d?.does || '')}${onEngine(k) ? '' : ' <span class="muted">Studio only.</span>'}</td><td>${who(k)}</td><td>${d?.cli ? `<code>${esc(d.cli)}</code>` : ''}</td></tr>`;
  });
  return `<table class="t"><thead><tr><th>Endpoint</th><th>What it does</th><th>Who may call it</th><th>sutra command</th></tr></thead><tbody>\n${rows.join('\n')}\n</tbody></table>`;
}

/** Every documented route, in the order of API_DOCS, sorted into GROUPS. */
export function groupedRoutes() {
  const out = new Map(GROUPS.map(g => [g.id, [] as string[]]));
  for (const key of Object.keys(API_DOCS)) {
    const g = GROUPS.find(x => x.match(key.split(' ')[1]))!;
    out.get(g.id)!.push(key);
  }
  return out;
}

function overview(): Chapter {
  const perms = PERMISSIONS.map(p => `<tr><td><code>${p.id}</code></td><td>${esc(p.name)}</td><td>${p.scope === 'project' ? 'Per project' : 'Server'}</td><td>${esc(p.help)}</td></tr>`).join('\n');
  const cliRows = Object.entries(API_DOCS).filter(([, d]) => d.cli).map(([k, d]) => `<tr><td><code>${esc(d.cli!)}</code></td><td><code>${esc(k)}</code></td></tr>`).join('\n');
  const total = Object.keys(API_DOCS).length;
  return {
    id: 'api-overview', title: 'The admin API: addresses, signing in and conventions',
    html: `
<p>Everything the designer, the Admin Console and the <code>sutra</code> command do goes through one HTTP API on the <strong>admin port</strong> (4800 by default; 4801 for an engine beside the studio). This part of the guide lists all ${total} endpoints: what each does, who may call it, whether headless engines serve it, and the <code>sutra</code> command that calls it. The tables are made from the server's own route and permission tables, so they match the version you run.</p>
<p>This is the API for <em>running</em> SutraFlow. The APIs your Sutras offer to callers (REST, SOAP, MCP, agents) are on the <strong>gateway</strong> ports and are described by the gateway's OpenAPI document (<code>GET /api/gateway/openapi</code>) and the <em>SutraFlow Design Guide</em>.</p>
<p class="h">Addresses</p>
<table class="t"><thead><tr><th>Where</th><th>Base address</th></tr></thead><tbody>
<tr><td>Studio on this machine</td><td><code>http://127.0.0.1:4800</code></td></tr>
<tr><td>An engine beside the studio</td><td><code>http://127.0.0.1:4801</code></td></tr>
<tr><td>A cluster</td><td>Any engine's admin port, or the internal load balancer in front of them (<a href="#ch-cluster-console">One Admin Console for the whole cluster</a>): every engine answers for the whole cluster</td></tr>
<tr><td>Docker or Kubernetes</td><td>The container's port 4800; from inside a container, <code>sutra</code> finds it by itself</td></tr>
</tbody></table>
<p>Keep the admin port on a private network or behind a VPN. Callers of your APIs never need it.</p>
<p class="h">Signing in</p>
<table class="t"><thead><tr><th>Caller</th><th>How</th><th>May</th></tr></thead><tbody>
<tr><td><b>Admin token</b></td><td><code>Authorization: Bearer &lt;SUTRA_ADMIN_TOKEN&gt;</code></td><td>Everything. For the launcher and bootstrapping; give pipelines a system account instead.</td></tr>
<tr><td><b>System account token</b></td><td><code>Authorization: Bearer &lt;token&gt;</code> from <code>sutra token create &lt;account&gt;</code> (or Admin Console, System accounts)</td><td>What the account's roles allow. Tokens can expire and are revoked at once.</td></tr>
<tr><td><b>A person</b></td><td><code>POST /api/auth/login</code> (or single sign-on) sets the <code>sutra_session</code> cookie, valid 12 hours on every engine of the cluster</td><td>What their roles allow. Changing requests also need the header <code>X-Sutra: 1</code>.</td></tr>
</tbody></table>
<ul>
<li><strong>X-Sutra header</strong>: a request other than GET that is signed in by cookie must carry <code>X-Sutra: 1</code>, which a form on another site cannot send (protection against cross-site requests). Requests with a Bearer token do not need it. Without it: 403 <code>Missing X-Sutra header</code>.</li>
<li><strong>Open endpoints</strong> need no sign-in: the sign-in and single sign-on endpoints, OAuth callbacks, and <code>/health</code> and <code>/ready</code>.</li>
<li><strong>A password set by an administrator</strong> must be changed first: until then every call other than <code>POST /api/auth/password</code> and <code>GET /api/access/me</code> answers 403 with <code>mustChange: true</code>.</li>
<li><strong>Headless engines</strong> (<code>SUTRA_MODE=engine</code>) serve the endpoints for running and releasing, not the designer's: the others answer 404. They are marked <em>Studio only</em> in the tables. An engine without <code>SUTRA_ADMIN_TOKEN</code> takes only signed-in people; add them with <code>sutra user add</code> on the server.</li>
</ul>
<p class="h">Who may call what</p>
<p>Each endpoint needs one permission, on a project or for the server. Roles are sets of permissions given to a person or system account on one project or on all projects. "Signed in" means any caller; the answer then holds only the projects the caller may see.</p>
<table class="t"><thead><tr><th>Permission</th><th>Name</th><th>Given</th><th>Allows</th></tr></thead><tbody>
${perms}
</tbody></table>
<p class="h">Requests and answers</p>
<ul>
<li>Bodies and answers are JSON (<code>content-type: application/json</code>), apart from downloads (packages, release zips, CSV, documentation) and the event stream.</li>
<li>Ids in paths (<code>:id</code>) are the ids the list endpoints return; the <code>sutra</code> command looks them up from names for you.</li>
<li>Changing requests are written to the audit log with the caller, address, outcome and the names of what changed; reads and checks are not.</li>
</ul>
<table class="t"><thead><tr><th>Status</th><th>Meaning</th></tr></thead><tbody>
<tr><td>200, 202</td><td>Done (202: started, such as a drain)</td></tr>
<tr><td>400</td><td>The request is wrong: <code>{"error": "..."}</code> says why</td></tr>
<tr><td>401</td><td>Not signed in, wrong token, or wrong password</td></tr>
<tr><td>403</td><td>Signed in but not allowed (the error names the permission), the <code>X-Sutra</code> header missing, or a password to change first</td></tr>
<tr><td>404</td><td>Not found, or not served by a headless engine</td></tr>
<tr><td>409</td><td>In conflict with the server's state. A deployment that would replace or undeploy Sutras without approval answers 409 with <code>plan</code>: deploy again with <code>approve</code> set to <code>plan.planId</code></td></tr>
<tr><td>423, 429</td><td>Account locked after wrong passwords; too many sign-in attempts from one address</td></tr>
<tr><td>503</td><td><code>/ready</code> only: not ready, with the reasons</td></tr>
</tbody></table>
<p class="h">Examples</p>
<pre># bash: the cluster's engines, with a system account's token
curl -s -H "Authorization: Bearer $SUTRA_TOKEN" https://sutra-admin.internal/api/engine/status

# bash: check a release and deploy it with the approved plan id
ZIP=$(base64 -w0 orders-1.4.0.zip)
curl -s -X POST -H "Authorization: Bearer $SUTRA_TOKEN" -H "content-type: application/json" \\
  -d "{\\"zip\\":\\"$ZIP\\"}" https://sutra-admin.internal/api/packages/open        # .plan.planId
curl -s -X POST -H "Authorization: Bearer $SUTRA_TOKEN" -H "content-type: application/json" \\
  -d "{\\"zip\\":\\"$ZIP\\",\\"approve\\":\\"&lt;plan id&gt;\\"}" https://sutra-admin.internal/api/packages/deploy</pre>
<pre># PowerShell
$h = @{ Authorization = "Bearer $env:SUTRA_TOKEN" }
Invoke-RestMethod -Headers $h https://sutra-admin.internal/api/engine/status
Invoke-RestMethod -Headers $h "https://sutra-admin.internal/api/runs?status=failed&amp;limit=20"</pre>
<p class="h">The sutra command is this API</p>
<p>With <code>--server</code> (or <code>SUTRA_SERVER</code>) and a token, every <code>sutra</code> command is one or more of these calls; it resolves names to ids, reads files and environment variables on your side (config files, release zips) and prints the answers. Anything the command does, a script can do with the endpoint beside it:</p>
<table class="t"><thead><tr><th>sutra command</th><th>Endpoint</th></tr></thead><tbody>
${cliRows}
</tbody></table>
<p class="h">The admin port's other endpoints</p>
<table class="t"><thead><tr><th>Endpoint</th><th>What it does</th></tr></thead><tbody>
${ADMIN_PORT_ENDPOINTS.map(e => `<tr><td><code>${esc(e.path)}</code></td><td>${text(e.does)}</td></tr>`).join('\n')}
</tbody></table>`,
  };
}

/** The Admin API chapters: the overview, then one chapter per group of endpoints. */
export function apiChapters(): Chapter[] {
  const grouped = groupedRoutes();
  return [overview(), ...GROUPS.filter(g => grouped.get(g.id)!.length).map(g => ({
    id: g.id, title: g.title,
    html: `<p>${g.intro}</p>\n<p>${grouped.get(g.id)!.length} endpoints. Permissions, conventions and examples: <a href="#ch-api-overview">The admin API</a>.</p>\n${routeTable(grouped.get(g.id)!)}`,
  }))];
}

export const API_CHAPTER_IDS = ['api-overview', ...GROUPS.map(g => g.id)];

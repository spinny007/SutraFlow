import { useEffect, useState } from 'react';
import { get } from '../src/api';
import { useToast } from '../src/ui';
import { PageHead, Err, Empty, useLoad, ago, when, runState } from './shared';

interface Sutra { id: string; name: string; version: number; deployed: boolean; done: number; failed: number; cancelled: number; open: number; lastRun: string | null; lastFailure: string | null }
interface Project { id: string; name: string; sutras: Sutra[]; done: number; failed: number; cancelled: number; open: number }
interface StartedBy { kind: 'person' | 'client' | 'system' | 'run'; id: string; how?: string; app?: string; ip?: string; anonymous?: boolean; recorded?: boolean }
interface Run { id: string; flowId: string; flowName: string; projectId: string; version: number; status: string; source: string; error: string | null; steps: number; startedAt: string; finishedAt: string | null; ms: number | null; startedBy: StartedBy }

/** Who or what started a run, in words: a person, an API client (anonymous where the route has no security policy), the system, or another run. */
function by(b: StartedBy | undefined) {
  if (!b) return '-';
  if (b.recorded === false) return b.kind === 'system' ? `system: ${b.id}` : b.kind === 'run' ? 'another run' : `${b.kind === 'person' ? 'a person' : 'an API client'} (not recorded before 2.1.0)`;
  if (b.kind === 'person') return b.id;
  if (b.kind === 'client') return b.anonymous ? `${b.id.startsWith('visitor:') ? `visitor ${b.id.slice(8)}` : 'anonymous client'}${b.ip ? ` ${b.ip}` : ''}` : `${b.id}${b.app ? ` (app ${b.app})` : ''} · ${b.how}${b.ip ? ` · ${b.ip}` : ''}`;
  if (b.kind === 'run') return `run ${b.id.slice(0, 8)}`;
  return `system: ${b.id}`;
}
interface Found { runs: Run[]; more: boolean; next: string | null }
interface Link { id: string; flowName: string; status: string; startedAt: string | null; step: string }

const PERIODS: [number, string][] = [[1, 'Last hour'], [24, 'Last 24 hours'], [168, 'Last 7 days'], [720, 'Last 30 days'], [2160, 'Last 90 days']];
const duration = (ms: number | null) => (ms == null ? '-' : ms < 1000 ? `${ms} ms` : ms < 60000 ? `${(ms / 1000).toFixed(1)} s` : `${Math.round(ms / 60000)} min`);
const rate = (s: { done: number; failed: number }) => (s.done + s.failed ? `${Math.round((s.done / (s.done + s.failed)) * 100)}%` : '-');
const json = (v: unknown) => (v === undefined ? '' : JSON.stringify(v, null, 2));

/** An id with a button that copies it. */
function Id({ v }: { v: string }) {
  const toast = useToast();
  return <span className="mono xs">{v} <button className="btn link xs" onClick={() => { navigator.clipboard?.writeText(v).then(() => toast('Copied'), () => {}); }} aria-label={`Copy ${v}`}>copy</button></span>;
}

/** A value shown folded, opened on request (step inputs and outputs can be large). */
function Data({ label, v }: { label: string; v: unknown }) {
  if (v === undefined || v === null) return <span className="muted xs">{label}: none kept</span>;
  const text = json(v);
  // Large values are stored once and shown as a reference (2.1.1): each can be downloaded.
  const refs: { $payload: string; size: number }[] = [];
  const find = (x: any) => { if (!x || typeof x !== 'object') return; if (typeof x.$payload === 'string' && 'size' in x) { refs.push(x); return; } Object.values(x).forEach(find); };
  find(v);
  return <details><summary className="xs">{label} <span className="muted">({text.length < 1024 ? `${text.length} characters` : `${Math.round(text.length / 1024)} KB`})</span></summary><pre className="c-code">{text.length > 200000 ? text.slice(0, 200000) + '\n… (cut at 200 KB; Download has it all)' : text}</pre>
    {refs.map(r => <div key={r.$payload} className="xs">Stored once: {r.size < 1048576 ? `${Math.round(r.size / 1024)} KB` : `${(r.size / 1048576).toFixed(1)} MB`} <a href={`/api/console/trace/payloads/${r.$payload}`} download>Download</a></div>)}</details>;
}

/**
 * Traceability: each project's Sutras with their runs by outcome over a period, runs found by id, status or
 * a value in their input, and a run with its input, every step's input and output, its log and reply,
 * and the runs it called or was called by.
 */
export function Trace() {
  const [hours, setHours] = useState(24);
  const [projectId, setProjectId] = useState('');
  const [flowId, setFlowId] = useState('');
  const [status, setStatus] = useState('');
  const [text, setText] = useState('');
  const [search, setSearch] = useState('');
  const [found, setFound] = useState<Found | null>(null);
  const [err, setErr] = useState('');
  const [runId, setRunId] = useState('');
  const projects = useLoad<Project[]>(`/api/console/trace?hours=${hours}`, [hours]);
  const project = projects.data?.find(p => p.id === projectId);

  const query = (before?: string) => {
    const p = new URLSearchParams({ hours: String(hours), limit: '50' });
    if (projectId) p.set('projectId', projectId);
    if (flowId) p.set('flowId', flowId);
    if (status) p.set('status', status);
    if (search) p.set('q', search);
    if (before) p.set('before', before);
    return `/api/console/trace/runs?${p}`;
  };
  useEffect(() => {
    if (!projectId && !search) { setFound(null); return; }
    setErr('');
    get<Found>(query()).then(setFound, e => setErr(e.message));
  }, [hours, projectId, flowId, status, search]); // eslint-disable-line react-hooks/exhaustive-deps
  const more = async () => { if (!found?.next) return; try { const r = await get<Found>(query(found.next)); setFound({ runs: [...found.runs, ...r.runs], more: r.more, next: r.next }); } catch (e: any) { setErr(e.message); } };

  return (
    <>
      <PageHead title="Traceability" sub="Every project's Sutras with their runs by outcome, and each run as the database keeps it: what it started with, each step's input and output, its log and reply, and the runs it called. Open a project, then a Sutra; or find a run by its id or by a value in its input, such as an order number. What a step's data shows depends on the Sutra's Step data tuning (all, only for failed runs, or none)." />
      <div className="c-filters">
        <div className="fld"><label htmlFor="tr-period">Period</label>
          <select id="tr-period" className="inp" value={hours} onChange={e => setHours(Number(e.target.value))}>{PERIODS.map(([h, l]) => <option key={h} value={h}>{l}</option>)}</select></div>
        <div className="fld"><label htmlFor="tr-find">Find a run</label>
          <input id="tr-find" className="inp" type="search" placeholder="Run id, who started it, or a value in its input" value={text} onChange={e => setText(e.target.value)} onKeyDown={e => { if (e.key === 'Enter') setSearch(text.trim()); }} /></div>
        <button className="btn small" onClick={() => setSearch(text.trim())}>Find</button>
        {(projectId || search) && <button className="btn small" onClick={() => { setProjectId(''); setFlowId(''); setStatus(''); setText(''); setSearch(''); setRunId(''); }}>Clear</button>}
      </div>
      <Err text={projects.error || err} />

      {!projectId && projects.data && (projects.data.length ? (
        <table className="t c-table">
          <thead><tr><th>Project</th><th className="right">Done</th><th className="right">Failed</th><th className="right">Cancelled</th><th className="right">Open</th><th className="right">Success</th></tr></thead>
          <tbody>{projects.data.map(p => (
            <tr key={p.id} className="click" tabIndex={0} onClick={() => { setProjectId(p.id); setFlowId(''); }} onKeyDown={e => { if (e.key === 'Enter') setProjectId(p.id); }}>
              <td><b>{p.name}</b><div className="muted xs mono">{p.id}</div></td>
              <td className="right">{p.done}</td><td className="right">{p.failed ? <span className="c-err">{p.failed}</span> : 0}</td><td className="right">{p.cancelled}</td><td className="right">{p.open}</td><td className="right">{rate(p)}</td>
            </tr>
          ))}</tbody>
        </table>
      ) : <Empty title="No project">Projects you may see appear here.</Empty>)}

      {project && (
        <section className="c-section">
          <h2>{project.name} <Id v={project.id} /></h2>
          <table className="t c-table">
            <thead><tr><th>Sutra</th><th className="right">Done</th><th className="right">Failed</th><th className="right">Cancelled</th><th className="right">Open</th><th className="right">Success</th><th>Last run</th><th>Last failure</th></tr></thead>
            <tbody>{project.sutras.map(s => (
              <tr key={s.id} className="click" aria-selected={flowId === s.id} tabIndex={0} onClick={() => setFlowId(flowId === s.id ? '' : s.id)} onKeyDown={e => { if (e.key === 'Enter') setFlowId(flowId === s.id ? '' : s.id); }}>
                <td><b>{s.name}</b> <span className="muted xs">v{s.version}{s.deployed ? '' : ' · not deployed'}</span><div className="muted xs mono">{s.id}</div></td>
                <td className="right">{s.done}</td><td className="right">{s.failed ? <span className="c-err">{s.failed}</span> : 0}</td><td className="right">{s.cancelled}</td><td className="right">{s.open}</td><td className="right">{rate(s)}</td>
                <td className="nowrap" title={when(s.lastRun)}>{s.lastRun ? ago(s.lastRun) : '-'}</td><td className="nowrap" title={when(s.lastFailure)}>{s.lastFailure ? ago(s.lastFailure) : '-'}</td>
              </tr>
            ))}</tbody>
          </table>
        </section>
      )}

      {found && (
        <section className="c-section">
          <h2>Runs{flowId && project ? ` of ${project.sutras.find(s => s.id === flowId)?.name}` : project ? ` in ${project.name}` : ''}{search ? ` matching "${search}"` : ''}</h2>
          <div className="c-filters">
            <div className="fld"><label htmlFor="tr-status">Status</label>
              <select id="tr-status" className="inp" value={status} onChange={e => setStatus(e.target.value)}>
                <option value="">All</option><option value="failed">Failed</option><option value="done">Done</option><option value="open">Open (running, waiting, queued)</option><option value="cancelled">Cancelled</option>
              </select></div>
          </div>
          {found.runs.length ? (
            <div className="c-tablewrap"><table className="t c-table">
              <thead><tr><th>Started</th><th>Sutra</th><th>Status</th><th>Started by</th><th className="right">Took</th><th className="right">Steps</th><th>Error</th></tr></thead>
              <tbody>{found.runs.map(r => (
                <tr key={r.id} className="click" aria-selected={runId === r.id} tabIndex={0} onClick={() => setRunId(r.id)} onKeyDown={e => { if (e.key === 'Enter') setRunId(r.id); }}>
                  <td className="nowrap" title={when(r.startedAt)}>{ago(r.startedAt)}<div className="muted xs mono">{r.id.slice(0, 8)}</div></td>
                  <td>{r.flowName} <span className="muted xs">v{r.version}</span></td><td>{runState(r.status)}</td><td className="xs">{by(r.startedBy)}<div className="muted">{r.source}</div></td>
                  <td className="right nowrap">{duration(r.ms)}</td><td className="right">{r.steps}</td><td className="c-err">{r.error || ''}</td>
                </tr>
              ))}</tbody>
            </table></div>
          ) : <Empty title="No run">No run in this period{search ? ' matches' : ''}. Try a longer period.</Empty>}
          {found.more && <button className="btn small" onClick={more}>Show older runs</button>}
        </section>
      )}

      {runId && <RunTrace id={runId} onOpen={setRunId} onClose={() => setRunId('')} />}
    </>
  );
}

/** One run as stored: ids, input, each step's input and output, log, reply, and linked runs. */
function RunTrace({ id, onOpen, onClose }: { id: string; onOpen(id: string): void; onClose(): void }) {
  const run = useLoad<any>(`/api/console/trace/runs/${id}`, [id]);
  const r = run.data;
  const download = () => {
    const url = URL.createObjectURL(new Blob([JSON.stringify(r, null, 2)], { type: 'application/json' }));
    const a = Object.assign(document.createElement('a'), { href: url, download: `run-${id}.json` });
    a.click(); URL.revokeObjectURL(url);
  };
  const link = (l: Link, how: string) => <li key={l.id}>{how} <button className="btn link" onClick={() => onOpen(l.id)}>{l.flowName}</button> {runState(l.status)} <span className="muted xs mono">{l.id.slice(0, 8)}</span></li>;
  return (
    <section className="c-section" aria-label="Run">
      <div className="c-runhead">
        <h2>Run</h2>
        <span className="c-actions"><button className="btn small" disabled={!r} onClick={download}>Download</button><button className="btn small" onClick={onClose}>Close</button></span>
      </div>
      <Err text={run.error} />
      {r && <>
        <p>{runState(r.status)} <b>{r.flowName}</b> v{r.version} · {r.source} · started {when(r.startedAt)}{r.finishedAt ? `, finished ${when(r.finishedAt)}` : ''}</p>
        <div className="xs">Run <Id v={r.id} /> · Sutra <Id v={r.flowId || '-'} /> · Project <Id v={r.projectId || '-'} /></div>
        <p className="xs">Started by <b>{by(r.startedBy)}</b>{r.startedBy?.anonymous && <span className="muted"> · the route has no security policy; agent channels tell such callers apart by a signed visitor token, other routes do not</span>}</p>
        {r.error && <div className="errbox">{r.error}</div>}
        {(r.links?.parent || r.links?.children?.length > 0) && <ul className="xs">{r.links.parent && link(r.links.parent, 'Called by')}{(r.links.children || []).map((c: Link) => link(c, 'Called'))}</ul>}
        {r.stepData !== 'all' && <p className="muted xs">Step data: {r.stepData}. Step inputs and outputs are kept {r.stepData === 'none' ? 'for no run' : 'for failed runs only'} (the Sutra's Step data tuning).</p>}
        <Data label="Started with" v={r.tasks?.[0]?.input ?? null} />
        <h3>Steps</h3>
        <div className="c-tablewrap"><table className="t c-table">
          <thead><tr><th>Step</th><th>Status</th><th className="right">Try</th><th className="right">Time</th><th>Engine</th><th>Input and output</th></tr></thead>
          <tbody>{(r.tasks || []).map((t: any) => (
            <tr key={t.id}>
              <td><strong>{r.doc?.nodes?.find((n: any) => n.id === t.node_id)?.name || t.node_id}</strong>{t.port && t.port !== 'out' && <span className="muted xs"> → {t.port}</span>}</td>
              <td>{runState(t.status)}</td><td className="right">{(t.attempt || 0) + 1}</td><td className="right nowrap">{t.ms != null ? `${t.ms} ms` : ''}</td><td className="xs">{t.owner || ''}</td>
              <td>{t.error && <div className="c-err">{t.error}</div>}<Data label="Input" v={t.input} /><Data label="Output" v={t.output} /></td>
            </tr>
          ))}</tbody>
        </table></div>
        {r.reply && <Data label="Reply" v={r.reply} />}
        {r.logs?.length > 0 && <details><summary className="xs">Log ({r.logs.length})</summary><pre className="c-code">{r.logs.map((l: any) => `${l.t} ${l.level} ${l.msg}`).join('\n')}</pre></details>}
      </>}
    </section>
  );
}

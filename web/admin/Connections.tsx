import { useCallback, useState } from 'react';
import { PageHead, Err, Empty, State, useLoad, useEvery, ago } from './shared';
import { EChart, baseOption, type ChartTokens } from './EChart';

interface Holder { kind: 'step' | 'lease'; owner: string; since: number; run?: string; step?: string; sutra?: string; holder?: string }
interface Wait { task: number; since: number; reason: string; run?: string; step?: string; sutra?: string }
interface Use {
  id: string; name: string; kind: string; project: string | null; projectName: string;
  setting: string; limit: number; error?: string;
  active: number; steps: number; leases: number; waiting: number; oldestWaitMs: number;
  holders: Holder[]; waits: Wait[];
}
interface Data { connections: Use[]; history: Record<string, { at: number; active: number; waiting: number; limit: number }[]>; hours: number; sampleSeconds: number }

const span = (ms: number) => (ms < 60e3 ? `${Math.round(ms / 1000)} s` : ms < 3600e3 ? `${Math.round(ms / 60e3)} min` : `${(ms / 3600e3).toFixed(1)} h`);

/** Usage of one connection over time: in use, waiting, and its limit as a line. */
function UsageChart({ name, points }: { name: string; points: Data['history'][string] }) {
  const key = JSON.stringify(points);
  const option = useCallback((t: ChartTokens) => {
    const base = baseOption(t);
    return {
      ...base,
      series: [
        { name: 'in use', type: 'line', step: 'end', showSymbol: false, areaStyle: { opacity: 0.18 }, lineStyle: { width: 2 }, itemStyle: { color: t.auto }, data: points.map(p => [p.at, p.active]) },
        { name: 'waiting', type: 'line', step: 'end', showSymbol: false, lineStyle: { width: 2 }, itemStyle: { color: t.warn }, data: points.map(p => [p.at, p.waiting]) },
        { name: 'limit', type: 'line', step: 'end', showSymbol: false, lineStyle: { width: 1, type: 'dashed' }, itemStyle: { color: t.err }, data: points.map(p => [p.at, p.limit]) },
      ],
    };
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key]);
  if (!points.length) return <p className="muted xs">No samples yet: the leader records one every half minute while the connection has a limit.</p>;
  return <EChart option={option} height={180} label={`${name}: connections in use and waiting over time`} />;
}

/**
 * Connection limits: every connection with a Maximum concurrent activities limit, what uses it now
 * (Sutra steps and listener or background leases), what waits for it and why, and its use over time.
 */
export function Connections() {
  const [hours, setHours] = useState(1);
  const [open, setOpen] = useState('');
  const data = useLoad<Data>(`/api/console/connections?hours=${hours}`, [hours]);
  useEvery(useCallback(() => { data.reload(); }, [data.reload]), 10000);
  const list = data.data?.connections || [];
  return (
    <>
      <PageHead title="Connection limits" sub="Connections with a Maximum concurrent activities limit, across all engines: what uses them now, what waits and why, and their use over time. Set a limit on the connection in the designer (Resources); a Project property ({{gv.NAME}}) can set it per server." />
      <div className="c-filters">
        <div className="fld"><label htmlFor="cl-hours">Period</label>
          <select id="cl-hours" className="inp" value={hours} onChange={e => setHours(Number(e.target.value))}>
            <option value={1}>Last hour</option><option value={6}>Last 6 hours</option><option value={24}>Last 24 hours</option><option value={168}>Last 7 days</option>
          </select></div>
      </div>
      <Err text={data.error} />
      {data.data && !list.length && <Empty title="No connection has a limit">Open a connection in the designer (Resources) and set Maximum concurrent activities. 0 or empty means no limit.</Empty>}
      {list.length > 0 && (
        <table className="t c-table">
          <thead><tr><th>Connection</th><th>Project</th><th>Limit</th><th>In use</th><th>Waiting</th><th>Longest wait</th></tr></thead>
          <tbody>{list.map(c => (
            <tr key={c.id} aria-selected={open === c.id}>
              <td><button className="btn link c-name" aria-expanded={open === c.id} onClick={() => setOpen(open === c.id ? '' : c.id)}><b>{c.name}</b></button> <span className="muted xs">{c.kind}</span>
                {c.error && <div className="xs"><State kind="err">{c.error}</State></div>}</td>
              <td>{c.projectName}</td>
              <td>{c.limit || '-'}{c.setting !== String(c.limit) && <div className="muted xs">set as <code>{c.setting}</code></div>}</td>
              <td><State kind={c.limit && c.active >= c.limit ? 'warn' : 'ok'}>{c.active} of {c.limit || '-'}</State>
                {c.active > 0 && <div className="muted xs">{c.steps} steps, {c.leases} listener or background</div>}</td>
              <td>{c.waiting ? <State kind="warn">{c.waiting}</State> : '0'}</td>
              <td>{c.waiting ? span(c.oldestWaitMs) : '-'}</td>
            </tr>
          ))}</tbody>
        </table>
      )}
      {list.filter(c => c.id === open).map(c => (
        <section key={c.id} className="c-section">
          <h2>{c.name}</h2>
          <UsageChart name={c.name} points={data.data?.history[c.id] || []} />
          <h3>In use now</h3>
          {c.holders.length ? (
            <table className="t c-table"><thead><tr><th>What</th><th>Engine</th><th>Since</th></tr></thead>
              <tbody>{c.holders.map((h, i) => (
                <tr key={i}><td>{h.kind === 'step' ? <>Step <b>{h.step}</b> of {h.sutra} <span className="muted xs">run {String(h.run).slice(0, 8)}</span></> : h.holder}</td>
                  <td>{h.owner}</td><td>{h.since ? ago(new Date(h.since).toISOString()) : '-'}</td></tr>
              ))}</tbody></table>
          ) : <p className="muted">Nothing uses it now.</p>}
          <h3>Waiting</h3>
          {c.waits.length ? (
            <table className="t c-table"><thead><tr><th>Step</th><th>Why</th><th>Waiting for</th></tr></thead>
              <tbody>{c.waits.map(w => (
                <tr key={w.task}><td><b>{w.step}</b> of {w.sutra} <span className="muted xs">run {String(w.run).slice(0, 8)}</span></td><td>{w.reason}</td><td>{span(Date.now() - w.since)}</td></tr>
              ))}</tbody></table>
          ) : <p className="muted">No step waits. Waiting steps keep their place in the queue: they use no retry attempt and hold no worker, and their timeout starts only when they run.</p>}
        </section>
      ))}
    </>
  );
}

import { useCallback, useState } from 'react';
import { useToast } from '../src/ui';
import { PageHead, State, Err, Confirm, useLoad, useEvery, ago, when, can, useMe } from './shared';
import { act, type Action } from './log';
import { EngineTuning } from './Tuning';

interface Memory { heapUsedMb: number; heapLimitMb: number; rssMb: number; machineMb: number; machineFreeMb: number; startedMb: number; wantedMb: number; restartable: boolean; settingsFile: string; note: string }
interface EngineRow { id: string; name: string; host: string; pid: number; mode: string; version: string; startedAt: string; alive: boolean; heartbeatAgeMs: number; workers: number; running: number; draining: boolean; leader: boolean; canLead?: boolean; memory?: Memory | null }
interface ClusterData { self: string; clusterName?: string; leader: string | null; engines: EngineRow[]; tasks: { pending: number; running: number; waiting: number; paused: number } }

const drainCmd = (id: string): Action => ({ label: `Drain ${id}`, method: 'POST', url: `/api/console/engines/${encodeURIComponent(id)}/drain`, cli: ['engines', 'drain', id] });
const restartCmd = (id: string): Action => ({ label: `Restart ${id}`, method: 'POST', url: `/api/console/engines/${encodeURIComponent(id)}/restart`, cli: ['engines', 'restart', id] });
const gb = (mb: number) => (mb >= 1024 ? `${(mb / 1024).toFixed(1)} GB` : `${mb} MB`);
const HOUSEKEEPING: Action = { label: 'Delete old runs now', method: 'POST', url: '/api/engine/housekeeping', body: {}, cli: ['engines', 'housekeeping'] };

/** Every engine sharing this database: liveness, leader, load; drain one; tuning. */
export function Engines() {
  const { me } = useMe();
  const toast = useToast();
  const { data, error, reload } = useLoad<ClusterData>('/api/engine/status');
  useEvery(useCallback(() => { reload(); }, [reload]), 5000);
  const [drain, setDrain] = useState<EngineRow | null>(null);
  const [restart, setRestart] = useState<EngineRow | null>(null);
  const [rename, setRename] = useState<{ id: string; name: string } | null>(null);
  const toastR = useToast();
  const saveName = async () => {
    if (!rename) return;
    await act({ label: `Name engine ${rename.id}`, method: 'PUT', url: `/api/console/engines/${encodeURIComponent(rename.id)}/name`, body: { name: rename.name }, cli: ['engines', 'name', rename.id, rename.name || '""'] });
    toastR(rename.name ? `${rename.id} is shown as ${rename.name}` : `${rename.id} is shown by its id`);
    setRename(null); reload();
  };
  const [cleanup, setCleanup] = useState(false);
  const [naming, setNaming] = useState<string | null>(null);
  const saveClusterName = async () => {
    if (naming === null) return;
    const r: any = await act({ label: 'Name the cluster', method: 'PUT', url: '/api/console/cluster/name', body: { name: naming }, cli: ['engines', 'cluster-name', naming || '""'] });
    toast(r.name ? `The cluster is named ${r.name}` : 'The cluster has no name');
    setNaming(null); reload();
  };
  // Who may lead: the leader is elected among the engines that may; the server refuses leaving none.
  const setLead = async (e: EngineRow, mayLead: boolean) => {
    try {
      await act({ label: `${e.id} ${mayLead ? 'may lead' : 'never leads'}`, method: 'PUT', url: `/api/console/engines/${encodeURIComponent(e.id)}/lead`, body: { mayLead }, cli: ['engines', 'lead', e.id, mayLead ? '--yes' : '--no'] });
      toast(mayLead ? `${e.id} may lead` : `${e.id} never leads`);
    } catch (err: any) { toast(err?.message || String(err)); }
    reload();
  };
  const manage = can(me, 'engines');
  return (
    <>
      <PageHead title={data?.clusterName ? `Engines of ${data.clusterName}` : 'Engines'} sub="Engines sharing this database. Work is shared; the leader, elected among the engines that may lead, also runs timers, listeners, recovery and housekeeping.">
        {manage && data && <button className="btn small" onClick={() => setNaming(data.clusterName || '')}>{data.clusterName ? 'Rename the cluster' : 'Name the cluster'}</button>}
        {manage && <button className="btn small" onClick={() => setCleanup(true)}>Delete old runs now</button>}
        <button className="btn small" onClick={reload}>Refresh</button>
      </PageHead>
      <Err text={error} />
      {data && (
        <>
          <div className="c-tiles c-tiles-sm">
            {(['pending', 'running', 'waiting', 'paused'] as const).map(k => (
              <div key={k} className="c-tile static"><span className="c-tile-label">Steps {k}</span><span className="c-tile-value">{data.tasks[k]}</span></div>
            ))}
          </div>
          <div className="c-tablewrap"><table className="t c-table">
            <thead><tr><th>Engine</th><th>State</th><th>Host</th><th>Mode</th><th>Version</th><th className="right">Steps</th><th>Memory</th><th>Heartbeat</th><th>Started</th><th /></tr></thead>
            <tbody>{data.engines.map(e => (
              <tr key={e.id}>
                <td>
                  {e.name ? <><b>{e.name}</b><div className="muted xs">id <code>{e.id}</code></div></> : <code>{e.id}</code>}
                  {e.leader && <span className="c-badge">leader</span>}{e.canLead === false && <span className="c-badge soft">never leads</span>}
                  {manage && <button className="btn link xs" onClick={() => setLead(e, e.canLead === false)}>{e.canLead === false ? 'May lead' : 'Never lead'}</button>}{e.id === data.self && <span className="c-badge soft">this one</span>}
                  {manage && <button className="btn link xs" onClick={() => setRename({ id: e.id, name: e.name })}>Rename</button>}
                </td>
                <td>{!e.alive ? <State kind="err">silent</State> : e.draining ? <State kind="warn">draining</State> : <State kind="ok">alive</State>}</td>
                <td>{e.host} <span className="muted xs">pid {e.pid}</span></td>
                <td>{e.mode === 'engine' ? 'headless' : e.mode}</td>
                <td>{e.version}</td>
                <td className="right nowrap">{e.running} / {e.workers}</td>
                <td className="nowrap">{e.memory ? <>
                  <span title={`Heap used of its limit; process ${e.memory.rssMb} MB; machine ${gb(e.memory.machineMb)} (${gb(e.memory.machineFreeMb)} free)`}>{e.memory.heapUsedMb} / {e.memory.heapLimitMb} MB</span>
                  <div className="muted xs">machine {gb(e.memory.machineMb)}, {gb(e.memory.machineFreeMb)} free</div>
                  {e.memory.wantedMb !== e.memory.startedMb && <div title={e.memory.note}><State kind="warn">restart for {e.memory.wantedMb ? `${e.memory.wantedMb} MB` : 'the default'}</State></div>}
                </> : <span className="muted">—</span>}</td>
                <td className="nowrap">{Math.round(e.heartbeatAgeMs / 1000)} s ago</td>
                <td className="nowrap" title={when(e.startedAt)}>{ago(e.startedAt)}</td>
                <td className="right nowrap">{manage && e.alive && !e.draining && e.memory?.restartable && <button className="btn small" onClick={() => setRestart(e)}>Restart</button>} {manage && e.alive && !e.draining && <button className="btn small c-danger-soft" onClick={() => setDrain(e)}>Drain and stop</button>}</td>
              </tr>
            ))}</tbody>
          </table></div>
          {naming !== null && (
            <div className="c-card">
              <div className="fld"><label htmlFor="cl-name">Cluster name</label>
                <input id="cl-name" className="inp" value={naming} maxLength={60} placeholder="Production" onChange={e => setNaming(e.target.value)} /></div>
              <p className="hint">Shown here and on every engine's Admin Console. Empty = no name.</p>
              <div className="c-actions"><button className="btn primary small" onClick={saveClusterName}>Save</button><button className="btn small" onClick={() => setNaming(null)}>Cancel</button></div>
            </div>
          )}
          {rename && (
            <div className="c-card">
              <div className="fld"><label htmlFor="en-name">Display name of {rename.id}</label>
                <input id="en-name" className="inp" value={rename.name} maxLength={60} placeholder="Azure West Europe 1" onChange={e => setRename({ ...rename, name: e.target.value })} /></div>
              <p className="hint">What people see in the console. The engine id stays the same: it is the engine's identity in the cluster (running steps and recovery use it) and is set with SUTRA_ENGINE_ID, by default the computer name. Empty = show the id.</p>
              <div className="c-actions"><button className="btn primary small" onClick={saveName}>Save</button><button className="btn small" onClick={() => setRename(null)}>Cancel</button></div>
            </div>
          )}
          <p className="muted xs">An engine silent for three heartbeats is presumed stopped; the leader gives its unfinished steps to the others. Memory is the engine's heap in use of its limit: each engine is its own Node.js process with its own memory, set with <b>Node memory</b> under Tuning and applied by Restart (engines started by a service manager or Docker: Drain and stop, and set it where they are started).</p>
        </>
      )}
      {data && <EngineTuning engines={data.engines} />}
      {drain && <Confirm title={`Drain ${drain.id}`} danger action="Drain and stop" cmd={drainCmd(drain.id)}
        text={<>The engine stops taking new work, gives up leadership, lets running steps finish (up to its drain time), hands the rest to other engines, and stops. Your service manager or orchestrator starts it again.{data && data.engines.filter(x => x.alive && !x.draining).length <= 1 && <strong> It is the only engine: nothing runs until it is started again.</strong>}</>}
        onYes={async () => { await act(drainCmd(drain.id)); toast(`${drain.id} drains on its next heartbeat`); reload(); }} onClose={() => setDrain(null)} />}
      {restart && <Confirm title={`Restart ${restart.id}`} action="Restart" cmd={restartCmd(restart.id)}
        text={<>The engine stops taking new work, lets running steps finish (up to its drain time), hands the rest to other engines, and starts again{restart.memory && restart.memory.wantedMb !== restart.memory.startedMb ? <> with {restart.memory.wantedMb ? `${restart.memory.wantedMb} MB` : 'the default'} of Node memory</> : ''}. {data && data.engines.filter(x => x.alive && !x.draining).length <= 1 && <strong>It is the only engine: requests wait or fail until it is back, usually within a minute.</strong>}</>}
        onYes={async () => { await act(restartCmd(restart.id)); toast(`${restart.id} restarts on its next heartbeat`); reload(); }} onClose={() => setRestart(null)} />}
      {cleanup && <Confirm title="Delete old runs now" action="Delete" cmd={HOUSEKEEPING}
        text="Finished runs older than the retention period are deleted with their steps, and old audit entries too. The leader also does this every minute."
        onYes={async () => { const r: any = await act(HOUSEKEEPING); toast(`${r.deletedRuns} runs and ${r.deletedAudit ?? 0} audit entries deleted`); }} onClose={() => setCleanup(false)} />}
    </>
  );
}

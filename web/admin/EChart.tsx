import { useEffect, useRef, useState } from 'react';
import type { EChartsCoreOption, ECharts } from 'echarts/core';

/**
 * Admin Console charts with Apache ECharts, shipped with SutraFlow (no CDN, works offline). ECharts is
 * loaded the first time a page shows a chart (echarts-setup.ts, a file of its own in the build), with
 * only the chart types the console uses. Colours come from the theme tokens, so light and dark themes
 * (and switching them) look right.
 */
let loading: Promise<typeof import('./echarts-setup')> | null = null;
const loadEcharts = () => (loading ||= import('./echarts-setup'));

export interface ChartTokens { ink: string; muted: string; line: string; card: string; ok: string; warn: string; err: string; edge: string; auto: string; focus: string; font: string }

function tokens(): ChartTokens {
  const css = getComputedStyle(document.documentElement);
  const v = (name: string, fallback: string) => css.getPropertyValue(name).trim() || fallback;
  return {
    ink: v('--ink', '#17242B'), muted: v('--muted', '#5E6E75'), line: v('--line', '#CDD5D3'), card: v('--card', '#FFFFFF'),
    ok: v('--ok', '#1B8A4E'), warn: v('--warn', '#B7791F'), err: v('--err', '#C2362F'), edge: v('--edge', '#6E8189'),
    auto: v('--c-auto', '#0E7A62'), focus: v('--focus', '#2F6FEB'), font: getComputedStyle(document.body).fontFamily || 'sans-serif',
  };
}

/** The theme changes with the console's switch (data-theme) and with the system setting. */
function useTheme() {
  const [n, setN] = useState(0);
  useEffect(() => {
    const bump = () => setN(x => x + 1);
    const mo = new MutationObserver(bump);
    mo.observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme', 'class'] });
    const mq = window.matchMedia?.('(prefers-color-scheme: dark)');
    mq?.addEventListener?.('change', bump);
    return () => { mo.disconnect(); mq?.removeEventListener?.('change', bump); };
  }, []);
  return n;
}

/** Axis, grid and tooltip styling shared by every console chart. */
export function baseOption(t: ChartTokens): EChartsCoreOption {
  const axis = { axisLine: { lineStyle: { color: t.line } }, axisLabel: { color: t.muted, fontSize: 11 }, splitLine: { lineStyle: { color: t.line, opacity: 0.6 } } };
  return {
    animation: false,
    textStyle: { fontFamily: t.font, color: t.ink },
    grid: { left: 44, right: 16, top: 16, bottom: 28, containLabel: false },
    tooltip: { trigger: 'axis', backgroundColor: t.card, borderColor: t.line, textStyle: { color: t.ink, fontSize: 12 } },
    legend: { bottom: 0, textStyle: { color: t.muted, fontSize: 11 }, icon: 'roundRect', itemWidth: 10, itemHeight: 10 },
    xAxis: { type: 'time', ...axis, splitLine: { show: false } },
    yAxis: { type: 'value', minInterval: 1, ...axis },
  };
}

export function EChart({ option, height = 200, label }: { option: (t: ChartTokens) => EChartsCoreOption; height?: number; label: string }) {
  const el = useRef<HTMLDivElement>(null);
  const chart = useRef<ECharts | null>(null);
  const [ready, setReady] = useState(false);
  const theme = useTheme();
  useEffect(() => {
    let gone = false, ro: ResizeObserver | undefined;
    loadEcharts().then(({ echarts }) => {
      if (gone || !el.current) return;
      chart.current = echarts.init(el.current, undefined, { renderer: 'svg' });
      ro = new ResizeObserver(() => chart.current?.resize());
      ro.observe(el.current);
      setReady(true);
    }).catch(() => { /* the chart stays empty; the page's figures remain */ });
    return () => { gone = true; ro?.disconnect(); chart.current?.dispose(); chart.current = null; };
  }, []);
  useEffect(() => { if (ready) chart.current?.setOption(option(tokens()), { notMerge: true }); }, [option, theme, ready]);
  return <div ref={el} className="c-echart" style={{ height }} role="img" aria-label={label} />;
}

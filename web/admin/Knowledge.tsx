import { useState } from 'react';
import { useToast } from '../src/ui';
import { act } from './log';
import { PageHead, Err, Empty, State, useLoad, useMe, can } from './shared';
import { api } from '../src/api';

interface Kb { id: string; name: string; project_id: string | null; config: { store?: string; table?: string } }
interface Index { indexed: boolean; possible: boolean; passages: number; note: string }

/**
 * Knowledge search: the search index of each knowledge base kept in PostgreSQL (pgvector). Without the
 * index every search compares each passage, so searches slow down as the knowledge base grows.
 */
export function Knowledge() {
  const { me } = useMe();
  const toast = useToast();
  const list = useLoad<Kb[]>('/api/resources?kind=aiKnowledge');
  const [state, setState] = useState<Record<string, Index | 'busy' | { error: string }>>({});
  const kbs = (list.data || []).filter(k => k.config.store === 'PostgreSQL (pgvector)');
  const check = async (k: Kb) => {
    setState(s => ({ ...s, [k.id]: 'busy' }));
    try { const r = await api<Index>('GET', `/api/resources/${k.id}/search-index`); setState(s => ({ ...s, [k.id]: r })); }
    catch (e: any) { setState(s => ({ ...s, [k.id]: { error: e.message } })); }
  };
  const build = async (k: Kb) => {
    setState(s => ({ ...s, [k.id]: 'busy' }));
    try {
      const r = await act<Index>({ label: `Build the search index of knowledge base ${k.name}`, method: 'POST', url: `/api/resources/${k.id}/search-index` });
      setState(s => ({ ...s, [k.id]: r }));
      toast(r.indexed ? `${k.name}: search index ready` : r.note);
    } catch (e: any) { setState(s => ({ ...s, [k.id]: { error: e.message } })); }
  };
  return (
    <>
      <PageHead title="Knowledge search" sub="Knowledge bases kept in PostgreSQL (pgvector) and their search index. A new table gets its index at once. A table that already holds passages is indexed when you build it here: building takes a few minutes per million passages, and adding passages goes on meanwhile. Without the index every search compares each passage and slows down as the knowledge base grows. Needs pgvector 0.8 or later." />
      <Err text={list.error} />
      {list.data && !kbs.length && <Empty title="No knowledge base in PostgreSQL">Knowledge bases on the built-in store, a folder, Qdrant, Chroma or Pinecone keep their own search structures.</Empty>}
      {kbs.length > 0 && (
        <table className="t c-table">
          <thead><tr><th>Knowledge base</th><th>Table</th><th>Search index</th><th /></tr></thead>
          <tbody>{kbs.map(k => {
            const st = state[k.id];
            const manage = can(me, 'connections', k.project_id || undefined);
            return (
              <tr key={k.id}>
                <td><b>{k.name}</b></td>
                <td><code>{k.config.table || 'sutra_knowledge'}</code></td>
                <td>{!st ? <span className="muted">Not checked</span>
                  : st === 'busy' ? <State kind="busy">Working</State>
                  : 'error' in st ? <State kind="err">{st.error}</State>
                  : <><State kind={st.indexed ? 'ok' : st.possible ? 'warn' : 'idle'}>{st.indexed ? 'In place' : st.possible ? 'Missing' : 'Not available'}</State><div className="muted xs">{st.note}</div></>}</td>
                <td className="c-actions">
                  <button className="btn small" disabled={st === 'busy'} onClick={() => check(k)}>Check</button>
                  {manage && st && st !== 'busy' && !('error' in st) && !st.indexed && st.possible && st.passages > 0 &&
                    <button className="btn small primary" onClick={() => build(k)}>Build search index</button>}
                </td>
              </tr>
            );
          })}</tbody>
        </table>
      )}
    </>
  );
}

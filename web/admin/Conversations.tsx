import { useState } from 'react';
import { useToast } from '../src/ui';
import { act, type Action } from './log';
import { PageHead, Err, Empty, Confirm, useLoad, useMe, can } from './shared';

interface Row { agent: string; projectId: string | null; active: number; expired: number; messages: number; firstAt: string; lastAt: string }

/**
 * Agent conversations (2.1.5): every published agent's conversations, active and expired. A conversation
 * token continues a conversation only until it expires; an administrator clears the expired ones, with
 * the AI memory they kept, from the database.
 */
export function Conversations() {
  const { me } = useMe();
  const toast = useToast();
  const list = useLoad<Row[]>('/api/console/conversations');
  const [confirm, setConfirm] = useState<{ title: string; text: string; action: Action } | null>(null);
  const rows = list.data || [];
  const admin = can(me, 'server');
  const expired = rows.reduce((n, r) => n + r.expired, 0);
  const clear = (agent?: string) => setConfirm({
    title: agent ? `Clear expired conversations of ${agent}` : 'Clear all expired conversations',
    text: `Removes ${agent ? `the expired conversations of ${agent}` : `${expired} expired conversations`} from the database with the AI memory they kept (messages, summaries). Active conversations stay. This cannot be undone.`,
    action: { label: agent ? `Clear expired conversations of agent ${agent}` : 'Clear expired agent conversations', method: 'POST', url: '/api/console/conversations/clear-expired', body: agent ? { agent } : {}, cli: ['agents', 'clear-expired', ...(agent ? ['--agent', agent] : [])] },
  });
  return (
    <>
      <PageHead title="Agent conversations" sub="Conversations of published agents. Each answer carries a signed conversation token that continues the conversation only for the caller who started it, and only until it expires (the agent channel's Conversation lasts setting). Expired conversations keep their memory in the database until an administrator clears them here." />
      <Err text={list.error} />
      {list.data && !rows.length && <Empty title="No conversations yet">Conversations appear when people chat with a published agent (chat page, chat API, OpenAI-compatible API, MCP or A2A).</Empty>}
      {rows.length > 0 && (
        <>
          <table className="t c-table">
            <thead><tr><th>Agent</th><th>Active</th><th>Expired</th><th>Messages</th><th>First</th><th>Last message</th><th /></tr></thead>
            <tbody>{rows.map(r => (
              <tr key={`${r.agent}-${r.projectId}`}>
                <td><b>{r.agent}</b></td><td>{r.active}</td><td>{r.expired}</td><td>{r.messages}</td>
                <td className="muted xs">{r.firstAt?.slice(0, 16).replace('T', ' ')}</td><td className="muted xs">{r.lastAt?.slice(0, 16).replace('T', ' ')}</td>
                <td>{admin && r.expired > 0 && <button className="btn small" onClick={() => clear(r.agent)}>Clear expired</button>}</td>
              </tr>
            ))}</tbody>
          </table>
          <div className="c-actions">
            {admin ? <button className="btn primary" disabled={!expired} onClick={() => clear()}>Clear all expired conversations</button>
              : <p className="muted xs">Clearing expired conversations needs the Server permission (administrators).</p>}
          </div>
        </>
      )}
      {confirm && <Confirm title={confirm.title} action="Clear" danger cmd={confirm.action} text={confirm.text}
        onYes={async () => { const r = await act<{ conversations: number; memorySessions: number }>(confirm.action); toast(`Cleared ${r.conversations} conversations and ${r.memorySessions} memory sessions`); list.reload(); }}
        onClose={() => setConfirm(null)} />}
    </>
  );
}

/* @sutra-file-overview
 * File: web/src/variable-drafts.ts
 * Purpose/support: Prepares project-variable saves by flushing pending encrypted Secret drafts first; only opaque references enter project settings. Stable editor keys are stripped, and failed storage aborts persistence.
 * Connects to (static imports): ./types.js
 * Functions/entry points (static scan): prepareVariableSave
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import type { ProjectVariable } from './types.js';
export type VariableDraft = ProjectVariable & { editKey: number };
export type SecretDraftStore = () => Promise<string | undefined>;
/** Only opaque references enter the project document. A failed store aborts the project save. */
export async function prepareVariableSave(rows: readonly VariableDraft[], stores: ReadonlyMap<number, SecretDraftStore>): Promise<ProjectVariable[]> {
  const result: ProjectVariable[] = [];
  for (const row of rows) {
    const { editKey, ...value } = row;
    const reference = row.type === 'secret' ? await stores.get(editKey)?.() : undefined;
    result.push(reference === undefined ? value : { ...value, value: reference });
  }
  return result;
}

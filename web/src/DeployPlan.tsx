/**
 * What deploying a release does (2.1.6), shown before anything changes: each Sutra new, unchanged or
 * replacing the version here, those undeployed, what is created, and the checklist of what is already
 * here and kept as it is. Replacing or undeploying needs a person: the project's name typed to
 * approve this plan (its id), as sutra deploy asks for "yes" or --approve.
 */
export interface Plan {
  planId: string;
  needsApproval: boolean;
  project: { name: string; exists: boolean };
  sutras: { name: string; action: 'new' | 'unchanged' | 'deploys' | 'replaces'; current?: number }[];
  undeploys: string[];
  schemas: { name: string; kind: string; action: 'new' | 'unchanged' | 'replaces' }[];
  creates: { what: string; name: string; kind?: string }[];
  checklist: { what: string; name: string; kind?: string; where?: string; note: string }[];
}

const LABEL = { new: 'new', unchanged: 'unchanged', deploys: 'deployed again', replaces: 'replaces' } as const;

export function PlanView({ plan }: { plan: Plan | null | undefined }) {
  if (!plan) return null;
  const changedSchemas = plan.schemas.filter(s => s.action !== 'unchanged');
  return (
    <table className="t c-table" aria-label="Deployment plan" style={{ marginTop: 8 }}><tbody>
      <tr><th>Sutras</th><td>{plan.sutras.map(s => (
        <div key={s.name}>{s.name} <span className={`pill ${s.action === 'replaces' ? 'warn' : s.action === 'new' ? 'ok' : ''}`}>{LABEL[s.action]}</span>
          {s.action === 'replaces' && <span className="muted xs"> version {s.current} here</span>}</div>
      ))}</td></tr>
      {plan.undeploys.length > 0 && <tr><th>Undeployed</th><td>{plan.undeploys.map(n => <div key={n}>{n} <span className="pill warn">not in the package</span></div>)}</td></tr>}
      {changedSchemas.length > 0 && <tr><th>Schemas</th><td>{changedSchemas.map(s => <div key={s.name}>{s.name} <span className={`pill ${s.action === 'replaces' ? 'warn' : 'ok'}`}>{s.action}</span></div>)}</td></tr>}
      <tr><th>Created</th><td>{plan.creates.length ? plan.creates.map(c => <div key={`${c.what}:${c.name}`}>{c.what} {c.name}{c.kind ? <span className="muted xs"> {c.kind}</span> : null}</div>) : <span className="muted">nothing</span>}</td></tr>
      {plan.checklist.length > 0 && (
        <tr><th>Checklist</th><td>
          <div className="muted xs">Already on this server and kept as it is: verify by hand.</div>
          {plan.checklist.map(c => <div key={`${c.what}:${c.name}`}>☐ {c.what} <b>{c.name}</b>{c.kind ? ` (${c.kind}${c.where ? `, ${c.where}` : ''})` : ''}<div className="muted xs">{c.note}</div></div>)}
        </td></tr>
      )}
      <tr><th>Plan</th><td><code>{plan.planId}</code></td></tr>
    </tbody></table>
  );
}

/** Whether the plan may be deployed: nothing replaced, or the project's name typed. */
export const planApproved = (plan: Plan | null | undefined, typed: string) =>
  !plan?.needsApproval || typed.trim().toLowerCase() === plan.project.name.trim().toLowerCase();

/** The approval: the project's name typed, when the plan replaces or undeploys Sutras. */
export function PlanApproval({ plan, typed, onType }: { plan: Plan | null | undefined; typed: string; onType(v: string): void }) {
  if (!plan?.needsApproval) return null;
  const n = plan.sutras.filter(s => s.action === 'replaces').length + plan.schemas.filter(s => s.action === 'replaces').length;
  return (
    <div className="warnbox" role="alert" style={{ marginTop: 8 }}>
      This deployment {n ? `replaces ${n} ${n === 1 ? 'item' : 'items'} already deployed` : ''}{n && plan.undeploys.length ? ' and ' : ''}{plan.undeploys.length ? `undeploys ${plan.undeploys.length} Sutra${plan.undeploys.length === 1 ? '' : 's'}` : ''}.
      {' '}Type the project name, <b>{plan.project.name}</b>, to approve plan <code>{plan.planId}</code>.
      <div className="fld" style={{ marginTop: 6 }}><label htmlFor="plan-approve">Project name</label>
        <input id="plan-approve" value={typed} autoComplete="off" onChange={e => onType(e.target.value)} /></div>
    </div>
  );
}

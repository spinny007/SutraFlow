import type { ActivityMeta, FlowDoc } from './types.js';
import { refsIn } from './mapping-sources.js';

export interface RefOrigin { ref: string; text: string; warn?: boolean }

/** Splits a reference path, keeping step names with spaces: nodes.Total revenue.chart -> nodes, Total revenue, chart. */
export function splitRef(ref: string, stepNames: readonly string[] = []): string[] {
  const s = ref.trim();
  const m = /^nodes\s*(?:\.|\[\s*["'`]?)/.exec(s);
  if (m) {
    const rest = s.slice(m[0].length);
    const name = [...stepNames].sort((a, b) => b.length - a.length).find(n => rest.startsWith(n) && /^(?:$|[.["'`\]\s])/.test(rest.slice(n.length)));
    if (name) return ['nodes', name, ...splitRef(rest.slice(name.length).replace(/^["'`]?\]?\.?/, ''))];
  }
  return s.split(/\.|\[|\]/).map(p => p.replace(/^["'`]|["'`]$/g, '').trim()).filter(Boolean);
}

/**
 * Where one reference used by a step comes from. `bound` marks fields that send run data to the
 * database as a bound parameter (SQL), where only properties are written into the text.
 */
export function refOrigin(ref: string, o: { doc: FlowDoc; nodeId: string; activities: Pick<ActivityMeta, 'type' | 'name' | 'trigger'>[]; bound?: boolean }): RefOrigin {
  const typeName = (type: string) => o.activities.find(a => a.type === type)?.name || type;
  const parts = splitRef(ref, o.doc.nodes.map(n => n.name));
  const rest = (from: number) => parts.slice(from).length ? ` → ${parts.slice(from).join(' → ')}` : '';
  const bound = (text: string) => (o.bound ? `${text}, sent as a bound parameter` : text);
  const before = new Set<string>();
  for (const pending = [o.nodeId]; pending.length;) {
    const id = pending.pop()!;
    for (const e of o.doc.edges) if (e.to === id && !before.has(e.from)) { before.add(e.from); pending.push(e.from); }
  }
  switch (parts[0]) {
    case 'trigger': {
      const t = o.doc.nodes.find(n => o.activities.find(a => a.type === n.type)?.trigger);
      return { ref, text: bound(`trigger data → ${t ? `${t.name} (${typeName(t.type)})` : 'the trigger'}${rest(1)}`) };
    }
    case 'input': {
      const incoming = o.doc.edges.filter(e => e.to === o.nodeId).map(e => o.doc.nodes.find(n => n.id === e.from)).filter(Boolean);
      const from = incoming.length === 1 ? ` (the output of ${incoming[0]!.name})` : incoming.length > 1 ? ` (from ${incoming.map(n => n!.name).join(', ')})` : '';
      return { ref, text: bound(`current input${from}${rest(1)}`) };
    }
    case 'nodes': {
      const n = o.doc.nodes.find(x => x.name === parts[1]);
      if (!n) return { ref, text: `no step is named "${parts[1] ?? ''}"`, warn: true };
      if (!before.has(n.id)) return { ref, text: `${n.name} (${typeName(n.type)}) is not on this step's path; the engine refuses it`, warn: true };
      return { ref, text: bound(`step ${n.name} (${typeName(n.type)})${rest(2)}`) };
    }
    case 'gv': return { ref, text: `project property ${parts[1] ?? ''}${o.bound ? ', written into the SQL' : ''}` };
    case 'ev': return { ref, text: `engine property ${parts[1] ?? ''} (read only)${o.bound ? ', written into the SQL' : ''}` };
    case 'vars': return { ref, text: bound(`Sutra variable ${parts[1] ?? ''}`) };
    case 'secret': return { ref, text: `secret ${parts[1] ?? ''} (the value is never shown)` };
    case 'run': case 'sutra': case 'process': return { ref, text: bound(`run details → ${parts.slice(1).join(' → ') || 'all'}`) };
    case 'now': return { ref, text: bound('the current time') };
    case 'item': case 'index': case 'iteration': return { ref, text: bound('the current item of the loop') };
    default: return { ref, text: `unknown root "${parts[0] ?? ''}"`, warn: true };
  }
}

/** The references a field value uses ({{…}} templates, = formulas), each once, in order. */
export function fieldRefs(value: unknown): string[] {
  return [...new Set(refsIn(value).filter(r => /^[A-Za-z_$]/.test(r)))];
}

/* @sutra-file-overview
 * File: web/src/line-colours.ts
 * Purpose/support: Line colours on the canvas (2.1.7): a palette of 8 named colours with light and dark values, automatic colours where two or more lines go into one step (by source step, distinct at each meeting step, stable when steps move), colours chosen by hand (edge.color), error lines that stay red, and the canvas highlighting of a step's lines and its path.
 * Connects to (static imports): ./types.js
 * Functions/entry points (static scan): preferred, autoColours, lineColour, incomingKey, highlightOf, contrast, isLineColour, colourName
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import type { FlowDoc, FlowEdge } from './types.js';

/**
 * The palette: names are stored in the Sutra (edge.color), values come from the theme, so a Sutra looks
 * right in light and dark. Red is left out: it means an error line. Each value keeps at least 3:1
 * contrast with the canvas (checked by test/connections217.test.ts).
 */
export const LINE_COLOURS = [
  { key: 'blue', name: 'Blue', light: '#1F6FD1', dark: '#6EA8FF' },
  { key: 'orange', name: 'Orange', light: '#B85F00', dark: '#F2A04B' },
  { key: 'green', name: 'Green', light: '#1B7F52', dark: '#4CC98A' },
  { key: 'purple', name: 'Purple', light: '#7B4FC9', dark: '#B69CFF' },
  { key: 'teal', name: 'Teal', light: '#0B7F95', dark: '#4FD0E6' },
  { key: 'gold', name: 'Gold', light: '#8A6D00', dark: '#E3C44A' },
  { key: 'pink', name: 'Pink', light: '#B83A80', dark: '#F07BBE' },
  { key: 'slate', name: 'Slate', light: '#4E5D7D', dark: '#A4B2CC' },
] as const;
export type LineColourKey = (typeof LINE_COLOURS)[number]['key'];
export const isLineColour = (v: unknown): v is LineColourKey => LINE_COLOURS.some(c => c.key === v);
export const colourName = (key: string) => LINE_COLOURS.find(c => c.key === key)?.name || key;

/** A stable starting colour for a step, from its id (so moving steps never changes colours). */
function preferred(id: string) {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % LINE_COLOURS.length;
}

/**
 * Automatic colours: only lines into a step that receives two or more lines (error lines excepted)
 * get one, and the colour follows the source step, so all lines leaving a step share it. Source steps
 * that meet at the same step get different colours (up to 8); the choice depends on the steps and
 * connections only, never on positions.
 */
export function autoColours(doc: Pick<FlowDoc, 'nodes' | 'edges'>): Map<string, LineColourKey> {
  const lines = doc.edges.filter(e => e.port !== 'error');
  const into = new Map<string, FlowEdge[]>();
  for (const e of lines) into.set(e.to, [...(into.get(e.to) || []), e]);
  const meeting = [...into.values()].filter(list => new Set(list.map(e => e.from)).size >= 2);
  const needs = new Set(meeting.flatMap(list => list.map(e => e.from)));
  // Sources that meet at a common step must differ.
  const conflicts = new Map<string, Set<string>>();
  for (const list of meeting) for (const a of list) for (const b of list) if (a.from !== b.from) {
    if (!conflicts.has(a.from)) conflicts.set(a.from, new Set());
    conflicts.get(a.from)!.add(b.from);
  }
  const bySource = new Map<string, number>();
  for (const n of doc.nodes) {
    if (!needs.has(n.id)) continue;
    const used = [...(conflicts.get(n.id) || [])].map(id => bySource.get(id)).filter((i): i is number => i !== undefined);
    const count = (c: number) => used.filter(u => u === c).length;
    // The first free colour from the step's own; with more than 8 sources, the least repeated one.
    const start = preferred(n.id);
    let pick = start;
    for (let i = 1; i < LINE_COLOURS.length; i++) { const c = (start + i) % LINE_COLOURS.length; if (count(c) < count(pick)) pick = c; }
    bySource.set(n.id, pick);
  }
  const out = new Map<string, LineColourKey>();
  for (const list of meeting) for (const e of list) out.set(e.id, LINE_COLOURS[bySource.get(e.from)!].key);
  return out;
}

/** The colour a line is drawn with: chosen by hand, else automatic, else none. Error lines stay red. */
export function lineColour(edge: FlowEdge, auto: Map<string, LineColourKey>): LineColourKey | undefined {
  if (edge.port === 'error') return undefined;
  if (isLineColour(edge.color)) return edge.color;
  return auto.get(edge.id);
}

/** The lines a step receives, with their colours: the key shown on its Input tab. */
export function incomingKey(doc: Pick<FlowDoc, 'nodes' | 'edges'>, nodeId: string) {
  const auto = autoColours(doc);
  return doc.edges.filter(e => e.to === nodeId).map(e => ({
    edge: e,
    from: doc.nodes.find(n => n.id === e.from)?.name || e.from,
    port: e.port,
    colour: lineColour(e, auto),
  }));
}

/**
 * What to highlight when a step is selected: its own lines and the steps at their other ends; with
 * `path`, every step before and after it and the lines among them. Everything else is dimmed.
 */
export function highlightOf(doc: Pick<FlowDoc, 'edges'>, nodeId: string, path = false) {
  const nodes = new Set<string>([nodeId]);
  const edges = new Set<string>();
  if (!path) {
    for (const e of doc.edges) if (e.from === nodeId || e.to === nodeId) { edges.add(e.id); nodes.add(e.from); nodes.add(e.to); }
    return { nodes, edges };
  }
  const walk = (dir: 'back' | 'forward') => {
    const seen = new Set<string>([nodeId]);
    for (const pending = [nodeId]; pending.length;) {
      const id = pending.pop()!;
      for (const e of doc.edges) {
        const next = dir === 'back' ? (e.to === id ? e.from : null) : (e.from === id ? e.to : null);
        if (next && !seen.has(next)) { seen.add(next); pending.push(next); }
      }
    }
    return seen;
  };
  const before = walk('back'), after = walk('forward');
  for (const id of [...before, ...after]) nodes.add(id);
  for (const e of doc.edges) if ((before.has(e.from) && before.has(e.to)) || (after.has(e.from) && after.has(e.to))) edges.add(e.id);
  return { nodes, edges };
}

/** WCAG contrast ratio of two #RRGGBB colours. */
export function contrast(a: string, b: string) {
  const lum = (hex: string) => {
    const [r, g, bl] = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(c => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
    return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
  };
  const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
}

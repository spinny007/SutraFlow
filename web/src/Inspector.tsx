export function Inspector(p: Props) {
  const { project } = useCatalog();
  if (p.sel?.kind === 'edge') {
    const e = p.doc.edges.find(x => x.id === p.sel!.id);
    const a = p.doc.nodes.find(n => n.id === e?.from), b = p.doc.nodes.find(n => n.id === e?.to);
    const setEdge = (patch: Partial<FlowEdge>) => p.setDoc(d => ({ ...d, edges: d.edges.map(x => (x.id === e?.id ? { ...x, ...patch } : x)) }));
    const when = e?.when || 'always';
    const sameOutput = p.doc.edges.filter(x => e && x.from === e.from && x.port === e.port);
    const defined = new Set((project?.config.variables || []).map(v => v.name));
    const missing = variablesUsed(e?.condition).filter(name => !defined.has(name));
    const autoColour = e ? autoColours(p.doc).get(e.id) : undefined;
    const insertCondition = (ref: string) => {
      const text = ref.startsWith('{{') ? ref.slice(1, -1) : ref;
      const input = document.getElementById('econd') as HTMLInputElement | null;
      if (input) insertAtCaret(input, text); else setEdge({ condition: `${e?.condition || ''}${text}` });
    };
    return (
      <aside className="side"><div className="tabbody">
        <div className="phead"><div><h2>{e?.label || 'Connection'}</h2><p>{a?.name} ({e?.port}) to {b?.name}</p></div></div>
        <MissingVariables names={missing} />
        {e?.port === 'error' && <p className="muted">Runs when {a?.name} fails after its retries. The step receives <code>{'{input.error.message}'}</code> and the original <code>{'{input.input}'}</code>.</p>}
        <div className="fld"><label htmlFor="elabel">Name</label>
          <input id="elabel" type="text" placeholder="e.g. Order > 1000" value={e?.label || ''} onChange={ev => setEdge({ label: ev.target.value })} />
          <div className="hint">Shown on the connection in the canvas.</div></div>
        <div className="fld"><label htmlFor="ewhen">Taken</label>
          <select id="ewhen" value={when} onChange={ev => setEdge({ when: ev.target.value as FlowEdge['when'], ...(ev.target.value === 'when' && !e?.condition ? { condition: '={input.amount} > 1000' } : {}) })}>
            <option value="always">Always</option>
            <option value="when">When a condition is true</option>
            <option value="otherwise">Otherwise (no other condition matched)</option>
          </select>
          <div className="hint">{when === 'otherwise' ? `Taken when none of the "when" connections from ${a?.name} (${e?.port}) is taken.` : when === 'when' ? `Checked on ${a?.name}'s output each time it finishes. Several "when" connections can be taken at once.` : `Taken every time ${a?.name} finishes on ${e?.port}.`}</div></div>
        {when === 'when' && (
          <div className="fld"><label htmlFor="econd">Condition <VarPicker target="econd" onInsert={insertCondition} /></label>
            <input id="econd" type="text" className="code" spellCheck={false} value={e?.condition || ''} onChange={ev => setEdge({ condition: ev.target.value })} />
            <div className="hint"><code>{'{input.x}'}</code> is {a?.name}'s output; <code>{'{nodes.Name.x}'}</code>, <code>{'{vars.x}'}</code>, <code>{'{gv.X}'}</code> and <code>{'{ev.X}'}</code> work too. Examples: <code>{'={input.amount} > {gv.LIMIT}'}</code>, <code>{"=upper-case({input.country}) = 'IN'"}</code>, <code>{'=count({input.rows}) = 0'}</code>.</div>
            {a && <ConditionDataBrowser from={a} doc={p.doc} design={p.design} run={p.run} outputs={p.run?.outputs || {}} localVars={p.run?.vars} onPick={path => insertCondition(`{${path}}`)} />}
          </div>
        )}
        {e?.port === 'error'
          ? <p className="muted xs">Error lines are always red and dashed, so they are never coloured.</p>
          : <div className="fld"><span className="lbl">Colour</span>
            <div className="swatches" role="group" aria-label="Line colour">
              {LINE_COLOURS.map(c => <button key={c.key} type="button" className={`swatch lc-${c.key}`} title={c.name} aria-label={c.name} aria-pressed={e?.color === c.key} onClick={() => setEdge({ color: c.key })} />)}
              <button type="button" className={`btn small${!e?.color ? ' on' : ''}`} aria-pressed={!e?.color} onClick={() => setEdge({ color: undefined })}>Automatic</button>
            </div>
            <div className="hint">{e?.color ? `Chosen by hand: ${colourName(e.color)}. Saved in the Sutra.` : autoColour ? `Automatic: ${colourName(autoColour)}, because ${b?.name} receives several lines (each source step has its own colour).` : `Automatic: the normal colour, because ${b?.name} receives only this line.`} Right-click a step to colour all its lines.</div>
          </div>}
        {sameOutput.length > 1 && <p className="muted xs">{sameOutput.length} connections leave {a?.name} ({e?.port}): {sameOutput.map(x => x.label || (x.when === 'when' ? x.condition : x.when) || 'always').join(' · ')}</p>}
        <button className="btn danger" onClick={p.removeSel}>Delete connection</button>
      </div></aside>
    );
  }
  if (!p.selNode) return <aside className="side"><Overview {...p} /></aside>;
  const tabs: [InspectorTab, string][] = [['general', 'General'], ['input', 'Input'], ['output', 'Output'], ['settings', 'Settings']];
  return (
    <aside className="side">
      <div className="tabs" role="tablist">
        {tabs.map(([t, l]) => <button key={t} role="tab" aria-selected={p.tab === t} className={p.tab === t ? 'act' : ''} onClick={() => p.setTab(t)}>{l}</button>)}
      </div>
      <div className="tabbody">
        <NodeVariables node={p.selNode} />
        {p.tab === 'general' && <General {...p} node={p.selNode} />}
        {p.tab === 'input' && <InputTab {...p} node={p.selNode} />}
        {p.tab === 'output' && <StepOutput {...p} node={p.selNode} />}
        {p.tab === 'settings' && <StepSettings {...p} node={p.selNode} />}
      </div>
    </aside>
  );
}

function NodeVariables({ node }: { node: FlowNode }) {
  const { project, resources } = useCatalog();
  const miss = missingInNode(node, project, resources);
  return <MissingVariables names={miss.map(m => m.name)} via={Object.fromEntries(miss.filter(m => m.via).map(m => [m.name, m.via]))} />;
}

const runOutputs = (p: Props) => p.run?.outputs || {};

function Overview({ flowId, doc, setDoc, run, onDelete }: Props) {
  const { meta } = useCatalog();
  const triggers = doc.nodes.filter(n => meta.activities.find(a => a.type === n.type)?.trigger);
  const undescribed = doc.nodes.filter(n => !n.description).length;
  return (
    <div className="tabbody">
      <div className="fld"><label htmlFor="fname">Sutra name</label><input id="fname" type="text" value={doc.name} onChange={e => setDoc(d => ({ ...d, name: e.target.value }))} /></div>
      <div className="fld"><label htmlFor="fdesc">Description</label><textarea id="fdesc" rows={2} value={doc.description || ''} onChange={e => setDoc(d => ({ ...d, description: e.target.value }))} /></div>
      <p className="muted" style={{ fontSize: 12 }}>{doc.nodes.length} activities · {doc.edges.length} transitions · {triggers.length} trigger{triggers.length === 1 ? '' : 's'}{undescribed > 0 && <> · {undescribed} without a description</>}</p>
      <div className="row" style={{ marginBottom: 10 }}>
        <a className="btn small" href={`/api/flows/${flowId}/documentation`} target="_blank" rel="noopener" title="What starts this Sutra and every step with its description and settings, as a page to read, print or share. Made from the saved Sutra.">Documentation</a>
        <a className="btn small" href={`/api/flows/${flowId}/documentation?format=md`} title="The same as Markdown, for a repository or wiki">Markdown</a>
      </div>
      <ProcessVariables vars={doc.variables || []} onChange={v => setDoc(d => ({ ...d, variables: v }))} />
      {run && <>
        <p className="sub">Last test run</p>
        <p style={{ marginTop: 0 }}><span className={`badge ${run.status}`}>{run.status}</span> <span className="muted">{run.steps} steps in {since(run.startedAt, run.finishedAt)}</span></p>
        {run.error && <div className="errbox">{run.error}</div>}
        {run.reply && <><p className="sub">Reply sent to the caller</p><Json value={run.reply} /></>}
        {run.logs.length > 0 && <ul className="log">{run.logs.slice(-30).reverse().map((l, i) => <li key={i}><time>{l.t.slice(11, 19)}</time><span className={l.level}>{l.step ? `${l.step}: ` : ''}{l.msg}</span></li>)}</ul>}
      </>}
      <div className="group">Mapping</div>
      <div className="muted" style={{ fontSize: 12.5 }}>
        <p>Select an activity and open its <b>Input</b> tab: drag fields from Sutra Data onto the activity's inputs, and build formulas with functions such as <code>{"concat('Name : ', {input.name})"}</code> or <code>{"format-date('DD-MM-YY', {input.date})"}</code>.</p>
        <p>Every activity except triggers has a red <b>error</b> output. Connect it to handle failures; otherwise a failure stops the run.</p>
      </div>
      <button className="btn danger" onClick={onDelete}>Delete Sutra</button>
    </div>
  );
}

function ProcessVariables({ vars, onChange }: { vars: ProcessVariable[]; onChange(v: ProcessVariable[]): void }) {
  const set = (i: number, k: keyof ProcessVariable, v: string) => onChange(vars.map((x, j) => (j === i ? { ...x, [k]: v } : x)));
  return (
    <div className="fld">
      <span className="lbl">Sutra variables <span className="muted" style={{ fontWeight: 400 }}>(local to this Sutra: {'{vars.name}'})</span></span>
      {vars.map((v, i) => (
        <div className="kv" key={i} style={{ gridTemplateColumns: '1fr 90px 1fr auto' }}>
          <input className="inp code" aria-label={`Variable ${i + 1} name`} value={v.name} placeholder="name" onChange={e => set(i, 'name', e.target.value)} />
          <select className="inp" aria-label={`Variable ${i + 1} type`} value={v.type} onChange={e => set(i, 'type', e.target.value)}>{['string', 'number', 'boolean', 'json'].map(t => <option key={t}>{t}</option>)}</select>
          <input className="inp code" aria-label={`Variable ${i + 1} initial value`} value={String(v.value ?? '')} placeholder="initial value" onChange={e => set(i, 'value', e.target.value)} />
          <button className="x" aria-label="Remove variable" onClick={() => onChange(vars.filter((_, j) => j !== i))}>✕</button>
        </div>
      ))}
      <button className="btn small" onClick={() => onChange([...vars, { name: '', type: 'string', value: '' }])}>+ Variable</button>
    </div>
  );
}

function General(p: Props & { node: FlowNode }) {
  const { node } = p;
  const { meta, projectId, resources, secrets } = useCatalog();
  const [preview, setPreview] = useState<any>(null);
  const [previewing, setPreviewing] = useState(false);
  const previewEpoch = useRef(0);
  useEffect(() => {
    previewEpoch.current++;
    setPreview(null); setPreviewing(false);
    return () => { previewEpoch.current++; };
  }, [node.id, node.config, p.run?.id, projectId, resources]);
  const a = meta.activities.find(x => x.type === node.type);
  if (!a) return <div className="errbox">Unknown activity type {node.type}</div>;
  // Mappable inputs (templates, formulas, structured mappings) are edited in the Input tab.
  const fields = a.fields.filter(f => !f.tpl && f.type !== 'mapping' && !(node.type === 'setVar' && f.k === 'id')
    // Call Sutra following the called Sutra's input contract: its own Input schema does not apply (2.1.7).
    && !(node.type === 'callProcess' && f.k === 'inputSchema' && (node.config.inputContract === true || node.config.inputContract === 'true')));
  const mappable = a.fields.some(f => (f.tpl || f.type === 'mapping') && visible(f, node.config, a.fields));
  const setCfg = (k: string, v: any) => p.updateNode(node.id, n => ({ ...n, config: { ...n.config, [k]: v } }));
  const setMany = (values: Record<string, any>) => p.updateNode(node.id, n => ({ ...n, config: { ...n.config, ...values } }));
  const contract = node.type === 'callProcess' ? p.design[node.id]?.contract : undefined;
  /**
   * Call Sutra (2.1.7): picking a Sutra makes its Manual start's payload schema the input contract, unless the
   * step keeps its own Input schema; turning the contract On records the contract the designer accepted.
   */
  const onField = async (k: string, v: any) => {
    if (node.type !== 'callProcess') return setCfg(k, v);
    if (k === 'inputContract' && (v === true || v === 'true')) return setMany({ inputContract: true, contractSeen: contract && !('problem' in contract) ? contract.fingerprint : '' });
    if (k !== 'process' || !v) return setCfg(k, v);
    const own = !!node.config.inputSchema && node.config.inputContract !== true;
    let found: CallContract | { problem: string } | null = null;
    try { found = await get(`/api/flows/${encodeURIComponent(v)}/contract?use=${node.config.use === 'deployed' ? 'deployed' : 'draft'}`); } catch { found = null; }
    const follow = !own && !!found && !('problem' in found) && !!found.ref;
    setMany({ process: v, ...(follow ? { inputContract: true, contractSeen: (found as CallContract).fingerprint } : {}) });
  };
  // Where each reference in a field comes from (SQL fields send run data as bound parameters).
  const describeRefs = (value: unknown, f: { help?: string }) => fieldRefs(value).map(ref => refOrigin(ref, { doc: p.doc, nodeId: node.id, activities: meta.activities, bound: !!f.help?.includes('bound parameter') }));
  const errors = p.design[node.id]?.errors || [];
  const warnings = p.design[node.id]?.warnings || [];
  const canPreview = node.type === 'dbQuery' || node.type === 'databricksSql';
  const testQuery = async () => {
    const epoch = ++previewEpoch.current;
    setPreviewing(true); setPreview(null);
    const outputs = p.run?.outputs || {};
    const taskInput = [...(p.run?.tasks || [])].reverse().find(t => t.node_id === node.id)?.input;
    const incoming = p.doc.edges.find(e => e.to === node.id);
    const previous = incoming ? p.doc.nodes.find(n => n.id === incoming.from) : undefined;
    const input = taskInput ?? (previous ? outputs[previous.name] : undefined) ?? {};
    try {
      // Only the steps before this one (the path rule), and the trigger's real data.
      const before = new Set<string>();
      for (const pending = [node.id]; pending.length;) { const id = pending.pop()!; for (const e of p.doc.edges) if (e.to === id && !before.has(e.from)) { before.add(e.from); pending.push(e.from); } }
      const visible = Object.fromEntries(p.doc.nodes.filter(n => before.has(n.id) && n.name in outputs).map(n => [n.name, outputs[n.name]]));
      const trigger = p.doc.nodes.find(n => meta.activities.find(x => x.type === n.type)?.trigger);
      const result = await post('/api/design/query-preview', { projectId, node, scope: { input, nodes: visible, vars: p.run?.vars || {}, trigger: (trigger && outputs[trigger.name]) || {} } });
      if (epoch === previewEpoch.current) setPreview(result);
    } catch (e: any) { if (epoch === previewEpoch.current) setPreview({ error: e.message }); }
    finally { if (epoch === previewEpoch.current) setPreviewing(false); }
  };
  return (
    <>
      <div className={`phead ${famOf(meta, a.palette)}`}><span className="glyph">{a.glyph}</span><div><h2>{a.name}</h2><p>{a.desc}</p></div></div>
      <div className="fld"><label htmlFor="sname">Activity name</label>
        <input id="sname" type="text" defaultValue={node.name} key={node.id + node.name} onBlur={e => p.renameNode(node.id, e.target.value)} onKeyDown={e => { if (e.key === 'Enter') (e.target as HTMLInputElement).blur(); }} />
        <div className="hint">Mappings refer to activities by name; renaming updates them.</div>
      </div>
      <div className="fld"><label htmlFor="sdesc">Description</label>
        <textarea id="sdesc" rows={2} defaultValue={node.description || ''} key={node.id + ':d'} placeholder="What this step does and why"
          onBlur={e => { const v = e.target.value.trim(); if (v !== (node.description || '')) p.updateNode(node.id, n => ({ ...n, description: v || undefined })); }} />
        <div className="hint">Shown when pointing at the step on the canvas, and in the Sutra's documentation (General tab of the Sutra: Documentation).</div>
      </div>
      {errors.length > 0 && <div className="errbox">{errors.join('\n')}</div>}
      {warnings.length > 0 && <div className="warnbox">{warnings.join('\n')}</div>}
      {a.palette === 'ai' && resources.find(r => r.id === node.config.provider) && <AiModelSummary r={resources.find(r => r.id === node.config.provider)!} projectId={projectId} timeoutMs={Number(node.settings?.timeoutMs) > 0 ? Number(node.settings?.timeoutMs) : undefined} />}
      <RefOriginContext.Provider value={describeRefs}>
        <FieldList fields={fields} values={node.config} onChange={onField} resources={resources} secrets={secrets}
          extra={f => (node.type === 'soapInvoke' && (f.k === 'wsdlUrl' || f.k === 'wsdlRef') ? <WsdlLoader node={node} setCfg={setCfg} />
            : node.type === 'callProcess' && f.k === 'inputContract' && contract ? <CallContractNote contract={contract} setMany={setMany} />
            : node.type === 'dashboardPage' && f.k === 'name' ? <PageLink flowId={p.flowId} nodeId={node.id} name={String(node.config.name || '')} /> : null)} />
      </RefOriginContext.Provider>
      {['setVar', 'getVar'].includes(node.type) && <LocalVariableSettings node={node} doc={p.doc} updateNode={p.updateNode} />}
      {canPreview && <div className="fld">
        <button className="btn" onClick={testQuery} disabled={previewing || !node.config.connection || errors.length > 0}>{previewing ? 'Testing query…' : 'Test query (10 rows)'}</button>
        <div className="hint">Uses the selected connection and the latest sample input. It never adds a limit to the deployed query.</div>
        {preview?.error ? <div className="errbox">{preview.error}</div> : preview ? <div className="okbox"><b>Sample result</b><Json value={preview} /></div> : null}
      </div>}
      {mappable && <p><button className="btn" onClick={() => p.setTab('input')}>Map inputs ›</button></p>}
      <div className="row" style={{ marginTop: 6 }}>
        {a.trigger && <button className="btn go" onClick={() => p.onTest(node.id)}>▶ Test from here</button>}
        <button className="btn" onClick={() => p.duplicate(node.id)}>Duplicate</button>
        <button className="btn danger" onClick={p.removeSel}>Delete activity</button>
      </div>
    </>
  );
}

/** Where a Dashboard page is published (2.1.7): a link once deployed, or that it is not deployed yet. */
function PageLink({ flowId, nodeId, name }: { flowId: string; nodeId: string; name: string }) {
  const [link, setLink] = useState<{ deployed: boolean; version: number | null; name: string; url: string } | null>(null);
  useEffect(() => {
    let live = true;
    get<{ deployed: boolean; version: number | null; name: string; url: string }>(`/api/flows/${encodeURIComponent(flowId)}/page-link?node=${encodeURIComponent(nodeId)}`).then(l => { if (live) setLink(l); }, () => { if (live) setLink(null); });
    return () => { live = false; };
  }, [flowId, nodeId, name]);
  if (!link) return null;
  if (!link.deployed) return <div className="hint page-link">Not deployed: the page is published at <code>/dash/{name || 'name'}</code> once this Sutra is deployed.</div>;
  return (
    <div className="hint page-link">Page: <a href={link.url} target="_blank" rel="noopener noreferrer">{link.url}</a> (deployed v{link.version})
      {name.trim() && name.trim() !== link.name ? <> Deploy again to publish it at <code>/dash/{name.trim()}</code>.</> : null}</div>
  );
}

/** What the called Sutra expects (2.1.7): its contract, a change since it was accepted, or a suggestion to use it. */
function CallContractNote({ contract, setMany }: { contract: NonNullable<NodeDesign['contract']>; setMany(values: Record<string, any>): void }) {
  if ('problem' in contract) return <div className="hint contract-note">{contract.problem}</div>;
  const version = contract.version ? `deployed v${contract.version}` : 'draft';
  if (!contract.ref) return <div className="hint contract-note">{contract.sutra} ({version}) has no payload schema on its Manual start, so it has no input contract.</div>;
  const what = <><b>{contract.schemaName}</b> ({contract.kind === 'xsd' ? 'an XSD: the input is XML' : 'JSON Schema'}), the payload schema of &ldquo;{contract.trigger}&rdquo; in {contract.sutra} ({version}). {contract.strict ? 'That Sutra refuses input that does not match it.' : 'It is descriptive there: its strict validation is Off.'}</>;
  if (!contract.follows) return (
    <div className="hint contract-note">{contract.sutra} describes its input with {what}{' '}
      <button className="btn" onClick={() => setMany({ inputContract: true, contractSeen: contract.fingerprint })}>Use its input contract</button></div>
  );
  if (contract.changed) return (
    <div className="warnbox contract-note">{contract.sutra} changed its input since this step was saved. Now: {what} Check the mapping on the Input tab.{' '}
      <button className="btn" onClick={() => setMany({ contractSeen: contract.fingerprint })}>Accept the new input</button></div>
  );
  return <div className="hint contract-note">Input contract: {what} With Input from set to mapping, the Input tab maps to it.</div>;
}

/** General-tab local variable editing shares the same config as Input mappings. Selecting a
 * declared name never changes scope implicitly; storage is explicitly plain or by record ID.
 */
function LocalVariableSettings({node, doc, updateNode}: {node: FlowNode; doc: FlowDoc; updateNode: Props['updateNode']}) {
  const set = (values: Record<string, any>) => updateNode(node.id, n => ({...n, config: {...n.config, ...values}}));
  const record = String(node.config.id ?? '').trim();
  const catalogue = localVariablesShape({...doc, nodes: doc.nodes.filter(n => n.id !== node.id)});
  const names = (record && node.type === 'setVar' ? catalogue.children?.find(n => n.name === record)?.children : catalogue.children)?.map(v => v.name) || [];
  const nameEditor = (name: string, change: (value: string) => void, label: string) => <>
    <select aria-label={label} value={names.includes(name) ? name : ''} onChange={e => change(e.target.value)}><option value="">New / custom name…</option>{names.map(n => <option key={n} value={n}>{n}</option>)}</select>
    {!names.includes(name) && <input type="text" aria-label={`${label} custom name`} value={name} placeholder="Variable name" onChange={e => change(e.target.value)} />}
  </>;
  if (node.type === 'getVar') return <>
    {node.config.what === 'one variable' && <div className="fld"><span className="lbl">Variable name</span>{nameEditor(String(node.config.name ?? ''), name => set({name}), 'Read variable')}<div className="hint">Choose a declared/plain variable, or enter its literal name, for example test. The value is returned separately. Use one ID to read a record.</div></div>}
    {node.config.what === 'one ID' && <div className="fld"><label htmlFor="local-get-id">Record ID</label><input id="local-get-id" type="text" value={node.config.name ?? ''} onChange={e => set({name: e.target.value})} /><div className="hint">For example 1 reads the record at vars.1, not a variable whose value is 1. Formulas/templates remain available on Input.</div></div>}
    {!!doc.variables?.length && <><p className="sub">Declared Sutra variables — initial values</p><table className="t"><thead><tr><th>Name</th><th>Initial value</th></tr></thead><tbody>{doc.variables.map(v => <tr key={v.name}><td><code>{v.name}</code></td><td><code>{String(v.value ?? '')}</code></td></tr>)}</tbody></table><p className="hint">These initialise each run. Current results appear on Output after this activity executes.</p></>}
  </>;
  const rows: {k: string; v: string}[] = node.config.vars || [];
  const row = (i: number, values: Partial<{k: string; v: string}>) => set({vars: rows.map((r, j) => j === i ? {...r, ...values} : r)});
  return <>
    <div className="fld"><label htmlFor="local-storage">Variable storage</label><select id="local-storage" value={record ? 'record' : 'plain'} onChange={e => set({id: e.target.value === 'record' ? '1' : ''})}><option value="plain">Declared / plain variables (vars.name)</option><option value="record">Record by ID (vars.ID.name)</option></select></div>
    {record && <div className="fld"><label htmlFor="local-record-id">Record ID</label><input id="local-record-id" type="text" value={node.config.id ?? ''} onChange={e => set({id: e.target.value})} /><div className="hint">ID 1 stores Name as vars.1.Name. Choose plain storage above to update a declared variable such as vars.test.</div></div>}
    <p className="sub">Name / value pairs</p>
    {rows.map((r, i) => <div className="card" key={i}><div className="fld"><span className="lbl">Name</span>{nameEditor(r.k, k => row(i, {k}), `Variable ${i + 1}`)}</div><div className="fld"><label htmlFor={`local-value-${i}`}>Value</label><textarea id={`local-value-${i}`} rows={2} className="code" value={r.v} onChange={e => row(i, {v: e.target.value})} /></div><div className="hint">Target: <code>{`vars.${record ? record + '.' : ''}${r.k || 'name'}`}</code>. Plain text is literal; = starts a formula, and templates such as {'{{input.name}}'} also work. Input edits the same values.</div><button className="btn small" aria-label={`Remove variable ${i + 1}`} onClick={() => set({vars: rows.filter((_, j) => j !== i)})}>Remove</button></div>)}
    <button className="btn small" onClick={() => set({vars: [...rows, {k: '', v: ''}]})}>+ Name / value pair</button>
  </>;
}

function InputTab(p: Props & { node: FlowNode }) {
  const { meta } = useCatalog();
  const a = meta.activities.find(x => x.type === p.node.type);
  if (!a) return null;
  // Where several lines meet (2.1.7): which step each line comes from, in its colour.
  const incoming = incomingKey(p.doc, p.node.id);
  return <>
    {incoming.length > 1 && <div className="incoming-key" aria-label={`Lines into ${p.node.name}`}>
      <b>{p.node.name} receives {incoming.length} lines:</b>
      <ul>{incoming.map(l => <li key={l.edge.id}><span className={`swatch-dot${l.colour ? ` lc-${l.colour}` : ''}`} />{l.from}{l.port !== 'out' ? ` (${l.port})` : ''}{l.colour ? <span className="muted"> · {colourName(l.colour)}</span> : null}</li>)}</ul>
    </div>}
    <Mapper node={p.node} act={a} doc={p.doc} design={p.design} run={p.run} outputs={runOutputs(p)} updateNode={p.updateNode} />
  </>;
}

function WsdlLoader({ node, setCfg }: { node: FlowNode; setCfg(k: string, v: any): void }) {
  const { projectId } = useCatalog();
  const toast = useToast();
  const [desc, setDesc] = useState<any>(null);
  const [busy, setBusy] = useState(false);
  const fromProject = node.config.wsdlSource === 'project';
  const load = async () => {
    setBusy(true);
    try {
      setDesc(await post('/api/soap/describe', fromProject ? { projectId, wsdlRef: node.config.wsdlRef } : { projectId, wsdlUrl: node.config.wsdlUrl, connection: node.config.connection || undefined, auth: node.config.auth || undefined }));
    } catch (e: any) { toast(e.message, true); } finally { setBusy(false); }
  };
  const choose = (svc: string, port: string, op: string) => {
    setCfg('service', svc); setCfg('port', port); setCfg('operation', op);
    const input = desc?.[svc]?.[port]?.[op]?.input;
    if (input && typeof input === 'object') {
      const skel = (o: any): any => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('targetNS')).map(([k, v]) => [k.replace(/\[\]$/, ''), v && typeof v === 'object' ? skel(v) : '']));
      setCfg('args', JSON.stringify(skel(input), null, 2));
    }
    setDesc(null);
  };
  if ((fromProject && !node.config.wsdlRef) || (!fromProject && !node.config.wsdlUrl)) return null;
  return (
    <div style={{ margin: '-6px 0 12px' }}>
      <button className="btn small" disabled={busy} onClick={load}>{busy ? 'Loading' : 'Load operations from WSDL'}</button>
      {desc && (
        <ul className="list" style={{ marginTop: 6 }}>
          {Object.entries(desc).flatMap(([svc, ports]: any) => Object.entries(ports).flatMap(([port, ops]: any) => Object.keys(ops).map(op => (
            <li key={`${svc}/${port}/${op}`}><button onClick={() => choose(svc, port, op)}><code>{op}</code><span className="muted" style={{ fontSize: 11 }}>{svc} / {port}</span></button></li>
          ))))}
        </ul>
      )}
    </div>
  );
}


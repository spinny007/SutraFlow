import { useEffect, useState, type FormEvent } from 'react';
import { get, post, del } from './api';
import { useToast } from './ui';

/**
 * The signed-in person's profile (2.1.8), in the designer and the Admin Console: who they are and their roles,
 * their own password, and their own API tokens for AI assistants (the studio MCP server) and scripts. A token
 * acts as the person, with their roles; it expires after 30, 60 or 90 days and is renewed with a new value.
 */
interface Me { username: string; displayName: string; email: string; hasPassword?: boolean; viaToken?: boolean; permissions: { all: string[]; projects: Record<string, string[]> } }
interface Token { id: string; name: string; createdAt: string; expiresAt: string | null; lastUsed: string | null; expired: boolean }
interface Tokens { allowed: boolean; days: number[]; tokens: Token[] }

const day = (iso?: string | null) => (iso ? new Date(iso).toLocaleDateString() : 'never');
const soon = (t: Token) => !!t.expiresAt && !t.expired && Date.parse(t.expiresAt) - Date.now() < 7 * 86400e3;

export function Profile() {
  const [me, setMe] = useState<Me | null>(null);
  const [projects, setProjects] = useState<Record<string, string>>({});
  useEffect(() => {
    get<Me>('/api/access/me').then(setMe).catch(() => {});
    get<{ id: string; name: string }[]>('/api/projects').then(l => setProjects(Object.fromEntries(l.map(p => [p.id, p.name])))).catch(() => {});
  }, []);
  if (!me) return <p className="muted">Loading</p>;
  const perProject = Object.entries(me.permissions.projects);
  return (
    <div className="profile">
      <section className="profile-sec" aria-labelledby="pf-who">
        <h3 id="pf-who">Account</h3>
        <div className="profile-who"><strong>{me.displayName || me.username}</strong><span className="muted">{me.username}{me.email ? ` · ${me.email}` : ''}</span></div>
        <p className="muted xs" style={{ marginBottom: 4 }}>What you may do</p>
        <ul className="profile-perms">
          {me.permissions.all.length > 0 && <li><strong>All projects</strong>: {me.permissions.all.join(', ')}</li>}
          {perProject.map(([id, perms]) => <li key={id}><strong>{projects[id] || id}</strong>: {perms.join(', ')}</li>)}
          {!me.permissions.all.length && !perProject.length && <li className="muted">No roles yet: ask an administrator.</li>}
        </ul>
      </section>
      {me.hasPassword && !me.viaToken
        ? <PasswordForm />
        : <section className="profile-sec"><h3>Password</h3><p className="muted xs">{me.viaToken ? 'Sign in to the studio to change your password.' : 'You sign in with single sign-on: your password is kept by your organisation\'s sign-in, not here.'}</p></section>}
      <MyTokens canMake={!me.viaToken} />
    </div>
  );
}

function PasswordForm() {
  const toast = useToast();
  const [current, setCurrent] = useState('');
  const [password, setPw] = useState('');
  const [confirm, setConfirm] = useState('');
  const [err, setErr] = useState('');
  const submit = async (e: FormEvent) => {
    e.preventDefault();
    setErr('');
    if (password !== confirm) return setErr('The new passwords do not match');
    try {
      await post('/api/auth/password', { current, password });
      setCurrent(''); setPw(''); setConfirm('');
      toast('Password changed. Other sessions are signed out.');
    } catch (x: any) { setErr(x.message); }
  };
  return (
    <section className="profile-sec" aria-labelledby="pf-pw">
      <h3 id="pf-pw">Change password</h3>
      <form className="profile-form" onSubmit={submit}>
        {err && <div className="errbox">{err}</div>}
        <div className="fld"><label htmlFor="pf-cur">Current password</label><input id="pf-cur" type="password" autoComplete="current-password" value={current} onChange={e => setCurrent(e.target.value)} required /></div>
        <div className="fld"><label htmlFor="pf-new">New password</label><input id="pf-new" type="password" autoComplete="new-password" value={password} onChange={e => setPw(e.target.value)} required /></div>
        <div className="fld"><label htmlFor="pf-new2">New password again</label><input id="pf-new2" type="password" autoComplete="new-password" value={confirm} onChange={e => setConfirm(e.target.value)} required /></div>
        <div><button className="btn primary small" type="submit">Change password</button></div>
      </form>
    </section>
  );
}

function MyTokens({ canMake }: { canMake: boolean }) {
  const toast = useToast();
  const [data, setData] = useState<Tokens | null>(null);
  const [err, setErr] = useState('');
  const [name, setName] = useState('');
  const [days, setDays] = useState(90);
  const [shown, setShown] = useState<{ token: string; expiresAt: string } | null>(null);
  const load = () => get<Tokens>('/api/access/me/tokens').then(d => { setData(d); setErr(''); }).catch(e => setErr(e.message));
  useEffect(() => { load(); }, []);
  const show = (r: { token: string; expiresAt: string }) => { setShown(r); load(); };
  const create = async () => {
    try { show(await post('/api/access/me/tokens', { name: name.trim() || 'token', expiresDays: days })); setName(''); } catch (e: any) { toast(e.message, true); }
  };
  const renew = async (t: Token) => { try { show(await post(`/api/access/me/tokens/${t.id}/renew`)); toast(`${t.name} renewed: update the app that uses it`); } catch (e: any) { toast(e.message, true); } };
  const revoke = async (t: Token) => { try { await del(`/api/access/me/tokens/${t.id}`); toast(`${t.name} revoked`); load(); } catch (e: any) { toast(e.message, true); } };
  const copy = async () => { try { await navigator.clipboard.writeText(shown!.token); toast('Copied'); } catch { toast('Select the token and copy it', true); } };
  const mcp = `${location.origin}/mcp/studio`;
  return (
    <section className="profile-sec" aria-labelledby="pf-tok">
      <h3 id="pf-tok">My API tokens</h3>
      <p className="muted xs">For AI assistants (GitHub Copilot, Claude, Antigravity and other MCP clients) and scripts. A token acts as you, with your roles, until it expires. Send it as <code>Authorization: Bearer &lt;token&gt;</code>; the studio MCP server is <code>{mcp}</code>.</p>
      {err && <div className="errbox">{err}</div>}
      {data && !data.allowed && <div className="errbox">An administrator has switched personal API tokens off. Your tokens do not work until they are switched on again.</div>}
      {shown && (
        <div className="profile-shown" role="status">
          <strong>Copy this token now. It is not shown again.</strong> <span className="muted xs">Expires {day(shown.expiresAt)}.</span>
          <div className="profile-row"><input className="mono" readOnly value={shown.token} onFocus={e => e.currentTarget.select()} aria-label="New token" /><button className="btn small" onClick={copy}>Copy</button><button className="btn small" onClick={() => setShown(null)}>Done</button></div>
          <p className="muted xs">With Claude Code: <code>claude mcp add --transport http sutraflow {mcp} --header "Authorization: Bearer &lt;token&gt;"</code></p>
        </div>
      )}
      {canMake && data?.allowed && (
        <div className="profile-row">
          <input type="text" placeholder="Name, such as Copilot on my laptop" aria-label="Token name" value={name} onChange={e => setName(e.target.value)} maxLength={80} />
          <select aria-label="Expires after" value={days} onChange={e => setDays(Number(e.target.value))}>
            {(data.days || [30, 60, 90]).map(d => <option key={d} value={d}>Expires in {d} days</option>)}
          </select>
          <button className="btn small primary" onClick={create}>Create token</button>
        </div>
      )}
      {!canMake && <p className="muted xs">You are signed in with a token: sign in to the studio to create or renew tokens.</p>}
      {data && data.tokens.length > 0 ? (
        <table className="t profile-table">
          <thead><tr><th>Name</th><th>Created</th><th>Expires</th><th>Last used</th><th /></tr></thead>
          <tbody>{data.tokens.map(t => (
            <tr key={t.id}>
              <td><strong>{t.name}</strong> <span className="muted xs mono">sut_{t.id}</span></td>
              <td className="nowrap">{day(t.createdAt)}</td>
              <td className="nowrap">{t.expired ? <span className="profile-expired">expired</span> : <>{day(t.expiresAt)}{soon(t) && <span className="muted xs"> (soon)</span>}</>}</td>
              <td className="nowrap">{t.lastUsed ? day(t.lastUsed) : 'never'}</td>
              <td className="nowrap">
                {canMake && data.allowed && (t.expired || soon(t)) && <button className="btn small primary" onClick={() => renew(t)} aria-label={`Renew ${t.name}`} title="A new token with the same name and period replaces this one">Renew</button>}{' '}
                <button className="btn small" onClick={() => revoke(t)} aria-label={`Revoke ${t.name}`}>Revoke</button>
              </td>
            </tr>
          ))}</tbody>
        </table>
      ) : data && <p className="muted xs">No tokens yet.</p>}
    </section>
  );
}

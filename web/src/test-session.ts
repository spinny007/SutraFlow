/* @sutra-file-overview
 * File: web/src/test-session.ts
 * Purpose/support: Confirms engine cancellation before discarding test preview state. Failed or unconfirmed stop requests retain controls; terminal completion races and repeated cancellation are safe.
 * Connects to (static imports): No static module imports; use purpose/entry points and adjacent contracts for external interactions.
 * Functions/entry points (static scan): stopTestSession, testIsActive
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
export const testIsActive = (status: string) => ['running', 'waiting', 'paused', 'queued'].includes(status);

/** Only clear the browser's session after the engine confirms a terminal run state. */
export async function stopTestSession(id: string, transport: { post(url: string): Promise<unknown>; get(url: string): Promise<{ status: string }> }) {
  await transport.post(`/api/runs/${encodeURIComponent(id)}/cancel`);
  const run = await transport.get(`/api/runs/${encodeURIComponent(id)}`);
  if (testIsActive(run.status)) throw new Error('The engine has not confirmed test cancellation yet. Test controls have been retained; try Stop test again.');
  return run.status;
}

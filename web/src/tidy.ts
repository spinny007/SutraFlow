/* @sutra-file-overview
 * File: web/src/tidy.ts
 * Purpose/support: Tidy (2.1.7): lays a Sutra out left to right in columns by the longest path from its trigger (loops ignored), orders each column by the positions of the steps before it so lines cross less, and stacks steps by their real heights. Changes positions only; the designer keeps it as one undo step.
 * Connects to (static imports): ./types.js
 * Functions/entry points (static scan): tidyLayout, crossings
 * Maintenance: generated by tools/file-overviews.mjs from architecture descriptions and declarations; update source descriptions, then regenerate. Detailed runtime contracts remain beside implementations.
 * @end-sutra-file-overview */
import type { FlowDoc } from './types.js';

/** Steps are 250 px wide; the column gap leaves room for the lines and their labels. */
export const TIDY = { left: 60, top: 60, columnGap: 340, rowGap: 36 };

/**
 * Columns by the longest path from the starting steps (the trigger and steps without incoming lines,
 * such as the Error handler); connections that loop back are ignored. Within a column, steps follow
 * the average row of the steps before them (two passes), which removes most crossings.
 */
export function tidyLayout(doc: FlowDoc, heightOf: (nodeId: string) => number = () => 80): FlowDoc {
  if (!doc.nodes.length) return doc;
  const ids = doc.nodes.map(n => n.id);
  const out = new Map<string, string[]>(ids.map(id => [id, []]));
  const inc = new Map<string, string[]>(ids.map(id => [id, []]));
  for (const e of doc.edges) if (out.has(e.from) && inc.has(e.to)) { out.get(e.from)!.push(e.to); inc.get(e.to)!.push(e.from); }
  // Loop-back connections: found by a depth-first walk from the starting steps.
  const back = new Set<string>();
  const state = new Map<string, 1 | 2>();
  const visit = (id: string) => {
    state.set(id, 1);
    for (const to of out.get(id)!) {
      if (state.get(to) === 1) back.add(`${id}>${to}`);
      else if (!state.has(to)) visit(to);
    }
    state.set(id, 2);
  };
  const starts = ids.filter(id => !inc.get(id)!.length);
  for (const id of [...starts, ...ids]) if (!state.has(id)) visit(id);
  // Longest path in the acyclic part.
  const layer = new Map<string, number>(ids.map(id => [id, 0]));
  for (let changed = true, guard = 0; changed && guard < ids.length + 2; guard++) {
    changed = false;
    for (const e of doc.edges) {
      if (back.has(`${e.from}>${e.to}`) || !layer.has(e.from) || !layer.has(e.to)) continue;
      const want = layer.get(e.from)! + 1;
      if (want > layer.get(e.to)!) { layer.set(e.to, want); changed = true; }
    }
  }
  const columns: string[][] = [];
  for (const id of ids) (columns[layer.get(id)!] ||= []).push(id);
  // Order: start with the document order, then sort each column by its predecessors' rows.
  const row = new Map<string, number>();
  const number = () => columns.forEach(col => col?.forEach((id, i) => row.set(id, i)));
  number();
  for (let pass = 0; pass < 2; pass++) {
    for (const col of columns) {
      if (!col) continue;
      const score = (id: string) => {
        const ps = inc.get(id)!.filter(p => !back.has(`${p}>${id}`) && layer.get(p)! < layer.get(id)!);
        return ps.length ? ps.reduce((s, p) => s + row.get(p)!, 0) / ps.length : row.get(id)!;
      };
      const scored = col.map(id => ({ id, s: score(id), i: row.get(id)! }));
      scored.sort((a, b) => a.s - b.s || a.i - b.i);
      col.splice(0, col.length, ...scored.map(x => x.id));
      col.forEach((id, i) => row.set(id, i));
    }
  }
  const pos = new Map<string, { x: number; y: number }>();
  columns.forEach((col, c) => {
    let y = TIDY.top;
    for (const id of col || []) { pos.set(id, { x: TIDY.left + c * TIDY.columnGap, y }); y += heightOf(id) + TIDY.rowGap; }
  });
  return { ...doc, nodes: doc.nodes.map(n => ({ ...n, ...pos.get(n.id)! })) };
}

/** How many pairs of lines cross between neighbouring columns (used by tests to show Tidy helps). */
export function crossings(doc: FlowDoc) {
  const at = new Map(doc.nodes.map(n => [n.id, n]));
  const segs: [{ x: number; y: number }, { x: number; y: number }][] = [];
  for (const e of doc.edges) { const a = at.get(e.from), b = at.get(e.to); if (a && b && a.x < b.x) segs.push([a, b]); }
  let n = 0;
  for (let i = 0; i < segs.length; i++) for (let j = i + 1; j < segs.length; j++) {
    const [a1, a2] = segs[i], [b1, b2] = segs[j];
    if (a1.x !== b1.x || a2.x !== b2.x) continue;
    if ((a1.y - b1.y) * (a2.y - b2.y) < 0) n++;
  }
  return n;
}

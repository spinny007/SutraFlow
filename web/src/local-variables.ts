/** Shared designer catalogue for run-local variables. Mirrors declared/plain versus record-ID
 * storage without executing formulas or borrowing values from another run. Dynamic record IDs
 * are intentionally not invented as flat variables. Used by General editors and both data trees.
 */
import type { FlowDoc, SNode } from './types.js';
import { observedShape } from './mapping-values.js';
export function localVariablesShape(doc: FlowDoc): SNode {
  const root: SNode = {name: 'vars', type: 'object', children: []};
  const add = (parent: SNode, child: SNode) => {
    const old = parent.children!.find(v => v.name === child.name);
    if (!old) parent.children!.push(child);
    else if (child.children) { old.type = 'object'; old.children ??= []; child.children.forEach(c => add(old, c)); }
  };
  for (const v of doc.variables || []) {
    let shape: SNode = {name: v.name, type: v.type === 'number' ? 'number' : v.type === 'boolean' ? 'boolean' : 'string'};
    if (v.type === 'json') { try { shape = observedShape(typeof v.value === 'string' ? JSON.parse(v.value) : v.value, v.name); } catch { shape = {name: v.name, type: 'any'}; } }
    add(root, shape);
  }
  for (const n of doc.nodes.filter(n => n.type === 'setVar')) {
    const id = String(n.config.id ?? '').trim();
    if (/[{}=]/.test(id)) continue;
    const children = ((n.config.vars || []) as {k: string}[]).filter(r => r?.k).map(r => ({name: String(r.k), type: 'any' as const}));
    if (id) add(root, {name: id, type: 'object', children}); else children.forEach(c => add(root, c));
  }
  return root;
}
/** A readable snapshot from this Get task's output, never from the run's later final variables. */
export function localVariablePairs(output: any, mode: string): {name: string; value: unknown}[] {
  if (!output || typeof output !== 'object') return [];
  if (mode === 'all variables') return Object.entries(output.variables || {}).map(([name, value]) => ({name, value}));
  if (output.found !== true) return [];
  if (mode === 'one ID' && output.value && typeof output.value === 'object' && !Array.isArray(output.value)) return Object.entries(output.value).map(([name, value]) => ({name: `${output.name}.${name}`, value}));
  return [{name: String(output.name), value: output.value}];
}

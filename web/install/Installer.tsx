import { useEffect, useRef, useState, type ReactNode } from 'react';
import { Logo } from '../src/Auth';

interface Check { name: string; ok: boolean; detail: string; required: boolean }
interface Found { folder: string; version: string; exists: boolean; settings: boolean; hasData: boolean; dataDir: string; database: string; port: number; host: string; upgradable: boolean; note: string }
interface MemoryInfo { machineMb: number; freeMb: number; nodeDefaultMb: number; suggestedMb: number }
interface State { version: string; home: string; locked: boolean; system: Check[]; here: Found; memory: MemoryInfo; hostname: string; defaults: Record<string, number> }
interface Step { step: string; state: string; detail?: string }
interface Job { kind?: string; steps: Step[]; done: boolean; error?: string; result?: any }
interface Engine { name: string; host: string; port: number; http: number; https: number; memoryMb: number; canLead: boolean }

// The one-time token the installer printed comes with the address; every request carries it.
const token = new URLSearchParams(location.search).get('t') || '';
async function call<T>(method: 'GET' | 'POST', url: string, body?: unknown): Promise<T> {
  const r = await fetch(url, { method, headers: { 'content-type': 'application/json', 'x-installer-token': token }, body: body === undefined ? undefined : JSON.stringify(body) });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(j.error || `${r.status}`);
  return j as T;
}

const INSTALL = ['Welcome', 'Administrator', 'Database', 'Server', 'Cluster', 'Review', 'Install', 'Done'];
const UPGRADE = ['Welcome', 'Installation', 'Review', 'Upgrade', 'Done'];

function Steps({ names, at }: { names: string[]; at: number }) {
  return <ol className="i-steps" aria-label="Installer steps">{names.map((n, i) => <li key={n} className={i < at ? 'done' : i === at ? 'now' : ''} aria-current={i === at ? 'step' : undefined}>{n}</li>)}</ol>;
}
function Field({ label, help, children }: { label: string; help?: string; children: ReactNode }) {
  return <div className="i-fld"><label>{label}{children}</label>{help && <small>{help}</small>}</div>;
}
const mark = (s: string) => (s === 'ok' ? <span className="i-ok" aria-label="done">✓</span> : s === 'fail' ? <span className="i-bad" aria-label="failed">✗</span> : s === 'run' ? <span className="i-run" aria-label="working">…</span> : <span className="i-warn">–</span>);

/** The installer: install SutraFlow here, or upgrade an installation from 2.1.0 on, page by page. */
export function Installer() {
  const [st, setSt] = useState<State | null>(null);
  const [err, setErr] = useState('');
  const [mode, setMode] = useState<'install' | 'upgrade'>('install');
  const [at, setAt] = useState(0);
  const [admin, setAdmin] = useState({ username: 'admin', password: '', again: '', email: '' });
  const [db, setDb] = useState({ kind: 'sqlite' as 'sqlite' | 'postgres', host: '127.0.0.1', port: 5432, database: 'sutraflow', user: 'postgres', password: '', sslMode: 'off' as 'off' | 'require' | 'verify', create: true, pgvector: 'required' as 'required' | 'optional', file: 'sutra.db' });
  const [dbTest, setDbTest] = useState<{ ok: boolean; message: string; notes: string[] } | null>(null);
  const [server, setServer] = useState({ host: '127.0.0.1', studioPort: 4800, gatewayHttp: 8080, gatewayHttps: 8443, environment: 'development' as 'development' | 'test' | 'production', engine: false, enginePort: 4801, engineHttp: 9080, engineHttps: 9443, studioMemoryMb: 0, engineMemoryMb: 0, engineId: '', engineName: '', studioMayLead: true, engineMayLead: true });
  const [clusterName, setClusterName] = useState('');
  const [ports, setPorts] = useState<{ port: number; free: boolean; suggest?: number }[] | null>(null);
  const [engines, setEngines] = useState<Engine[]>([]);
  const [start, setStart] = useState(true);
  const [folder, setFolder] = useState('');
  const [found, setFound] = useState<Found | null>(null);
  const [backupDir, setBackupDir] = useState('');
  const [job, setJob] = useState<Job | null>(null);
  const [busy, setBusy] = useState(false);
  const [moving, setMoving] = useState(false);
  const poll = useRef<number | undefined>(undefined);

  useEffect(() => {
    call<State>('GET', '/api/state').then(s => {
      setSt(s);
      setServer(v => ({ ...v, studioPort: s.defaults.studioPort, gatewayHttp: s.defaults.gatewayHttp, gatewayHttps: s.defaults.gatewayHttps, engineId: `${s.hostname}-studio`, engineName: `${s.hostname}-engine` }));
      if (s.locked) setMode('upgrade');
    }, e => setErr(e.message));
    return () => window.clearInterval(poll.current);
  }, []);

  const leaders = () => [...(server.studioMayLead ? [server.engineId || 'this server'] : []), ...(server.engine && server.engineMayLead ? [server.engineName || 'the engine beside it'] : []), ...engines.filter(e => e.canLead).map(e => e.name)];
  const totalEngines = () => 1 + (server.engine ? 1 : 0) + engines.length;
  const names = mode === 'install' ? INSTALL : UPGRADE;
  const page = names[at];
  const go = (n: number) => { setErr(''); setAt(n); window.scrollTo(0, 0); };
  const follow = (onDone: (j: Job) => void) => {
    window.clearInterval(poll.current);
    poll.current = window.setInterval(async () => {
      try { const j = await call<Job>('GET', '/api/job'); setJob(j); if (j.done) { window.clearInterval(poll.current); onDone(j); } } catch (e: any) { setErr(e.message); }
    }, 700);
  };
  const config = () => ({
    admin: { username: admin.username.trim(), password: admin.password, email: admin.email.trim() || undefined },
    database: db.kind === 'sqlite' ? { kind: 'sqlite', file: db.file.trim() || 'sutra.db' } : { kind: 'postgres', host: db.host, port: Number(db.port), database: db.database, user: db.user, password: db.password || undefined, sslMode: db.sslMode, create: db.create, pgvector: db.pgvector },
    server: { host: server.host, studioPort: Number(server.studioPort), gatewayHttp: Number(server.gatewayHttp), gatewayHttps: Number(server.gatewayHttps), environment: server.environment, studioMemoryMb: Number(server.studioMemoryMb) || 0, engineId: server.engineId.trim() || undefined, studioMayLead: server.studioMayLead,
      ...(server.engine ? { enginePort: Number(server.enginePort), engineHttp: Number(server.engineHttp), engineHttps: Number(server.engineHttps), engineMemoryMb: Number(server.engineMemoryMb) || 0, engineName: server.engineName.trim() || undefined, engineMayLead: server.engineMayLead } : {}) },
    cluster: { name: clusterName.trim(), engines },
    start,
  });

  // ---------- checks per page, before Next ----------
  const adminProblems = () => {
    const p: string[] = [];
    if (!/^[A-Za-z0-9._@-]{2,64}$/.test(admin.username.trim())) p.push('User name: 2 to 64 letters, digits, . _ @ -');
    if (admin.password.length < 12) p.push('Password: at least 12 characters');
    else if (!(/[a-z]/.test(admin.password) && /[A-Z]/.test(admin.password) && /\d/.test(admin.password))) p.push('Password: use upper and lower case letters and digits');
    if (admin.password !== admin.again) p.push('The two passwords differ');
    if (admin.email && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(admin.email)) p.push('Email: not an email address');
    return p;
  };
  const testDb = async () => {
    setBusy(true); setDbTest(null); setErr('');
    try { setDbTest(await call('POST', '/api/database', { database: config().database })); } catch (e: any) { setDbTest({ ok: false, message: e.message, notes: [] }); } finally { setBusy(false); }
  };
  const checkServerPorts = async () => {
    const list = [server.studioPort, server.gatewayHttp, server.gatewayHttps, ...(server.engine ? [server.enginePort, server.engineHttp, server.engineHttps] : [])].map(Number);
    const r = await call<{ port: number; free: boolean; suggest?: number }[]>('POST', '/api/ports', { host: server.host, ports: list });
    setPorts(r);
    return r;
  };
  const useSuggested = () => {
    if (!ports) return;
    const pick = (p: number) => { const x = ports.find(r => r.port === p); return x && !x.free && x.suggest ? x.suggest : p; };
    setServer(v => ({ ...v, studioPort: pick(Number(v.studioPort)), gatewayHttp: pick(Number(v.gatewayHttp)), gatewayHttps: pick(Number(v.gatewayHttps)), enginePort: pick(Number(v.enginePort)), engineHttp: pick(Number(v.engineHttp)), engineHttps: pick(Number(v.engineHttps)) }));
    setPorts(null);
  };
  /** Node memory: 0 (Node decides) or from 256 MB; the processes on this machine leave 15% for the system. */
  const memoryProblems = () => {
    const p: string[] = [];
    const mine = [['Studio memory', Number(server.studioMemoryMb) || 0], ...(server.engine ? [['Engine memory', Number(server.engineMemoryMb) || 0]] : [])] as [string, number][];
    for (const [what, n] of mine) if (n < 0 || (n > 0 && n < 256)) p.push(`${what}: 0 (Node.js decides) or from 256 MB`);
    const sum = mine.reduce((a, [, n]) => a + n, 0);
    if (st && sum > st.memory.machineMb * 0.85) p.push(`Memory: ${sum} MB of this machine's ${st.memory.machineMb} MB; leave at least 15% for the system`);
    return p;
  };
  const next = () => { setMoving(true); return step().finally(() => setMoving(false)); };
  const step = async () => {
    setErr('');
    try {
      if (page === 'Welcome' && mode === 'install') {
        const bad = (st?.system || []).filter(c => c.required && !c.ok);
        if (bad.length) return setErr(`Fix first: ${bad.map(b => b.detail).join('; ')}`);
      }
      if (page === 'Administrator') { const p = adminProblems(); if (p.length) return setErr(p.join('. ')); }
      if (page === 'Database' && db.kind === 'postgres' && !dbTest?.ok) return setErr('Test the connection first (Test connection).');
      if (page === 'Server') {
        const m = memoryProblems(); if (m.length) return setErr(m.join('. '));
        const r = await checkServerPorts();
        if (r.some(p => !p.free)) return setErr('Some ports are in use (below). Choose others, or use the suggested free ports.');
      }
      if (page === 'Cluster' && engines.length && db.kind !== 'postgres') return setErr('Several engines need PostgreSQL: go back to Database, or remove the engines.');
      if (page === 'Cluster' && !leaders().length) return setErr('At least one engine must be allowed to lead: timers, listeners and recovery need a leader.');
      if (page === 'Review' && mode === 'install') {
        const v = await call<{ errors: string[] }>('POST', '/api/validate', { config: config() });
        if (v.errors.length) return setErr(v.errors.join('. '));
        await call('POST', '/api/install', { config: config() });
        setJob({ steps: [], done: false });
        go(at + 1);
        follow(j => { if (!j.error) go(INSTALL.indexOf('Done')); });
        return;
      }
      if (page === 'Installation') {
        if (!found?.upgradable) return setErr(found ? found.note : 'Find the installation first (Check).');
      }
      if (page === 'Review' && mode === 'upgrade') {
        await call('POST', '/api/upgrade', { config: { from: found!.folder, backupDir: backupDir.trim() || undefined, start } });
        setJob({ steps: [], done: false });
        go(at + 1);
        follow(j => { if (!j.error) go(UPGRADE.indexOf('Done')); });
        return;
      }
      go(at + 1);
    } catch (e: any) { setErr(e.message); }
  };
  const detect = async () => {
    setBusy(true); setFound(null);
    try { setFound(await call('POST', '/api/detect', { folder })); } catch (e: any) { setErr(e.message); } finally { setBusy(false); }
  };

  const strength = admin.password.length >= 16 && /[^A-Za-z0-9]/.test(admin.password) ? 'strong' : admin.password.length >= 12 ? 'good' : admin.password ? 'too short' : '';
  const working = page === 'Install' || page === 'Upgrade';

  return (
    <div className="i-shell">
      <header className="i-head"><Logo /><div><h1>SutraFlow {st?.version || ''} installer</h1><p>{mode === 'install' ? 'Install SutraFlow on this server' : 'Upgrade an installation to this version'}{st ? ` · ${st.home}` : ''}</p></div></header>
      <Steps names={names} at={at} />
      <main className="i-card" aria-live="polite">
        {!st && !err && <p>Loading…</p>}

        {st && page === 'Welcome' && <>
          <h2>Welcome</h2>
          <p className="lead">This installer sets up SutraFlow page by page, or upgrades an existing installation. It answers on this machine only.</p>
          {st.locked && <div className="i-msg info">SutraFlow is already installed in this folder (version {st.here.version}). To install again, remove <span className="i-mono">data/install.lock</span> first; to bring another installation up to {st.version}, choose Upgrade.</div>}
          <div className="i-choice" role="group" aria-label="What to do">
            <button type="button" aria-pressed={mode === 'install'} disabled={st.locked} onClick={() => setMode('install')}><b>Install</b><span>A new SutraFlow in this folder: administrator, database, ports, and optionally a cluster.</span></button>
            <button type="button" aria-pressed={mode === 'upgrade'} onClick={() => setMode('upgrade')}><b>Upgrade</b><span>An installation of 2.1.0 or later, to {st.version}: backed up first, put back if anything fails.</span></button>
          </div>
          {mode === 'install' && <><h3>System check</h3><ul className="i-checks">{st.system.map(c => <li key={c.name}>{c.ok ? <span className="i-ok">✓</span> : c.required ? <span className="i-bad">✗</span> : <span className="i-warn">!</span>}<span><b>{c.name}</b><br /><small>{c.detail}</small></span></li>)}</ul></>}
        </>}

        {page === 'Administrator' && <>
          <h2>Administrator</h2>
          <p className="lead">The first account: it manages users, roles, projects and the server.</p>
          <div className="i-grid">
            <Field label="User name"><input value={admin.username} onChange={e => setAdmin({ ...admin, username: e.target.value })} autoComplete="username" /></Field>
            <Field label="Email" help="Optional; for notices"><input type="email" value={admin.email} onChange={e => setAdmin({ ...admin, email: e.target.value })} autoComplete="email" /></Field>
            <Field label="Password" help={`At least 12 characters with upper and lower case letters and digits${strength ? ` · ${strength}` : ''}`}><input type="password" value={admin.password} onChange={e => setAdmin({ ...admin, password: e.target.value })} autoComplete="new-password" /></Field>
            <Field label="Password again"><input type="password" value={admin.again} onChange={e => setAdmin({ ...admin, again: e.target.value })} autoComplete="new-password" /></Field>
          </div>
        </>}

        {page === 'Database' && <>
          <h2>Database</h2>
          <p className="lead">Where SutraFlow keeps its own data: projects, Sutras, runs, people and the vault.</p>
          <div className="i-choice" role="group" aria-label="Database">
            <button type="button" aria-pressed={db.kind === 'sqlite'} onClick={() => { setDb({ ...db, kind: 'sqlite' }); setDbTest(null); }}><b>SQLite</b><span>A file in the data folder. Nothing to set up; one engine.</span></button>
            <button type="button" aria-pressed={db.kind === 'postgres'} onClick={() => { setDb({ ...db, kind: 'postgres' }); setDbTest(null); }}><b>PostgreSQL</b><span>For several engines (a cluster) and larger volumes.</span></button>
          </div>
          {db.kind === 'sqlite' && <><div className="i-grid">
            <Field label="Database file" help="In the data folder, for example sutra.db"><input value={db.file} onChange={e => { setDb({ ...db, file: e.target.value }); setDbTest(null); }} spellCheck={false} /></Field>
          </div>
          <p className="lead" style={{ fontSize: 13 }}>SQLite has no user names or passwords: the database is a file, protected by the data folder's permissions, and passwords and keys inside SutraFlow are encrypted with <span className="i-mono">data/master.key</span>. For a database with its own logins and for several engines, choose PostgreSQL.</p></>}
          {db.kind === 'postgres' && <div className="i-grid">
            <Field label="Host"><input value={db.host} onChange={e => { setDb({ ...db, host: e.target.value }); setDbTest(null); }} /></Field>
            <Field label="Port"><input type="number" value={db.port} onChange={e => { setDb({ ...db, port: Number(e.target.value) }); setDbTest(null); }} /></Field>
            <Field label="Database"><input value={db.database} onChange={e => { setDb({ ...db, database: e.target.value }); setDbTest(null); }} /></Field>
            <Field label="User"><input value={db.user} onChange={e => { setDb({ ...db, user: e.target.value }); setDbTest(null); }} autoComplete="off" /></Field>
            <Field label="Password" help="Kept in sutraflow.env (SUTRA_DB_PASSWORD), readable by this server's account only"><input type="password" value={db.password} onChange={e => { setDb({ ...db, password: e.target.value }); setDbTest(null); }} autoComplete="new-password" /></Field>
            <Field label="SSL" help="off on this machine or a trusted network; require encrypts; verify also checks the certificate (hosted PostgreSQL)"><select value={db.sslMode} onChange={e => { setDb({ ...db, sslMode: e.target.value as any }); setDbTest(null); }}><option value="off">off</option><option value="require">require</option><option value="verify">verify</option></select></Field>
            <Field label="Create it when missing" help="The user then needs CREATEDB"><select value={db.create ? 'yes' : 'no'} onChange={e => setDb({ ...db, create: e.target.value === 'yes' })}><option value="yes">Yes</option><option value="no">No</option></select></Field>
            <Field label="pgvector" help="Knowledge bases and AI memory search in PostgreSQL. The test enables it in the database when it is installed on the server."><select value={db.pgvector} onChange={e => { setDb({ ...db, pgvector: e.target.value as any }); setDbTest(null); }}><option value="required">Required</option><option value="optional">Continue without pgvector</option></select></Field>
          </div>}
          {db.kind === 'postgres' && <p><button className="i-btn" onClick={testDb} disabled={busy}>{busy ? 'Testing…' : 'Test connection'}</button></p>}
          {dbTest && <div className={`i-msg ${dbTest.ok ? 'ok' : 'err'}`}>{dbTest.message}{dbTest.notes.length > 0 && <ul>{dbTest.notes.map(n => <li key={n}>{n}</li>)}</ul>}</div>}
        </>}

        {page === 'Server' && <>
          <h2>Server</h2>
          <p className="lead">The addresses SutraFlow listens on. Each port is checked before you go on; a busy one gets a free one suggested.</p>
          <div className="i-grid">
            <Field label="Listen on" help="127.0.0.1 keeps the designer and Admin Console on this machine (recommended; put a proxy in front to reach them from elsewhere)"><select value={server.host} onChange={e => setServer({ ...server, host: e.target.value })}><option value="127.0.0.1">127.0.0.1 (this machine)</option><option value="0.0.0.0">0.0.0.0 (every address)</option></select></Field>
            <Field label="Environment"><select value={server.environment} onChange={e => setServer({ ...server, environment: e.target.value as any })}><option>development</option><option>test</option><option>production</option></select></Field>
            <Field label="Designer and Admin Console port"><input type="number" value={server.studioPort} onChange={e => { setServer({ ...server, studioPort: Number(e.target.value) }); setPorts(null); }} /></Field>
            <Field label="Gateway HTTP port" help="REST, SOAP, MCP and agents"><input type="number" value={server.gatewayHttp} onChange={e => { setServer({ ...server, gatewayHttp: Number(e.target.value) }); setPorts(null); }} /></Field>
            <Field label="Gateway HTTPS port"><input type="number" value={server.gatewayHttps} onChange={e => { setServer({ ...server, gatewayHttps: Number(e.target.value) }); setPorts(null); }} /></Field>
            <Field label="A headless engine beside it" help="A second process on the same database (sutraflow start engine)"><select value={server.engine ? 'yes' : 'no'} onChange={e => { setServer({ ...server, engine: e.target.value === 'yes' }); setPorts(null); }}><option value="no">No</option><option value="yes">Yes</option></select></Field>
            {server.engine && <>
              <Field label="Engine port"><input type="number" value={server.enginePort} onChange={e => { setServer({ ...server, enginePort: Number(e.target.value) }); setPorts(null); }} /></Field>
              <Field label="Engine gateway HTTP"><input type="number" value={server.engineHttp} onChange={e => { setServer({ ...server, engineHttp: Number(e.target.value) }); setPorts(null); }} /></Field>
              <Field label="Engine gateway HTTPS"><input type="number" value={server.engineHttps} onChange={e => { setServer({ ...server, engineHttps: Number(e.target.value) }); setPorts(null); }} /></Field>
            </>}
          </div>
          <h3>Node memory</h3>
          <p className="lead" style={{ fontSize: 13 }}>Each engine is its own Node.js process with its own memory. 0 lets Node.js decide{st ? ` (about ${st.memory.nodeDefaultMb} MB here)` : ''}. {st ? `This machine has ${st.memory.machineMb} MB (${st.memory.freeMb} MB free); about ${st.memory.suggestedMb} MB per engine suits it.` : ''} It can be changed later in the Admin Console (Engines, Tuning) and applies at a restart.</p>
          <div className="i-grid">
            <Field label="Studio memory (MB)" help="0 = Node.js decides"><input type="number" min={0} step={256} value={server.studioMemoryMb} onChange={e => setServer({ ...server, studioMemoryMb: Number(e.target.value) })} /></Field>
            {server.engine && <Field label="Engine memory (MB)" help="The headless engine beside it"><input type="number" min={0} step={256} value={server.engineMemoryMb} onChange={e => setServer({ ...server, engineMemoryMb: Number(e.target.value) })} /></Field>}
            {st && <p style={{ alignSelf: 'end' }}><button className="i-btn" onClick={() => setServer({ ...server, studioMemoryMb: st.memory.suggestedMb, engineMemoryMb: st.memory.suggestedMb })}>Use {st.memory.suggestedMb} MB</button></p>}
          </div>
          <p><button className="i-btn" onClick={() => checkServerPorts().catch(e => setErr(e.message))}>Check ports</button></p>
          {ports && <ul className="i-checks">{ports.map(p => <li key={p.port}>{p.free ? <span className="i-ok">✓</span> : <span className="i-bad">✗</span>}<span>{p.port} {p.free ? 'is free' : `is in use${p.suggest ? `; ${p.suggest} is free` : ''}`}</span></li>)}</ul>}
          {ports?.some(p => !p.free && p.suggest) && <p><button className="i-btn" onClick={useSuggested}>Use the free ports</button></p>}
        </>}

        {page === 'Cluster' && <>
          <h2>Cluster</h2>
          <p className="lead">The engines that share the work through one database: this server, an engine beside it, and further engines on other machines (PostgreSQL only). The leader runs timers, listeners, recovery and housekeeping; it is elected among the engines that may lead, and another takes over when it stops.</p>
          <div className="i-grid">
            <Field label="Cluster name" help="Shown in the Admin Console, for example Production or Shop cluster"><input value={clusterName} maxLength={60} onChange={e => setClusterName(e.target.value)} /></Field>
          </div>
          <table className="i-engines"><thead><tr><th>Engine name</th><th>Where</th><th>Listen on</th><th>Port</th><th>Gateway HTTP</th><th>Gateway HTTPS</th><th>Memory (MB)</th><th>May lead</th><th /></tr></thead>
            <tbody>
              <tr><td><input aria-label="This server's engine name" value={server.engineId} onChange={e => setServer({ ...server, engineId: e.target.value })} /></td><td className="muted">this server</td><td colSpan={5} className="muted">{server.host}:{server.studioPort}, gateway {server.gatewayHttp}/{server.gatewayHttps} (Server page)</td>
                <td><input type="checkbox" aria-label="This server may lead" checked={server.studioMayLead} onChange={e => setServer({ ...server, studioMayLead: e.target.checked })} /></td><td /></tr>
              {server.engine && <tr><td><input aria-label="The engine beside it: name" value={server.engineName} onChange={e => setServer({ ...server, engineName: e.target.value })} /></td><td className="muted">beside it</td><td colSpan={5} className="muted">{server.host}:{server.enginePort}, gateway {server.engineHttp}/{server.engineHttps} (Server page)</td>
                <td><input type="checkbox" aria-label="The engine beside it may lead" checked={server.engineMayLead} onChange={e => setServer({ ...server, engineMayLead: e.target.checked })} /></td><td /></tr>}
              {engines.map((e, i) => <tr key={i}>
                <td><input aria-label={`Engine ${i + 1} name`} value={e.name} onChange={ev => setEngines(engines.map((x, j) => (j === i ? { ...x, name: ev.target.value } : x)))} /></td><td className="muted">another machine</td>
                {(['host', 'port', 'http', 'https', 'memoryMb'] as const).map(k => <td key={k}><input aria-label={`Engine ${i + 1} ${k}`} value={(e as any)[k]} onChange={ev => setEngines(engines.map((x, j) => (j === i ? { ...x, [k]: k === 'host' ? ev.target.value : Number(ev.target.value) } : x)))} /></td>)}
                <td><input type="checkbox" aria-label={`Engine ${i + 1} may lead`} checked={e.canLead} onChange={ev => setEngines(engines.map((x, j) => (j === i ? { ...x, canLead: ev.target.checked } : x)))} /></td>
                <td><button className="i-btn" onClick={() => setEngines(engines.filter((_x, j) => j !== i))} aria-label={`Remove engine ${i + 1}`}>Remove</button></td></tr>)}
            </tbody></table>
          <p><button className="i-btn" disabled={db.kind !== 'postgres'} onClick={() => setEngines([...engines, { name: `engine-${engines.length + 2}`, host: '0.0.0.0', port: 4801, http: 9080, https: 9443, memoryMb: 0, canLead: true }])}>Add an engine on another machine</button></p>
          {db.kind !== 'postgres' && <div className="i-msg info">Engines on other machines need PostgreSQL; this installation uses SQLite (this server, and an engine beside it).</div>}
          {leaders().length === 1 && totalEngines() > 1 && <div className="i-msg info">Only {leaders()[0]} may lead: it is always the leader, and timers, listeners and recovery stop while it is down. Allow a second engine for failover.</div>}
          <p className="lead" style={{ fontSize: 13 }}>Change names, the cluster's name and who may lead later in the Admin Console (Engines). Memory 0 lets Node.js decide on that machine. Each further engine needs the same SutraFlow release, its settings file, and a copy of this server's <span className="i-mono">data/master.key</span> (the vault key); it joins when started with <span className="i-mono">sutraflow start engine</span>.</p>
        </>}

        {page === 'Review' && mode === 'install' && <>
          <h2>Review</h2>
          <p className="lead">Nothing is changed until you choose Install.</p>
          <dl className="i-review">
            <dt>Folder</dt><dd className="i-mono">{st?.home}</dd>
            <dt>Administrator</dt><dd>{admin.username}{admin.email ? ` (${admin.email})` : ''}</dd>
            <dt>Database</dt><dd>{db.kind === 'sqlite' ? `SQLite: ${db.file || 'sutra.db'} in the data folder` : `PostgreSQL ${db.user}@${db.host}:${db.port}/${db.database} (SSL ${db.sslMode}); pgvector ${db.pgvector === 'optional' ? 'when available' : 'required'}`}</dd>
            <dt>Designer and Admin Console</dt><dd>http://{server.host === '0.0.0.0' ? '127.0.0.1' : server.host}:{server.studioPort}</dd>
            <dt>Gateway</dt><dd>HTTP {server.gatewayHttp}, HTTPS {server.gatewayHttps}{server.engine ? `; engine ${server.enginePort} (${server.engineHttp}/${server.engineHttps})` : ''}</dd>
            <dt>Environment</dt><dd>{server.environment}</dd>
            <dt>Node memory</dt><dd>studio {server.studioMemoryMb ? `${server.studioMemoryMb} MB` : 'Node.js decides'}{server.engine ? `; engine ${server.engineMemoryMb ? `${server.engineMemoryMb} MB` : 'Node.js decides'}` : ''}</dd>
            <dt>Cluster</dt><dd>{clusterName.trim() || '(no name)'}: {[server.engineId || 'this server', ...(server.engine ? [server.engineName || 'the engine beside it'] : []), ...engines.map(e => `${e.name}${e.memoryMb ? ` (${e.memoryMb} MB)` : ''}`)].join(', ')}</dd>
            <dt>May lead</dt><dd>{leaders().join(', ') || 'none'}</dd>
          </dl>
          <label><input type="checkbox" checked={start} onChange={e => setStart(e.target.checked)} /> Start SutraFlow when installed</label>
        </>}

        {page === 'Installation' && <>
          <h2>Installation to upgrade</h2>
          <p className="lead">The folder of a SutraFlow 2.1.0 or later installation. This package ({st?.version}) is installed into it; its data and settings stay.</p>
          <div className="i-row"><div className="i-fld" style={{ flex: 1 }}><label>Folder<input value={folder} onChange={e => { setFolder(e.target.value); setFound(null); }} placeholder="C:\laragon\www\sutra" /></label></div><button className="i-btn" onClick={detect} disabled={busy || !folder.trim()}>{busy ? 'Looking…' : 'Check'}</button></div>
          {found && <div className={`i-msg ${found.upgradable ? 'ok' : 'err'}`}>{found.note}</div>}
          {found?.exists && <dl className="i-review"><dt>Version</dt><dd>{found.version}</dd><dt>Database</dt><dd className="i-mono">{found.database}</dd><dt>Data folder</dt><dd className="i-mono">{found.dataDir}</dd><dt>Address</dt><dd>http://{found.host === '0.0.0.0' ? '127.0.0.1' : found.host}:{found.port}</dd></dl>}
        </>}

        {page === 'Review' && mode === 'upgrade' && found && <>
          <h2>Review</h2>
          <p className="lead">SutraFlow {found.version} is stopped gracefully (running steps finish), backed up, upgraded to {st?.version}, checked and started again. If any step fails, the previous version is put back and started.</p>
          <dl className="i-review"><dt>Installation</dt><dd className="i-mono">{found.folder}</dd><dt>From</dt><dd>{found.version}</dd><dt>To</dt><dd>{st?.version}</dd></dl>
          <Field label="Backup folder" help="Empty: a backups folder inside the installation. It gets the data folder, the settings and the whole database."><input value={backupDir} onChange={e => setBackupDir(e.target.value)} placeholder={`${found.folder}${found.folder.includes('\\') ? '\\' : '/'}backups`} /></Field>
          <p><label><input type="checkbox" checked={start} onChange={e => setStart(e.target.checked)} /> Start it again when upgraded</label></p>
        </>}

        {working && <>
          <h2>{page === 'Install' ? 'Installing' : 'Upgrading'}</h2>
          <ul className="i-checks">{(job?.steps || []).map(s => <li key={s.step}>{mark(s.state)}<span><b>{s.step}</b>{s.detail && <><br /><small>{s.detail}</small></>}</span></li>)}</ul>
          {!job?.done && <p className="lead">Working…</p>}
          {job?.error && <div className="i-msg err">{job.error}</div>}
        </>}

        {page === 'Done' && <>
          <h2>{mode === 'install' ? 'SutraFlow is installed' : 'SutraFlow is upgraded'}</h2>
          {mode === 'install' && job?.result && <>
            <p className="lead">Sign in as <b>{admin.username}</b> at <a href={job.result.address} target="_blank" rel="noreferrer">{job.result.address}</a>{start ? '' : ' after starting it (sutraflow start)'}.</p>
            {(job.result.cluster || []).length > 0 && <><h3>Engines of the cluster</h3><ul>{job.result.cluster.map((e: any) => <li key={e.name}>{e.name}: <a href={`/api/cluster-file?t=${token}&name=${encodeURIComponent(e.name)}`}>download its settings file</a></li>)}</ul></>}
            <div className="i-msg info">The installer is locked now. Keep <span className="i-mono">data/master.key</span> safe and backed up: it unlocks the vault. To start SutraFlow with the machine: <span className="i-mono">sutraflow service</span>.</div>
          </>}
          {mode === 'upgrade' && job?.result && <p className="lead">{job.result.upgraded} in <span className="i-mono">{job.result.folder}</span>. The backup is in <span className="i-mono">{job.result.backup}</span>.</p>}
          <p><button className="i-btn" onClick={() => call('POST', '/api/quit').then(() => window.close(), () => {})}>Close the installer</button></p>
        </>}

        {err && <div className="i-msg err" role="alert">{err}</div>}

        {st && !working && page !== 'Done' && (
          <div className="i-foot">
            <button className="i-btn" onClick={() => go(at - 1)} disabled={at === 0}>Back</button>
            <button className="i-btn primary" onClick={next} disabled={busy || moving || (page === 'Welcome' && mode === 'install' && !!st.locked)}>{moving ? 'Checking…' : page === 'Review' ? (mode === 'install' ? 'Install' : 'Upgrade') : 'Next'}</button>
          </div>
        )}
        {working && job?.done && job.error && <div className="i-foot"><button className="i-btn" onClick={() => go(at - 1)}>Back</button></div>}
      </main>
    </div>
  );
}
